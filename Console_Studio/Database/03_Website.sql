/*===============================================================
  AppCore Console : website settings + website requests.

  Run in pgAdmin connected to "AppCore_Control" (the Query Tool
  title must start with AppCore_Control/), the whole file (F5).
  Safe to run again.

  SiteSettings : the website's content (company, contact, home
  page, pricing plans, about, switches), edited in the Console at
  Settings > Website settings; one row per key ('website'), the
  value is JSON written by the Console API.

  SiteRequests : the public website (appcoretech.net) saves each
  demo / purchase request here; the Console "Requests" page reviews
  them and converts one into a Customer (then a Tenant).
===============================================================*/

BEGIN;

CREATE TABLE IF NOT EXISTS public."SiteSettings"
(
    "SettingKey"    varchar(60)  PRIMARY KEY,
    "SettingValue"  text         NOT NULL,
    "ModifiedDate"  timestamptz  NOT NULL DEFAULT now(),
    "ModifiedBy"    bigint
);

CREATE TABLE IF NOT EXISTS public."SiteRequests"
(
    "SiteRequestId"      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"           uuid          NOT NULL DEFAULT gen_random_uuid(),
    "RequestNo"          varchar(20)   NOT NULL,              -- REQ-00001
    "RequestType"        varchar(20)   NOT NULL,              -- Demo / Purchase
    "ProductCode"        varchar(30)   NOT NULL,

    -- company (same fields as a Console customer)
    "LegalName"          varchar(200)  NOT NULL,
    "DisplayName"        varchar(200),
    "BinNo"              varchar(20),
    "TinNo"              varchar(20),
    "Address"            varchar(500),
    "City"               varchar(100),
    "Country"            varchar(60),

    -- contact person
    "ContactName"        varchar(150)  NOT NULL,
    "Designation"        varchar(100),
    "Phone"              varchar(30)   NOT NULL,
    "Email"              varchar(150)  NOT NULL,

    -- setup wishes
    "Branches"           integer,
    "Users"              integer,
    "PreferredSubdomain" varchar(63),                         -- motozone -> motozone.appcoretech.net
    "PreferredDate"      date,
    "PreferredTime"      varchar(20),
    "Message"            varchar(2000),
    "HeardFrom"          varchar(60),

    -- handling in the Console
    "Status"             varchar(20)   NOT NULL DEFAULT 'New',
    "StaffNotes"         text,
    "CustomerId"         bigint        REFERENCES public."Customers" ("CustomerId"),
    "IpAddress"          varchar(60),
    "UserAgent"          varchar(300),
    "CreatedDate"        timestamptz   NOT NULL DEFAULT now(),
    "ModifiedDate"       timestamptz,
    "ModifiedBy"         bigint,

    CONSTRAINT "UX_SiteRequests_No"       UNIQUE ("RequestNo"),
    CONSTRAINT "UX_SiteRequests_PublicId" UNIQUE ("PublicId"),
    CONSTRAINT "CK_SiteRequests_Type"     CHECK ("RequestType" IN ('Demo', 'Purchase')),
    CONSTRAINT "CK_SiteRequests_Status"   CHECK ("Status" IN ('New', 'Contacted', 'DemoBooked', 'Converted', 'Closed'))
);

-- added after the first version (safe to run again)
ALTER TABLE public."SiteRequests" ADD COLUMN IF NOT EXISTS "Country" varchar(60);

CREATE INDEX IF NOT EXISTS "IX_SiteRequests_Date"   ON public."SiteRequests" ("CreatedDate" DESC);
CREATE INDEX IF NOT EXISTS "IX_SiteRequests_Status" ON public."SiteRequests" ("Status");

COMMIT;

-- Check : 4 and 31
SELECT 'SiteSettings columns (4)' AS "Item", count(*)::text AS "Value"
FROM information_schema.columns
WHERE table_schema = 'public' AND table_name = 'SiteSettings'
UNION ALL
SELECT 'SiteRequests columns (31)', count(*)::text
FROM information_schema.columns
WHERE table_schema = 'public' AND table_name = 'SiteRequests';
