/*===============================================================
  AppCore Console : step 2 / 2 - the control schema.

  Run in pgAdmin connected to "AppCore_Control" (Query Tool on that
  database), the whole file (F5). Safe to run again.

  Products (industries) -> Customers -> Tenants (one per product a
  customer uses, one database each) -> domains / modules / status.
  Console staff, roles, sessions and the audit log.

  Seeds : the 4 products (Two Wheeler active, the rest Planned)
  and the Console staff roles. The first staff user is created by the Console API
  on first start (no password in this file).
===============================================================*/

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ------------------------------------------------------------
-- Products (industries)
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."Products"
(
    "ProductId"     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"      uuid         NOT NULL DEFAULT gen_random_uuid(),
    "ProductCode"   varchar(30)  NOT NULL,
    "ProductName"   varchar(100) NOT NULL,
    "Industry"      varchar(100) NOT NULL,
    "Description"   varchar(500),
    "Status"        varchar(20)  NOT NULL DEFAULT 'Planned',
    "DisplayOrder"  integer      NOT NULL DEFAULT 0,
    "CreatedDate"   timestamptz  NOT NULL DEFAULT now(),
    "ModifiedDate"  timestamptz,
    CONSTRAINT "UX_Products_Code"     UNIQUE ("ProductCode"),
    CONSTRAINT "UX_Products_PublicId" UNIQUE ("PublicId"),
    CONSTRAINT "CK_Products_Status"   CHECK ("Status" IN ('Planned', 'Active', 'Retired'))
);

CREATE TABLE IF NOT EXISTS public."ProductModules"
(
    "ProductModuleId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ProductId"       bigint       NOT NULL REFERENCES public."Products" ("ProductId"),
    "ModuleCode"      varchar(30)  NOT NULL,
    "ModuleName"      varchar(100) NOT NULL,
    "IsCore"          boolean      NOT NULL DEFAULT false,   -- always on, cannot be switched off
    "DisplayOrder"    integer      NOT NULL DEFAULT 0,
    CONSTRAINT "UX_ProductModules" UNIQUE ("ProductId", "ModuleCode")
);

CREATE TABLE IF NOT EXISTS public."ProductTemplates"
(
    "ProductTemplateId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ProductId"         bigint       NOT NULL REFERENCES public."Products" ("ProductId"),
    "TemplateName"      varchar(100) NOT NULL,
    "DatabaseName"      varchar(100) NOT NULL,
    "SchemaVersion"     varchar(30),
    "IsCurrent"         boolean      NOT NULL DEFAULT false,
    "CreatedDate"       timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public."ProductReleases"
(
    "ProductReleaseId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ProductId"        bigint       NOT NULL REFERENCES public."Products" ("ProductId"),
    "Version"          varchar(30)  NOT NULL,
    "ReleaseDate"      date,
    "Notes"            text,
    "CreatedDate"      timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT "UX_ProductReleases" UNIQUE ("ProductId", "Version")
);

-- ------------------------------------------------------------
-- Database servers (where tenant databases live)
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."DatabaseServers"
(
    "DatabaseServerId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ServerCode"       varchar(30)  NOT NULL,
    "ServerName"       varchar(100) NOT NULL,
    "Host"             varchar(200) NOT NULL,
    "Port"             integer      NOT NULL DEFAULT 5432,
    -- the login is never stored here : the Console reads it from
    -- its own configuration by this key
    "CredentialKey"    varchar(100) NOT NULL,
    "Status"           varchar(20)  NOT NULL DEFAULT 'Active',
    "CreatedDate"      timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT "UX_DatabaseServers_Code" UNIQUE ("ServerCode"),
    CONSTRAINT "CK_DatabaseServers_Status" CHECK ("Status" IN ('Active', 'Full', 'Retired'))
);

-- ------------------------------------------------------------
-- Customers (the business) and Tenants (one per product)
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."Customers"
(
    "CustomerId"    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"      uuid         NOT NULL DEFAULT gen_random_uuid(),
    "CustomerCode"  varchar(30)  NOT NULL,
    "LegalName"     varchar(200) NOT NULL,
    "DisplayName"   varchar(200) NOT NULL,
    "Phone"         varchar(30),
    "Email"         varchar(150),
    "Address"       varchar(500),
    "Country"       varchar(60)  NOT NULL DEFAULT 'Bangladesh',
    "BinNo"         varchar(20),
    "TinNo"         varchar(20),
    "Remarks"       varchar(1000),
    "Status"        varchar(20)  NOT NULL DEFAULT 'Active',
    "CreatedDate"   timestamptz  NOT NULL DEFAULT now(),
    "CreatedBy"     bigint,
    "ModifiedDate"  timestamptz,
    "ModifiedBy"    bigint,
    CONSTRAINT "UX_Customers_Code"     UNIQUE ("CustomerCode"),
    CONSTRAINT "UX_Customers_PublicId" UNIQUE ("PublicId"),
    CONSTRAINT "CK_Customers_Status"   CHECK ("Status" IN ('Active', 'Inactive'))
);

CREATE TABLE IF NOT EXISTS public."CustomerContacts"
(
    "CustomerContactId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CustomerId"        bigint       NOT NULL REFERENCES public."Customers" ("CustomerId") ON DELETE CASCADE,
    "ContactName"       varchar(150) NOT NULL,
    "Designation"       varchar(100),
    "Phone"             varchar(30),
    "Email"             varchar(150),
    "IsPrimary"         boolean      NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS public."Tenants"
(
    "TenantId"          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"          uuid         NOT NULL DEFAULT gen_random_uuid(),
    "TenantCode"        varchar(30)  NOT NULL,          -- e.g. MOTOZONE
    "CustomerId"        bigint       NOT NULL REFERENCES public."Customers" ("CustomerId"),
    "ProductId"         bigint       NOT NULL REFERENCES public."Products" ("ProductId"),
    "DisplayName"       varchar(200) NOT NULL,
    "DatabaseServerId"  bigint       REFERENCES public."DatabaseServers" ("DatabaseServerId"),
    "DatabaseName"      varchar(100),
    "TimeZone"          varchar(60)  NOT NULL DEFAULT 'Asia/Dhaka',
    "Currency"          varchar(10)  NOT NULL DEFAULT 'BDT',
    "Status"            varchar(20)  NOT NULL DEFAULT 'Provisioning',
    "TrialEndsOn"       date,
    "AppVersion"        varchar(30),
    "SchemaVersion"     varchar(30),
    "Remarks"           varchar(1000),
    "CreatedDate"       timestamptz  NOT NULL DEFAULT now(),
    "CreatedBy"         bigint,
    "ModifiedDate"      timestamptz,
    "ModifiedBy"        bigint,
    CONSTRAINT "UX_Tenants_Code"     UNIQUE ("TenantCode"),
    CONSTRAINT "UX_Tenants_PublicId" UNIQUE ("PublicId"),
    CONSTRAINT "UX_Tenants_Database" UNIQUE ("DatabaseServerId", "DatabaseName"),
    CONSTRAINT "CK_Tenants_Status"   CHECK ("Status" IN ('Provisioning', 'Trial', 'Active', 'Grace', 'ReadOnly', 'Suspended', 'Cancelled'))
);

CREATE TABLE IF NOT EXISTS public."TenantDomains"
(
    "TenantDomainId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "TenantId"       bigint       NOT NULL REFERENCES public."Tenants" ("TenantId") ON DELETE CASCADE,
    "HostName"       varchar(200) NOT NULL,             -- e.g. motozone.appcoretech.net
    "DomainType"     varchar(20)  NOT NULL DEFAULT 'Subdomain',
    "IsPrimary"      boolean      NOT NULL DEFAULT false,
    "CreatedDate"    timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT "UX_TenantDomains_Host" UNIQUE ("HostName"),
    CONSTRAINT "CK_TenantDomains_Type" CHECK ("DomainType" IN ('Subdomain', 'Custom', 'Legacy'))
);

CREATE TABLE IF NOT EXISTS public."TenantModules"
(
    "TenantModuleId"  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "TenantId"        bigint      NOT NULL REFERENCES public."Tenants" ("TenantId") ON DELETE CASCADE,
    "ProductModuleId" bigint      NOT NULL REFERENCES public."ProductModules" ("ProductModuleId"),
    "IsEnabled"       boolean     NOT NULL DEFAULT true,
    "ModifiedDate"    timestamptz NOT NULL DEFAULT now(),
    "ModifiedBy"      bigint,
    CONSTRAINT "UX_TenantModules" UNIQUE ("TenantId", "ProductModuleId")
);

CREATE TABLE IF NOT EXISTS public."TenantStatusHistory"
(
    "TenantStatusHistoryId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "TenantId"              bigint       NOT NULL REFERENCES public."Tenants" ("TenantId") ON DELETE CASCADE,
    "FromStatus"            varchar(20),
    "ToStatus"              varchar(20)  NOT NULL,
    "Reason"                varchar(500),
    "ChangedDate"           timestamptz  NOT NULL DEFAULT now(),
    "ChangedBy"             bigint
);

-- ------------------------------------------------------------
-- Console staff, roles, sessions, audit
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."StaffRoles"
(
    "StaffRoleId"  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "RoleCode"     varchar(30)  NOT NULL,
    "RoleName"     varchar(100) NOT NULL,
    "Description"  varchar(500),
    CONSTRAINT "UX_StaffRoles_Code" UNIQUE ("RoleCode")
);

CREATE TABLE IF NOT EXISTS public."StaffUsers"
(
    "StaffUserId"       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"          uuid         NOT NULL DEFAULT gen_random_uuid(),
    "LoginId"           varchar(60)  NOT NULL,
    "FullName"          varchar(150) NOT NULL,
    "Email"             varchar(150),
    "Phone"             varchar(30),
    "StaffRoleId"       bigint       NOT NULL REFERENCES public."StaffRoles" ("StaffRoleId"),
    "PasswordHash"      varchar(500) NOT NULL,
    "MustChangePassword" boolean     NOT NULL DEFAULT true,
    "TwoFactorSecret"   varchar(200),                    -- set when 2FA is turned on
    "FailedLogins"      integer      NOT NULL DEFAULT 0,
    "LockedUntil"       timestamptz,
    "LastLoginDate"     timestamptz,
    "Status"            varchar(20)  NOT NULL DEFAULT 'Active',
    "CreatedDate"       timestamptz  NOT NULL DEFAULT now(),
    "ModifiedDate"      timestamptz,
    CONSTRAINT "UX_StaffUsers_Login"    UNIQUE ("LoginId"),
    CONSTRAINT "UX_StaffUsers_PublicId" UNIQUE ("PublicId"),
    CONSTRAINT "CK_StaffUsers_Status"   CHECK ("Status" IN ('Active', 'Inactive'))
);

CREATE TABLE IF NOT EXISTS public."StaffSessions"
(
    "StaffSessionId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "StaffUserId"    bigint       NOT NULL REFERENCES public."StaffUsers" ("StaffUserId") ON DELETE CASCADE,
    "RefreshHash"    varchar(200) NOT NULL,
    "IpAddress"      varchar(60),
    "UserAgent"      varchar(300),
    "CreatedDate"    timestamptz  NOT NULL DEFAULT now(),
    "ExpiresDate"    timestamptz  NOT NULL,
    "RevokedDate"    timestamptz
);

CREATE TABLE IF NOT EXISTS public."AuditLog"
(
    "AuditLogId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "StaffUserId"  bigint,
    "Action"       varchar(60)  NOT NULL,       -- e.g. Tenant.Create, Login.Failed
    "EntityName"   varchar(60),
    "EntityId"     varchar(60),
    "TenantId"     bigint,
    "Details"      text,
    "IpAddress"    varchar(60),
    "CreatedDate"  timestamptz  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS "IX_AuditLog_Date"   ON public."AuditLog" ("CreatedDate" DESC);
CREATE INDEX IF NOT EXISTS "IX_AuditLog_Tenant" ON public."AuditLog" ("TenantId", "CreatedDate" DESC);

