/*===============================================================
  AppCore Console : modules, packages, users and brands of a
  tenant (2026-11-20, owner : "both modules and users ... the
  starter basic package may not include warranty management,
  fixed assets, emi, vat").

  Run in pgAdmin on "AppCore_Control" (Query Tool on that
  database), the whole file (F5). Safe to run again.
  Run it BEFORE the Console update that uses it.

  1. The Two Wheeler modules (ModuleCode = the ERP module's
     route key). Security & Permission and Settings are core
     (always on).
  2. Packages : STARTER, STANDARD, PROFESSIONAL (lists below;
     change them here later and run again).
  3. Tenants get :
       PackageCode      the package chosen in the Console
       MaxUsers         empty = no limit
       DisabledModules  written by the Console on Save : the
                        module route keys that are OFF, comma
                        separated. The ERP reads only this.
     Existing tenants : PROFESSIONAL, nothing off, no user limit.
  4. TenantBrands : the brands a tenant carries (brand packs,
     step 2 of the design; filled later).
  ASCII only.
===============================================================*/

DO $$
BEGIN
    IF current_database() <> 'AppCore_Control' THEN
        RAISE EXCEPTION 'Wrong database (%). Run this on AppCore_Control.', current_database();
    END IF;
END $$;

BEGIN;

-- 3. tenant columns ---------------------------------------------------
ALTER TABLE public."Tenants" ADD COLUMN IF NOT EXISTS "PackageCode"     varchar(30);
ALTER TABLE public."Tenants" ADD COLUMN IF NOT EXISTS "MaxUsers"        integer;
ALTER TABLE public."Tenants" ADD COLUMN IF NOT EXISTS "DisabledModules" varchar(2000) NOT NULL DEFAULT '';

ALTER TABLE public."Tenants" DROP CONSTRAINT IF EXISTS "CK_Tenants_MaxUsers";
ALTER TABLE public."Tenants" ADD CONSTRAINT "CK_Tenants_MaxUsers" CHECK ("MaxUsers" IS NULL OR "MaxUsers" >= 1);

-- 2. packages ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public."ProductPackages"
(
    "ProductPackageId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ProductId"        bigint       NOT NULL REFERENCES public."Products" ("ProductId"),
    "PackageCode"      varchar(30)  NOT NULL,
    "PackageName"      varchar(100) NOT NULL,
    "Description"      varchar(500),
    "DisplayOrder"     integer      NOT NULL DEFAULT 0,
    CONSTRAINT "UX_ProductPackages" UNIQUE ("ProductId", "PackageCode")
);

CREATE TABLE IF NOT EXISTS public."ProductPackageModules"
(
    "ProductPackageId" bigint NOT NULL REFERENCES public."ProductPackages" ("ProductPackageId") ON DELETE CASCADE,
    "ProductModuleId"  bigint NOT NULL REFERENCES public."ProductModules" ("ProductModuleId") ON DELETE CASCADE,
    PRIMARY KEY ("ProductPackageId", "ProductModuleId")
);

-- 4. brands ----------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public."TenantBrands"
(
    "TenantBrandId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "TenantId"      bigint       NOT NULL REFERENCES public."Tenants" ("TenantId") ON DELETE CASCADE,
    "BrandCode"     varchar(30)  NOT NULL,
    "BrandName"     varchar(100) NOT NULL,
    "IsEnabled"     boolean      NOT NULL DEFAULT true,
    "PackVersion"   varchar(30),
    "InstalledDate" timestamptz,
    "CreatedDate"   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT "UX_TenantBrands" UNIQUE ("TenantId", "BrandCode")
);

-- 1. Two Wheeler modules -------------------------------------------------
CREATE TEMP TABLE tmp_modules (code text, name text, core boolean, ord int, pkg text) ON COMMIT DROP;

INSERT INTO tmp_modules VALUES
    ('security-permission',        'Security & Permission',      true,   1, 'STARTER'),
    ('settings',                   'Settings',                   true,   2, 'STARTER'),
    ('accounts-finance',           'Accounts & Finance',         false,  3, 'STARTER'),
    ('procurement',                'Procurement',                false,  4, 'STARTER'),
    ('inventory-management',       'Inventory Management',       false,  5, 'STARTER'),
    ('sales-operations',           'Sales Operations',           false,  6, 'STARTER'),
    ('service-operations',         'Service Operations',         false,  7, 'STARTER'),
    ('accessories-operations',     'Accessories Operations',     false,  8, 'STARTER'),
    ('enquiry-management',         'Enquiry Management',         false,  9, 'STARTER'),
    ('reports',                    'Reports',                    false, 10, 'STARTER'),
    ('registration-management',    'Registration Management',    false, 11, 'STANDARD'),
    ('membership-management',      'Membership Management',      false, 12, 'STANDARD'),
    ('human-resource-manangement', 'Human Resource Management',  false, 13, 'STANDARD'),
    ('warranty-management',        'Warranty Management',        false, 14, 'PROFESSIONAL'),
    ('emi-management',             'EMI Management',             false, 15, 'PROFESSIONAL'),
    ('vat-management',             'VAT Management',             false, 16, 'PROFESSIONAL'),
    ('fixed-assets-management',    'Fixed Assets Management',    false, 17, 'PROFESSIONAL');

INSERT INTO public."ProductModules" ("ProductId", "ModuleCode", "ModuleName", "IsCore", "DisplayOrder")
SELECT p."ProductId", m.code, m.name, m.core, m.ord
FROM   tmp_modules m
CROSS  JOIN public."Products" p
WHERE  p."ProductCode" = 'TWO-WHEELER'
ON CONFLICT ("ProductId", "ModuleCode") DO UPDATE
SET    "ModuleName" = EXCLUDED."ModuleName", "IsCore" = EXCLUDED."IsCore", "DisplayOrder" = EXCLUDED."DisplayOrder";

INSERT INTO public."ProductPackages" ("ProductId", "PackageCode", "PackageName", "Description", "DisplayOrder")
SELECT p."ProductId", x.code, x.name, x.descr, x.ord
FROM   (VALUES
          ('STARTER',      'Starter',      'Sales, service, accessories, stock and accounts.', 1),
          ('STANDARD',     'Standard',     'Starter + Registration, Membership, Human Resource.', 2),
          ('PROFESSIONAL', 'Professional', 'Standard + Warranty, EMI, VAT, Fixed Assets.', 3)
       ) AS x(code, name, descr, ord)
CROSS  JOIN public."Products" p
WHERE  p."ProductCode" = 'TWO-WHEELER'
ON CONFLICT ("ProductId", "PackageCode") DO UPDATE
SET    "PackageName" = EXCLUDED."PackageName", "Description" = EXCLUDED."Description", "DisplayOrder" = EXCLUDED."DisplayOrder";

-- package contents : each package = its own modules + every smaller package
DELETE FROM public."ProductPackageModules" pm
USING  public."ProductPackages" pk, public."Products" p
WHERE  pm."ProductPackageId" = pk."ProductPackageId" AND pk."ProductId" = p."ProductId" AND p."ProductCode" = 'TWO-WHEELER';

INSERT INTO public."ProductPackageModules" ("ProductPackageId", "ProductModuleId")
SELECT pk."ProductPackageId", pm."ProductModuleId"
FROM   public."Products" p
JOIN   public."ProductPackages" pk ON pk."ProductId" = p."ProductId"
JOIN   tmp_modules m ON (CASE m.pkg WHEN 'STARTER' THEN 1 WHEN 'STANDARD' THEN 2 ELSE 3 END)
                     <= (CASE pk."PackageCode" WHEN 'STARTER' THEN 1 WHEN 'STANDARD' THEN 2 ELSE 3 END)
JOIN   public."ProductModules" pm ON pm."ProductId" = p."ProductId" AND pm."ModuleCode" = m.code
WHERE  p."ProductCode" = 'TWO-WHEELER';

-- existing Two Wheeler tenants : everything they have today
UPDATE public."Tenants" t
SET    "PackageCode" = 'PROFESSIONAL'
FROM   public."Products" p
WHERE  t."ProductId" = p."ProductId" AND p."ProductCode" = 'TWO-WHEELER' AND t."PackageCode" IS NULL;

COMMIT;

-- Check
SELECT pk."PackageName" AS "Package", count(*) AS "Modules",
       string_agg(m."ModuleName", ', ' ORDER BY m."DisplayOrder") AS "List"
FROM   public."ProductPackages" pk
JOIN   public."ProductPackageModules" x ON x."ProductPackageId" = pk."ProductPackageId"
JOIN   public."ProductModules" m ON m."ProductModuleId" = x."ProductModuleId"
GROUP  BY pk."PackageName", pk."DisplayOrder"
ORDER  BY pk."DisplayOrder";

SELECT "TenantCode", "PackageCode", "MaxUsers", "DisabledModules" FROM public."Tenants" ORDER BY "TenantCode";
