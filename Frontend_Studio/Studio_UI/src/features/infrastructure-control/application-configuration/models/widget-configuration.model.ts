//===============================================================
// Widget Configuration Model
//===============================================================

export interface WidgetConfiguration
{
    //===========================================================
    // Primary Key
    //===========================================================

    widgetConfigurationId:
        number;


    //===========================================================
    // Dashboard
    //===========================================================

    dashboardId:
        number;

    dashboardCode:
        string;

    dashboardName:
        string;

    displayName?:
        string;


    //===========================================================
    // Widget Configuration Summary
    //===========================================================

    widgetCount:
        number;


    //===========================================================
    // Status
    //===========================================================

    isActive:
        boolean;


    //===========================================================
    // Details
    //===========================================================

    details:
        WidgetConfigurationDetail[];
}



//===============================================================
// Widget Configuration Detail
//===============================================================

export interface WidgetConfigurationDetail
{
    //===========================================================
    // Primary Key
    //===========================================================

    widgetConfigurationDetailId:
        number;

    widgetConfigurationId:
        number;


    //===========================================================
    // Widget
    //===========================================================

    widgetId:
        number;

    widgetCode:
        string;

    widgetName:
        string;


    //===========================================================
    // Layout
    //===========================================================

    columnSpan:
        number;

    displayOrder:
        number;


    //===========================================================
    // Status
    //===========================================================

    isActive:
        boolean;
}