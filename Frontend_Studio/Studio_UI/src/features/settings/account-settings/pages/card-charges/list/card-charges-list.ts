    applyFilters():
        void
    {
        const keyword:
            string =
            this.searchText
                .trim()
                .toLowerCase();

        this.filteredCardCharges =
            this.cardCharges.filter
            (
                (
                    item:
                        CardCharges
                ):
                    boolean =>
                {
                    if
                    (
                        this.selectedStatus !== null
                        &&
                        item.Status !==
                        this.selectedStatus
                    )
                    {
                        return false;
                    }

                    if
                    (
                        !keyword
                    )
                    {
                        return true;
                    }

                    const values:
                        unknown[] =
                    [
                        item.POSAccountCode,
                        item.POSAccountName,
                        item.CardNames,
                        item.CardCount,
                        item.Status ? 'active' : 'inactive',
                        ...item.Details.map
                        (
                            line =>
                                `${line.CardCode} ${line.CardName} ${line.ChargePercent}`
                        )
                    ];

                    return values.some
                    (
                        value =>
                            String(value ?? '')
                                .toLowerCase()
                                .includes(keyword)
                    );
                }
            );

        this.currentPage =
            1;

        this.updatePagination();

        this.cdr.detectChanges();
    }

