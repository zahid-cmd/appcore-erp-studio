    //===========================================================

    ServicePolicyId:
        number;

    PolicyCode:
        string;

    BrandManagementId:
        number;

    BrandName:
        string;

    SequenceNo:
        number;

    // Free / Paid
    ServiceType:
        string;

    ServiceTypeNo:
        number;

    // "1st Free Service"
    PositionName:
        string;

    // "1st Free Service - Revoo"
    ServiceName:
        string;

    IntervalDays:
        number;

    IntervalKm:
        number;

    GraceDays:
        number;

    InPolicy:
        boolean;

    //===========================================================
    // Configuration
    //===========================================================

    IsConfigured:
        boolean;

    ServiceSubCategoryId:
        number | null;

    SubCategoryCode:
        string;

    SubCategoryName:
        string;

