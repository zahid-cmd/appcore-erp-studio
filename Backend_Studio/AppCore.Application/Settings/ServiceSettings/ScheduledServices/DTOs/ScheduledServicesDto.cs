//===============================================================
// Namespace
//===============================================================

namespace AppCore.Application.Settings.ServiceSettings;


//===============================================================
// Scheduled Service DTO
//===============================================================

public class ScheduledServicesDto
{
    //===========================================================
    // Primary Key
    //===========================================================

    public long ScheduledServiceId
    {
        get;
        set;
    }


    //===========================================================
    // Service Policy position (copied from the policy; kept in sync)
    //===========================================================

    // Generated by Service Policy : one row per schedule position,
    // matched by (ServicePolicyId, SequenceNo)
    public long ServicePolicyId
    {
        get;
        set;
    }


    public long BrandManagementId
    {
        get;
        set;
    }


    public int SequenceNo
    {
        get;
        set;
    }


    // Free / Paid
    public string ServiceType
    {
        get;
        set;
    } = string.Empty;


    // 1 for the 1st Free (or Paid) service, 2 for the 2nd ...
    public int ServiceTypeNo
    {
        get;
        set;
    }


    // The policy's name for the position, e.g. "1st Free Service"
    public string PositionName
    {
        get;
        set;
    } = string.Empty;


    // "<Position Name> - <Brand>", e.g. "1st Free Service - Revoo"
    public string ServiceName
    {
        get;
        set;
    } = string.Empty;


    // Due after the previous service (row 1 : after the sale date)
    public int IntervalDays
    {
        get;
        set;
    }


    // Reference only
    public int IntervalKm
    {
        get;
        set;
    }


    public int GraceDays
    {
        get;
        set;
    }


    // False once the position is removed from the policy (or the
    // policy is deleted) : kept, inactive, never invoiced
    public bool InPolicy
    {
        get;
        set;
    } = true;


    //===========================================================
    // Policy / Brand (display)
    //===========================================================

    public string PolicyCode
    {
        get;
        set;
    } = string.Empty;


    public string BrandName
    {
        get;
        set;
    } = string.Empty;


    //===========================================================
    // Configuration (set on the Scheduled Services page)
    //===========================================================

    // Price saved : the service is Ready (invoiceable while active)
    public bool IsConfigured
    {
        get;
        set;
    } = false;


    // The brand's Scheduled Services sub category (set on the first save)
    public long? ServiceSubCategoryId
    {
        get;
        set;
    }


    // <Sub Category Code>-nnnnn, assigned on the first save
    public string ServiceCode
    {
        get;
        set;
    } = string.Empty;


    // Paid services only
    public decimal CustomerCharge
    {
        get;
        set;
    }


    // Free services only (claimed from the brand)
    public decimal BrandReimbursement
    {
        get;
        set;
    }


    //===========================================================
    // Income Ledger (General Ledger under the sub category's sub group)
    //===========================================================

    // GLR-ccc-ggg-sss-nnnnn, created on the first save
    public string IncomeLedgerCode
    {
        get;
        set;
    } = string.Empty;


    // Always equal to the Service Name
    public string IncomeLedgerName
    {
        get;
        set;
    } = string.Empty;


    public string Remarks
    {
        get;
        set;
    } = string.Empty;


    //===========================================================
    // Status
    //===========================================================

    public bool IsActive
    {
        get;
        set;
    } = true;


    //===========================================================
    // Readiness (Pending / Ready / Not in Policy)
    //===========================================================

    public string Readiness
    {
        get;
        set;
    } = string.Empty;


    // Ready, in policy and active
    public bool IsInvoiceable
    {
        get;
        set;
    }


    //===========================================================
    // Sub Category (display; for a Pending row : the one it will use)
    //===========================================================

    public string SubCategoryCode
    {
        get;
        set;
    } = string.Empty;


    public string SubCategoryName
    {
        get;
        set;
    } = string.Empty;


    // Why the row cannot be configured yet (empty when it can)
    public string SubCategoryMessage
    {
        get;
        set;
    } = string.Empty;


    //===========================================================
    // Preview of the codes the first save will assign
    //===========================================================

    public string NextServiceCode
    {
        get;
        set;
    } = string.Empty;


    public string NextIncomeLedgerCode
    {
        get;
        set;
    } = string.Empty;


    //===========================================================
    // Soft Delete
    //===========================================================

    public bool IsDeleted
    {
        get;
        set;
    } = false;


    public long? DeletedBy
    {
        get;
        set;
    }


    public DateTime? DeletedDate
    {
        get;
        set;
    }


    //===========================================================
    // Audit Information
    //===========================================================

    public long CreatedBy
    {
        get;
        set;
    }


    public DateTime CreatedDate
    {
        get;
        set;
    }


    public long? ModifiedBy
    {
        get;
        set;
    }


    public DateTime? ModifiedDate
    {
        get;
        set;
    }
}