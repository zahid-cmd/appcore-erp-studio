namespace AppCore.Application.Settings.GeneralSettings;


//===============================================================
// Locations Repository Interface
//===============================================================

public interface ILocationsRepository
{
    //===========================================================
    // Get All
    //===========================================================

    Task<List<LocationsDto>> GetAllAsync();


    //===========================================================
    // Get By Id
    //===========================================================

    Task<LocationsDto?> GetByIdAsync(
        long id);


    //===========================================================
    // Create
    //===========================================================

    Task<long> CreateAsync(
        CreateLocationsDto dto,
        long userId);


    //===========================================================
    // Update
    //===========================================================

    Task UpdateAsync(
        UpdateLocationsDto dto,
        long userId);


    //===========================================================
    // Delete
    //===========================================================

    Task DeleteAsync(
        long id,
        long userId);


    //===========================================================
    // Restore
    //===========================================================

    Task<bool> RestoreAsync(
        long userId);


    //===========================================================
    // Exists
    //===========================================================

    Task<bool> ExistsAsync(
        long id);


    //===========================================================
    // Get Defaults
    // (next code + divisions with their districts)
    //===========================================================

    Task<LocationsDefaultsDto> GetDefaultsAsync();
}