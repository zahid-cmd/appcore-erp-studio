using Microsoft.AspNetCore.Mvc;

using AppCore.Application.Common.ActivityHistory.DTOs;
using AppCore.Application.Common.ActivityHistory.Interfaces;

using AppCore.Application.Settings.ServiceSettings;


//===============================================================
// Namespace
//===============================================================

namespace AppCore.API.Controllers.Settings.ServiceSettings;


//===============================================================
// Scheduled Service Controller
//
// Rows are generated by Service Policy; this API only prices
// them (PUT). No POST / DELETE / restore.
//===============================================================

[ApiController]

[Route("api/settings/service-settings/scheduled-services")]

public class ScheduledServicesController : ControllerBase
{
    //===========================================================
    // Fields
    //===========================================================

    private readonly IScheduledServicesRepository _repository;

    private readonly IActivityHistoryRepository _activityHistoryRepository;


    //===========================================================
    // Constructor
    //===========================================================

    public ScheduledServicesController(
        IScheduledServicesRepository repository,
        IActivityHistoryRepository activityHistoryRepository)
    {
        _repository = repository;

        _activityHistoryRepository = activityHistoryRepository;
    }


    //===========================================================
    // Get All
    //===========================================================

    [HttpGet]

    public async Task<ActionResult<List<ScheduledServicesDto>>> GetAll()
    {
        try
        {
            return Ok(
                await _repository.GetAllAsync());
        }
        catch
        (
            Exception ex
        )
        {
            // Shows the real cause (e.g. table not rebuilt yet)
            return StatusCode(
                500,
                ex.GetBaseException().Message);
        }
    }


    //===========================================================
    // Get By Id
    //===========================================================

    [HttpGet("{id:long}")]

    public async Task<ActionResult<ScheduledServicesDto>> GetById(
        long id)
    {
        ScheduledServicesDto? scheduledService =
            await _repository.GetByIdAsync(id);

        if (scheduledService == null)
        {
            return NotFound();
        }

        return Ok(scheduledService);
    }


    //===========================================================
    // Configure (price)
    //===========================================================

    [HttpPut]

    public async Task<IActionResult> Configure(
        ConfigureScheduledServicesDto dto)
    {
           long userId = this.CurrentUserId();

        try
        {
            await _repository.ConfigureAsync(
                dto,
                userId);
        }
        catch
        (
            KeyNotFoundException ex
        )
        {
            return NotFound(ex.Message);
        }
        catch
        (
            InvalidOperationException ex
        )
        {
            return BadRequest(ex.Message);
        }

        return NoContent();
    }


    //===========================================================
    // Get History
    //===========================================================

    [HttpGet("history")]

    public async Task<ActionResult<List<ActivityHistoryDto>>> GetHistory()
    {
        return Ok(
            await _activityHistoryRepository.GetListHistoryAsync(
                "Service Settings",
                "Scheduled Service"));
    }
}