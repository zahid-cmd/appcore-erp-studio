-- Human Resource Management, phase 2 : attendance and leave
-- (hand-written pages : NEVER run Submenu / Code Sync for them)
-- Run HumanResource_Phase1_Engine.sql first.
--
--   Attendance Management (new menu)
--     Daily Attendance    /human-resource-manangement/attendance-management/daily-attendance
--     Leave Applications  /human-resource-manangement/attendance-management/leave-applications
--     Monthly Attendance  /human-resource-manangement/attendance-management/monthly-attendance
--
--   HrAttendance          one row per employee per day
--                         P Present, L Late, H Half Day, A Absent,
--                         LV Leave, WO Weekly Off, HD Holiday
--   HrLeaveApplications   LVA-0001  Pending / Approved / Rejected /
--                         Cancelled. Approving writes the leave
--                         days into HrAttendance; cancelling takes
--                         them out again.
--
-- Safe to run again (tables / indexes / menu / submenus are skipped
-- when they exist). Run the whole script (F5) on AppCoreERP_Studio.
--
-- AFTER : Security & Permission > Activity Assignment : tick View /
-- Add / Update / Delete / Restore (and Approve on Leave
-- Applications) on the three pages for the roles, then log in again.
-- ASCII only.
-- =====================================================================

-- ------------------------------------------------------------
-- 1. Tables
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."HrLeaveApplications"
(
    "LeaveApplicationId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"           uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"               character varying(20)    NOT NULL,
    "EmployeeId"         bigint                   NOT NULL,
    "LeaveTypeId"        bigint                   NOT NULL,
    "FromDate"           date                     NOT NULL,
    "ToDate"             date                     NOT NULL,
    -- Working days in the range (weekly off days and holidays
    -- are not leave)
    "Days"               numeric(6,2)             NOT NULL DEFAULT 0,
    "Reason"             character varying(500)   NOT NULL DEFAULT '',
    -- Pending / Approved / Rejected / Cancelled
    "Status"             character varying(10)    NOT NULL DEFAULT 'Pending',
    "DecidedBy"          bigint                   NULL,
    "DecidedDate"        timestamp with time zone NULL,
    "DecisionNote"       character varying(500)   NOT NULL DEFAULT '',
    "IsDeleted"          boolean                  NOT NULL DEFAULT false,
    "DeletedBy"          bigint                   NULL,
    "DeletedDate"        timestamp with time zone NULL,
    "CreatedBy"          bigint                   NOT NULL,
    "CreatedDate"        timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"         bigint                   NULL,
    "ModifiedDate"       timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrLeaveApplications_PublicId" ON public."HrLeaveApplications" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrLeaveApplications_Code"     ON public."HrLeaveApplications" ("Code");
CREATE INDEX        IF NOT EXISTS "IX_HrLeaveApplications_Employee" ON public."HrLeaveApplications" ("EmployeeId", "FromDate");


CREATE TABLE IF NOT EXISTS public."HrAttendance"
(
    "AttendanceId"       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "EmployeeId"         bigint                   NOT NULL,
    "AttendanceDate"     date                     NOT NULL,
    -- P / L / H / A / LV / WO / HD
    "Status"             character varying(2)     NOT NULL,
    -- HH:mm (24 hours); '' = not noted
    "InTime"             character varying(5)     NOT NULL DEFAULT '',
    "OutTime"            character varying(5)     NOT NULL DEFAULT '',
    "LateMinutes"        integer                  NOT NULL DEFAULT 0,
    "OvertimeHours"      numeric(5,2)             NOT NULL DEFAULT 0,
    -- LV : the leave type; the application that wrote the row
    -- (NULL = marked on Daily Attendance)
    "LeaveTypeId"        bigint                   NULL,
    "LeaveApplicationId" bigint                   NULL,
    "Remarks"            character varying(200)   NOT NULL DEFAULT '',
    "CreatedBy"          bigint                   NOT NULL,
    "CreatedDate"        timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"         bigint                   NULL,
    "ModifiedDate"       timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrAttendance_EmployeeDate" ON public."HrAttendance" ("EmployeeId", "AttendanceDate");
CREATE INDEX        IF NOT EXISTS "IX_HrAttendance_Date"         ON public."HrAttendance" ("AttendanceDate");
CREATE INDEX        IF NOT EXISTS "IX_HrAttendance_Application"  ON public."HrAttendance" ("LeaveApplicationId");


-- ------------------------------------------------------------
-- 2. Menu Attendance Management + the three pages
-- ------------------------------------------------------------

DO $$
DECLARE
    v_module   record;
    v_menu     record;
    v_seq      int;
    v_code     text;
    s          record;
BEGIN
    SELECT "Id", "SequenceNo", "RouteKey", "Code", "Name" INTO v_module
    FROM   "NavigationModules"
    WHERE  lower(trim("RouteKey")) = 'human-resource-manangement'
    AND    "IsDeleted" = false
    LIMIT  1;

    IF v_module."Id" IS NULL THEN
        RAISE EXCEPTION 'Module with route key human-resource-manangement not found - no menu or page was added.';
    END IF;

    -- ---------- Menu ----------
    IF NOT EXISTS (SELECT 1 FROM "NavigationMenus"
                   WHERE "NavigationModuleId" = v_module."Id"
                   AND   lower(trim("RouteKey")) = 'attendance-management'
                   AND   "IsDeleted" = false) THEN

        SELECT COALESCE(MAX("SequenceNo"), 0) + 1 INTO v_seq
        FROM   "NavigationMenus"
        WHERE  "NavigationModuleId" = v_module."Id";

        INSERT INTO "NavigationMenus"
            ("NavigationModuleId", "SequenceNo", "Code", "Name", "Icon",
             "RouteKey", "Route", "DisplayOrder", "Remarks",
             "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
        VALUES
            (v_module."Id", v_seq,
             'MNU-' || lpad(v_module."SequenceNo"::text, 3, '0') || '-' || lpad(v_seq::text, 3, '0'),
             'Attendance Management', 'fa-solid fa-calendar-check',
             'attendance-management', '/' || v_module."RouteKey" || '/attendance-management',
             v_seq, NULL,
             true, false, 1, now());

        RAISE NOTICE 'Menu created : Attendance Management';
    ELSE
        RAISE NOTICE 'Menu exists, skipped : Attendance Management';
    END IF;

    SELECT "Id", "SequenceNo", "RouteKey" INTO v_menu
    FROM   "NavigationMenus"
    WHERE  "NavigationModuleId" = v_module."Id"
    AND    lower(trim("RouteKey")) = 'attendance-management'
    AND    "IsDeleted" = false
    LIMIT  1;

    -- ---------- Pages ----------
    FOR s IN
        SELECT * FROM (VALUES
            (1, 'Daily Attendance',   'fa-solid fa-user-check',     'daily-attendance',   'One day of a branch on one screen : present, late, absent, leave.'),
            (2, 'Leave Applications', 'fa-solid fa-plane-departure', 'leave-applications', 'Leave applications with approval and the leave balance.'),
            (3, 'Monthly Attendance', 'fa-solid fa-table-cells',    'monthly-attendance', 'The month of a branch : every employee, every day, with totals.')
        ) AS x (ord, name, icon, route_key, remarks)
        ORDER BY ord
    LOOP
        IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
                   WHERE "NavigationMenuId" = v_menu."Id"
                   AND   lower(trim("RouteKey")) = s.route_key
                   AND   "IsDeleted" = false) THEN
            RAISE NOTICE 'Page exists, skipped : %', s.name;
            CONTINUE;
        END IF;

        IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
                   WHERE lower(trim("Name")) = lower(s.name) AND "IsDeleted" = false) THEN
            RAISE EXCEPTION 'A submenu named "%" already exists elsewhere : names must be unique. Tell Claude.', s.name;
        END IF;

        SELECT COALESCE(MAX("SequenceNo"), 0) + 1 INTO v_seq
        FROM   "NavigationSubmenus"
        WHERE  "NavigationMenuId" = v_menu."Id";

        v_code :=
            'SUB-' || lpad(v_module."SequenceNo"::text, 3, '0')
                   || '-' || lpad(v_menu."SequenceNo"::text, 3, '0')
                   || '-' || lpad(v_seq::text, 3, '0');

        INSERT INTO "NavigationSubmenus"
            ("NavigationMenuId", "SequenceNo", "Code", "Name", "Icon",
             "RouteKey", "Route", "DisplayOrder", "Remarks",
             "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
        VALUES
            (v_menu."Id", v_seq, v_code, s.name, s.icon,
             s.route_key,
             '/' || v_module."RouteKey" || '/' || v_menu."RouteKey" || '/' || s.route_key,
             v_seq, s.remarks || ' Hand-written page : never run Submenu / Code Sync.',
             true, false, 1, now());

        RAISE NOTICE 'Page created : % %', v_code, s.name;
    END LOOP;
END $$;


-- ------------------------------------------------------------
-- 3. Page activity "Approve" on Leave Applications
--    (only when Approve is a page activity : a common activity
--    is on every page already)
-- ------------------------------------------------------------

INSERT INTO "MasterActivityPages" ("MasterActivityCode", "NavigationSubmenuCode", "CreatedBy")
SELECT a."Code", s."Code", 1
FROM   "MasterActivities" a
JOIN   "NavigationSubmenus" s
       ON s."IsDeleted" = false
      AND lower(s."Route") = '/human-resource-manangement/attendance-management/leave-applications'
WHERE  a."IsDeleted" = false
AND    a."ActivityScope" = 'Page'
AND    lower(trim(a."Name")) = 'approve'
AND    NOT EXISTS
(
    SELECT 1 FROM "MasterActivityPages" p
    WHERE  p."MasterActivityCode" = a."Code"
    AND    p."NavigationSubmenuCode" = s."Code"
);


