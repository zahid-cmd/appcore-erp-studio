-- ==============================================================
-- Bike Accessory Schemes : tables
--
--   BikeAccessorySchemes       the scheme (kind, source, brand,
--                              validity)
--   BikeAccessorySchemeModels  the bike models it covers
--   BikeAccessorySchemeItems   the accessories given per bike
--
-- 1. Drops the Code Sync baseline table "BikeAccessorySchemes"
--    (the one with an "Id" column) only when it is empty.
-- 2. Creates the three tables (safe to run again).
--
-- Needs PostgreSQL 18 (uuidv7). ASCII only.
-- ==============================================================

BEGIN;

-- --------------------------------------------------------------
-- 1. Baseline table from Code Sync
-- --------------------------------------------------------------

DO $$
DECLARE
    v_rows bigint;
BEGIN
    IF EXISTS
    (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'BikeAccessorySchemes'
          AND column_name = 'Id'
    )
    THEN
        EXECUTE 'SELECT count(*) FROM "BikeAccessorySchemes"' INTO v_rows;

        IF v_rows = 0 THEN
            DROP TABLE "BikeAccessorySchemes";
            RAISE NOTICE 'Baseline table BikeAccessorySchemes dropped.';
        ELSE
            RAISE EXCEPTION 'Baseline table BikeAccessorySchemes has % row(s). Clear it first, then run this script again.', v_rows;
        END IF;
    END IF;
END $$;


-- --------------------------------------------------------------
-- 2. Schemes
-- --------------------------------------------------------------

CREATE TABLE IF NOT EXISTS "BikeAccessorySchemes"
(
    "BikeAccessorySchemeId"  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"               uuid          NOT NULL DEFAULT uuidv7(),
    "SchemeCode"             varchar(30)   NOT NULL,
    "SchemeName"             varchar(150)  NOT NULL,
    "SchemeKind"             varchar(20)   NOT NULL DEFAULT 'Additional',
    "SchemeSource"           varchar(20)   NOT NULL DEFAULT 'Supplier',
    "BrandManagementId"      bigint        NOT NULL,
    "ValidFrom"              date          NOT NULL,
    "ValidTo"                date          NULL,
    "Remarks"                varchar(1000) NOT NULL DEFAULT '',
    "Status"                 boolean       NOT NULL DEFAULT true,
    "IsDeleted"              boolean       NOT NULL DEFAULT false,
    "DeletedBy"              bigint        NULL,
    "DeletedDate"            timestamp with time zone NULL,
    "CreatedBy"              bigint        NOT NULL DEFAULT 0,
    "CreatedDate"            timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"             bigint        NULL,
    "ModifiedDate"           timestamp with time zone NULL,

    CONSTRAINT "CK_BikeAccessorySchemes_Kind"
        CHECK ("SchemeKind" IN ('Additional', 'Promotional')),

    CONSTRAINT "CK_BikeAccessorySchemes_Source"
        CHECK ("SchemeSource" IN ('Supplier', 'Company')),

    CONSTRAINT "CK_BikeAccessorySchemes_Dates"
        CHECK ("ValidTo" IS NULL OR "ValidTo" >= "ValidFrom")
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_BikeAccessorySchemes_PublicId"
    ON "BikeAccessorySchemes" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_BikeAccessorySchemes_SchemeCode"
    ON "BikeAccessorySchemes" ("SchemeCode");

CREATE INDEX IF NOT EXISTS "IX_BikeAccessorySchemes_Brand"
    ON "BikeAccessorySchemes" ("BrandManagementId");


-- --------------------------------------------------------------
-- 3. Models covered
-- --------------------------------------------------------------

CREATE TABLE IF NOT EXISTS "BikeAccessorySchemeModels"
(
    "BikeAccessorySchemeModelId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BikeAccessorySchemeId"      bigint NOT NULL
        REFERENCES "BikeAccessorySchemes" ("BikeAccessorySchemeId") ON DELETE CASCADE,
    "BikeModelId"                bigint NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_BikeAccessorySchemeModels_Scheme_Model"
    ON "BikeAccessorySchemeModels" ("BikeAccessorySchemeId", "BikeModelId");

CREATE INDEX IF NOT EXISTS "IX_BikeAccessorySchemeModels_Model"
    ON "BikeAccessorySchemeModels" ("BikeModelId");


-- --------------------------------------------------------------
-- 4. Accessories per bike
-- --------------------------------------------------------------

CREATE TABLE IF NOT EXISTS "BikeAccessorySchemeItems"
(
    "BikeAccessorySchemeItemId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BikeAccessorySchemeId"     bigint  NOT NULL
        REFERENCES "BikeAccessorySchemes" ("BikeAccessorySchemeId") ON DELETE CASCADE,
    "LineNo"                    integer NOT NULL DEFAULT 1,
    "AccessoryId"               bigint  NOT NULL,
    "QuantityPerBike"           integer NOT NULL DEFAULT 1,

    CONSTRAINT "CK_BikeAccessorySchemeItems_Qty"
        CHECK ("QuantityPerBike" BETWEEN 1 AND 99)
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_BikeAccessorySchemeItems_Scheme_Accessory"
    ON "BikeAccessorySchemeItems" ("BikeAccessorySchemeId", "AccessoryId");

CREATE INDEX IF NOT EXISTS "IX_BikeAccessorySchemeItems_Accessory"
    ON "BikeAccessorySchemeItems" ("AccessoryId");

COMMIT;


-- Check
SELECT table_name, count(*) AS columns
FROM information_schema.columns
WHERE table_schema = current_schema()
  AND table_name IN ('BikeAccessorySchemes', 'BikeAccessorySchemeModels', 'BikeAccessorySchemeItems')
GROUP BY table_name
ORDER BY table_name;
