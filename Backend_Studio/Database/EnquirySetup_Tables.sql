-- ------------------------------------------------------------
-- 1. Table
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."EnquirySetups"
(
    "EnquirySetupId"  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "SetupType"       character varying(30)  NOT NULL,
    "Code"            character varying(20)  NOT NULL,
    "Name"            character varying(100) NOT NULL,
    "ColorCode"       character varying(20)  NOT NULL DEFAULT '',
    "Stage"           character varying(10)  NOT NULL DEFAULT '',
    "DisplayOrder"    integer                NOT NULL DEFAULT 0,
    "IsDefault"       boolean                NOT NULL DEFAULT false,
    "IsSystem"        boolean                NOT NULL DEFAULT false,
    "Remarks"         character varying(500) NOT NULL DEFAULT '',
    "IsActive"        boolean                NOT NULL DEFAULT true,

    "IsDeleted"       boolean                NOT NULL DEFAULT false,
    "DeletedBy"       bigint                 NULL,
    "DeletedDate"     timestamp with time zone NULL,
    "CreatedBy"       bigint                 NOT NULL,
    "CreatedDate"     timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"      bigint                 NULL,
    "ModifiedDate"    timestamp with time zone NULL,

    CONSTRAINT "CK_EnquirySetups_SetupType"
        CHECK ("SetupType" IN ('Source', 'Status', 'InterestLevel', 'FollowUpMethod', 'LostReason')),

    CONSTRAINT "CK_EnquirySetups_Stage"
        CHECK ("Stage" IN ('', 'Open', 'Won', 'Lost'))
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_EnquirySetups_Code"
    ON public."EnquirySetups" ("Code");

CREATE INDEX IF NOT EXISTS "IX_EnquirySetups_Type_Order"
    ON public."EnquirySetups" ("SetupType", "DisplayOrder");


