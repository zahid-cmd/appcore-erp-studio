CREATE TABLE IF NOT EXISTS public."HrShifts"
(
    "ShiftId"       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"      uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"          character varying(20)    NOT NULL,
    "Name"          character varying(100)   NOT NULL,
    -- HH:mm (24 hours); an end before the start = a night shift
    "StartTime"     character varying(5)     NOT NULL,
    "EndTime"       character varying(5)     NOT NULL,
    "GraceMinutes"  integer                  NOT NULL DEFAULT 0,
    "BreakMinutes"  integer                  NOT NULL DEFAULT 0,
    -- (the weekly off days moved to HrWeeklyHolidays / HrEmployees :
    --  HumanResource_WeeklyHoliday_Engine.sql)
    "Remarks"       character varying(500)   NOT NULL DEFAULT '',
    "IsActive"      boolean                  NOT NULL DEFAULT true,
    "IsDeleted"     boolean                  NOT NULL DEFAULT false,
    "DeletedBy"     bigint                   NULL,
    "DeletedDate"   timestamp with time zone NULL,
    "CreatedBy"     bigint                   NOT NULL,
    "CreatedDate"   timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"    bigint                   NULL,
    "ModifiedDate"  timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrShifts_PublicId" ON public."HrShifts" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrShifts_Code"     ON public."HrShifts" ("Code");


