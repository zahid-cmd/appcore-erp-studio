CREATE TABLE IF NOT EXISTS public."HrSalaryHeads"
(
    "SalaryHeadId"  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"      uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"          character varying(20)    NOT NULL,
    "Name"          character varying(100)   NOT NULL,
    -- Earning / Deduction
    "HeadType"      character varying(10)    NOT NULL,
    -- Fixed (Tk) / Percent (% of Basic)
    "CalcType"      character varying(10)    NOT NULL DEFAULT 'Fixed',
    "DefaultValue"  numeric(18,2)            NOT NULL DEFAULT 0,
    -- '' = a normal head (on the employee's salary structure).
    -- BASIC = the basic salary (on the structure).
