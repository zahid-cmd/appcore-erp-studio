-- Human Resource Management, phase 1 : setup + employees
-- (hand-written pages : NEVER run Submenu / Code Sync for them)
--
--   Human Resource Setup (existing menu)
--     Shifts         /human-resource-manangement/human-resource-setup/shifts
--     Holidays       /human-resource-manangement/human-resource-setup/holidays
--     Leave Types    /human-resource-manangement/human-resource-setup/leave-types
--     Salary Heads   /human-resource-manangement/human-resource-setup/salary-heads
--   Employee Management (new menu)
--     Employee Profiles
--                    /human-resource-manangement/employee-management/employees
--
--   HrShifts                SFT-001  working hours, grace, weekly off days
--   HrHolidays              HOL-0001 a holiday (one day or a range)
--   HrLeaveTypes            LVT-001  days per year, paid / unpaid
--   HrSalaryHeads           SLH-001  earnings and deductions
--   HrEmployees             EMP-0001 the staff record
--   HrEmployeeSalaryLines            an employee's salary structure
--
-- Starter rows (only when the table is empty) : one shift, five
-- leave types, the salary heads. Change them on the pages.
--
-- Safe to run again (tables / indexes / menu / submenus / starter
-- rows are skipped when they exist). Run the whole script (F5) on
-- AppCoreERP_Studio.
--
-- AFTER : Security & Permission > Activity Assignment : tick View /
-- Add / Update / Delete / Restore on the five pages for the roles,
-- then log in again.
-- ASCII only.
-- =====================================================================

