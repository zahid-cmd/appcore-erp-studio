-- ------------------------------------------------------------
-- 3. Menu Employee Management + the five pages
-- ------------------------------------------------------------

DO $$
DECLARE
    v_module   record;
    v_menu     record;
    v_seq      int;
    v_code     text;
    s          record;
BEGIN
    SELECT "Id", "SequenceNo", "RouteKey", "Code", "Name" INTO v_module
    FROM   "NavigationModules"
    WHERE  lower(trim("RouteKey")) = 'human-resource-manangement'
    AND    "IsDeleted" = false
    LIMIT  1;

    IF v_module."Id" IS NULL THEN
        RAISE EXCEPTION 'Module with route key human-resource-manangement not found - no menu or page was added.';
    END IF;

    RAISE NOTICE 'Module % % (route key %)', v_module."Code", v_module."Name", v_module."RouteKey";

    -- ---------- Menu : Employee Management ----------
    IF NOT EXISTS (SELECT 1 FROM "NavigationMenus"
                   WHERE "NavigationModuleId" = v_module."Id"
                   AND   lower(trim("RouteKey")) = 'employee-management'
                   AND   "IsDeleted" = false) THEN

        SELECT COALESCE(MAX("SequenceNo"), 0) + 1 INTO v_seq
        FROM   "NavigationMenus"
        WHERE  "NavigationModuleId" = v_module."Id";

        INSERT INTO "NavigationMenus"
            ("NavigationModuleId", "SequenceNo", "Code", "Name", "Icon",
             "RouteKey", "Route", "DisplayOrder", "Remarks",
             "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
        VALUES
            (v_module."Id", v_seq,
             'MNU-' || lpad(v_module."SequenceNo"::text, 3, '0') || '-' || lpad(v_seq::text, 3, '0'),
             'Employee Management', 'fa-solid fa-id-card-clip',
             'employee-management', '/' || v_module."RouteKey" || '/employee-management',
             v_seq, NULL,
             true, false, 1, now());

        RAISE NOTICE 'Menu created : Employee Management';
    ELSE
        RAISE NOTICE 'Menu exists, skipped : Employee Management';
    END IF;

    -- ---------- Pages ----------
    FOR s IN
        SELECT * FROM (VALUES
            (1, 'human-resource-setup', 'Shifts',       'fa-solid fa-business-time',        'shifts',       'Working hours, grace time and weekly off days.'),
            (2, 'human-resource-setup', 'Holidays',     'fa-solid fa-umbrella-beach',       'holidays',     'Public, festival and company holidays.'),
            (3, 'human-resource-setup', 'Leave Types',  'fa-solid fa-plane-departure',      'leave-types',  'Leave types : days per year, paid or unpaid.'),
            (4, 'human-resource-setup', 'Salary Heads', 'fa-solid fa-money-bill-wave',      'salary-heads', 'Earnings and deductions of the salary structure.'),
            (5, 'employee-management',  'Employee Profiles', 'fa-solid fa-users',           'employees',    'Staff records : personal, job and salary structure.')
        ) AS x (ord, menu_key, name, icon, route_key, remarks)
        ORDER BY ord
    LOOP
        SELECT "Id", "SequenceNo", "RouteKey" INTO v_menu
        FROM   "NavigationMenus"
        WHERE  "NavigationModuleId" = v_module."Id"
        AND    lower(trim("RouteKey")) = s.menu_key
        AND    "IsDeleted" = false
        LIMIT  1;

        IF v_menu."Id" IS NULL THEN
            RAISE EXCEPTION 'Menu % not found under % - page % was not added.', s.menu_key, v_module."Name", s.name;
        END IF;

        IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
                   WHERE "NavigationMenuId" = v_menu."Id"
                   AND   lower(trim("RouteKey")) = s.route_key
                   AND   "IsDeleted" = false) THEN
            RAISE NOTICE 'Page exists, skipped : %', s.name;
            CONTINUE;
        END IF;

        IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
                   WHERE lower(trim("Name")) = lower(s.name) AND "IsDeleted" = false) THEN
            RAISE EXCEPTION 'A submenu named "%" already exists elsewhere : names must be unique. Tell Claude.', s.name;
        END IF;

        SELECT COALESCE(MAX("SequenceNo"), 0) + 1 INTO v_seq
        FROM   "NavigationSubmenus"
        WHERE  "NavigationMenuId" = v_menu."Id";

        v_code :=
            'SUB-' || lpad(v_module."SequenceNo"::text, 3, '0')
                   || '-' || lpad(v_menu."SequenceNo"::text, 3, '0')
                   || '-' || lpad(v_seq::text, 3, '0');

        INSERT INTO "NavigationSubmenus"
            ("NavigationMenuId", "SequenceNo", "Code", "Name", "Icon",
             "RouteKey", "Route", "DisplayOrder", "Remarks",
             "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
        VALUES
            (v_menu."Id", v_seq, v_code, s.name, s.icon,
             s.route_key,
             '/' || v_module."RouteKey" || '/' || v_menu."RouteKey" || '/' || s.route_key,
             v_seq, s.remarks || ' Hand-written page : never run Submenu / Code Sync.',
             true, false, 1, now());

        RAISE NOTICE 'Page created : % %', v_code, s.name;
    END LOOP;
END $$;


