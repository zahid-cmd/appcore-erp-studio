-- ------------------------------------------------------------
-- 1. Tables
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public."TermsConditionSets"
(
    "TermsConditionSetId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"            uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"                character varying(20)    NOT NULL,
    "Title"               character varying(150)   NOT NULL,
    "OperationCode"       character varying(10)    NOT NULL,
    "IsDefault"           boolean                  NOT NULL DEFAULT false,
    "Note"                character varying(500)   NOT NULL DEFAULT '',
    "IsActive"            boolean                  NOT NULL DEFAULT true,
    "IsDeleted"           boolean                  NOT NULL DEFAULT false,
    "DeletedBy"           bigint                   NULL,
    "DeletedDate"         timestamp with time zone NULL,
    "CreatedBy"           bigint                   NOT NULL,
    "CreatedDate"         timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"          bigint                   NULL,
    "ModifiedDate"        timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_TermsConditionSets_PublicId"
    ON public."TermsConditionSets" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_TermsConditionSets_Code"
    ON public."TermsConditionSets" ("Code");

-- one Default per operation among live, active sets
CREATE UNIQUE INDEX IF NOT EXISTS "UX_TermsConditionSets_Default"
    ON public."TermsConditionSets" ("OperationCode")
    WHERE "IsDefault" AND "IsActive" AND NOT "IsDeleted";

CREATE INDEX IF NOT EXISTS "IX_TermsConditionSets_Operation"
    ON public."TermsConditionSets" ("OperationCode");

CREATE TABLE IF NOT EXISTS public."TermsConditionLines"
(
    "TermsConditionLineId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "TermsConditionSetId"  bigint                  NOT NULL
        REFERENCES public."TermsConditionSets" ("TermsConditionSetId") ON DELETE CASCADE,
    "LineNo"               integer                 NOT NULL,
    "TextEn"               character varying(1000) NOT NULL,
    "TextBn"               character varying(1000) NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS "IX_TermsConditionLines_Set"
    ON public."TermsConditionLines" ("TermsConditionSetId", "LineNo");

-- ------------------------------------------------------------
-- 2. Submenu Settings > General Settings > Terms & Conditions
-- ------------------------------------------------------------
DO $$
DECLARE
    v_module record;
    v_menu   record;
    v_seq    int;
BEGIN
    SELECT "Id", "SequenceNo", "RouteKey" INTO v_module
    FROM   "NavigationModules"
    WHERE  lower("RouteKey") = 'settings' AND "IsDeleted" = false;

    IF v_module."Id" IS NULL THEN
        RAISE EXCEPTION 'Module with route key settings not found - nothing changed.';
    END IF;

    SELECT "Id", "SequenceNo", "RouteKey" INTO v_menu
    FROM   "NavigationMenus"
    WHERE  "NavigationModuleId" = v_module."Id"
    AND    lower("RouteKey") = 'general-settings'
    AND    "IsDeleted" = false;

    IF v_menu."Id" IS NULL THEN
        RAISE EXCEPTION 'Menu general-settings not found under Settings - nothing changed.';
    END IF;

    IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
               WHERE "NavigationMenuId" = v_menu."Id"
               AND   lower("RouteKey") = 'terms-conditions'
               AND   "IsDeleted" = false) THEN
        RAISE NOTICE 'Submenu Terms & Conditions exists, skipped.';
    ELSE
        IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
                   WHERE lower("Name") = 'terms & conditions' AND "IsDeleted" = false) THEN
            RAISE EXCEPTION 'A submenu named "Terms & Conditions" already exists elsewhere : names must be unique.';
        END IF;

        SELECT COALESCE(MAX("SequenceNo"), 0) + 1 INTO v_seq
        FROM   "NavigationSubmenus"
        WHERE  "NavigationMenuId" = v_menu."Id";

        INSERT INTO "NavigationSubmenus"
            ("NavigationMenuId", "SequenceNo", "Code", "Name", "Icon",
             "RouteKey", "Route", "DisplayOrder", "Remarks",
             "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
        VALUES
            (v_menu."Id", v_seq,
             'SUB-' || lpad(v_module."SequenceNo"::text, 3, '0')
                    || '-' || lpad(v_menu."SequenceNo"::text, 3, '0')
                    || '-' || lpad(v_seq::text, 3, '0'),
             'Terms & Conditions', 'fa-solid fa-file-contract',
             'terms-conditions',
             '/' || v_module."RouteKey" || '/' || v_menu."RouteKey" || '/terms-conditions',
             v_seq, 'Hand-written page : never run Submenu / Code Sync.',
             true, false, 1, now());

        RAISE NOTICE 'Submenu created : Terms & Conditions';
    END IF;
END $$;

