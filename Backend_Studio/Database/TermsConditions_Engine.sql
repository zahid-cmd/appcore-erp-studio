--                                 operation (document type), one set
--                                 per operation may be the Default
--   TermsConditionLines           the numbered lines : English and
--                                 Bangla text (the database is UTF8)
--
-- Operations (fixed list in the code) : SIMB SISP SIAC (Sales
-- Invoice), SQMB SQSP SQAC (Sales Quotation), BKMB BKSP BKAC
-- (Booking), POMB POSP POAC (Purchase Order).
--
-- Safe to run again (tables / index / submenu are skipped when
-- they exist). Run the whole script (F5) on AppCoreERP_Studio.
