-- ------------------------------------------------------------
-- 2a. Stock Batches : one per purchase line (or opening line)
--     Cost is exact : value depletes, the last unit out takes
--     the remainder so a batch closes at 0.00
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."StockBatches"
(
    "StockBatchId"        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BatchNo"             character varying(40)  NOT NULL,
    "ProductType"         character varying(5)   NOT NULL,
    "ProductId"           bigint                 NOT NULL,
    "ProductCode"         character varying(40)  NOT NULL,
    "ProductName"         character varying(250) NOT NULL DEFAULT '',
    "InventoryLedgerCode" character varying(40)  NOT NULL,

    "SourceType"          character varying(20)  NOT NULL,
    "SourceId"            bigint                 NOT NULL,
    "SourceLineId"        bigint                 NOT NULL,
    "SourceNo"            character varying(30)  NOT NULL DEFAULT '',
    "SourceDate"          date                   NOT NULL,
    "SupplierCode"        character varying(30)  NOT NULL DEFAULT '',
    "BranchId"            bigint                 NOT NULL,

    "Quantity"            numeric(18,2)          NOT NULL,
    "UnitCost"            numeric(18,4)          NOT NULL,
    "TotalValue"          numeric(18,2)          NOT NULL,
    "QuantityInTransit"   numeric(18,2)          NOT NULL DEFAULT 0,
    "QuantityOnHand"      numeric(18,2)          NOT NULL DEFAULT 0,
    "QuantityOut"         numeric(18,2)          NOT NULL DEFAULT 0,
    "RemainingValue"      numeric(18,2)          NOT NULL,
    "Status"              character varying(20)  NOT NULL DEFAULT 'InTransit',

    "CreatedBy"           bigint                 NOT NULL,
    "CreatedDate"         timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"          bigint                 NULL,
    "ModifiedDate"        timestamp with time zone NULL,

    CONSTRAINT "CK_StockBatches_ProductType" CHECK ("ProductType" IN ('MB', 'SP', 'AC')),
    CONSTRAINT "CK_StockBatches_SourceType"  CHECK ("SourceType" IN ('Purchase', 'Opening')),
    CONSTRAINT "CK_StockBatches_Status"      CHECK ("Status" IN ('InTransit', 'OnHand', 'Closed', 'Cancelled')),
    CONSTRAINT "CK_StockBatches_Quantities"  CHECK ("Quantity" >= 0 AND "QuantityInTransit" >= 0 AND "QuantityOnHand" >= 0 AND "QuantityOut" >= 0 AND "RemainingValue" >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_StockBatches_BatchNo"
    ON public."StockBatches" ("BatchNo");

CREATE UNIQUE INDEX IF NOT EXISTS "IX_StockBatches_Source"
    ON public."StockBatches" ("SourceType", "ProductType", "SourceLineId");

-- FIFO pick : oldest open batch of an item first
CREATE INDEX IF NOT EXISTS "IX_StockBatches_Product"
    ON public."StockBatches" ("ProductType", "ProductId", "SourceDate", "StockBatchId")
    WHERE "Status" IN ('InTransit', 'OnHand');


-- ------------------------------------------------------------
-- 2b. Stock Movements : every quantity change of a batch
--     Bucket InTransit / OnHand; stock of a warehouse = sum of
--     its OnHand rows (QuantityIn - QuantityOut)
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."StockMovements"
(
    "StockMovementId"  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "StockBatchId"     bigint                 NOT NULL REFERENCES public."StockBatches" ("StockBatchId"),
    "ProductType"      character varying(5)   NOT NULL,
    "ProductId"        bigint                 NOT NULL,
    "BranchId"         bigint                 NOT NULL,
    "WarehouseId"      bigint                 NULL,
    "Bucket"           character varying(20)  NOT NULL,
    "MovementType"     character varying(30)  NOT NULL,
    "QuantityIn"       numeric(18,2)          NOT NULL DEFAULT 0,
    "QuantityOut"      numeric(18,2)          NOT NULL DEFAULT 0,
    "UnitCost"         numeric(18,4)          NOT NULL DEFAULT 0,
    "Value"            numeric(18,2)          NOT NULL DEFAULT 0,

    "DocumentType"     character varying(20)  NOT NULL,
    "DocumentId"       bigint                 NOT NULL,
    "DocumentLineId"   bigint                 NULL,
    "DocumentNo"       character varying(30)  NOT NULL DEFAULT '',
    "DocumentDate"     date                   NOT NULL,
    "IsReversal"       boolean                NOT NULL DEFAULT false,
    "Narration"        character varying(300) NOT NULL DEFAULT '',

    "CreatedBy"        bigint                 NOT NULL,
    "CreatedDate"      timestamp with time zone NOT NULL DEFAULT now(),

    CONSTRAINT "CK_StockMovements_Bucket"   CHECK ("Bucket" IN ('InTransit', 'OnHand')),
    CONSTRAINT "CK_StockMovements_Type"     CHECK ("MovementType" IN
        ('Purchase', 'Receive', 'ShortSupply', 'PurchaseReturn', 'PurchaseCancel',
         'Sale', 'SaleReturn', 'TransferOut', 'TransferIn', 'Adjustment', 'Opening')),
    CONSTRAINT "CK_StockMovements_Quantity" CHECK ("QuantityIn" >= 0 AND "QuantityOut" >= 0 AND ("QuantityIn" > 0 OR "QuantityOut" > 0))
);

CREATE INDEX IF NOT EXISTS "IX_StockMovements_Batch"
    ON public."StockMovements" ("StockBatchId");

CREATE INDEX IF NOT EXISTS "IX_StockMovements_Stock"
    ON public."StockMovements" ("ProductType", "ProductId", "BranchId", "WarehouseId", "Bucket");

CREATE INDEX IF NOT EXISTS "IX_StockMovements_Document"
    ON public."StockMovements" ("DocumentType", "DocumentId");


-- ------------------------------------------------------------
-- 2c. Stock Allocations : which batch an issue line took
--     (sale, purchase return, transfer ...) at what cost
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."StockAllocations"
(
    "StockAllocationId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "StockBatchId"      bigint                 NOT NULL REFERENCES public."StockBatches" ("StockBatchId"),
    "DocumentType"      character varying(20)  NOT NULL,
    "DocumentId"        bigint                 NOT NULL,
    "DocumentLineId"    bigint                 NOT NULL,
    "Quantity"          numeric(18,2)          NOT NULL,
    "UnitCost"          numeric(18,4)          NOT NULL,
    "Value"             numeric(18,2)          NOT NULL,
    "IsReversed"        boolean                NOT NULL DEFAULT false,
    "CreatedBy"         bigint                 NOT NULL,
    "CreatedDate"       timestamp with time zone NOT NULL DEFAULT now(),

    CONSTRAINT "CK_StockAllocations_Quantity" CHECK ("Quantity" > 0 AND "Value" >= 0)
);

CREATE INDEX IF NOT EXISTS "IX_StockAllocations_Line"
    ON public."StockAllocations" ("DocumentType", "DocumentLineId");

CREATE INDEX IF NOT EXISTS "IX_StockAllocations_Batch"
    ON public."StockAllocations" ("StockBatchId");


-- ------------------------------------------------------------
-- 2d. VAT Register : one row per document line with VAT
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."VatRegister"
(
    "VatRegisterId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Direction"       character varying(10)  NOT NULL,
    "DocumentType"    character varying(20)  NOT NULL,
    "DocumentId"      bigint                 NOT NULL,
    "DocumentLineId"  bigint                 NULL,
    "DocumentNo"      character varying(30)  NOT NULL DEFAULT '',
    "DocumentDate"    date                   NOT NULL,
    "MushakNo"        character varying(50)  NOT NULL DEFAULT '',
    "MushakDate"      date                   NULL,
    "PartyType"       character varying(20)  NOT NULL DEFAULT '',
    "PartyCode"       character varying(30)  NOT NULL DEFAULT '',
    "PartyName"       character varying(200) NOT NULL DEFAULT '',
    "PartyBin"        character varying(30)  NOT NULL DEFAULT '',
    "BranchId"        bigint                 NOT NULL,
    "ProductType"     character varying(5)   NOT NULL,
    "ProductId"       bigint                 NULL,
    "ProductCode"     character varying(40)  NOT NULL DEFAULT '',
    "ProductName"     character varying(250) NOT NULL DEFAULT '',
    "Quantity"        numeric(18,2)          NOT NULL DEFAULT 0,
    "TaxableValue"    numeric(18,2)          NOT NULL DEFAULT 0,
    "VatRate"         numeric(7,2)           NOT NULL DEFAULT 0,
    "VatAmount"       numeric(18,2)          NOT NULL DEFAULT 0,
    "VatClaimable"    numeric(18,2)          NOT NULL DEFAULT 0,
    "VatLedgerCode"   character varying(30)  NOT NULL DEFAULT '',
    "IsReversal"      boolean                NOT NULL DEFAULT false,
    "CreatedBy"       bigint                 NOT NULL,
    "CreatedDate"     timestamp with time zone NOT NULL DEFAULT now(),

    CONSTRAINT "CK_VatRegister_Direction"   CHECK ("Direction" IN ('Purchase', 'Sale')),
    CONSTRAINT "CK_VatRegister_ProductType" CHECK ("ProductType" IN ('MB', 'SP', 'AC', 'SV'))
);

CREATE INDEX IF NOT EXISTS "IX_VatRegister_Period"
    ON public."VatRegister" ("Direction", "DocumentDate", "BranchId");

CREATE INDEX IF NOT EXISTS "IX_VatRegister_Document"
    ON public."VatRegister" ("DocumentType", "DocumentId");


-- ------------------------------------------------------------
-- Check : the purposes and whether each ledger exists
-- ------------------------------------------------------------

SELECT p."DisplayOrder", p."PurposeCode", p."PurposeName", p."LedgerCode",
       COALESCE(g."LedgerName", CASE WHEN p."LedgerCode" = '' THEN '(not set)' ELSE '** NOT FOUND **' END) AS "Ledger"
FROM   public."PostingSetups" p
LEFT   JOIN public."GeneralLedgers" g
       ON g."LedgerCode" = p."LedgerCode" AND NOT g."IsDeleted"
ORDER  BY p."DisplayOrder";
