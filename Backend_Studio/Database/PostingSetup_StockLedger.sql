-- ============================================================
-- Posting Setup + Stock Ledger tables (Stage 1, 2026-10-30)
--
-- 1. PostingSetups / PostingSetupHistory
--    Page : Settings > Account Settings > Posting Setup
--           (SUB-003-002-015, /settings/account-settings/posting-setup)
--    One row per posting purpose (fixed list, made here).
--    The page only picks the ledger of each row.
--
--      VAT-MB         VAT - Motor Bikes                GLR-002-002-011-00001
--      VAT-SP         VAT - Spare Parts & Lubricants   GLR-002-002-011-00002
--      VAT-SV         VAT - Service Charges            GLR-002-002-011-00003
--      VAT-AC         VAT - Accessories                GLR-002-002-011-00004
--      INTER-BRANCH   Inter-Branch Current Account     GLR-002-002-010-00001
--      OPENING-STOCK  Opening Stock                    (not set)
--
--    Bank / MFS / POS / EMI charges (were written in the code
--    of the vouchers and reconciliations until 2026-10-30) :
--      BANK-CHARGES        Bank Charges                GLR-004-001-001-00001
--      MFS-CHARGES         MFS Charges                 GLR-004-001-001-00003
--      POS-CHARGES         POS Charges                 GLR-004-001-001-00004
--      EMI-CHARGES         EMI Charges                 GLR-004-001-001-00005
--      MFS-RECOVERY        MFS Charges Recovery        GLR-011-001-001-00001
--      POS-RECOVERY        POS Charges Recovery        GLR-011-001-001-00002
--      EMI-RECOVERY        EMI Charges Recovery        GLR-011-001-001-00003
--      DISHONOUR-RECOVERY  Cheque Dishonour Recovery   GLR-011-001-001-00004
--      MFS / POS / EMI-RESERVE  Recovery reserves      GLR-001-002-004-00001..3
--
-- 2. Stock ledger (exact batch costing, no average)
--      StockBatches      one batch per purchase line (cost lives here)
--      StockMovements    every in / out, bucket In transit / On hand,
--                        per branch and warehouse
--      StockAllocations  issue line -> batch -> qty -> cost
--      VatRegister       item-level VAT of purchases and sales
--                        (Mushak 6.1 / 6.2 books, 9.1 return)
--
-- Safe to run more than once : a ledger already chosen on the
-- page is never overwritten. Run the whole script (F5).
-- ============================================================


