DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = 'BikeModels' AND column_name = 'SampleField')
    THEN
        DROP TABLE public."BikeModels";
        RAISE NOTICE 'Baseline BikeModels table dropped.';
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS public."BikeModels"
(
    "BikeModelId"       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"          uuid                     NOT NULL DEFAULT uuidv7(),
    "ModelCode"         character varying(30)    NOT NULL,
    "BrandManagementId" bigint                   NOT NULL,
    "ModelName"         character varying(150)   NOT NULL,
    "BikeType"          character varying(30)    NOT NULL DEFAULT '',
    "ShowOnWebsite"     boolean                  NOT NULL DEFAULT false,
    "IsFeatured"        boolean                  NOT NULL DEFAULT false,
    "Tagline"           character varying(200)   NOT NULL DEFAULT '',
    "Description"       character varying(2000)  NOT NULL DEFAULT '',
    "DisplayOrder"      integer                  NOT NULL DEFAULT 0,
    "Remarks"           character varying(1000)  NOT NULL DEFAULT '',
    "Status"            boolean                  NOT NULL DEFAULT true,
    "IsDeleted"         boolean                  NOT NULL DEFAULT false,
    "DeletedBy"         bigint                   NULL,
    "DeletedDate"       timestamp with time zone NULL,
    "CreatedBy"         bigint                   NOT NULL,
    "CreatedDate"       timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"        bigint                   NULL,
    "ModifiedDate"      timestamp with time zone NULL,
    CONSTRAINT "CK_BikeModels_BikeType" CHECK ("BikeType" IN ('Scooter', 'Commuter', 'Sports', 'Cruiser', 'Electric Bike', 'Electric Scooter', 'Off-road'))
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_BikeModels_PublicId" ON public."BikeModels" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "IX_BikeModels_ModelCode" ON public."BikeModels" ("ModelCode") WHERE "IsDeleted" = false;

CREATE INDEX IF NOT EXISTS "IX_BikeModels_Brand" ON public."BikeModels" ("BrandManagementId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_BikeModels_Brand_Name" ON public."BikeModels" ("BrandManagementId", lower("ModelName")) WHERE "IsDeleted" = false;

SELECT count(*) AS "BikeModels" FROM public."BikeModels";
