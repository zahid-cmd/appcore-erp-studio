/*===============================================================
  Website Configuration : tables
  (Settings › General Settings › Website Configuration)

  One row in "WebsiteConfigurations" holds the website's
  switches and texts; the other tables hold its lists. The page
  saves everything in one go.

  Plain statements, safe to run more than once
  (CREATE ... IF NOT EXISTS). Run in a fresh Query Tool.

  Check afterwards (run on its own) :
    -- SELECT table_name FROM information_schema.tables
    -- WHERE table_name LIKE 'Website%' ORDER BY 1;
===============================================================*/


-- 1. The configuration (one row)
CREATE TABLE IF NOT EXISTS public."WebsiteConfigurations"
(
    "WebsiteConfigurationId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    "IsEnabled"        boolean                NOT NULL DEFAULT true,
    "DefaultTheme"     character varying(10)  NOT NULL DEFAULT 'auto',
    "Template"         character varying(40)  NOT NULL DEFAULT 'website-page-1',

    "Tagline"          character varying(200) NOT NULL DEFAULT '',
    "About"            character varying(1000) NOT NULL DEFAULT '',

    "Hotline"          character varying(30)  NOT NULL DEFAULT '',
    "WhatsApp"         character varying(30)  NOT NULL DEFAULT '',
    "Email"            character varying(150) NOT NULL DEFAULT '',
    "MapQuery"         character varying(300) NOT NULL DEFAULT '',

    "FacebookUrl"      character varying(300) NOT NULL DEFAULT '',
    "YoutubeUrl"       character varying(300) NOT NULL DEFAULT '',
    "InstagramUrl"     character varying(300) NOT NULL DEFAULT '',
    "TiktokUrl"        character varying(300) NOT NULL DEFAULT '',

    "ShowBrandsMenu"   boolean NOT NULL DEFAULT true,
    "ShowOfferRibbon"  boolean NOT NULL DEFAULT true,
    "ShowMovingStrip"  boolean NOT NULL DEFAULT true,
    "ShowWhyUs"        boolean NOT NULL DEFAULT true,
    "ShowEmi"          boolean NOT NULL DEFAULT true,
    "ShowService"      boolean NOT NULL DEFAULT true,
    "ShowBranches"     boolean NOT NULL DEFAULT true,
    "ShowFaq"          boolean NOT NULL DEFAULT true,

    "WhyPhotoPath"     character varying(300) NOT NULL DEFAULT '',

    "EmiExamplePrice"  numeric(14,2)          NOT NULL DEFAULT 0,
    "EmiDownPercents"  character varying(100) NOT NULL DEFAULT '10,20,30,50',
    "EmiMonths"        character varying(100) NOT NULL DEFAULT '3,6,12,18,24',
    "EmiNote"          character varying(500) NOT NULL DEFAULT '',

    "CreatedBy"        bigint                   NOT NULL DEFAULT 1,
    "CreatedDate"      timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"       bigint                   NULL,
    "ModifiedDate"     timestamp with time zone NULL
);


-- 2. Opening hours ("10:00" style times; empty when closed)
CREATE TABLE IF NOT EXISTS public."WebsiteOpeningHours"
(
    "WebsiteOpeningHourId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Days"         character varying(80) NOT NULL,
    "OpensAt"      character varying(10) NOT NULL DEFAULT '',
    "ClosesAt"     character varying(10) NOT NULL DEFAULT '',
    "IsClosed"     boolean               NOT NULL DEFAULT false,
    "DisplayOrder" integer               NOT NULL DEFAULT 0
);


-- 3. Simple lists, by Kind :
--    tag (moving strip) · why-point · why-stat (Title = number,
--    Text = label) · service · faq (Title = question, Text = answer)
CREATE TABLE IF NOT EXISTS public."WebsiteContentItems"
(
    "WebsiteContentItemId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Kind"         character varying(20)   NOT NULL,
    "Title"        character varying(200)  NOT NULL,
    "Text"         character varying(2000) NOT NULL DEFAULT '',
    "PhotoPath"    character varying(300)  NOT NULL DEFAULT '',
    "DisplayOrder" integer                 NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS "IX_WebsiteContentItems_Kind"
    ON public."WebsiteContentItems" ("Kind", "DisplayOrder");


-- 4. Brands on the website (one row per brand of Brand Management)
CREATE TABLE IF NOT EXISTS public."WebsiteBrands"
(
    "WebsiteBrandId"    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BrandManagementId" bigint                 NOT NULL,
    "ShowOnWebsite"     boolean                NOT NULL DEFAULT true,
    "ShowBrandPage"     boolean                NOT NULL DEFAULT true,
    "DisplayOrder"      integer                NOT NULL DEFAULT 0,
    "About"             character varying(1000) NOT NULL DEFAULT ''
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_WebsiteBrands_Brand"
    ON public."WebsiteBrands" ("BrandManagementId");


-- 5. Brands each branch sells
CREATE TABLE IF NOT EXISTS public."WebsiteBranchBrands"
(
    "WebsiteBranchBrandId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BranchId"             bigint NOT NULL,
    "BrandManagementId"    bigint NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_WebsiteBranchBrands_Pair"
    ON public."WebsiteBranchBrands" ("BranchId", "BrandManagementId");


-- 6. Policy pages : warranty / terms / privacy.
--    BrandManagementId 0 = the general part; warranty may also
--    have one part per brand.
CREATE TABLE IF NOT EXISTS public."WebsitePolicies"
(
    "WebsitePolicyId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PolicyKey"         character varying(20)  NOT NULL,
    "BrandManagementId" bigint                 NOT NULL DEFAULT 0,
    "Title"             character varying(150) NOT NULL DEFAULT '',
    "UpdatedOn"         date                   NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_WebsitePolicies_KeyBrand"
    ON public."WebsitePolicies" ("PolicyKey", "BrandManagementId");


-- 7. The sections of each policy part
CREATE TABLE IF NOT EXISTS public."WebsitePolicySections"
(
    "WebsitePolicySectionId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WebsitePolicyId"        bigint                  NOT NULL,
    "Heading"                character varying(200)  NOT NULL DEFAULT '',
    "Text"                   character varying(4000) NOT NULL DEFAULT '',
    "DisplayOrder"           integer                 NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS "IX_WebsitePolicySections_Policy"
    ON public."WebsitePolicySections" ("WebsitePolicyId", "DisplayOrder");
