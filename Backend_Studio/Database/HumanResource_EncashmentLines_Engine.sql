-- Leave Encashments : one encashment of an employee for a leave year
-- covers ALL the leave types that can be encashed (it is paid once a
-- year on the whole balance left). Each leave type is a line :
--
--   HrLeaveEncashmentLines   the leave type, the entitlement, the
--                            leave used, the days encashed and the
--                            money of them
--
-- The header keeps the total days and the total amount; one approval,
-- one Journal Voucher, one amount to pay.
--
-- An encashment saved before this script (one leave type) gets its
-- one line.
--
-- Run AFTER HumanResource_EncashmentApproval_Engine.sql. Safe to run
-- more than once. ASCII only.
-- =====================================================================

CREATE TABLE IF NOT EXISTS public."HrLeaveEncashmentLines"
(
    "LeaveEncashmentLineId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "LeaveEncashmentId"     bigint NOT NULL
        REFERENCES public."HrLeaveEncashments" ("LeaveEncashmentId") ON DELETE CASCADE,
    "LeaveTypeId"           bigint                 NOT NULL,
    "LeaveTypeName"         character varying(100) NOT NULL DEFAULT '',
    "Entitled"              numeric(6,2)           NOT NULL DEFAULT 0,
    "Used"                  numeric(6,2)           NOT NULL DEFAULT 0,
    "Days"                  numeric(6,2)           NOT NULL DEFAULT 0,
    "Amount"                numeric(18,2)          NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS "IX_HrLeaveEncashmentLines_Encashment" ON public."HrLeaveEncashmentLines" ("LeaveEncashmentId");
CREATE INDEX IF NOT EXISTS "IX_HrLeaveEncashmentLines_LeaveType"  ON public."HrLeaveEncashmentLines" ("LeaveTypeId");

-- the encashments from before : their one leave type as a line
INSERT INTO public."HrLeaveEncashmentLines"
    ("LeaveEncashmentId", "LeaveTypeId", "LeaveTypeName", "Entitled", "Used", "Days", "Amount")
SELECT e."LeaveEncashmentId", e."LeaveTypeId", COALESCE(t."Name", ''), COALESCE(t."DaysPerYear", 0), 0, e."Days", e."Amount"
FROM   public."HrLeaveEncashments" e
LEFT JOIN public."HrLeaveTypes" t ON t."LeaveTypeId" = e."LeaveTypeId"
WHERE  e."LeaveTypeId" > 0
AND    NOT EXISTS (SELECT 1 FROM public."HrLeaveEncashmentLines" l WHERE l."LeaveEncashmentId" = e."LeaveEncashmentId");

-- Check (run on its own)
SELECT e."Code", e."Status", l."LeaveTypeName", l."Days", l."Amount"
FROM   public."HrLeaveEncashments" e
JOIN   public."HrLeaveEncashmentLines" l ON l."LeaveEncashmentId" = e."LeaveEncashmentId"
WHERE  e."IsDeleted" = false
ORDER  BY e."Code", l."LeaveEncashmentLineId";
