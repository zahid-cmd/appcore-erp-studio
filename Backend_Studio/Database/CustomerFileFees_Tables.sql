-- ============================================================
-- Customer Files : Fees Collection (2026-11-08)
--
-- Registration Management > Customer File > Customer Files,
-- tab Fees Collection. Run AFTER CustomerFiles_Tables.sql.
--
--   1. CustomerFileNameTransfers."Status"
--        FeePending : saved, waits for its fee; the file is not
--                     changed yet
--        Completed  : the new owner holds the file
--   2. CustomerFileFees : a name transfer fee or a custody charge
--        Pending   : to be collected (the action waits for it)
--        Due       : the action went ahead without payment (the
--                    switch below); booked by a Journal Voucher :
--                    Dr the customer's receivable / Cr Customer
--                    File Income
--        Paid      : collected by a Receipt Voucher (Payment Desk)
--        Cancelled : the pending action was dropped
--   3. Switch CFG-MOD-011-0101 "Customer Files : Allow Without
--      Fee Payment" (critical, OFF). ON : the page may transfer
--      a name / deliver a file before its fee is paid (the fee
--      becomes the customer's due).
--
-- Plain statements, safe to run again. ASCII only.
-- ============================================================


-- Clears a transaction left open by an earlier failed run in the
-- same pgAdmin tab (a harmless warning when there is none).
ROLLBACK;


-- 1. Transfer status ------------------------------------------

ALTER TABLE public."CustomerFileNameTransfers"
    ADD COLUMN IF NOT EXISTS "Status" character varying(20) NOT NULL DEFAULT 'Completed';

ALTER TABLE public."CustomerFileNameTransfers"
    DROP CONSTRAINT IF EXISTS "CK_CustomerFileNameTransfers_Status";

ALTER TABLE public."CustomerFileNameTransfers"
    ADD CONSTRAINT "CK_CustomerFileNameTransfers_Status"
    CHECK ("Status" IN ('FeePending', 'Completed'));


-- 2. Fees ------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."CustomerFileFees"
(
    "CustomerFileFeeId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"            uuid                   NOT NULL DEFAULT uuidv7(),
    "FeeNo"               character varying(20)  NOT NULL,
    "CustomerFileId"      bigint                 NOT NULL
        REFERENCES public."CustomerFiles" ("CustomerFileId"),
    -- NameTransfer / Custody
    "FeeType"             character varying(20)  NOT NULL,
    "NameTransferId"      bigint                 NULL
        REFERENCES public."CustomerFileNameTransfers" ("NameTransferId"),
    "FeeDate"             date                   NOT NULL,
    -- The customer who pays (Customer Profiles)
    "CustomerId"          bigint                 NOT NULL,
    "Amount"              numeric(18,2)          NOT NULL,
    -- Custody : the collected date the charge was worked out for
    "CustodyUpTo"         date                   NULL,
    "Status"              character varying(20)  NOT NULL DEFAULT 'Pending',
    "BranchId"            bigint                 NOT NULL DEFAULT 0,

    -- Due : the Journal Voucher that booked it
    "DueVoucherId"        bigint                 NULL,
    "DueVoucherNo"        character varying(40)  NOT NULL DEFAULT '',
    -- Paid : the Receipt Voucher that collected it
    "ReceiptVoucherId"    bigint                 NULL,
    "ReceiptVoucherNo"    character varying(40)  NOT NULL DEFAULT '',
    "PaidDate"            date                   NULL,

    "Remarks"             character varying(500) NOT NULL DEFAULT '',

    "IsDeleted"           boolean                NOT NULL DEFAULT false,
    "DeletedBy"           bigint                 NULL,
    "DeletedDate"         timestamp with time zone NULL,
    "CreatedBy"           bigint                 NOT NULL,
    "CreatedDate"         timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"          bigint                 NULL,
    "ModifiedDate"        timestamp with time zone NULL,

    CONSTRAINT "CK_CustomerFileFees_Type"
        CHECK ("FeeType" IN ('NameTransfer', 'Custody')),

    CONSTRAINT "CK_CustomerFileFees_Status"
        CHECK ("Status" IN ('Pending', 'Due', 'Paid', 'Cancelled')),

    CONSTRAINT "CK_CustomerFileFees_Amount"
        CHECK ("Amount" > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_CustomerFileFees_PublicId"
    ON public."CustomerFileFees" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_CustomerFileFees_No"
    ON public."CustomerFileFees" ("FeeNo");

CREATE INDEX IF NOT EXISTS "IX_CustomerFileFees_File"
    ON public."CustomerFileFees" ("CustomerFileId");

-- One pending custody charge per file at a time
CREATE UNIQUE INDEX IF NOT EXISTS "UX_CustomerFileFees_PendingCustody"
    ON public."CustomerFileFees" ("CustomerFileId")
    WHERE "IsDeleted" = false AND "Status" = 'Pending' AND "FeeType" = 'Custody';


-- 3. Switch ----------------------------------------------------

DO $$
DECLARE
    v_module_id   bigint;
    v_module_code text;
    v_menu_code   text;
    v_page_code   text;
BEGIN
    SELECT m."Id", m."Code"
    INTO   v_module_id, v_module_code
    FROM   "NavigationModules" m
    WHERE  lower(trim(m."Name")) = 'registration management'
    AND    NOT m."IsDeleted"
    LIMIT  1;

    IF v_module_id IS NULL THEN
        RAISE EXCEPTION 'Registration Management module not found - nothing changed.';
    END IF;

    IF upper(trim(v_module_code)) <> 'MOD-011' THEN
        RAISE EXCEPTION 'Registration Management module code is % (expected MOD-011) - nothing changed. Tell Claude.', v_module_code;
    END IF;

    IF EXISTS
    (
        SELECT 1
        FROM   "SystemConfigurations" c
        WHERE  c."ConfigurationCode" = 'CFG-MOD-011-0101'
        AND    c."ConfigurationName" <> 'Customer Files : Allow Without Fee Payment'
    )
    THEN
        RAISE EXCEPTION 'CFG-MOD-011-0101 is already used by another switch - nothing changed. Tell Claude.';
    END IF;

    SELECT s."Code", mn."Code"
    INTO   v_page_code, v_menu_code
    FROM   "NavigationSubmenus" s
    JOIN   "NavigationMenus" mn ON mn."Id" = s."NavigationMenuId"
    WHERE  s."Route" ILIKE '/registration-management/%/customer-files'
    AND    NOT s."IsDeleted"
    LIMIT  1;

    IF v_page_code IS NULL THEN
        RAISE EXCEPTION 'Customer Files page not found by route (/registration-management/.../customer-files) - nothing changed.';
    END IF;

    INSERT INTO "SystemConfigurations"
    (
        "NavigationModuleId", "ScopeType", "NavigationMenuCode", "NavigationSubmenuCode",
        "ConfigurationCode", "ConfigurationName", "OnDescription", "OffDescription",
        "IsEnabled", "Value",
        "ValueType", "ValueUnit", "ValueMin", "ValueMax", "ValueEmptyText",
        "DefaultEnabled", "DefaultValue", "ParentConfigurationCode",
        "IsCritical", "IsSystemDefined", "DisplayOrder", "Remarks",
        "IsDeleted", "CreatedBy", "CreatedDate"
    )
    SELECT
        v_module_id, 'Submenu', v_menu_code, v_page_code,
        'CFG-MOD-011-0101',
        'Customer Files : Allow Without Fee Payment',
        'A name transfer / file delivery may go ahead before its fee is paid (the user ticks "without payment"). The fee is booked as the customer''s due (Journal Voucher : Dr receivable / Cr Customer File Income) and collected later on Fees Collection.',
        'A name transfer takes effect, and a file is delivered, only after its fee is collected on Fees Collection.',
        false, '',
        'None', '', NULL, NULL, '',
        false, '', NULL,
        true, true, 10, 'Critical : changing it needs a reason / approval.',
        false, 1, now()
    WHERE NOT EXISTS
    (
        SELECT 1
        FROM   "SystemConfigurations" c
        WHERE  c."ConfigurationCode" = 'CFG-MOD-011-0101'
    );
END $$;


-- Check
SELECT 'Fees' AS "List", count(*) AS "Rows" FROM public."CustomerFileFees" WHERE "IsDeleted" = false
UNION ALL
SELECT 'Switch CFG-MOD-011-0101', count(*) FROM "SystemConfigurations" WHERE "ConfigurationCode" = 'CFG-MOD-011-0101';
