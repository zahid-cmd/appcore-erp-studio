-- Service Operations, step 1 (claude\blueprint-service-operations.md) :
-- the tables of Workshop Configuration and Job Cards, and the Posting
-- Setup rows of the workshop.
--
--   WorkshopBays            BAY-0001 : a work bay of a service center
--   WorkshopTechnicians     TEC-0001 : an employee (Human Resource)
--                           who works on job cards
--   WorkshopChecklistItems  CHK-0001 : what is checked when a bike
--                           comes in (mirrors, tool kit ...)
--   WorkshopConfiguration   one row : the workshop switches
--   JobCards                JC-000001 : a bike taken in for work.
--                           Open -> In Progress -> Waiting Parts ->
--                           Work Done -> Ready; Cancelled.
--                           (Invoiced / Delivered come with Service
--                           Invoices.)
--   JobCardComplaints       what the customer says
--   JobCardServices         the labour lines (Scheduled Services /
--                           Labor Chart / Customized Services /
--                           Membership Services / Other)
--   JobCardParts            the parts the job needs (a list only :
--                           stock moves on Parts Issues, later)
--   JobCardWorkEntries      a technician on the job : start and end
--                           time stamps (one technician may be on
--                           more than one job)
--   JobCardChecklist        the check-in checklist as filled
--   JobCardStatusHistory    every status change with its time
--
-- The menus and pages are there already (ServiceOperations_
-- Navigation.sql, Operations_Restructure.sql) : Workshop Management >
-- Job Cards, Service Setup > Workshop Configuration. Hand-written
-- pages : NEVER run Menu / Submenu / Code Sync for them.
--
-- Safe to run more than once. Run the whole script (F5). ASCII only.
--
-- AFTER : Security & Permission > Activity Assignment : tick Job Cards
-- and Workshop Configuration for the roles, log in again. Settings >
-- Account Settings > Posting Setup, group "Service Operations" : the
-- ledgers are needed only when Parts Issues / Service Invoices are
-- built.
-- =====================================================================


-- ------------------------------------------------------------
-- 1. Workshop Configuration
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."WorkshopBays"
(
    "WorkshopBayId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"      uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"          character varying(20)    NOT NULL,
    "Name"          character varying(100)   NOT NULL,
    "BranchId"      bigint                   NOT NULL,
    "Remarks"       character varying(500)   NOT NULL DEFAULT '',
    "IsActive"      boolean                  NOT NULL DEFAULT true,
    "IsDeleted"     boolean                  NOT NULL DEFAULT false,
    "DeletedBy"     bigint                   NULL,
    "DeletedDate"   timestamp with time zone NULL,
    "CreatedBy"     bigint                   NOT NULL,
    "CreatedDate"   timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"    bigint                   NULL,
    "ModifiedDate"  timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_WorkshopBays_PublicId" ON public."WorkshopBays" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_WorkshopBays_Code"     ON public."WorkshopBays" ("Code");

CREATE TABLE IF NOT EXISTS public."WorkshopTechnicians"
(
    "WorkshopTechnicianId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"             uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"                 character varying(20)    NOT NULL,
    -- an employee (Human Resource)
    "EmployeeId"           bigint                   NOT NULL,
    -- the service center the technician works at
    "BranchId"             bigint                   NOT NULL,
    -- e.g. Engine, Electrical, General
    "Skill"                character varying(100)   NOT NULL DEFAULT '',
    "Remarks"              character varying(500)   NOT NULL DEFAULT '',
    "IsActive"             boolean                  NOT NULL DEFAULT true,
    "IsDeleted"            boolean                  NOT NULL DEFAULT false,
    "DeletedBy"            bigint                   NULL,
    "DeletedDate"          timestamp with time zone NULL,
    "CreatedBy"            bigint                   NOT NULL,
    "CreatedDate"          timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"           bigint                   NULL,
    "ModifiedDate"         timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_WorkshopTechnicians_PublicId" ON public."WorkshopTechnicians" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_WorkshopTechnicians_Code"     ON public."WorkshopTechnicians" ("Code");

CREATE TABLE IF NOT EXISTS public."WorkshopChecklistItems"
(
    "WorkshopChecklistItemId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"                uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"                    character varying(20)    NOT NULL,
    "Name"                    character varying(100)   NOT NULL,
    "SortOrder"               integer                  NOT NULL DEFAULT 0,
    "Remarks"                 character varying(500)   NOT NULL DEFAULT '',
    "IsActive"                boolean                  NOT NULL DEFAULT true,
    "IsDeleted"               boolean                  NOT NULL DEFAULT false,
    "DeletedBy"               bigint                   NULL,
    "DeletedDate"             timestamp with time zone NULL,
    "CreatedBy"               bigint                   NOT NULL,
    "CreatedDate"             timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"              bigint                   NULL,
    "ModifiedDate"            timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_WorkshopChecklistItems_PublicId" ON public."WorkshopChecklistItems" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_WorkshopChecklistItems_Code"     ON public."WorkshopChecklistItems" ("Code");

