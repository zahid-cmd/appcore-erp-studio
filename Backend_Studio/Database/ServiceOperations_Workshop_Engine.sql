CREATE TABLE IF NOT EXISTS public."JobCards"
(
    "JobCardId"                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"                 uuid                     NOT NULL DEFAULT uuidv7(),
    "JobCardNo"                character varying(30)    NOT NULL,
    "JobDate"                  date                     NOT NULL,
    "CheckInAt"                timestamp with time zone NOT NULL DEFAULT now(),
    "BranchId"                 bigint                   NOT NULL,
    -- the bike : a Service Vehicle (sold by us or added before), or
    -- NULL for a bike typed on the job card
    "ServiceVehicleId"         bigint                   NULL,
    "ChassisNo"                character varying(50)    NOT NULL DEFAULT '',
    "EngineNo"                 character varying(50)    NOT NULL DEFAULT '',
    "RegistrationNo"           character varying(50)    NOT NULL DEFAULT '',
    -- Product Sub Category of a Motor Bikes category (NULL : a model
    -- we do not sell, typed)
    "ModelId"                  bigint                   NULL,
    "ModelName"                character varying(150)   NOT NULL DEFAULT '',
    "BrandManagementId"        bigint                   NULL,
    "BrandName"                character varying(100)   NOT NULL DEFAULT '',
    "ColorName"                character varying(60)    NOT NULL DEFAULT '',
    "CustomerId"               bigint                   NULL,
    "CustomerName"             character varying(150)   NOT NULL DEFAULT '',
    "Mobile"                   character varying(20)    NOT NULL DEFAULT '',
    "KmReading"                integer                  NULL,
    -- '' / Empty / Quarter / Half / Three Quarter / Full
    "FuelLevel"                character varying(15)    NOT NULL DEFAULT '',
    -- Free Service / Paid Service / General Repair / Warranty /
    -- Membership Service / Rework / Internal
    "JobType"                  character varying(20)    NOT NULL DEFAULT 'General Repair',
    -- the schedule position a Free / Paid Service takes
    "ServiceVehicleScheduleId" bigint                   NULL,
    "ServiceEnquiryId"         bigint                   NULL,
    -- the service advisor : an employee (Human Resource)
    "AdvisorEmployeeId"        bigint                   NULL,
    -- what the engineer finds the bike needs
    "BasicRequirement"         character varying(1000)  NOT NULL DEFAULT '',
    "PromisedAt"               timestamp with time zone NULL,
    "PickupDrop"               boolean                  NOT NULL DEFAULT false,
    -- Open / In Progress / Waiting Parts / Work Done / Ready /
    -- Invoiced / Delivered / Cancelled
    "Status"                   character varying(15)    NOT NULL DEFAULT 'Open',
    "StatusDate"               timestamp with time zone NOT NULL DEFAULT now(),
    "CancelReason"             character varying(300)   NOT NULL DEFAULT '',
    "LabourTotal"              numeric(18,2)            NOT NULL DEFAULT 0,
    "PartsTotal"               numeric(18,2)            NOT NULL DEFAULT 0,
    "Remarks"                  character varying(500)   NOT NULL DEFAULT '',
    "IsDeleted"                boolean                  NOT NULL DEFAULT false,
    "DeletedBy"                bigint                   NULL,
    "DeletedDate"              timestamp with time zone NULL,
    "CreatedBy"                bigint                   NOT NULL,
    "CreatedDate"              timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"               bigint                   NULL,
    "ModifiedDate"             timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_JobCards_PublicId"  ON public."JobCards" ("PublicId");
-- the number is <PREFIX>-<branch>-<FY>-<MM>-00001 (2026-11-16) :
-- a table made before that gets the room for it
ALTER TABLE public."JobCards" ALTER COLUMN "JobCardNo" TYPE character varying(30);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_JobCards_JobCardNo" ON public."JobCards" ("JobCardNo");
CREATE INDEX        IF NOT EXISTS "IX_JobCards_Branch"    ON public."JobCards" ("BranchId", "Status");
CREATE INDEX        IF NOT EXISTS "IX_JobCards_Vehicle"   ON public."JobCards" ("ServiceVehicleId");
CREATE INDEX        IF NOT EXISTS "IX_JobCards_Chassis"   ON public."JobCards" ("ChassisNo");

CREATE TABLE IF NOT EXISTS public."JobCardComplaints"
(
    "JobCardComplaintId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "JobCardId"          bigint NOT NULL
        REFERENCES public."JobCards" ("JobCardId") ON DELETE CASCADE,
    "LineNo"             integer                NOT NULL DEFAULT 0,
    "Complaint"          character varying(300) NOT NULL
);

CREATE INDEX IF NOT EXISTS "IX_JobCardComplaints_JobCard" ON public."JobCardComplaints" ("JobCardId");

CREATE TABLE IF NOT EXISTS public."JobCardServices"
(
    "JobCardServiceId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "JobCardId"        bigint NOT NULL
        REFERENCES public."JobCards" ("JobCardId") ON DELETE CASCADE,
    "LineNo"           integer                NOT NULL DEFAULT 0,
    -- Scheduled / LaborChart / Customized / Membership / Other
    "ItemKind"         character varying(15)  NOT NULL DEFAULT 'Other',
    "ItemId"           bigint                 NULL,
    "ItemCode"         character varying(40)  NOT NULL DEFAULT '',
    "ItemName"         character varying(200) NOT NULL,
    "Quantity"         numeric(10,2)          NOT NULL DEFAULT 1,
    -- the customer charge (a free scheduled service : 0)
    "Rate"             numeric(18,2)          NOT NULL DEFAULT 0,
    "Amount"           numeric(18,2)          NOT NULL DEFAULT 0,
    -- a free scheduled service : its charge is waived for the customer
    "IsFree"           boolean                NOT NULL DEFAULT false,
    "Note"             character varying(200) NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS "IX_JobCardServices_JobCard" ON public."JobCardServices" ("JobCardId");

CREATE TABLE IF NOT EXISTS public."JobCardParts"
(
    "JobCardPartId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "JobCardId"     bigint NOT NULL
        REFERENCES public."JobCards" ("JobCardId") ON DELETE CASCADE,
    "LineNo"        integer                NOT NULL DEFAULT 0,
    -- SparePart / Accessory / Other
    "ItemKind"      character varying(15)  NOT NULL DEFAULT 'Other',
    "ItemId"        bigint                 NULL,
    "ItemCode"      character varying(40)  NOT NULL DEFAULT '',
    "ItemName"      character varying(200) NOT NULL,
    "Quantity"      numeric(10,2)          NOT NULL DEFAULT 1,
    -- the price at the time (an estimate : the invoice prices again)
    "Rate"          numeric(18,2)          NOT NULL DEFAULT 0,
    "Amount"        numeric(18,2)          NOT NULL DEFAULT 0,
    "Note"          character varying(200) NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS "IX_JobCardParts_JobCard" ON public."JobCardParts" ("JobCardId");

CREATE TABLE IF NOT EXISTS public."JobCardWorkEntries"
(
    "JobCardWorkEntryId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "JobCardId"            bigint NOT NULL
        REFERENCES public."JobCards" ("JobCardId") ON DELETE CASCADE,
    "WorkshopTechnicianId" bigint                   NOT NULL,
    "WorkshopBayId"        bigint                   NULL,
    -- what the technician works on (free text, e.g. a labour line)
    "WorkNote"             character varying(200)   NOT NULL DEFAULT '',
    "StartAt"              timestamp with time zone NOT NULL,
    -- NULL : still working
    "EndAt"                timestamp with time zone NULL,
    "CreatedBy"            bigint                   NOT NULL,
    "CreatedDate"          timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS "IX_JobCardWorkEntries_JobCard"    ON public."JobCardWorkEntries" ("JobCardId");
CREATE INDEX IF NOT EXISTS "IX_JobCardWorkEntries_Technician" ON public."JobCardWorkEntries" ("WorkshopTechnicianId", "StartAt");

CREATE TABLE IF NOT EXISTS public."JobCardChecklist"
(
    "JobCardChecklistId"      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "JobCardId"               bigint NOT NULL
        REFERENCES public."JobCards" ("JobCardId") ON DELETE CASCADE,
    "WorkshopChecklistItemId" bigint                 NOT NULL,
    "LineNo"                  integer                NOT NULL DEFAULT 0,
    -- the name at the time
    "ItemName"                character varying(100) NOT NULL,
    -- '' (not marked) / OK / Not OK / N/A
    "Result"                  character varying(10)  NOT NULL DEFAULT '',
    "Note"                    character varying(200) NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS "IX_JobCardChecklist_JobCard" ON public."JobCardChecklist" ("JobCardId");

CREATE TABLE IF NOT EXISTS public."JobCardStatusHistory"
(
    "JobCardStatusHistoryId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "JobCardId"              bigint NOT NULL
        REFERENCES public."JobCards" ("JobCardId") ON DELETE CASCADE,
    "Status"                 character varying(15)    NOT NULL,
    "Note"                   character varying(300)   NOT NULL DEFAULT '',
    "ChangedBy"              bigint                   NOT NULL,
    "ChangedAt"              timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS "IX_JobCardStatusHistory_JobCard" ON public."JobCardStatusHistory" ("JobCardId");


