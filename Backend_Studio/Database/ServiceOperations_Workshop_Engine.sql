CREATE TABLE IF NOT EXISTS public."WorkshopConfiguration"
(
    "WorkshopConfigurationId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- a job card cannot be saved without the km reading
    "RequireKm"               boolean                  NOT NULL DEFAULT true,
    -- every checklist item must be marked before work starts
    "RequireChecklist"        boolean                  NOT NULL DEFAULT false,
    "ModifiedBy"              bigint                   NULL,
    "ModifiedDate"            timestamp with time zone NULL
);

INSERT INTO public."WorkshopConfiguration" ("RequireKm", "RequireChecklist")
SELECT true, false
WHERE  NOT EXISTS (SELECT 1 FROM public."WorkshopConfiguration");


