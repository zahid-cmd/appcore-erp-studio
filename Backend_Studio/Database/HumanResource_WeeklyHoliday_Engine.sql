-- Human Resource Management : the weekly holiday
-- (hand-written pages : NEVER run Submenu / Code Sync for them)
-- Run HumanResource_Phase1_Engine.sql first.
--
--   The weekly off days are no longer on the shift.
--
--   HrWeeklyHolidays   ONE row : the weekly holiday of every employee
--                      (Human Resource Setup > Holidays > Weekly
--                      Holidays tab). It is edited, never added twice :
--                      the table cannot hold a second row.
--   HrEmployees."WeeklyOffDays"
--                      the employee's own weekly holiday ('' = the
--                      default above), on the Employee Profile.
--   HrShifts."WeeklyOffDays"  is removed.
--
--   What was on the shifts is kept : the off days of the shift most
--   employees are on become the weekly holiday, and an employee on a
--   shift with other off days gets them as the employee's own.
--
-- IMPORTANT : run this before opening Shifts, Holidays, Employee
-- Profiles or the attendance pages again : the program reads the new
-- table and column.
--
-- Safe to run again. Run the whole script (F5) on AppCoreERP_Studio.
-- ASCII only.
-- =====================================================================

-- ------------------------------------------------------------
-- 1. The weekly holiday (one row only)
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."HrWeeklyHolidays"
(
    "WeeklyHolidayId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Sun,Mon,Tue,Wed,Thu,Fri,Sat (comma separated; '' = none)
    "WeeklyOffDays"   character varying(40)    NOT NULL DEFAULT '',
    "Remarks"         character varying(500)   NOT NULL DEFAULT '',
    -- always true and unique : a second row cannot be added
    "OnlyOne"         boolean                  NOT NULL DEFAULT true,
    "CreatedBy"       bigint                   NOT NULL DEFAULT 1,
    "CreatedDate"     timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"      bigint                   NULL,
    "ModifiedDate"    timestamp with time zone NULL,
    CONSTRAINT "CK_HrWeeklyHolidays_OnlyOne" CHECK ("OnlyOne")
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrWeeklyHolidays_OnlyOne"
    ON public."HrWeeklyHolidays" ("OnlyOne");

-- ------------------------------------------------------------
-- 2. The employee's own weekly holiday ('' = the default)
-- ------------------------------------------------------------

ALTER TABLE public."HrEmployees"
    ADD COLUMN IF NOT EXISTS "WeeklyOffDays" character varying(40) NOT NULL DEFAULT '';

-- ------------------------------------------------------------
-- 3. From the shifts to the weekly holiday, then the shift column
--    goes
-- ------------------------------------------------------------

DO $$
DECLARE
    v_default character varying(40);
BEGIN
    IF EXISTS (SELECT 1
               FROM  information_schema.columns
               WHERE table_schema = 'public'
               AND   table_name = 'HrShifts'
               AND   column_name = 'WeeklyOffDays')
    THEN
        IF NOT EXISTS (SELECT 1 FROM public."HrWeeklyHolidays")
        THEN
            -- the off days of the shift most employees are on
            -- (the first shift when no employee has one)
            SELECT s."WeeklyOffDays"
            INTO   v_default
            FROM   public."HrShifts" s
            LEFT JOIN public."HrEmployees" e
                   ON e."ShiftId" = s."ShiftId" AND e."IsDeleted" = false
            WHERE  s."IsDeleted" = false
            GROUP BY s."ShiftId", s."WeeklyOffDays"
            ORDER BY COUNT(e."EmployeeId") DESC, s."ShiftId"
            LIMIT 1;

            INSERT INTO public."HrWeeklyHolidays" ("WeeklyOffDays", "Remarks")
            VALUES (COALESCE(v_default, 'Fri'), 'Taken from the shifts.');
        END IF;

        SELECT "WeeklyOffDays" INTO v_default FROM public."HrWeeklyHolidays" LIMIT 1;

        -- an employee on a shift with other off days keeps them
        UPDATE public."HrEmployees" e
        SET    "WeeklyOffDays" = s."WeeklyOffDays"
        FROM   public."HrShifts" s
        WHERE  s."ShiftId" = e."ShiftId"
        AND    e."WeeklyOffDays" = ''
        AND    s."WeeklyOffDays" <> ''
        AND    s."WeeklyOffDays" <> v_default;

        ALTER TABLE public."HrShifts" DROP COLUMN "WeeklyOffDays";
    END IF;

    IF NOT EXISTS (SELECT 1 FROM public."HrWeeklyHolidays")
    THEN
        INSERT INTO public."HrWeeklyHolidays" ("WeeklyOffDays", "Remarks")
        VALUES ('Fri', 'Starter weekly holiday : change it to yours.');
    END IF;
END $$;

-- ------------------------------------------------------------
-- 4. The Shifts submenu text
-- ------------------------------------------------------------

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = 'Submenus' AND column_name = 'Description')
    THEN
        UPDATE public."Submenus"
        SET    "Description" = 'Working hours and grace time.'
        WHERE  "Description" = 'Working hours, grace time and weekly off days.';
    END IF;
END $$;
