-- ============================================================
-- Price Adjustment (2026-11-02).
-- Plain statements : run in a NEW pgAdmin Query Tool (F5).
-- Safe to run again.
--
-- 1. The sample table made by the page sync ("PriceAdjustment"
--    with id / code / name / sampleField ...) is dropped : it
--    only held test rows. The real tables take its place.
-- 2. PriceAdjustments         : one adjustment (PA-<MB|SP|AC>-0001)
--    PriceAdjustmentProducts  : one row per product (last / new MRP)
--    PriceAdjustmentLines     : one row per batch with stock on the
--                               cut-off date (cost, margin, new cost,
--                               difference, amount, old MRP)
--    PriceAdjustmentSuppliers : one row per supplier group and how
--                               its increase / reduction is settled
--    PriceAdjustmentReleases  : what was released from Stock Price
--                               Adjustment (units sold since the
--                               cut-off at posting; later each sale)
-- 3. Posting Setup purposes (ledger left empty : choose it on
--    Settings › Account Settings › Posting Setup) :
--      STOCK-PRICE-ADJ    Stock Price Adjustment
--      PRICE-INC-RESERVE  Price Increase Reserve
--      PRICE-INC-INCOME   Price Increase Income
--      PRICE-RED-EXPENSE  Price Reduction Expense
--      PRICE-ADJ-COST     Price Adjustment on Cost of Sales
-- 4. Page actions Post and Cancel linked to the Price Adjustment
--    page (Add, Update, Delete, View, Print, Restore are common).
-- 5. Auto Journal Registers : voucher type PA → this page.
-- ============================================================


-- 1. The sync's sample table : a "PriceAdjustment" table without
--    the real "AdjustmentNo" column is dropped

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables
               WHERE table_schema = 'public' AND table_name = 'PriceAdjustment')
       AND NOT EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = 'PriceAdjustment' AND column_name = 'AdjustmentNo') THEN
        DROP TABLE public."PriceAdjustment" CASCADE;
        RAISE NOTICE 'The sample PriceAdjustment table was dropped.';
    END IF;
END $$;


-- 2. Tables

CREATE TABLE IF NOT EXISTS public."PriceAdjustments"
(
    "PriceAdjustmentId"  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "AdjustmentNo"       character varying(30)  NOT NULL,
    "SequenceNo"         integer                NOT NULL DEFAULT 0,
    "PageType"           character varying(2)   NOT NULL,
    "BranchId"           bigint                 NOT NULL DEFAULT 0,
    "CircularRef"        character varying(100) NOT NULL DEFAULT '',
    "CircularDate"       date                   NULL,
    "CutOffDate"         date                   NOT NULL,
    "Remarks"            character varying(500) NOT NULL DEFAULT '',
    "Status"             character varying(20)  NOT NULL DEFAULT 'Draft',
    "ProductCount"       integer                NOT NULL DEFAULT 0,
    "BatchCount"         integer                NOT NULL DEFAULT 0,
    "IncreaseAmount"     numeric(18,2)          NOT NULL DEFAULT 0,
    "ReductionAmount"    numeric(18,2)          NOT NULL DEFAULT 0,
    "NetAmount"          numeric(18,2)          NOT NULL DEFAULT 0,
    "VoucherNo"          character varying(30)  NOT NULL DEFAULT '',
    "PostedBy"           bigint                 NULL,
    "PostedDate"         timestamp with time zone NULL,
    "CancelledBy"        bigint                 NULL,
    "CancelledDate"      timestamp with time zone NULL,
    "CancelReason"       character varying(500) NOT NULL DEFAULT '',
    "IsDeleted"          boolean                NOT NULL DEFAULT false,
    "DeletedBy"          bigint                 NULL,
    "DeletedDate"        timestamp with time zone NULL,
    "CreatedBy"          bigint                 NOT NULL,
    "CreatedDate"        timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"         bigint                 NULL,
    "ModifiedDate"       timestamp with time zone NULL,
    CONSTRAINT "CK_PriceAdjustments_PageType" CHECK ("PageType" IN ('MB', 'SP', 'AC')),
    CONSTRAINT "CK_PriceAdjustments_Status"   CHECK ("Status" IN ('Draft', 'Posted', 'Cancelled'))
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_PriceAdjustments_AdjustmentNo"
    ON public."PriceAdjustments" ("AdjustmentNo");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_PriceAdjustments_Type_Sequence"
    ON public."PriceAdjustments" ("PageType", "SequenceNo")
    WHERE "SequenceNo" > 0;

CREATE INDEX IF NOT EXISTS "IX_PriceAdjustments_VoucherNo"
    ON public."PriceAdjustments" ("VoucherNo")
    WHERE "VoucherNo" <> '';


CREATE TABLE IF NOT EXISTS public."PriceAdjustmentProducts"
(
    "PriceAdjustmentProductId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PriceAdjustmentId"  bigint                 NOT NULL REFERENCES public."PriceAdjustments" ("PriceAdjustmentId") ON DELETE CASCADE,
    "LineNo"             integer                NOT NULL,
    "ProductId"          bigint                 NOT NULL,
    "ProductCode"        character varying(40)  NOT NULL DEFAULT '',
    "ProductName"        character varying(250) NOT NULL DEFAULT '',
    "PartNumber"         character varying(100) NOT NULL DEFAULT '',
    "OldMrp"             numeric(18,2)          NOT NULL DEFAULT 0,
    "NewMrp"             numeric(18,2)          NOT NULL DEFAULT 0,
    "Direction"          character varying(10)  NOT NULL DEFAULT '',
    "BatchCount"         integer                NOT NULL DEFAULT 0,
    "Quantity"           numeric(18,4)          NOT NULL DEFAULT 0,
    "Amount"             numeric(18,2)          NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS "IX_PriceAdjustmentProducts_PriceAdjustmentId"
    ON public."PriceAdjustmentProducts" ("PriceAdjustmentId");


CREATE TABLE IF NOT EXISTS public."PriceAdjustmentLines"
(
    "PriceAdjustmentLineId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PriceAdjustmentId"  bigint                 NOT NULL REFERENCES public."PriceAdjustments" ("PriceAdjustmentId") ON DELETE CASCADE,
    "ProductId"          bigint                 NOT NULL,
    "StockBatchId"       bigint                 NOT NULL,
    "BatchNo"            character varying(40)  NOT NULL DEFAULT '',
    "SupplierCode"       character varying(40)  NOT NULL DEFAULT '',
    "SupplierName"       character varying(200) NOT NULL DEFAULT '',
    "VatRate"            numeric(9,4)           NOT NULL DEFAULT 0,
    "Quantity"           numeric(18,4)          NOT NULL DEFAULT 0,
    "SoldSinceCutOff"    numeric(18,4)          NOT NULL DEFAULT 0,
    "ReleasedQuantity"   numeric(18,4)          NOT NULL DEFAULT 0,
    "UnitCost"           numeric(18,4)          NOT NULL DEFAULT 0,
    "OldMrp"             numeric(18,2)          NOT NULL DEFAULT 0,
    "NewMrp"             numeric(18,2)          NOT NULL DEFAULT 0,
    "MarginPercent"      numeric(9,4)           NOT NULL DEFAULT 0,
    "MarginEdited"       boolean                NOT NULL DEFAULT false,
    "NewUnitCost"        numeric(18,4)          NOT NULL DEFAULT 0,
    "DifferencePerUnit"  numeric(18,4)          NOT NULL DEFAULT 0,
    "Amount"             numeric(18,2)          NOT NULL DEFAULT 0,
    "MrpApplied"         boolean                NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS "IX_PriceAdjustmentLines_PriceAdjustmentId"
    ON public."PriceAdjustmentLines" ("PriceAdjustmentId");

CREATE INDEX IF NOT EXISTS "IX_PriceAdjustmentLines_StockBatchId"
    ON public."PriceAdjustmentLines" ("StockBatchId");


CREATE TABLE IF NOT EXISTS public."PriceAdjustmentSuppliers"
(
    "PriceAdjustmentSupplierId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PriceAdjustmentId"  bigint                 NOT NULL REFERENCES public."PriceAdjustments" ("PriceAdjustmentId") ON DELETE CASCADE,
    "SupplierCode"       character varying(40)  NOT NULL DEFAULT '',
    "SupplierName"       character varying(200) NOT NULL DEFAULT '',
    "IncreaseTo"         character varying(20)  NOT NULL DEFAULT 'Reserve',
    "ReductionTo"        character varying(20)  NOT NULL DEFAULT 'Expense',
    "IncreaseAmount"     numeric(18,2)          NOT NULL DEFAULT 0,
    "ReductionAmount"    numeric(18,2)          NOT NULL DEFAULT 0,
    CONSTRAINT "CK_PriceAdjustmentSuppliers_IncreaseTo"  CHECK ("IncreaseTo" IN ('Supplier', 'Reserve', 'Income')),
    CONSTRAINT "CK_PriceAdjustmentSuppliers_ReductionTo" CHECK ("ReductionTo" IN ('Supplier', 'Expense'))
);

CREATE INDEX IF NOT EXISTS "IX_PriceAdjustmentSuppliers_PriceAdjustmentId"
    ON public."PriceAdjustmentSuppliers" ("PriceAdjustmentId");


CREATE TABLE IF NOT EXISTS public."PriceAdjustmentReleases"
(
    "PriceAdjustmentReleaseId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PriceAdjustmentLineId" bigint              NOT NULL REFERENCES public."PriceAdjustmentLines" ("PriceAdjustmentLineId") ON DELETE CASCADE,
    "PriceAdjustmentId"  bigint                 NOT NULL,
    "StockBatchId"       bigint                 NOT NULL,
    "Quantity"           numeric(18,4)          NOT NULL DEFAULT 0,
    "Amount"             numeric(18,2)          NOT NULL DEFAULT 0,
    "SourceType"         character varying(20)  NOT NULL,
    "SourceNo"           character varying(40)  NOT NULL DEFAULT '',
    "ReleaseDate"        date                   NOT NULL,
    "CreatedBy"          bigint                 NOT NULL,
    "CreatedDate"        timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT "CK_PriceAdjustmentReleases_SourceType" CHECK ("SourceType" IN ('Posting', 'Sale'))
);

CREATE INDEX IF NOT EXISTS "IX_PriceAdjustmentReleases_PriceAdjustmentId"
    ON public."PriceAdjustmentReleases" ("PriceAdjustmentId");

CREATE INDEX IF NOT EXISTS "IX_PriceAdjustmentReleases_Line"
    ON public."PriceAdjustmentReleases" ("PriceAdjustmentLineId");

CREATE INDEX IF NOT EXISTS "IX_PriceAdjustmentReleases_StockBatchId"
    ON public."PriceAdjustmentReleases" ("StockBatchId");


