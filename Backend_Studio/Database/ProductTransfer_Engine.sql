-- 1. The sync's sample table : a "ProductTransfer" table without
--    the real "TransferNo" column is dropped

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables
               WHERE table_schema = 'public' AND table_name = 'ProductTransfer')
       AND NOT EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = 'ProductTransfer' AND column_name = 'TransferNo') THEN
        DROP TABLE public."ProductTransfer" CASCADE;
        RAISE NOTICE 'The sample ProductTransfer table was dropped.';
    END IF;
END $$;


-- 2. Tables

CREATE TABLE IF NOT EXISTS public."ProductTransfers"
(
    "ProductTransferId"  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "TransferNo"         character varying(30)  NOT NULL,
    "SequenceNo"         integer                NOT NULL DEFAULT 0,
    "PageType"           character varying(2)   NOT NULL,
    "TransferDate"       date                   NOT NULL,
    "FromWarehouseId"    bigint                 NOT NULL,
    "FromBranchId"       bigint                 NOT NULL,
    "ToWarehouseId"      bigint                 NOT NULL,
    "ToBranchId"         bigint                 NOT NULL,
    "IsInterBranch"      boolean                NOT NULL DEFAULT false,
    "Remarks"            character varying(500) NOT NULL DEFAULT '',
    "Status"             character varying(20)  NOT NULL DEFAULT 'Draft',
    "LineCount"          integer                NOT NULL DEFAULT 0,
    "TotalQuantity"      numeric(18,4)          NOT NULL DEFAULT 0,
    "TotalValue"         numeric(18,2)          NOT NULL DEFAULT 0,
    "VoucherNo"          character varying(40)  NOT NULL DEFAULT '',
    "PostedBy"           bigint                 NULL,
    "PostedDate"         timestamp with time zone NULL,
    "ReceivedBy"         bigint                 NULL,
    "ReceivedDate"       timestamp with time zone NULL,
    "ReceiveDate"        date                   NULL,
    "CancelledBy"        bigint                 NULL,
    "CancelledDate"      timestamp with time zone NULL,
    "CancelReason"       character varying(500) NOT NULL DEFAULT '',
    "IsDeleted"          boolean                NOT NULL DEFAULT false,
    "DeletedBy"          bigint                 NULL,
    "DeletedDate"        timestamp with time zone NULL,
    "CreatedBy"          bigint                 NOT NULL,
    "CreatedDate"        timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"         bigint                 NULL,
    "ModifiedDate"       timestamp with time zone NULL,
    CONSTRAINT "CK_ProductTransfers_PageType"   CHECK ("PageType" IN ('MB', 'SP', 'AC')),
    CONSTRAINT "CK_ProductTransfers_Status"     CHECK ("Status" IN ('Draft', 'In Transit', 'Completed', 'Received', 'Cancelled')),
    CONSTRAINT "CK_ProductTransfers_Warehouses" CHECK ("FromWarehouseId" <> "ToWarehouseId")
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_ProductTransfers_TransferNo"
    ON public."ProductTransfers" ("TransferNo");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_ProductTransfers_Type_Sequence"
    ON public."ProductTransfers" ("PageType", "SequenceNo")
    WHERE "SequenceNo" > 0;

CREATE INDEX IF NOT EXISTS "IX_ProductTransfers_VoucherNo"
