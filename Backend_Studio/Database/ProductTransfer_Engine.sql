-- 3. CHECK constraints of the shared stock tables : the values
--    this page writes are added (rows already there are not
--    re-checked : NOT VALID). Only when the constraint exists.

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_constraint
               WHERE conname = 'CK_StockMovements_Type'
               AND   conrelid = 'public."StockMovements"'::regclass) THEN
        ALTER TABLE public."StockMovements" DROP CONSTRAINT "CK_StockMovements_Type";

        ALTER TABLE public."StockMovements"
            ADD CONSTRAINT "CK_StockMovements_Type" CHECK ("MovementType" IN
                ('Purchase', 'PurchaseCancel', 'Receive', 'ReceiveCancel', 'ShortSupply', 'PurchaseReturn',
                 'Sale', 'SaleReturn', 'TransferOut', 'TransferIn', 'Adjustment', 'Opening', 'OpeningCancel',
                 'Transfer', 'TransferSend', 'TransferReceive', 'TransferCancel'))
            NOT VALID;

        RAISE NOTICE 'CK_StockMovements_Type : transfer movement types added.';
    END IF;

    IF EXISTS (SELECT 1 FROM pg_constraint
               WHERE conname = 'CK_MotorBikeUnits_Status'
               AND   conrelid = 'public."MotorBikeUnits"'::regclass) THEN
        ALTER TABLE public."MotorBikeUnits" DROP CONSTRAINT "CK_MotorBikeUnits_Status";

        ALTER TABLE public."MotorBikeUnits"
            ADD CONSTRAINT "CK_MotorBikeUnits_Status"
            CHECK ("Status" IN ('Pending', 'InStock', 'InTransit', 'Sold', 'Returned', 'Transferred'))
            NOT VALID;

        RAISE NOTICE 'CK_MotorBikeUnits_Status : InTransit added.';
    END IF;
END $$;


-- 4. Page actions Post, Receive, Cancel
--    "Receive" is made when no live activity has that name

INSERT INTO "MasterActivities"
    ("SequenceNo", "Code", "Name", "DisplayOrder", "Remarks",
     "ActivityScope", "LinkToSwitchPages",
     "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
SELECT
    m.max_seq + 1,
    'ACT-' || lpad((m.max_seq + 1)::text, 4, '0'),
    'Receive',
    m.max_order + 1,
    'Receive a document sent to your branch (e.g. a product transfer in transit).',
    'Page',
    false,
    true,
    false,
    1,
    now()
FROM
(
    SELECT COALESCE(MAX("SequenceNo"), 0)   AS max_seq,
           COALESCE(MAX("DisplayOrder"), 0) AS max_order
    FROM   "MasterActivities"
) AS m
WHERE NOT EXISTS
(
    SELECT 1
    FROM   "MasterActivities" a
    WHERE  a."IsDeleted" = false
    AND    lower(trim(a."Name")) = 'receive'
);

INSERT INTO "MasterActivityPages" ("MasterActivityCode", "NavigationSubmenuCode", "CreatedBy")
SELECT a."Code", s."Code", 1
FROM   "MasterActivities" a
JOIN   "NavigationSubmenus" s
       ON s."Route" ILIKE '/inventory-management/%/product-transfer'
      AND s."IsDeleted" = false
WHERE  a."IsDeleted" = false
AND    a."ActivityScope" = 'Page'
AND    a."Name" IN ('Post', 'Receive', 'Cancel')
ON CONFLICT ("MasterActivityCode", "NavigationSubmenuCode") DO NOTHING;


-- 5. Auto Journal Registers : TRF journals under this page (only
--    when AutoJournalRegisters_Sources.sql has made the table; a
--    row that exists keeps its settings, an empty page code is
--    filled in)

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables
               WHERE table_schema = 'public' AND table_name = 'AutoJournalSources') THEN
        INSERT INTO public."AutoJournalSources"
            ("VoucherType", "SourceTable", "NavigationSubmenuCode", "IsAutoJournal", "DisplayOrder", "Remarks")
        SELECT 'TRF', 'ProductTransfers', COALESCE(s."Code", ''), true, 22, 'Product Transfer (between branches)'
        FROM   (SELECT 1) AS one
        LEFT   JOIN LATERAL
        (
            SELECT n."Code"
            FROM   "NavigationSubmenus" n
            WHERE  n."IsDeleted" = false
            AND    lower(n."Route") LIKE '%/product-transfer'
            ORDER  BY n."Id"
            LIMIT  1
        ) AS s ON true
        ON CONFLICT ("VoucherType", "SourceTable") DO UPDATE
        SET    "NavigationSubmenuCode" = EXCLUDED."NavigationSubmenuCode"
        WHERE  public."AutoJournalSources"."NavigationSubmenuCode" = ''
        AND    EXCLUDED."NavigationSubmenuCode" <> '';
    ELSE
        RAISE NOTICE 'AutoJournalSources does not exist yet : run AutoJournalRegisters_Sources.sql, then this script again.';
    END IF;
END $$;


