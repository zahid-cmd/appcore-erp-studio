-- ------------------------------------------------------------
-- 1. Tables
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."HrEmployeeMovements"
(
    "MovementId"          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"            uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"                character varying(20)    NOT NULL,
    "EmployeeId"          bigint                   NOT NULL,
    -- Increment / Promotion / Transfer / Confirmation / Separation
    "MovementType"        character varying(15)    NOT NULL,
    "EffectiveDate"       date                     NOT NULL,

    -- The employee before and after (the same on both sides when
    -- the movement did not change it)
    "OldBranchId"         bigint                   NOT NULL DEFAULT 0,
    "NewBranchId"         bigint                   NOT NULL DEFAULT 0,
    "OldDepartmentId"     bigint                   NOT NULL DEFAULT 0,
    "NewDepartmentId"     bigint                   NOT NULL DEFAULT 0,
    "OldDesignationId"    bigint                   NOT NULL DEFAULT 0,
    "NewDesignationId"    bigint                   NOT NULL DEFAULT 0,
    "OldShiftId"          bigint                   NOT NULL DEFAULT 0,
    "NewShiftId"          bigint                   NOT NULL DEFAULT 0,
    "OldEmploymentType"   character varying(15)    NOT NULL DEFAULT '',
    "NewEmploymentType"   character varying(15)    NOT NULL DEFAULT '',
    "OldConfirmationDate" date                     NULL,
    "OldGrossSalary"      numeric(18,2)            NOT NULL DEFAULT 0,
    "NewGrossSalary"      numeric(18,2)            NOT NULL DEFAULT 0,

    -- Separation : Resignation / Termination / Retirement /
    -- Contract End / Other; the final settlement agreed
    "SeparationType"      character varying(20)    NOT NULL DEFAULT '',
    "SettlementAmount"    numeric(18,2)            NOT NULL DEFAULT 0,
    "SettlementNote"      character varying(300)   NOT NULL DEFAULT '',

    "Remarks"             character varying(500)   NOT NULL DEFAULT '',
    "IsDeleted"           boolean                  NOT NULL DEFAULT false,
    "DeletedBy"           bigint                   NULL,
    "DeletedDate"         timestamp with time zone NULL,
    "CreatedBy"           bigint                   NOT NULL,
    "CreatedDate"         timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"          bigint                   NULL,
    "ModifiedDate"        timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrEmployeeMovements_PublicId" ON public."HrEmployeeMovements" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrEmployeeMovements_Code"     ON public."HrEmployeeMovements" ("Code");
CREATE INDEX        IF NOT EXISTS "IX_HrEmployeeMovements_Employee" ON public."HrEmployeeMovements" ("EmployeeId", "EffectiveDate");

-- The salary structure before and after (2026-11-14 : an increment
-- moves the employee to another salary structure;
-- HumanResource_SalaryStructures_Engine.sql adds the same columns
-- when this table was made before)
ALTER TABLE public."HrEmployeeMovements"
    ADD COLUMN IF NOT EXISTS "OldSalaryStructureId" bigint NULL,
    ADD COLUMN IF NOT EXISTS "NewSalaryStructureId" bigint NULL;


CREATE TABLE IF NOT EXISTS public."HrEmployeeMovementLines"
(
    "MovementLineId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "MovementId"     bigint        NOT NULL
        REFERENCES public."HrEmployeeMovements" ("MovementId") ON DELETE CASCADE,
    "SalaryHeadId"   bigint        NOT NULL,
    -- Tk per month
    "OldAmount"      numeric(18,2) NOT NULL DEFAULT 0,
    "NewAmount"      numeric(18,2) NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS "IX_HrEmployeeMovementLines_Movement" ON public."HrEmployeeMovementLines" ("MovementId");


-- ------------------------------------------------------------
-- 2. Page Employee Management > Employee Movements
-- ------------------------------------------------------------

DO $$
DECLARE
    v_module record;
    v_menu   record;
    v_seq    int;
BEGIN
    SELECT "Id", "SequenceNo", "RouteKey" INTO v_module
    FROM   "NavigationModules"
    WHERE  lower(trim("RouteKey")) = 'human-resource-manangement'
    AND    "IsDeleted" = false
    LIMIT  1;

    IF v_module."Id" IS NULL THEN
        RAISE EXCEPTION 'Module with route key human-resource-manangement not found - no page was added.';
    END IF;

    SELECT "Id", "SequenceNo", "RouteKey" INTO v_menu
    FROM   "NavigationMenus"
    WHERE  "NavigationModuleId" = v_module."Id"
    AND    lower(trim("RouteKey")) = 'employee-management'
    AND    "IsDeleted" = false
    LIMIT  1;

    IF v_menu."Id" IS NULL THEN
        RAISE EXCEPTION 'Menu employee-management not found : run HumanResource_Phase1_Engine.sql first.';
    END IF;

    IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
               WHERE "NavigationMenuId" = v_menu."Id"
               AND   lower(trim("RouteKey")) = 'employee-movements'
               AND   "IsDeleted" = false) THEN
        RAISE NOTICE 'Page exists, skipped : Employee Movements';
    ELSE
        IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
                   WHERE lower(trim("Name")) = 'employee movements' AND "IsDeleted" = false) THEN
            RAISE EXCEPTION 'A submenu named "Employee Movements" already exists elsewhere : names must be unique. Tell Claude.';
        END IF;

        SELECT COALESCE(MAX("SequenceNo"), 0) + 1 INTO v_seq
        FROM   "NavigationSubmenus"
        WHERE  "NavigationMenuId" = v_menu."Id";

        INSERT INTO "NavigationSubmenus"
            ("NavigationMenuId", "SequenceNo", "Code", "Name", "Icon",
             "RouteKey", "Route", "DisplayOrder", "Remarks",
             "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
        VALUES
            (v_menu."Id", v_seq,
             'SUB-' || lpad(v_module."SequenceNo"::text, 3, '0')
                    || '-' || lpad(v_menu."SequenceNo"::text, 3, '0')
                    || '-' || lpad(v_seq::text, 3, '0'),
             'Employee Movements', 'fa-solid fa-people-arrows',
             'employee-movements',
             '/' || v_module."RouteKey" || '/' || v_menu."RouteKey" || '/employee-movements',
             v_seq, 'Increment, promotion, transfer, confirmation and separation of employees. Hand-written page : never run Submenu / Code Sync.',
             true, false, 1, now());

        RAISE NOTICE 'Page created : Employee Movements';
    END IF;
END $$;


