-- 1. Print history

CREATE TABLE IF NOT EXISTS public."BarcodePrintRuns"
(
    "BarcodePrintRunId"  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ProductType"        character varying(5)   NOT NULL,
    "LabelKind"          character varying(20)  NOT NULL DEFAULT 'Label',
    "PaperCode"          character varying(20)  NOT NULL DEFAULT '',
    "SourceType"         character varying(20)  NOT NULL DEFAULT '',
    "SourceId"           bigint                 NOT NULL DEFAULT 0,
    "SourceNo"           character varying(60)  NOT NULL DEFAULT '',
    "StartAt"            integer                NOT NULL DEFAULT 1,
    "PrintMrp"           boolean                NOT NULL DEFAULT true,
    "LineCount"          integer                NOT NULL DEFAULT 0,
    "LabelCount"         integer                NOT NULL DEFAULT 0,
    "SheetCount"         integer                NOT NULL DEFAULT 0,
    "BranchId"           bigint                 NOT NULL DEFAULT 0,
    "PrintedBy"          bigint                 NOT NULL DEFAULT 1,
    "PrintedByName"      character varying(150) NOT NULL DEFAULT '',
    "PrintedDate"        timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT "CK_BarcodePrintRuns_Type" CHECK ("ProductType" IN ('MB', 'SP', 'AC'))
);

CREATE INDEX IF NOT EXISTS "IX_BarcodePrintRuns_Date"
    ON public."BarcodePrintRuns" ("ProductType", "PrintedDate" DESC);

CREATE TABLE IF NOT EXISTS public."BarcodePrintRunLines"
(
    "BarcodePrintRunLineId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BarcodePrintRunId"     bigint                 NOT NULL
                            REFERENCES public."BarcodePrintRuns" ("BarcodePrintRunId") ON DELETE CASCADE,
    "LineNo"                integer                NOT NULL,
    "StockBatchId"          bigint                 NOT NULL DEFAULT 0,
    "BatchNo"               character varying(40)  NOT NULL DEFAULT '',
    "ProductId"             bigint                 NOT NULL DEFAULT 0,
    "ProductCode"           character varying(40)  NOT NULL DEFAULT '',
    "ProductName"           character varying(250) NOT NULL DEFAULT '',
    "MotorBikeUnitId"       bigint                 NOT NULL DEFAULT 0,
    "ChassisNo"             character varying(50)  NOT NULL DEFAULT '',
    "Quantity"              integer                NOT NULL DEFAULT 1,
    "Mrp"                   numeric(18,2)          NOT NULL DEFAULT 0,
    "BarcodeValue"          character varying(60)  NOT NULL DEFAULT '',
    CONSTRAINT "CK_BarcodePrintRunLines_Qty" CHECK ("Quantity" > 0)
);

CREATE INDEX IF NOT EXISTS "IX_BarcodePrintRunLines_Run"
    ON public."BarcodePrintRunLines" ("BarcodePrintRunId");

CREATE INDEX IF NOT EXISTS "IX_BarcodePrintRunLines_Batch"
    ON public."BarcodePrintRunLines" ("StockBatchId");


-- 2. Switches

