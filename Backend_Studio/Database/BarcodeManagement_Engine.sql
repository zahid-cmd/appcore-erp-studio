--                        (A4-3x8 / A4-4x10 / A4-5x13 / Roll-38x25 / Roll-50x25)
--      CFG-MOD-012-0025  Keep Barcode Print History          ON
--    A switch that already exists is left as it is. The switches
--    are placed on the submenu by its code (SUB-012-004-002) : run
--    the Submenu Synchronization of the page first.
