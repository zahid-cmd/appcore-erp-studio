-- 2. Switches on the Barcode Management page :
--      CFG-MOD-012-0014  Print MRP on Labels                 ON
--      CFG-MOD-012-0015  MRP Text Format on Labels           ON  Text "MRP {0}"
--      CFG-MOD-012-0016  Show Product Name on Labels         ON
--      CFG-MOD-012-0017  Show Part Number on Labels          ON
--      CFG-MOD-012-0018  Show Brand on Labels                ON
--      CFG-MOD-012-0019  Brand on Labels As                  ON  Text "Name" (Name / Logo)
