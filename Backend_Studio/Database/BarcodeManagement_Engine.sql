(
    SELECT sm."Code", sm."NavigationMenuId"
    FROM   "NavigationSubmenus" sm
    WHERE  sm."Code" = 'SUB-012-004-002'
    AND    NOT sm."IsDeleted"
    LIMIT  1
) AS s
