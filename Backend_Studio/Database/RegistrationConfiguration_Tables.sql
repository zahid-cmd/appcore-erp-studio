-- ------------------------------------------------------------
-- 1. Registration Types
--    Plan : Installment (validity 2 years) / FullRegistration
--    (10 years). Mode : Online / Offline.
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."RegistrationTypes"
(
    "RegistrationTypeId"  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"            uuid                   NOT NULL DEFAULT uuidv7(),
    "Code"                character varying(20)  NOT NULL,
    "RegistrationPlan"    character varying(30)  NOT NULL,
    "ValidityYears"       integer                NOT NULL,
    "RegistrationMode"    character varying(20)  NOT NULL,
    "Name"                character varying(100) NOT NULL,
    "DisplayOrder"        integer                NOT NULL DEFAULT 0,
    "IsDefault"           boolean                NOT NULL DEFAULT false,
    "IsSystem"            boolean                NOT NULL DEFAULT false,
    "Remarks"             character varying(500) NOT NULL DEFAULT '',
    "IsActive"            boolean                NOT NULL DEFAULT true,

    "IsDeleted"           boolean                NOT NULL DEFAULT false,
    "DeletedBy"           bigint                 NULL,
    "DeletedDate"         timestamp with time zone NULL,
    "CreatedBy"           bigint                 NOT NULL,
    "CreatedDate"         timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"          bigint                 NULL,
    "ModifiedDate"        timestamp with time zone NULL,

    CONSTRAINT "CK_RegistrationTypes_Plan"
        CHECK ("RegistrationPlan" IN ('Installment', 'FullRegistration')),

    CONSTRAINT "CK_RegistrationTypes_Mode"
        CHECK ("RegistrationMode" IN ('Online', 'Offline')),

    CONSTRAINT "CK_RegistrationTypes_Validity"
        CHECK ("ValidityYears" > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_RegistrationTypes_PublicId"
    ON public."RegistrationTypes" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_RegistrationTypes_Code"
    ON public."RegistrationTypes" ("Code");


-- ------------------------------------------------------------
-- 2. Registration Fees (what the customer is charged)
--    A rate change is a NEW row with its own Effective From.
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."RegistrationFees"
(
    "RegistrationFeeId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"            uuid                   NOT NULL DEFAULT uuidv7(),
    "Code"                character varying(20)  NOT NULL,
    "RegistrationTypeId"  bigint                 NOT NULL
        REFERENCES public."RegistrationTypes" ("RegistrationTypeId"),
    "EffectiveFrom"       date                   NOT NULL,
    "MinimumCollection"   numeric(18,2)          NOT NULL,
    "MaximumCollection"   numeric(18,2)          NOT NULL,
    "Remarks"             character varying(500) NOT NULL DEFAULT '',
    "IsActive"            boolean                NOT NULL DEFAULT true,

    "IsDeleted"           boolean                NOT NULL DEFAULT false,
    "DeletedBy"           bigint                 NULL,
    "DeletedDate"         timestamp with time zone NULL,
    "CreatedBy"           bigint                 NOT NULL,
    "CreatedDate"         timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"          bigint                 NULL,
    "ModifiedDate"        timestamp with time zone NULL,

    CONSTRAINT "CK_RegistrationFees_Amounts"
        CHECK ("MinimumCollection" > 0 AND "MaximumCollection" >= "MinimumCollection")
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_RegistrationFees_PublicId"
    ON public."RegistrationFees" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_RegistrationFees_Code"
    ON public."RegistrationFees" ("Code");

-- One active rate per type and date
CREATE UNIQUE INDEX IF NOT EXISTS "UX_RegistrationFees_Type_Date"
    ON public."RegistrationFees" ("RegistrationTypeId", "EffectiveFrom")
    WHERE "IsDeleted" = false AND "IsActive" = true;


-- ------------------------------------------------------------
-- 3. Registration Costs (what the dealer pays out)
--    Posting : BRTA fee + submission -> BRTA Fees Payable;
--    tips -> BRTA Tips Payable; commission -> Registration
--    Commission Account (see decisions-registration-management).
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."RegistrationCosts"
(
    "RegistrationCostId"     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"               uuid                   NOT NULL DEFAULT uuidv7(),
    "Code"                   character varying(20)  NOT NULL,
    "RegistrationTypeId"     bigint                 NOT NULL
        REFERENCES public."RegistrationTypes" ("RegistrationTypeId"),
    "EffectiveFrom"          date                   NOT NULL,
    "BrtaFees"               numeric(18,2)          NOT NULL,
    "SubmissionCharges"      numeric(18,2)          NOT NULL DEFAULT 0,
    "BrtaTips"               numeric(18,2)          NOT NULL DEFAULT 0,
    "RegistrationCommission" numeric(18,2)          NOT NULL DEFAULT 0,
    "Remarks"                character varying(500) NOT NULL DEFAULT '',
    "IsActive"               boolean                NOT NULL DEFAULT true,

    "IsDeleted"              boolean                NOT NULL DEFAULT false,
    "DeletedBy"              bigint                 NULL,
    "DeletedDate"            timestamp with time zone NULL,
    "CreatedBy"              bigint                 NOT NULL,
    "CreatedDate"            timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"             bigint                 NULL,
    "ModifiedDate"           timestamp with time zone NULL,

    CONSTRAINT "CK_RegistrationCosts_Amounts"
        CHECK ("BrtaFees" > 0 AND "SubmissionCharges" >= 0
               AND "BrtaTips" >= 0 AND "RegistrationCommission" >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_RegistrationCosts_PublicId"
    ON public."RegistrationCosts" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_RegistrationCosts_Code"
    ON public."RegistrationCosts" ("Code");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_RegistrationCosts_Type_Date"
    ON public."RegistrationCosts" ("RegistrationTypeId", "EffectiveFrom")
    WHERE "IsDeleted" = false AND "IsActive" = true;


-- ------------------------------------------------------------
-- 4. Stage Timings : the 6 fixed registration statuses
--    (the status list is hard-coded in the program; only the
--    expected days, colour and remarks are edited here)
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."RegistrationStageTimings"
(
    "RegistrationStageTimingId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"            uuid                   NOT NULL DEFAULT uuidv7(),
    "Code"                character varying(20)  NOT NULL,
    "StageKey"            character varying(30)  NOT NULL,
    "StageName"           character varying(100) NOT NULL,
    "StageOrder"          integer                NOT NULL,
    "ExpectedDays"        integer                NULL,
    "ColorCode"           character varying(20)  NOT NULL DEFAULT '',
    "Remarks"             character varying(500) NOT NULL DEFAULT '',

    "CreatedBy"           bigint                 NOT NULL,
    "CreatedDate"         timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"          bigint                 NULL,
    "ModifiedDate"        timestamp with time zone NULL,

    CONSTRAINT "CK_RegistrationStageTimings_Key"
        CHECK ("StageKey" IN ('Pending', 'Processing', 'SubmittedToBrta',
                              'RegistrationCompleted', 'Delivered', 'Cancelled')),

    CONSTRAINT "CK_RegistrationStageTimings_Days"
        CHECK ("ExpectedDays" IS NULL OR ("ExpectedDays" >= 0 AND "ExpectedDays" <= 365))
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_RegistrationStageTimings_PublicId"
    ON public."RegistrationStageTimings" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_RegistrationStageTimings_Key"
    ON public."RegistrationStageTimings" ("StageKey");


-- ------------------------------------------------------------
-- 5. Starter rows
-- ------------------------------------------------------------

-- The 4 system registration types (cannot be deleted; plan and
-- mode locked). Installment System - Online is the default.
INSERT INTO public."RegistrationTypes"
    ("Code", "RegistrationPlan", "ValidityYears", "RegistrationMode", "Name",
     "DisplayOrder", "IsDefault", "IsSystem", "Remarks", "IsActive", "IsDeleted",
     "CreatedBy", "CreatedDate")
SELECT
    v.code, v.plan, v.years, v.mode, v.name,
    v.ord, v.is_default, true, '', true, false,
    1, now()
FROM
(
    VALUES
        ('RTY-001', 'Installment',      2,  'Online',  'Installment System - Online',          1, true),
        ('RTY-002', 'Installment',      2,  'Offline', 'Installment System - Offline',         2, false),
        ('RTY-003', 'FullRegistration', 10, 'Online',  'One Time Full Registration - Online',  3, false),
        ('RTY-004', 'FullRegistration', 10, 'Offline', 'One Time Full Registration - Offline', 4, false)
) AS v (code, plan, years, mode, name, ord, is_default)
WHERE NOT EXISTS
(
    SELECT 1
    FROM   public."RegistrationTypes" t
    WHERE  t."Code" = v.code
       OR  (lower(t."Name") = lower(v.name) AND t."IsDeleted" = false)
);


-- The 6 stages (expected days empty = no overdue check; set
-- them on the page)
INSERT INTO public."RegistrationStageTimings"
    ("Code", "StageKey", "StageName", "StageOrder", "ExpectedDays",
     "ColorCode", "Remarks", "CreatedBy", "CreatedDate")
SELECT
    v.code, v.stage_key, v.name, v.ord, NULL,
    v.color, v.remarks, 1, now()
FROM
(
    VALUES
        ('RST-001', 'Pending',               'Pending',                1, '#F59E0B', 'Sale saved; registration fee not yet fully collected.'),
        ('RST-002', 'Processing',            'Processing',             2, '#2563EB', 'Fee fully collected; Registration File opened; documents being prepared.'),
        ('RST-003', 'SubmittedToBrta',       'Submitted To BRTA',      3, '#8B5CF6', 'BRTA payment made and application submitted.'),
        ('RST-004', 'RegistrationCompleted', 'Registration Completed', 4, '#0D9488', 'BRTA acknowledgment slip received. Surplus posted; commission becomes payable.'),
        ('RST-005', 'Delivered',             'Delivered',              5, '#16A34A', 'Delivery Acknowledgement signed; the Registration File is closed.'),
        ('RST-006', 'Cancelled',             'Cancelled / Refunded',   6, '#DC2626', 'Registration fee refunded or forfeited.')
) AS v (code, stage_key, name, ord, color, remarks)
WHERE NOT EXISTS
(
    SELECT 1
    FROM   public."RegistrationStageTimings" s
    WHERE  s."StageKey" = v.stage_key
);


-- ------------------------------------------------------------
-- 6. Check
-- ------------------------------------------------------------

SELECT 'Types' AS "List", count(*) AS "Rows" FROM public."RegistrationTypes" WHERE "IsDeleted" = false
UNION ALL
SELECT 'Fees', count(*) FROM public."RegistrationFees" WHERE "IsDeleted" = false
UNION ALL
SELECT 'Costs', count(*) FROM public."RegistrationCosts" WHERE "IsDeleted" = false
UNION ALL
SELECT 'Stage Timings', count(*) FROM public."RegistrationStageTimings";
