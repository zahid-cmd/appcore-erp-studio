-- ============================================================
-- Registration Configuration : tables + starter rows (2026-11-08)
--
-- Registration Management > Registration Control >
-- Registration Configuration (hand-written page, 4 tabs) :
--
--   RegistrationTypes         RTY-nnn  plan + mode (no amounts)
--   RegistrationFees          RFE-nnn  min / max collection, dated
--   RegistrationCosts         RCO-nnn  BRTA fee, submission,
--                                      tips, commission, dated
--   RegistrationStageTimings  RST-nnn  the 6 fixed statuses :
--                                      expected days, colour
--
-- Hand-written page : NEVER run Submenu / Code Synchronization
-- for the submenu "Registration Configuration".
--
