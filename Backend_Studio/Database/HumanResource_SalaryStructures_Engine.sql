-- HumanResource_SalaryStructures_Engine.sql   (2026-11-14, percent)
-- ---------------------------------------------------------------------
-- Human Resource Management : salary structures
-- (hand-written page : NEVER run Submenu / Code Sync for it)
-- Run HumanResource_Phase1_Engine.sql first.
--
--   Human Resource Setup (existing menu)
--     Salary Structures
--       /human-resource-manangement/human-resource-setup/salary-structures
--
--   HrSalaryStructures       SST-001  a named split of the gross
--                                     salary : a percent for each
--                                     salary head. One structure is
--                                     the Default.
--   HrSalaryStructureLines            its lines (percent of the gross)
--
--   The Employee Profile takes the gross salary (Tk a month) and one
--   salary structure : HrEmployees.GrossSalary and
--   HrEmployees.SalaryStructureId. The employee's own lines
--   (HrEmployeeSalaryLines, used by payroll) are worked out from the
--   two; saving a structure works them out again for every employee
--   on it.
--   An increment (Employee Movements) changes the gross salary and /
--   or the structure (HrEmployeeMovements.Old / NewSalaryStructureId).
--
-- IMPORTANT : run this before opening Employee Profiles or Salary
-- Structures again : the program reads the new columns.
--
-- This script was first written with amounts (Tk) on the structure.
-- It now also changes a table made by that first version : the
-- amount columns go and the percent columns come. Structures saved
-- with amounts keep their name but lose their lines : open each one
-- and type the percents.
--
-- Employees saved before salary structures keep the salary lines
-- they have until their profile is saved with a gross salary and a
-- structure.
--
-- Safe to run again. Run the whole script (F5) on AppCoreERP_Studio.
--
-- AFTER : Security & Permission > Activity Assignment : tick View /
-- Add / Update / Delete / Restore on Salary Structures for the
-- roles, then log in again.
-- ASCII only.
-- =====================================================================

-- ------------------------------------------------------------
-- 1. Tables
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."HrSalaryStructures"
(
    "SalaryStructureId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"          uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"              character varying(20)    NOT NULL,
    "Name"              character varying(100)   NOT NULL,
    -- The earning lines added up (always 100) / the deduction lines
    -- added up, percent of the gross salary
    "EarningPercent"    numeric(7,3)             NOT NULL DEFAULT 0,
    "DeductionPercent"  numeric(7,3)             NOT NULL DEFAULT 0,
    -- The structure a new Employee Profile starts with (one only)
    "IsDefault"         boolean                  NOT NULL DEFAULT false,
    "Remarks"           character varying(500)   NOT NULL DEFAULT '',
    "IsActive"          boolean                  NOT NULL DEFAULT true,
    "IsDeleted"         boolean                  NOT NULL DEFAULT false,
    "DeletedBy"         bigint                   NULL,
    "DeletedDate"       timestamp with time zone NULL,
    "CreatedBy"         bigint                   NOT NULL,
    "CreatedDate"       timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"        bigint                   NULL,
    "ModifiedDate"      timestamp with time zone NULL
);

CREATE TABLE IF NOT EXISTS public."HrSalaryStructureLines"
(
    "SalaryStructureLineId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "SalaryStructureId"     bigint       NOT NULL
        REFERENCES public."HrSalaryStructures" ("SalaryStructureId") ON DELETE CASCADE,
    "SalaryHeadId"          bigint       NOT NULL,
    -- Percent of the gross salary
    "Percent"               numeric(7,3) NOT NULL DEFAULT 0
);


-- ------------------------------------------------------------
-- 2. From the first version (amounts) to percents
-- ------------------------------------------------------------

ALTER TABLE public."HrSalaryStructures"
    ADD COLUMN IF NOT EXISTS "EarningPercent"   numeric(7,3) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS "DeductionPercent" numeric(7,3) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS "IsDefault"        boolean      NOT NULL DEFAULT false;

ALTER TABLE public."HrSalaryStructures"
    DROP COLUMN IF EXISTS "GrossSalary",
    DROP COLUMN IF EXISTS "TotalDeductions";

DO $$
BEGIN
    -- lines typed as amounts mean nothing as percents : they go
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public'
               AND   table_name = 'HrSalaryStructureLines'
               AND   column_name = 'Amount') THEN

        DELETE FROM public."HrSalaryStructureLines";

        ALTER TABLE public."HrSalaryStructureLines" DROP COLUMN "Amount";

        RAISE NOTICE 'Salary structure lines typed as amounts were removed : type the percents on each structure.';
    END IF;
END $$;

ALTER TABLE public."HrSalaryStructureLines"
    ADD COLUMN IF NOT EXISTS "Percent" numeric(7,3) NOT NULL DEFAULT 0;

-- A deduction is worked out in one of three ways (2026-11-14) :
--   Gross  "Percent" of the gross salary (every earning is this)
--   Basic  "Percent" of the basic salary
--   Fixed  "FixedAmount" Tk a month
ALTER TABLE public."HrSalaryStructureLines"
    ADD COLUMN IF NOT EXISTS "Basis"       character varying(10) NOT NULL DEFAULT 'Gross',
    ADD COLUMN IF NOT EXISTS "FixedAmount" numeric(18,2)         NOT NULL DEFAULT 0;


-- ------------------------------------------------------------
-- 3. Indexes
-- ------------------------------------------------------------

CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrSalaryStructures_PublicId" ON public."HrSalaryStructures" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrSalaryStructures_Code"     ON public."HrSalaryStructures" ("Code");

-- one Default among live, active structures
CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrSalaryStructures_Default"
    ON public."HrSalaryStructures" ("IsDefault")
    WHERE "IsDefault" AND "IsActive" AND NOT "IsDeleted";

CREATE INDEX IF NOT EXISTS "IX_HrSalaryStructureLines_Structure"
    ON public."HrSalaryStructureLines" ("SalaryStructureId");


-- ------------------------------------------------------------
-- 4. The employee's salary structure; the structure before and
--    after a movement (when phase 4 was run already)
-- ------------------------------------------------------------

ALTER TABLE public."HrEmployees"
    ADD COLUMN IF NOT EXISTS "SalaryStructureId" bigint NULL;

CREATE INDEX IF NOT EXISTS "IX_HrEmployees_SalaryStructure"
    ON public."HrEmployees" ("SalaryStructureId");

ALTER TABLE IF EXISTS public."HrEmployeeMovements"
    ADD COLUMN IF NOT EXISTS "OldSalaryStructureId" bigint NULL,
    ADD COLUMN IF NOT EXISTS "NewSalaryStructureId" bigint NULL;


-- ------------------------------------------------------------
-- 5. Page Human Resource Setup > Salary Structures
-- ------------------------------------------------------------

DO $$
DECLARE
    v_module record;
    v_menu   record;
    v_seq    int;
BEGIN
    SELECT "Id", "SequenceNo", "RouteKey" INTO v_module
    FROM   "NavigationModules"
    WHERE  lower(trim("RouteKey")) = 'human-resource-manangement'
    AND    "IsDeleted" = false
    LIMIT  1;

    IF v_module."Id" IS NULL THEN
        RAISE EXCEPTION 'Module with route key human-resource-manangement not found - no page was added.';
    END IF;

    SELECT "Id", "SequenceNo", "RouteKey" INTO v_menu
    FROM   "NavigationMenus"
    WHERE  "NavigationModuleId" = v_module."Id"
    AND    lower(trim("RouteKey")) = 'human-resource-setup'
    AND    "IsDeleted" = false
    LIMIT  1;

    IF v_menu."Id" IS NULL THEN
        RAISE EXCEPTION 'Menu human-resource-setup not found - no page was added.';
    END IF;

    IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
               WHERE "NavigationMenuId" = v_menu."Id"
               AND   lower(trim("RouteKey")) = 'salary-structures'
               AND   "IsDeleted" = false) THEN
        RAISE NOTICE 'Page exists, skipped : Salary Structures';
    ELSE
        IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
                   WHERE lower(trim("Name")) = 'salary structures' AND "IsDeleted" = false) THEN
            RAISE EXCEPTION 'A submenu named "Salary Structures" already exists elsewhere : names must be unique. Tell Claude.';
        END IF;

        SELECT COALESCE(MAX("SequenceNo"), 0) + 1 INTO v_seq
        FROM   "NavigationSubmenus"
        WHERE  "NavigationMenuId" = v_menu."Id";

        INSERT INTO "NavigationSubmenus"
            ("NavigationMenuId", "SequenceNo", "Code", "Name", "Icon",
             "RouteKey", "Route", "DisplayOrder", "Remarks",
             "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
        VALUES
            (v_menu."Id", v_seq,
             'SUB-' || lpad(v_module."SequenceNo"::text, 3, '0')
                    || '-' || lpad(v_menu."SequenceNo"::text, 3, '0')
                    || '-' || lpad(v_seq::text, 3, '0'),
             'Salary Structures', 'fa-solid fa-layer-group',
             'salary-structures',
             '/' || v_module."RouteKey" || '/' || v_menu."RouteKey" || '/salary-structures',
             v_seq, 'How a gross salary is split : a percent for each salary head; picked on the Employee Profile. Hand-written page : never run Submenu / Code Sync.',
             true, false, 1, now());

        RAISE NOTICE 'Page created : Salary Structures';
    END IF;
END $$;


-- ------------------------------------------------------------
-- Check (run on its own)
-- ------------------------------------------------------------
SELECT s."Code", s."Name", s."Route"
FROM   "NavigationSubmenus" s
WHERE  lower(s."RouteKey") = 'salary-structures' AND s."IsDeleted" = false;

SELECT column_name, data_type
FROM   information_schema.columns
WHERE  table_schema = 'public'
AND    table_name IN ('HrSalaryStructures', 'HrSalaryStructureLines')
ORDER  BY table_name, ordinal_position;
