-- ============================================================
-- Auto Journal Registers : journal sources (2026-10-31)
--
-- Accounts & Finance › Accounting Registers › Auto Journal
-- Registers lists the journals that pages post by themselves
-- (purchases, reconciliations …) under the page that made them.
--
-- AutoJournalSources links a voucher type to its page BY CODE
-- (NavigationSubmenuCode); the page names on the register come
-- from Navigation, so renames follow.
--
--   VoucherType            prefix in VoucherEntries (PIMB, RRV …)
--   SourceTable            only when one voucher type is posted by
--                          several pages : the voucher belongs to
--                          the page whose table holds its number
--                          (column "VoucherNo")
--   NavigationSubmenuCode  the page (found here by its route)
--   IsAutoJournal          false = manual voucher, kept off the
--                          register (Receipt / Payment / Journal /
--                          Fund Transfer). Set true to show them.
--
-- A voucher type posted but not listed here shows under "Other".
-- A new posting page adds one row (same INSERT pattern).
--
-- Safe to run more than once : a row that exists keeps its
-- settings; only an empty page code is filled in.
-- Run the whole script (F5); then run the SELECT at the bottom
-- on its own.
-- ============================================================

BEGIN;

-- ------------------------------------------------------------
-- 1. Table
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."AutoJournalSources"
(
    "AutoJournalSourceId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "VoucherType"           character varying(10)  NOT NULL,
    "SourceTable"           character varying(100) NOT NULL DEFAULT '',
    "NavigationSubmenuCode" character varying(50)  NOT NULL DEFAULT '',
    "IsAutoJournal"         boolean                NOT NULL DEFAULT true,
    "DisplayOrder"          integer                NOT NULL DEFAULT 0,
    "Remarks"               character varying(250) NOT NULL DEFAULT '',
    "CreatedDate"           timestamp without time zone NOT NULL DEFAULT now(),
    CONSTRAINT "UX_AutoJournalSources_Type_Table" UNIQUE ("VoucherType", "SourceTable")
);

-- ------------------------------------------------------------
-- 2. Sources (page found by the end of its route)
-- ------------------------------------------------------------

INSERT INTO public."AutoJournalSources"
    ("VoucherType", "SourceTable", "NavigationSubmenuCode", "IsAutoJournal", "DisplayOrder", "Remarks")
SELECT
    v.voucher_type,
    v.source_table,
    COALESCE(s."Code", ''),
    v.is_auto,
    v.ord,
    v.remarks
FROM
(
    VALUES
        -- Procurement › Purchases
        (1,  'PIMB', '',                            '/purchases-mb',           true,  'Purchases - Motor Bikes'),
        (2,  'PISP', '',                            '/purchases-sp',           true,  'Purchases - Spare Parts & Lubricants'),
        (3,  'PIAC', '',                            '/purchases-ac',           true,  'Purchases - Accessories'),

        -- Accounts Reconciliation (RRV : cheque / MFS / POS; RRP : issued cheques)
        (11, 'RRV',  'CheckReconciliationVouchers', '/check-reconciliations',  true,  'Cheque clearing (received)'),
        (12, 'RRP',  'CheckReconciliationVouchers', '/check-reconciliations',  true,  'Cheque clearing (issued)'),
        (13, 'RRV',  'MfsReconciliationVouchers',   '/mfs-reconciliations',    true,  'MFS settlement'),
        (14, 'RRV',  'PosReconciliationVouchers',   '/pos-reconciliations',    true,  'POS settlement'),

        -- Manual vouchers : off the register
        (91, 'RV',   '',                            '/receipt-voucher',        false, 'Manual : Receipt Voucher'),
        (92, 'PV',   '',                            '/payment-voucher',        false, 'Manual : Payment Voucher'),
        (93, 'JV',   '',                            '/journal-voucher',        false, 'Manual : Journal Voucher'),
        (94, 'FT',   '',                            '/fund-transfer',          false, 'Manual : Fund Transfer')
) AS v (ord, voucher_type, source_table, route_end, is_auto, remarks)
LEFT JOIN LATERAL
(
    SELECT n."Code"
    FROM   "NavigationSubmenus" n
    WHERE  n."IsDeleted" = false
    AND    lower(n."Route") LIKE '%' || v.route_end
    ORDER  BY n."Id"
    LIMIT  1
) AS s ON true
ON CONFLICT ("VoucherType", "SourceTable") DO UPDATE
SET    "NavigationSubmenuCode" = EXCLUDED."NavigationSubmenuCode"
WHERE  public."AutoJournalSources"."NavigationSubmenuCode" = ''
AND    EXCLUDED."NavigationSubmenuCode" <> '';

COMMIT;


-- ------------------------------------------------------------
-- Check (run on its own) : every source, its page and route.
-- An empty Page means the route was not found : put the page's
-- code in "NavigationSubmenuCode" by hand.
-- ------------------------------------------------------------

SELECT j."VoucherType",
       j."SourceTable",
       j."NavigationSubmenuCode" AS "Submenu",
       COALESCE(s."Name", '')    AS "Page",
       COALESCE(s."Route", '')   AS "Route",
       j."IsAutoJournal",
       j."Remarks"
FROM   public."AutoJournalSources" j
LEFT   JOIN "NavigationSubmenus" s ON s."Code" = j."NavigationSubmenuCode" AND s."IsDeleted" = false
ORDER  BY j."DisplayOrder", j."VoucherType";
