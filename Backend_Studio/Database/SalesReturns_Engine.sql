    "DiscountSource"       character varying(20)    NOT NULL DEFAULT 'None',
    "CampaignMembershipAmount" numeric(18,2)        NOT NULL DEFAULT 0,
    "SpecialAmount"        numeric(18,2)            NOT NULL DEFAULT 0,
    "FractionalShare"      numeric(18,2)            NOT NULL DEFAULT 0,
    "LineTotal"            numeric(18,2)            NOT NULL DEFAULT 0,
