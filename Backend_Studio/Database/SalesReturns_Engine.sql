CREATE INDEX IF NOT EXISTS "IX_SalesReturnLines_Return" ON public."SalesReturnLines" ("SalesReturnId");

CREATE INDEX IF NOT EXISTS "IX_SalesReturnLines_InvoiceLine" ON public."SalesReturnLines" ("SalesInvoiceLineId");


-- ------------------------------------------------------------
-- 2. Auto Journal Registers : the return journals under their
--    pages (only when AutoJournalRegisters_Sources.sql was run)
-- ------------------------------------------------------------

DO $$
DECLARE
    p      record;
    v_code text;
BEGIN
    IF to_regclass('public."AutoJournalSources"') IS NULL THEN
        RAISE NOTICE 'AutoJournalSources not found : skipped (the returns show under Other).';
        RETURN;
    END IF;

    FOR p IN
        SELECT * FROM (VALUES
            ('SRMB', 'sales-returns-mb', 61),
            ('SRSP', 'sales-returns-sp', 62),
            ('SRAC', 'sales-returns-ac', 63)
        ) AS x (voucher_type, route_key, ord)
    LOOP
        SELECT s."Code" INTO v_code
        FROM   "NavigationSubmenus" s
        WHERE  s."Route" ILIKE '/sales-operations/%/' || p.route_key
        AND    NOT s."IsDeleted"
        LIMIT  1;

        INSERT INTO public."AutoJournalSources"
            ("VoucherType", "SourceTable", "NavigationSubmenuCode", "IsAutoJournal", "DisplayOrder", "Remarks")
        VALUES
            (p.voucher_type, '', COALESCE(v_code, ''), true, p.ord, 'Sales return : credit to the customer, stock back')
        ON CONFLICT ("VoucherType", "SourceTable") DO UPDATE
        SET "NavigationSubmenuCode" = EXCLUDED."NavigationSubmenuCode"
        WHERE public."AutoJournalSources"."NavigationSubmenuCode" = '';
    END LOOP;
END $$;


-- ------------------------------------------------------------
-- 3. Restock Returned Items : not used yet (text only)
-- ------------------------------------------------------------

UPDATE "SystemConfigurations"
SET    "Remarks" = 'Not used yet : returned items always go back to their batches (sellable). Held-as-Returned stock comes later.'
WHERE  "ConfigurationCode" IN ('CFG-MOD-008-0064', 'CFG-MOD-008-0068', 'CFG-MOD-008-0072')
AND    "Remarks" IS DISTINCT FROM 'Not used yet : returned items always go back to their batches (sellable). Held-as-Returned stock comes later.';


