    "ProductName"          character varying(250)   NOT NULL DEFAULT '',
    "Unit"                 character varying(30)    NOT NULL DEFAULT '',

    -- MB : the chassis
    "MotorBikeUnitId"      bigint                   NULL,
    "ChassisNo"            character varying(50)    NOT NULL DEFAULT '',
    "EngineNo"             character varying(50)    NOT NULL DEFAULT '',
    "ColorName"            character varying(50)    NOT NULL DEFAULT '',

    "SoldQuantity"         numeric(18,2)            NOT NULL DEFAULT 0,
    "Quantity"             numeric(18,2)            NOT NULL DEFAULT 0,
    "UnitPrice"            numeric(18,4)            NOT NULL DEFAULT 0,

    -- The invoice line's figures for this quantity
