-- ============================================================
-- Sales Returns - MB / SP / AC (2026-11-11)
--
-- The return pages are hand-written (NEVER run Code Sync for
-- them again : the placeholder tables SalesReturnsMb / Sp / Ac
-- stay unused).
--
-- One return = ONE posted sales invoice (owner) : the user finds
-- the invoice first, then returns quantities of its lines.
--
-- 1. SalesReturns + SalesReturnLines (ProductType MB / SP / AC).
--    Status : Draft -> Approved -> Posted, or Cancelled
--    (Post on Approval OFF : saving posts at once).
--    Posting (number SRMB / SRSP / SRAC) :
--      Cr the customer's receivable (always to the ledger; the
--         refund, if any, is a normal Payment Voucher)
--      Dr Sales, VAT, VAT Payable - MB, price diff, Cr discounts
--         (the invoice's figures, pro-rata of the quantity)
--      Dr Inventory / Cr COGS : the units back to the same
--         batches at their cost (movement SaleReturn)
--      VAT register : reversal rows (Credit Note, Mushak 6.7)
--      MB : whole chassis; refused once its registration was sent
--         to BRTA; its Registration Profile, Customer File and
--         delivery are cancelled, the bike is back in stock and
--         the registration fee is refunded to the customer.
-- 2. AutoJournalSources : SRMB / SRSP / SRAC under their pages
--    (only when the table exists).
-- 3. Switch "Restock Returned Items" (0064 / 0068 / 0072) : not
--    used yet (returned items always go back to stock); its
--    remark says so.
--
-- Safe to run again. ASCII only.
-- ============================================================

ROLLBACK;


-- ------------------------------------------------------------
-- 1. Tables
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."SalesReturns"
(
    "SalesReturnId"        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"             uuid                     NOT NULL DEFAULT uuidv7(),
    "ProductType"          character varying(2)     NOT NULL,
    -- '' until the first save takes the number
    "ReturnNo"             character varying(40)    NOT NULL DEFAULT '',
    "ReturnDate"           date                     NOT NULL,

    "BranchId"             bigint                   NOT NULL,
    "WarehouseId"          bigint                   NOT NULL DEFAULT 0,

    -- The one invoice returned from
    "SalesInvoiceId"       bigint                   NOT NULL,
    "SalesInvoiceNo"       character varying(50)    NOT NULL DEFAULT '',
    "SalesInvoiceDate"     date                     NOT NULL,

    "CustomerId"           bigint                   NOT NULL,
    "CustomerCode"         character varying(20)    NOT NULL DEFAULT '',
    "CustomerName"         character varying(200)   NOT NULL DEFAULT '',
    "CustomerPhone"        character varying(20)    NOT NULL DEFAULT '',
    "ReceivableLedgerCode" character varying(30)    NOT NULL DEFAULT '',

    "Reason"               character varying(500)   NOT NULL DEFAULT '',
    "Narration"            character varying(500)   NOT NULL DEFAULT '',

    "TotalQuantity"        numeric(18,2)            NOT NULL DEFAULT 0,
    "GrossAmount"          numeric(18,2)            NOT NULL DEFAULT 0,
    "DiscountAmount"       numeric(18,2)            NOT NULL DEFAULT 0,
    -- Goods returned (net of discounts)
    "ItemsAmount"          numeric(18,2)            NOT NULL DEFAULT 0,
    -- MB : registration fees refunded with the chassis
    "RegistrationRefund"   numeric(18,2)            NOT NULL DEFAULT 0,
    -- Credited to the customer's ledger
    "ReturnTotal"          numeric(18,2)            NOT NULL DEFAULT 0,
    "TotalVatInside"       numeric(18,2)            NOT NULL DEFAULT 0,
    "TotalBaseVat"         numeric(18,2)            NOT NULL DEFAULT 0,
    "CostAmount"           numeric(18,2)            NOT NULL DEFAULT 0,

    -- Draft / Approved / Posted / Cancelled
    "Status"               character varying(20)    NOT NULL DEFAULT 'Draft',
    "VoucherNo"            character varying(50)    NOT NULL DEFAULT '',
    "CancelReason"         character varying(500)   NOT NULL DEFAULT '',

    "ApprovedBy"           bigint                   NULL,
    "ApprovedDate"         timestamp with time zone NULL,
    "PostedBy"             bigint                   NULL,
    "PostedDate"           timestamp with time zone NULL,
    "CancelledBy"          bigint                   NULL,
    "CancelledDate"        timestamp with time zone NULL,

    "IsDeleted"            boolean                  NOT NULL DEFAULT false,
    "DeletedBy"            bigint                   NULL,
    "DeletedDate"          timestamp with time zone NULL,
    "CreatedBy"            bigint                   NOT NULL,
    "CreatedDate"          timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"           bigint                   NULL,
    "ModifiedDate"         timestamp with time zone NULL,

    CONSTRAINT "CK_SalesReturns_Type"   CHECK ("ProductType" IN ('MB', 'SP', 'AC')),
    CONSTRAINT "CK_SalesReturns_Status" CHECK ("Status" IN ('Draft', 'Approved', 'Posted', 'Cancelled'))
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_SalesReturns_PublicId" ON public."SalesReturns" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_SalesReturns_No" ON public."SalesReturns" ("ReturnNo") WHERE "ReturnNo" <> '';

CREATE INDEX IF NOT EXISTS "IX_SalesReturns_Type" ON public."SalesReturns" ("ProductType", "Status", "ReturnDate");

CREATE INDEX IF NOT EXISTS "IX_SalesReturns_Invoice" ON public."SalesReturns" ("ProductType", "SalesInvoiceId");


