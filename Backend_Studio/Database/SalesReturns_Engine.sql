       (SELECT count(*) FROM information_schema.tables WHERE table_schema = 'public' AND table_name IN ('SalesReturns', 'SalesReturnLines'))::text AS "Value"
UNION ALL
SELECT 'Return switches 0061-0072 (12; from SalesOperations_Switches.sql)',
       (SELECT count(*) FROM "SystemConfigurations" WHERE "ConfigurationCode" BETWEEN 'CFG-MOD-008-0061' AND 'CFG-MOD-008-0072' AND NOT "IsDeleted")::text;
