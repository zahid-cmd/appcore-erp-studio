-- =====================================================================
-- ServiceOperations_JobCard_Opening.sql   (2026-11-18)
-- ---------------------------------------------------------------------
-- The New Job page (the opening of a job card), owner 2026-11-18 :
--
--   JobCards              + PurchaseDate, LastServiceDate
--                           A bike sold by us : the sale date and the
--                           newest job card, from the records. A bike
--                           of another showroom : asked from the
--                           customer (a new bike, never serviced : the
--                           purchase date only).
--   WorkshopObservations  + IsDefault (the default observation)
--   JobCardObservations   what the opening desk sees on the bike : the
--                           observations of Workshop Configuration,
--                           each with a note (tab Observations).
--
-- Run ServiceOperations_JobCard_Stages.sql and
-- ServiceOperations_JobCard_Desks.sql first.
-- Safe to run more than once. Run the whole script (F5). ASCII only.
--
-- AFTER : restart the API.
-- =====================================================================

ALTER TABLE public."JobCards"
    ADD COLUMN IF NOT EXISTS "PurchaseDate"    date NULL,
    ADD COLUMN IF NOT EXISTS "LastServiceDate" date NULL;

CREATE TABLE IF NOT EXISTS public."JobCardObservations"
(
    "JobCardObservationId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "JobCardId"            bigint NOT NULL
        REFERENCES public."JobCards" ("JobCardId") ON DELETE CASCADE,
    "LineNo"               integer      NOT NULL DEFAULT 0,
    -- null : typed, not of the list
    "WorkshopObservationId" bigint      NULL,
    "Observation"          varchar(200) NOT NULL DEFAULT '',
    "Note"                 varchar(300) NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS "IX_JobCardObservations_JobCard" ON public."JobCardObservations" ("JobCardId");


-- ------------------------------------------------------------
-- The default observation (Workshop Configuration > Observations,
-- switch Default) : one only. A new job card and a new estimate
-- start with it.
-- ------------------------------------------------------------

ALTER TABLE public."WorkshopObservations"
    ADD COLUMN IF NOT EXISTS "IsDefault" boolean NOT NULL DEFAULT false;


-- ------------------------------------------------------------
-- Check (run on its own) : the two columns and the table
-- ------------------------------------------------------------
SELECT c.table_name, c.column_name, c.data_type
FROM   information_schema.columns c
WHERE  c.table_schema = 'public'
AND    (   (c.table_name = 'JobCards' AND c.column_name IN ('PurchaseDate', 'LastServiceDate'))
        OR  c.table_name = 'JobCardObservations')
ORDER  BY c.table_name, c.ordinal_position;
