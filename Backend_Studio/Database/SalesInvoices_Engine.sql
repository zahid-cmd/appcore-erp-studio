-- ------------------------------------------------------------
-- 1. The sync's sample table out (only while it has the sample
--    columns and not the real ones)
-- ------------------------------------------------------------

DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['SalesInvoicesSp']
    LOOP
        -- The generator names its columns in camelCase ("sampleField",
        -- "code" ...) : compared without case
        IF EXISTS (SELECT 1 FROM information_schema.tables
                   WHERE table_schema = 'public' AND table_name = t)
           AND EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = 'public' AND table_name = t
                   AND lower(column_name) IN ('samplefield', 'samplesearchdropdownid'))
           AND NOT EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = 'public' AND table_name = t AND column_name = 'InvoiceNo') THEN
            EXECUTE format('DROP TABLE public.%I CASCADE', t);
            RAISE NOTICE '% : the sample table was dropped', t;
        ELSIF EXISTS (SELECT 1 FROM information_schema.tables
                      WHERE table_schema = 'public' AND table_name = t)
              AND NOT EXISTS (SELECT 1 FROM information_schema.columns
                      WHERE table_schema = 'public' AND table_name = t AND column_name = 'InvoiceNo') THEN
            RAISE EXCEPTION 'Table % exists but is neither the sample table nor the sales invoice table : nothing changed. Tell Claude its columns.', t;
        END IF;
    END LOOP;
END $$;


