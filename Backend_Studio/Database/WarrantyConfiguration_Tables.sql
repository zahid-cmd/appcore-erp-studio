-- ============================================================
-- Warranty Configuration : tables + starter parts (2026-11-08)
--
-- Warranty Management > Warranty Control > Warranty
-- Configuration (hand-written page, 3 tabs) :
--
--   WarrantyParts       WPT-nnn  Battery, Motor, Controller ...
--   WarrantyPolicies    WPO-nnn  per brand (optional model) :
--                                Effective From / To, the
--                                whole-bike period + km limit,
--                                terms, exclusions
--   WarrantyCoverages   WCV-nnn  part-level warranty of a policy :
--                                one part, its period + km limit
--
-- New database : run this file only. An older database : run
-- WarrantyConfiguration_Redesign.sql, then
-- WarrantyConfiguration_PolicyPeriods.sql.
--
-- Hand-written page : NEVER run Submenu / Code Synchronization
-- for the submenu "Warranty Configuration".
--
-- Run it in a NEW pgAdmin Query Tool with F5. Safe to run again
-- (tables / rows that exist are skipped). ASCII only (WIN1252).
-- ============================================================


-- ------------------------------------------------------------
-- 1. Warranty Parts
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."WarrantyParts"
(
    "WarrantyPartId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"         uuid                   NOT NULL DEFAULT uuidv7(),
    "Code"             character varying(20)  NOT NULL,
    "Name"             character varying(100) NOT NULL,
    "DisplayOrder"     integer                NOT NULL DEFAULT 0,
    "Remarks"          character varying(500) NOT NULL DEFAULT '',
    "IsActive"         boolean                NOT NULL DEFAULT true,

    "IsDeleted"        boolean                NOT NULL DEFAULT false,
    "DeletedBy"        bigint                 NULL,
    "DeletedDate"      timestamp with time zone NULL,
    "CreatedBy"        bigint                 NOT NULL,
    "CreatedDate"      timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"       bigint                 NULL,
    "ModifiedDate"     timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_WarrantyParts_PublicId"
    ON public."WarrantyParts" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_WarrantyParts_Code"
    ON public."WarrantyParts" ("Code");


-- ------------------------------------------------------------
-- 2. Warranty Policies : the warranty of a brand (or one model
--    of it). BikeModelId empty = every model of the brand; a
--    model policy wins over the brand policy.
--    EffectiveTo empty = open-ended. Policies of the same brand /
--    model may not overlap in dates (checked by the page).
--    Period* = the whole-bike warranty : number + Days / Months /
--    Years, optional km limit (whichever ends first).
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."WarrantyPolicies"
(
    "WarrantyPolicyId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"           uuid                   NOT NULL DEFAULT uuidv7(),
    "Code"               character varying(20)  NOT NULL,
    "Name"               character varying(100) NOT NULL,
    "BrandManagementId"  bigint                 NOT NULL,
    "BikeModelId"        bigint                 NULL,
    "EffectiveFrom"      date                   NOT NULL,
    "EffectiveTo"        date                   NULL,
    "PeriodValue"        integer                NOT NULL,
    "PeriodUnit"         character varying(10)  NOT NULL,
    "KmLimit"            integer                NULL,
    "Terms"              text                   NOT NULL DEFAULT '',
    "Exclusions"         text                   NOT NULL DEFAULT '',
    "Remarks"            character varying(500) NOT NULL DEFAULT '',
    "IsActive"           boolean                NOT NULL DEFAULT true,

    "IsDeleted"          boolean                NOT NULL DEFAULT false,
    "DeletedBy"          bigint                 NULL,
    "DeletedDate"        timestamp with time zone NULL,
    "CreatedBy"          bigint                 NOT NULL,
    "CreatedDate"        timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"         bigint                 NULL,
    "ModifiedDate"       timestamp with time zone NULL,

    CONSTRAINT "CK_WarrantyPolicies_Unit"
        CHECK ("PeriodUnit" IN ('Days', 'Months', 'Years')),

    CONSTRAINT "CK_WarrantyPolicies_Period"
        CHECK ("PeriodValue" > 0),

    CONSTRAINT "CK_WarrantyPolicies_Dates"
        CHECK ("EffectiveTo" IS NULL OR "EffectiveTo" >= "EffectiveFrom")
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_WarrantyPolicies_PublicId"
    ON public."WarrantyPolicies" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_WarrantyPolicies_Code"
    ON public."WarrantyPolicies" ("Code");

CREATE INDEX IF NOT EXISTS "IX_WarrantyPolicies_Scope"
    ON public."WarrantyPolicies" ("BrandManagementId", "BikeModelId");


-- ------------------------------------------------------------
-- 3. Warranty Coverages : the part-level warranty of a policy,
--    one part each, once per policy. Period = number + Days /
--    Months / Years, optional km limit.
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."WarrantyCoverages"
(
    "WarrantyCoverageId"  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"            uuid                   NOT NULL DEFAULT uuidv7(),
    "Code"                character varying(20)  NOT NULL,
    "WarrantyPolicyId"    bigint                 NOT NULL
        REFERENCES public."WarrantyPolicies" ("WarrantyPolicyId"),
    "WarrantyPartId"      bigint                 NOT NULL
        REFERENCES public."WarrantyParts" ("WarrantyPartId"),
    "PeriodValue"         integer                NOT NULL,
    "PeriodUnit"          character varying(10)  NOT NULL,
    "KmLimit"             integer                NULL,
    "Notes"               character varying(200) NOT NULL DEFAULT '',
    "IsActive"            boolean                NOT NULL DEFAULT true,

    "IsDeleted"           boolean                NOT NULL DEFAULT false,
    "DeletedBy"           bigint                 NULL,
    "DeletedDate"         timestamp with time zone NULL,
    "CreatedBy"           bigint                 NOT NULL,
    "CreatedDate"         timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"          bigint                 NULL,
    "ModifiedDate"        timestamp with time zone NULL,

    CONSTRAINT "CK_WarrantyCoverages_Unit"
        CHECK ("PeriodUnit" IN ('Days', 'Months', 'Years')),

    CONSTRAINT "CK_WarrantyCoverages_Period"
        CHECK ("PeriodValue" > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_WarrantyCoverages_PublicId"
    ON public."WarrantyCoverages" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_WarrantyCoverages_Code"
    ON public."WarrantyCoverages" ("Code");

CREATE INDEX IF NOT EXISTS "IX_WarrantyCoverages_Policy"
    ON public."WarrantyCoverages" ("WarrantyPolicyId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_WarrantyCoverages_Policy_Part"
    ON public."WarrantyCoverages" ("WarrantyPolicyId", "WarrantyPartId")
    WHERE "IsDeleted" = false;


-- ------------------------------------------------------------
-- 4. Starter parts (only when the list is still empty)
-- ------------------------------------------------------------

INSERT INTO public."WarrantyParts" ("Code", "Name", "DisplayOrder", "Remarks", "IsActive", "CreatedBy")
SELECT x.code, x.name, x.ord, '', true, 1
FROM (VALUES
        ('WPT-001', 'Battery',          1),
        ('WPT-002', 'Motor',            2),
        ('WPT-003', 'Controller',       3),
        ('WPT-004', 'Charger',          4),
        ('WPT-005', 'Frame / Chassis',  5),
        ('WPT-006', 'Converter',        6),
        ('WPT-007', 'Display / Meter',  7)
     ) AS x (code, name, ord)
WHERE NOT EXISTS (SELECT 1 FROM public."WarrantyParts");


-- ------------------------------------------------------------
-- Check
-- ------------------------------------------------------------

SELECT 'WarrantyParts' AS table_name, COUNT(*) AS rows FROM public."WarrantyParts"
UNION ALL
SELECT 'WarrantyPolicies', COUNT(*) FROM public."WarrantyPolicies"
UNION ALL
SELECT 'WarrantyCoverages', COUNT(*) FROM public."WarrantyCoverages";
