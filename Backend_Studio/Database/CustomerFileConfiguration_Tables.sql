-- 1. Name Transfer rules ----------------------------------------

CREATE TABLE IF NOT EXISTS public."CustomerFileNameTransferRules"
(
    "NameTransferRuleId"  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"            uuid                   NOT NULL DEFAULT uuidv7(),
    "Code"                character varying(20)  NOT NULL,
    "EffectiveFrom"       date                   NOT NULL,
    "TransfersAllowed"    integer                NOT NULL,
    "FeePerTransfer"      numeric(18,2)          NOT NULL DEFAULT 0,
    "Remarks"             character varying(500) NOT NULL DEFAULT '',
    "IsActive"            boolean                NOT NULL DEFAULT true,

    "IsDeleted"           boolean                NOT NULL DEFAULT false,
    "DeletedBy"           bigint                 NULL,
    "DeletedDate"         timestamp with time zone NULL,
    "CreatedBy"           bigint                 NOT NULL,
    "CreatedDate"         timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"          bigint                 NULL,
    "ModifiedDate"        timestamp with time zone NULL,

    CONSTRAINT "CK_CustomerFileNameTransferRules_Values"
        CHECK ("TransfersAllowed" >= 0 AND "TransfersAllowed" <= 20 AND "FeePerTransfer" >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_CustomerFileNameTransferRules_PublicId"
    ON public."CustomerFileNameTransferRules" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_CustomerFileNameTransferRules_Code"
    ON public."CustomerFileNameTransferRules" ("Code");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_CustomerFileNameTransferRules_Date"
    ON public."CustomerFileNameTransferRules" ("EffectiveFrom")
    WHERE "IsDeleted" = false AND "IsActive" = true;


-- 2. File Delivery rules (custody charge) -----------------------
--    within Free Days : 0; then up to one year : FirstYearAmount
--    (once); 2nd year : SecondYearAmount (once); beyond 2 years :
--    years x PerYearAmount (a part year counts as a full year).

CREATE TABLE IF NOT EXISTS public."CustomerFileDeliveryRules"
(
    "DeliveryRuleId"      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"            uuid                   NOT NULL DEFAULT uuidv7(),
    "Code"                character varying(20)  NOT NULL,
    "EffectiveFrom"       date                   NOT NULL,
    "FreeDays"            integer                NOT NULL,
    "FirstYearAmount"     numeric(18,2)          NOT NULL DEFAULT 0,
    "SecondYearAmount"    numeric(18,2)          NOT NULL DEFAULT 0,
    "PerYearAmount"       numeric(18,2)          NOT NULL DEFAULT 0,
    "Remarks"             character varying(500) NOT NULL DEFAULT '',
    "IsActive"            boolean                NOT NULL DEFAULT true,

    "IsDeleted"           boolean                NOT NULL DEFAULT false,
    "DeletedBy"           bigint                 NULL,
    "DeletedDate"         timestamp with time zone NULL,
    "CreatedBy"           bigint                 NOT NULL,
    "CreatedDate"         timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"          bigint                 NULL,
    "ModifiedDate"        timestamp with time zone NULL,

    CONSTRAINT "CK_CustomerFileDeliveryRules_Values"
        CHECK ("FreeDays" >= 0 AND "FreeDays" <= 365
               AND "FirstYearAmount" >= 0 AND "SecondYearAmount" >= 0 AND "PerYearAmount" >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_CustomerFileDeliveryRules_PublicId"
    ON public."CustomerFileDeliveryRules" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_CustomerFileDeliveryRules_Code"
    ON public."CustomerFileDeliveryRules" ("Code");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_CustomerFileDeliveryRules_Date"
    ON public."CustomerFileDeliveryRules" ("EffectiveFrom")
    WHERE "IsDeleted" = false AND "IsActive" = true;


-- 3. Required documents (both tabs) -----------------------------

CREATE TABLE IF NOT EXISTS public."CustomerFileDocuments"
(
    "CustomerFileDocumentId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"            uuid                   NOT NULL DEFAULT uuidv7(),
    "DocumentFor"         character varying(20)  NOT NULL,
    "Code"                character varying(20)  NOT NULL,
    "Name"                character varying(150) NOT NULL,
    "IsRequired"          boolean                NOT NULL DEFAULT true,
    "DisplayOrder"        integer                NOT NULL DEFAULT 0,
    "Remarks"             character varying(500) NOT NULL DEFAULT '',
    "IsActive"            boolean                NOT NULL DEFAULT true,

    "IsDeleted"           boolean                NOT NULL DEFAULT false,
    "DeletedBy"           bigint                 NULL,
    "DeletedDate"         timestamp with time zone NULL,
    "CreatedBy"           bigint                 NOT NULL,
    "CreatedDate"         timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"          bigint                 NULL,
    "ModifiedDate"        timestamp with time zone NULL,

    CONSTRAINT "CK_CustomerFileDocuments_For"
        CHECK ("DocumentFor" IN ('NameTransfer', 'FileDelivery'))
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_CustomerFileDocuments_PublicId"
    ON public."CustomerFileDocuments" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_CustomerFileDocuments_Code"
    ON public."CustomerFileDocuments" ("Code");


-- 4. Starter documents (edit / deactivate them on the page) -----

INSERT INTO public."CustomerFileDocuments"
    ("DocumentFor", "Code", "Name", "IsRequired", "DisplayOrder", "Remarks",
     "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
SELECT v.doc_for, v.code, v.name, v.req, v.ord, '', true, false, 1, now()
FROM
(
    VALUES
        ('NameTransfer', 'NTD-001', 'NID of the new buyer',              true,  1),
        ('NameTransfer', 'NTD-002', 'NID of the original buyer',         true,  2),
        ('NameTransfer', 'NTD-003', 'Signed name transfer request',      true,  3),
        ('NameTransfer', 'NTD-004', 'Original sales invoice',            true,  4),
        ('FileDelivery', 'FDD-001', 'NID of the customer',               true,  1),
        ('FileDelivery', 'FDD-002', 'Delivery Acknowledgement Slip',     true,  2),
        ('FileDelivery', 'FDD-003', 'Authorization letter (if someone else collects)', false, 3)
) AS v (doc_for, code, name, req, ord)
WHERE NOT EXISTS
(
    SELECT 1
    FROM   public."CustomerFileDocuments" d
    WHERE  d."Code" = v.code
       OR  (d."DocumentFor" = v.doc_for AND lower(d."Name") = lower(v.name) AND d."IsDeleted" = false)
);


-- 5. Check ------------------------------------------------------

SELECT 'Name Transfer rules' AS "List", count(*) AS "Rows" FROM public."CustomerFileNameTransferRules" WHERE "IsDeleted" = false
UNION ALL
SELECT 'File Delivery rules', count(*) FROM public."CustomerFileDeliveryRules" WHERE "IsDeleted" = false
UNION ALL
SELECT 'Documents', count(*) FROM public."CustomerFileDocuments" WHERE "IsDeleted" = false;
