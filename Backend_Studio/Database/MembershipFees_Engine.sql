-- Membership Fees Collection (2026-11-11)
--
-- The page is hand-written now (NEVER run Code Sync for it
-- again : the template table "MembershipFeesCollection" stays
-- unused).
--
-- A Pending membership with a fee (Membership Status) is the
-- fee to collect; it needs no row. One row here = one
-- COLLECTION :
--   Paid      : collected by a posted Receipt Voucher (Payment
--               Desk) : Dr cash / bank / MFS / POS, Cr the card's
--               Membership Fees ledger; the membership is Active
--   Cancelled : the collection was cancelled (its Receipt
--               Voucher cancelled; only while nothing was used);
--               the membership is Pending again
--   Refunded  : the membership was cancelled unused; the whole
--               fee is credited to the customer's ledger by a
--               posted Journal Voucher (Dr Membership Fees - card
--               / Cr the customer)
-- "Used" = a free service taken, or a member discount on a
-- posted / approved sales invoice.
--
-- FeeType : Enrollment now; Renewal / Upgrade later.
--
-- Safe to run again. ASCII only. Needs PostgreSQL 18 (uuidv7).
-- ============================================================

ROLLBACK;


CREATE TABLE IF NOT EXISTS public."MembershipFees"
(
    "MembershipFeeId"        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"               uuid                     NOT NULL DEFAULT uuidv7(),
    -- MFC-000001
    "FeeNo"                  character varying(20)    NOT NULL,
    "FeeType"                character varying(20)    NOT NULL DEFAULT 'Enrollment',

    "MembershipId"           bigint                   NOT NULL,
    "MembershipNo"           character varying(30)    NOT NULL DEFAULT '',
    "MembershipCardId"       bigint                   NOT NULL,
    "CardName"               character varying(100)   NOT NULL DEFAULT '',
    "FeeLedgerCode"          character varying(30)    NOT NULL DEFAULT '',
    "CustomerId"             bigint                   NOT NULL,
    "CustomerCode"           character varying(20)    NOT NULL DEFAULT '',
    "CustomerName"           character varying(200)   NOT NULL DEFAULT '',
    "ChassisNo"              character varying(50)    NOT NULL DEFAULT '',

    "Amount"                 numeric(18,2)            NOT NULL DEFAULT 0,
    "CollectedDate"          date                     NOT NULL,
    "BranchId"               bigint                   NOT NULL,
    "Narration"              character varying(500)   NOT NULL DEFAULT '',
    "ReceiptVoucherId"       bigint                   NULL,
    "ReceiptVoucherNo"       character varying(50)    NOT NULL DEFAULT '',

    -- Paid / Cancelled / Refunded
    "Status"                 character varying(20)    NOT NULL DEFAULT 'Paid',

    "CancelReason"           character varying(500)   NOT NULL DEFAULT '',
    "CancelledBy"            bigint                   NULL,
    "CancelledDate"          timestamp with time zone NULL,

    "RefundDate"             date                     NULL,
    "RefundReason"           character varying(500)   NOT NULL DEFAULT '',
    "RefundJournalVoucherId" bigint                   NULL,
    "RefundJournalVoucherNo" character varying(50)    NOT NULL DEFAULT '',
    "RefundedBy"             bigint                   NULL,

    "CreatedBy"              bigint                   NOT NULL,
    "CreatedDate"            timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"             bigint                   NULL,
    "ModifiedDate"           timestamp with time zone NULL,

    CONSTRAINT "CK_MembershipFees_Status" CHECK ("Status" IN ('Paid', 'Cancelled', 'Refunded'))
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_MembershipFees_PublicId" ON public."MembershipFees" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_MembershipFees_No" ON public."MembershipFees" ("FeeNo");

CREATE INDEX IF NOT EXISTS "IX_MembershipFees_Membership" ON public."MembershipFees" ("MembershipId", "Status");


SELECT 'MembershipFees table (1)' AS "Item",
       (SELECT count(*) FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'MembershipFees')::text AS "Value";
