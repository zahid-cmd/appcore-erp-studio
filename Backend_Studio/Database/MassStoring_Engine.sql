-- 1. The sync's sample table : a "MassStoring" table without the
--    real "StoringNo" column is dropped

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables
               WHERE table_schema = 'public' AND table_name = 'MassStoring')
       AND NOT EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = 'MassStoring' AND column_name = 'StoringNo') THEN
        DROP TABLE public."MassStoring" CASCADE;
        RAISE NOTICE 'The sample MassStoring table was dropped.';
    END IF;
END $$;


-- 2. Tables

CREATE TABLE IF NOT EXISTS public."MassStorings"
(
    "MassStoringId"      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "StoringNo"          character varying(30)  NOT NULL,
    "SequenceNo"         integer                NOT NULL DEFAULT 0,
    "PageType"           character varying(2)   NOT NULL,
    "StoringDate"        date                   NOT NULL,
    "BranchId"           bigint                 NOT NULL,
    "WarehouseId"        bigint                 NOT NULL,
    "Remarks"            character varying(500) NOT NULL DEFAULT '',
    "Status"             character varying(20)  NOT NULL DEFAULT 'Draft',
    "LineCount"          integer                NOT NULL DEFAULT 0,
    "PostedBy"           bigint                 NULL,
    "PostedDate"         timestamp with time zone NULL,
    "CancelledBy"        bigint                 NULL,
    "CancelledDate"      timestamp with time zone NULL,
    "CancelReason"       character varying(500) NOT NULL DEFAULT '',
    "IsDeleted"          boolean                NOT NULL DEFAULT false,
    "DeletedBy"          bigint                 NULL,
    "DeletedDate"        timestamp with time zone NULL,
    "CreatedBy"          bigint                 NOT NULL,
    "CreatedDate"        timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"         bigint                 NULL,
    "ModifiedDate"       timestamp with time zone NULL,
    CONSTRAINT "CK_MassStorings_PageType" CHECK ("PageType" IN ('SP', 'AC')),
    CONSTRAINT "CK_MassStorings_Status"   CHECK ("Status" IN ('Draft', 'Posted', 'Cancelled'))
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_MassStorings_StoringNo"
    ON public."MassStorings" ("StoringNo");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_MassStorings_Type_Sequence"
    ON public."MassStorings" ("PageType", "SequenceNo")
    WHERE "SequenceNo" > 0;

CREATE INDEX IF NOT EXISTS "IX_MassStorings_Warehouse_Status"
    ON public."MassStorings" ("WarehouseId", "Status");


CREATE TABLE IF NOT EXISTS public."MassStoringLines"
(
    "MassStoringLineId"  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "MassStoringId"      bigint                 NOT NULL REFERENCES public."MassStorings" ("MassStoringId") ON DELETE CASCADE,
    "LineNo"             integer                NOT NULL,
    "ProductId"          bigint                 NOT NULL,
    "ProductCode"        character varying(40)  NOT NULL DEFAULT '',
    "ProductName"        character varying(250) NOT NULL DEFAULT '',
    "PartNumber"         character varying(100) NOT NULL DEFAULT '',
    "Unit"               character varying(20)  NOT NULL DEFAULT '',
    "FromRackId"         bigint                 NULL,
    "FromShelfNo"        integer                NULL,
    "ToRackId"           bigint                 NULL,
    "ToShelfNo"          integer                NULL,
    "StockQuantity"      numeric(18,4)          NOT NULL DEFAULT 0,
    "Notes"              character varying(200) NOT NULL DEFAULT '',
    -- A new place needs both the rack and the shelf; Unplaced has
    -- neither
    CONSTRAINT "CK_MassStoringLines_To" CHECK
        (("ToRackId" IS NULL AND "ToShelfNo" IS NULL) OR ("ToRackId" IS NOT NULL AND "ToShelfNo" IS NOT NULL))
);

-- One line per product per document
CREATE UNIQUE INDEX IF NOT EXISTS "UX_MassStoringLines_Storing_Product"
    ON public."MassStoringLines" ("MassStoringId", "ProductId");

CREATE INDEX IF NOT EXISTS "IX_MassStoringLines_ProductId"
    ON public."MassStoringLines" ("ProductId");


-- 3. Page actions Post and Cancel (the page found by its route)

INSERT INTO "MasterActivityPages" ("MasterActivityCode", "NavigationSubmenuCode", "CreatedBy")
SELECT a."Code", s."Code", 1
FROM   "MasterActivities" a
JOIN   "NavigationSubmenus" s
       ON s."Route" ILIKE '%/stock-movement/mass-storing%'
      AND s."IsDeleted" = false
WHERE  a."IsDeleted" = false
AND    a."ActivityScope" = 'Page'
AND    a."Name" IN ('Post', 'Cancel')
ON CONFLICT ("MasterActivityCode", "NavigationSubmenuCode") DO NOTHING;


