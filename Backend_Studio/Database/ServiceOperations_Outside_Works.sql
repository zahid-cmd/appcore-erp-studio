-- Service Operations : the list of outside works.
--
--   WorkshopOutsideWorks   OW-0001 : a work done outside the workshop
--                          ("Lathe work", "Chassis straightening") with
--                          its usual charge to the customer. Kept in
--                          Workshop Configuration, tab Outside Works.
--
-- On the service estimate and the job card the button Outside Works
-- opens this list : the work is picked, not typed, and its charge can
-- be changed on the line. A work that is not in the list is added in
-- Workshop Configuration (the + button beside the list goes there).
--
-- No new page. Hand-written pages : NEVER run Menu / Submenu / Code
-- Sync for them.
--
-- Run ServiceOperations_Workshop_Engine.sql first.
-- Safe to run more than once. Run the whole script (F5). ASCII only.
--
-- AFTER : restart the API.
-- =====================================================================

CREATE TABLE IF NOT EXISTS public."WorkshopOutsideWorks"
(
    "WorkshopOutsideWorkId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"              uuid                     NOT NULL DEFAULT gen_random_uuid(),
    "Code"                  character varying(20)    NOT NULL,
    "Name"                  character varying(150)   NOT NULL,
    "Rate"                  numeric(18,2)            NOT NULL DEFAULT 0,
    "Remarks"               character varying(500)   NOT NULL DEFAULT '',
    "IsActive"              boolean                  NOT NULL DEFAULT true,
    "IsDeleted"             boolean                  NOT NULL DEFAULT false,
    "DeletedBy"             bigint                   NULL,
    "DeletedDate"           timestamp with time zone NULL,
    "CreatedBy"             bigint                   NOT NULL,
    "CreatedDate"           timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"            bigint                   NULL,
    "ModifiedDate"          timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_WorkshopOutsideWorks_PublicId" ON public."WorkshopOutsideWorks" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_WorkshopOutsideWorks_Code"     ON public."WorkshopOutsideWorks" ("Code");


-- ------------------------------------------------------------
-- Check (run on its own)
-- ------------------------------------------------------------
SELECT w."Code", w."Name", w."Rate", w."IsActive"
FROM   public."WorkshopOutsideWorks" w
WHERE  w."IsDeleted" = false
ORDER  BY w."Code";
