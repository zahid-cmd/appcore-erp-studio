-- Leave Encashment Policies (Human Resource Setup), and the Employee
-- Profile's own bonus structure / encashment policy.
--
-- LEAVE ENCASHMENT POLICIES
--   HrLeaveEncashPolicies      LEP-0001 "Encashment Policy - 1" ...;
--                              one is the Default.
--                                RateBase          Basic / Gross
--                                MonthDays         day rate = salary /
--                                                  this
--                                ConfirmedOnly     confirmed employees
--                                MinServiceMonths  service needed
--                                MaxDaysPerYear    most days a leave
--                                                  year (0 = no limit)
--                                KeepDays          days that must stay
--                                                  in the balance
--                                AfterYearEnd      only a leave year
--                                                  that has ended
--   HrLeaveEncashPolicyTypes   the leave types the policy lets encash
--
--   A leave encashment depends on the leave balance, and is paid
--   on a year basis : once a leave year for a leave type, for the
--   days the employee has left of it (less the days that must stay,
--   within the yearly limit of the policy). No balance : nothing.
--
-- WHICH POLICY / STRUCTURE AN EMPLOYEE HAS
--   The Default applies to everyone. An Employee Profile can name its
--   own :
--       HrEmployees."LeaveEncashPolicyId"   (NULL = the Default)
--       HrEmployees."BonusStructureId"      (NULL = the Default)
--   A festival bonus sheet works each employee out by that employee's
--   bonus structure.
--
-- Run AFTER HumanResource_BonusStructures_Engine.sql. Safe to run more
-- than once. ASCII only.
-- =====================================================================


-- ------------------------------------------------------------
-- 1. Tables
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."HrLeaveEncashPolicies"
(
    "LeaveEncashPolicyId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"            uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"                character varying(20)    NOT NULL,
    "Name"                character varying(100)   NOT NULL,
    -- Basic / Gross
    "RateBase"            character varying(10)    NOT NULL DEFAULT 'Basic',
    "MonthDays"           integer                  NOT NULL DEFAULT 30,
    "ConfirmedOnly"       boolean                  NOT NULL DEFAULT false,
    "MinServiceMonths"    integer                  NOT NULL DEFAULT 0,
    -- 0 = no limit
    "MaxDaysPerYear"      numeric(6,2)             NOT NULL DEFAULT 0,
    "KeepDays"            numeric(6,2)             NOT NULL DEFAULT 0,
    "AfterYearEnd"        boolean                  NOT NULL DEFAULT false,
    "IsDefault"           boolean                  NOT NULL DEFAULT false,
    "Remarks"             character varying(500)   NOT NULL DEFAULT '',
    "IsActive"            boolean                  NOT NULL DEFAULT true,
    "IsDeleted"           boolean                  NOT NULL DEFAULT false,
    "DeletedBy"           bigint                   NULL,
    "DeletedDate"         timestamp with time zone NULL,
    "CreatedBy"           bigint                   NOT NULL,
    "CreatedDate"         timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"          bigint                   NULL,
    "ModifiedDate"        timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrLeaveEncashPolicies_PublicId" ON public."HrLeaveEncashPolicies" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrLeaveEncashPolicies_Code"     ON public."HrLeaveEncashPolicies" ("Code");

CREATE TABLE IF NOT EXISTS public."HrLeaveEncashPolicyTypes"
(
    "LeaveEncashPolicyTypeId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "LeaveEncashPolicyId"     bigint NOT NULL
        REFERENCES public."HrLeaveEncashPolicies" ("LeaveEncashPolicyId") ON DELETE CASCADE,
    "LeaveTypeId"             bigint NOT NULL
);

CREATE INDEX IF NOT EXISTS "IX_HrLeaveEncashPolicyTypes_Policy" ON public."HrLeaveEncashPolicyTypes" ("LeaveEncashPolicyId");


-- ------------------------------------------------------------
-- 2. The Employee Profile's own policy / structure; what an
--    encashment and a bonus line were worked out with
-- ------------------------------------------------------------

ALTER TABLE public."HrEmployees"
    ADD COLUMN IF NOT EXISTS "LeaveEncashPolicyId" bigint NULL,
    ADD COLUMN IF NOT EXISTS "BonusStructureId"    bigint NULL;

ALTER TABLE public."HrLeaveEncashments"
    ADD COLUMN IF NOT EXISTS "LeaveEncashPolicyId" bigint                 NULL,
    ADD COLUMN IF NOT EXISTS "PolicyName"          character varying(100) NOT NULL DEFAULT '';

ALTER TABLE public."HrBonusSheetLines"
    ADD COLUMN IF NOT EXISTS "StructureName" character varying(100) NOT NULL DEFAULT '';


-- ------------------------------------------------------------
-- 3. A first policy (only when there is none) : on Basic / 30, for
--    the leave types marked Encashable before policies
-- ------------------------------------------------------------

DO $$
DECLARE
    v_id bigint;
BEGIN
    IF EXISTS (SELECT 1 FROM public."HrLeaveEncashPolicies") THEN
        RAISE NOTICE 'Leave encashment policies exist : no starter policy added.';
        RETURN;
    END IF;

    INSERT INTO public."HrLeaveEncashPolicies"
        ("Code", "Name", "RateBase", "MonthDays", "ConfirmedOnly", "MinServiceMonths", "MaxDaysPerYear", "KeepDays",
         "AfterYearEnd", "IsDefault", "Remarks", "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
    VALUES
        ('LEP-0001', 'Encashment Policy - 1', 'Basic', 30, false, 0, 0, 0,
         false, true, 'Starter policy : change it to your rule.', true, false, 1, now())
    RETURNING "LeaveEncashPolicyId" INTO v_id;

    INSERT INTO public."HrLeaveEncashPolicyTypes" ("LeaveEncashPolicyId", "LeaveTypeId")
    SELECT v_id, t."LeaveTypeId"
    FROM   public."HrLeaveTypes" t
    WHERE  t."IsDeleted" = false AND t."IsEncashable" = true;

    RAISE NOTICE 'Starter policy added : LEP-0001 Encashment Policy - 1 (Default). Tick its leave types on the page.';
END $$;


-- ------------------------------------------------------------
-- 4. Page : Leave Encashment Policies (Human Resource Setup)
-- ------------------------------------------------------------

DO $$
DECLARE
    v_module   record;
    v_menu     record;
    v_seq      int;
    v_code     text;
BEGIN
    SELECT "Id", "SequenceNo", "RouteKey" INTO v_module
    FROM   "NavigationModules"
    WHERE  lower(trim("RouteKey")) = 'human-resource-manangement'
    AND    "IsDeleted" = false
    LIMIT  1;

    IF v_module."Id" IS NULL THEN
        RAISE EXCEPTION 'Module with route key human-resource-manangement not found - no page was added.';
    END IF;

    SELECT "Id", "SequenceNo", "RouteKey" INTO v_menu
    FROM   "NavigationMenus"
    WHERE  "NavigationModuleId" = v_module."Id"
    AND    lower(trim("RouteKey")) = 'human-resource-setup'
    AND    "IsDeleted" = false
    LIMIT  1;

    IF v_menu."Id" IS NULL THEN
        RAISE EXCEPTION 'Menu human-resource-setup not found - no page was added.';
    END IF;

    IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
               WHERE "NavigationMenuId" = v_menu."Id"
               AND   lower(trim("RouteKey")) = 'leave-encashment-policies'
               AND   "IsDeleted" = false) THEN
        RAISE NOTICE 'Page exists, skipped : Leave Encashment Policies';
        RETURN;
    END IF;

    IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
               WHERE lower(trim("Name")) = 'leave encashment policies' AND "IsDeleted" = false) THEN
        RAISE EXCEPTION 'A submenu named "Leave Encashment Policies" already exists elsewhere : names must be unique. Tell Claude.';
    END IF;

    SELECT COALESCE(MAX("SequenceNo"), 0) + 1 INTO v_seq
    FROM   "NavigationSubmenus"
    WHERE  "NavigationMenuId" = v_menu."Id";

    v_code :=
        'SUB-' || lpad(v_module."SequenceNo"::text, 3, '0')
               || '-' || lpad(v_menu."SequenceNo"::text, 3, '0')
               || '-' || lpad(v_seq::text, 3, '0');

    INSERT INTO "NavigationSubmenus"
        ("NavigationMenuId", "SequenceNo", "Code", "Name", "Icon",
         "RouteKey", "Route", "DisplayOrder", "Remarks",
         "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
    VALUES
        (v_menu."Id", v_seq, v_code, 'Leave Encashment Policies', 'fa-solid fa-calendar-check',
         'leave-encashment-policies',
         '/' || v_module."RouteKey" || '/' || v_menu."RouteKey" || '/leave-encashment-policies',
         v_seq, 'The rules of leave encashment : which leave, on what salary, who, and how many days. Hand-written page : never run Submenu / Code Sync.',
         true, false, 1, now());

    RAISE NOTICE 'Page created : % Leave Encashment Policies', v_code;
END $$;


-- ------------------------------------------------------------
-- Check (run on its own)
-- ------------------------------------------------------------
SELECT p."Code", p."Name", p."RateBase", p."MonthDays", p."IsDefault",
       (SELECT string_agg(t."Name", ', ' ORDER BY t."Name")
        FROM   public."HrLeaveEncashPolicyTypes" x
        JOIN   public."HrLeaveTypes" t ON t."LeaveTypeId" = x."LeaveTypeId"
        WHERE  x."LeaveEncashPolicyId" = p."LeaveEncashPolicyId") AS "LeaveTypes"
FROM   public."HrLeaveEncashPolicies" p
WHERE  p."IsDeleted" = false
ORDER  BY p."Code";
