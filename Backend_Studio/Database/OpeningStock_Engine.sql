-- ============================================================
-- Opening Stock : tables, bikes, batches, actions, journal
-- source (2026-11-01; numbering, MRP / cost basis added the same
-- day). Run after ProductReceiving_Engine.sql.
--
-- Opening Voucher No : OS-<branch code>-<MB|SP|AC>-0001, per
-- branch and type, never reset, never reused (SequenceNo).
--
-- 1. Tables
--      OpeningStock        header (one warehouse + one type)
--      OpeningStockLines   one row per product
--    The empty baseline table made by the page generator is
--    replaced. A table that already has the real columns is left
--    as it is.
-- 2. MotorBikeUnits : + OpeningStockId. An opening bike has no
--    purchase (PurchaseId / PurchaseLineId = 0), so the foreign
--    keys to PurchasesMb / PurchasesMbLines are taken off (the
--    purchase page removes its own bikes itself) and a check
--    keeps every bike tied to a purchase or an opening stock.
-- 3. StockBatches : + Mrp (VAT inclusive). MRP is the sale
--    price : no separate SalePrice column.
-- 4. Page actions Post and Cancel linked to the Opening Stock
--    page (Add, Edit, Delete, View, Print are common actions).
-- 5. Auto Journal Registers : OPMB / OPSP / OPAC under the page.
-- 6. Switch CFG-MOD-012-0006 Lock Opening Stock Ledger (critical,
--    ON by default : the credit ledger is the Posting Setup one).
--
-- After running : tick Add / Edit / Delete / View / Print / Post /
-- Cancel for the roles in Security & Permission › Activity
-- Assignment, set the Opening Stock ledger in Settings ›
-- Account Settings › Posting Setup, then log in again.
--
-- Safe to run more than once. Run the whole script (F5).
-- ============================================================


-- ------------------------------------------------------------
-- 1a. Baseline table out (only the generator's empty one)
-- ------------------------------------------------------------

DO $$
BEGIN
    IF EXISTS
    (
        SELECT 1 FROM information_schema.tables
        WHERE  table_schema = 'public' AND table_name = 'OpeningStock'
    )
    AND NOT EXISTS
    (
        SELECT 1 FROM information_schema.columns
        WHERE  table_schema = 'public' AND table_name = 'OpeningStock' AND column_name = 'OpeningNo'
    )
    THEN
        DROP TABLE public."OpeningStock" CASCADE;
        RAISE NOTICE 'OpeningStock : baseline table replaced';
    END IF;
END $$;


-- ------------------------------------------------------------
-- 1b. Header and lines
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."OpeningStock"
(
    "OpeningStockId"     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PageType"           character varying(5)   NOT NULL,
    "OpeningNo"          character varying(30)  NOT NULL,
    "SequenceNo"         integer                NOT NULL DEFAULT 0,
    "JournalNo"          character varying(30)  NOT NULL DEFAULT '',
    "OpeningDate"        date                   NOT NULL,
    "BranchId"           bigint                 NOT NULL,
    "BranchCode"         character varying(30)  NOT NULL DEFAULT '',
    "BranchName"         character varying(150) NOT NULL DEFAULT '',
    "FinancialYearId"    bigint                 NOT NULL,
    "WarehouseId"        bigint                 NOT NULL,
    "WarehouseName"      character varying(150) NOT NULL DEFAULT '',
    "LedgerCode"         character varying(40)  NOT NULL,
    "LedgerName"         character varying(250) NOT NULL DEFAULT '',
    "Remarks"            character varying(500) NOT NULL DEFAULT '',
    "CostBasis"          character varying(10)  NOT NULL DEFAULT 'Cost',
    "TotalQuantity"      numeric(18,2)          NOT NULL DEFAULT 0,
    "TotalValue"         numeric(18,2)          NOT NULL DEFAULT 0,
    "VatIncluded"        boolean                NOT NULL DEFAULT false,
    "TotalVat"           numeric(18,2)          NOT NULL DEFAULT 0,

    "Status"             character varying(20)  NOT NULL DEFAULT 'Draft',
    "PostedBy"           bigint                 NULL,
    "PostedDate"         timestamp with time zone NULL,
    "CancelReason"       character varying(500) NOT NULL DEFAULT '',
    "CancelledBy"        bigint                 NULL,
    "CancelledDate"      timestamp with time zone NULL,

    "IsDeleted"          boolean                NOT NULL DEFAULT false,
    "DeletedBy"          bigint                 NULL,
    "DeletedDate"        timestamp with time zone NULL,
    "CreatedBy"          bigint                 NOT NULL,
    "CreatedDate"        timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"         bigint                 NULL,
    "ModifiedDate"       timestamp with time zone NULL,

    CONSTRAINT "CK_OpeningStock_PageType" CHECK ("PageType" IN ('MB', 'SP', 'AC')),
    CONSTRAINT "CK_OpeningStock_Status"   CHECK ("Status" IN ('Draft', 'Posted', 'Cancelled'))
);

-- Tables made by the first version of this script : the new
-- columns
ALTER TABLE public."OpeningStock"      ADD COLUMN IF NOT EXISTS "SequenceNo"    integer               NOT NULL DEFAULT 0;
ALTER TABLE public."OpeningStock"      ADD COLUMN IF NOT EXISTS "CostBasis"     character varying(10) NOT NULL DEFAULT 'Cost';
ALTER TABLE public."OpeningStock"      ADD COLUMN IF NOT EXISTS "JournalNo"     character varying(30) NOT NULL DEFAULT '';

-- Numbers made before the branch code lost its letter prefix
-- (OS-BRN-01-01-01-MB-0001 → OS-01-01-01-MB-0001) : drafts only
UPDATE public."MotorBikeUnits" u
SET    "PurchaseNo" = regexp_replace(o."OpeningNo", '^OS-[A-Za-z]+-', 'OS-')
FROM   public."OpeningStock" o
WHERE  u."OpeningStockId" = o."OpeningStockId"
AND    o."Status" = 'Draft'
AND    o."OpeningNo" ~ '^OS-[A-Za-z]+-';

UPDATE public."OpeningStock"
SET    "OpeningNo" = regexp_replace("OpeningNo", '^OS-[A-Za-z]+-', 'OS-')
WHERE  "Status" = 'Draft'
AND    "OpeningNo" ~ '^OS-[A-Za-z]+-';

-- A number is never reused : unique over every row, deleted too
DROP INDEX IF EXISTS public."IX_OpeningStock_OpeningNo";

CREATE UNIQUE INDEX IF NOT EXISTS "UX_OpeningStock_OpeningNo"
    ON public."OpeningStock" ("OpeningNo");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_OpeningStock_Branch_Type_Sequence"
    ON public."OpeningStock" ("BranchId", "PageType", "SequenceNo")
    WHERE "SequenceNo" > 0;

