-- ------------------------------------------------------------
-- 2. Motor bike units : opening bikes
-- ------------------------------------------------------------

ALTER TABLE public."MotorBikeUnits" ADD COLUMN IF NOT EXISTS "OpeningStockId" bigint NULL;

CREATE INDEX IF NOT EXISTS "IX_MotorBikeUnits_OpeningStockId"
    ON public."MotorBikeUnits" ("OpeningStockId");

-- Foreign keys to the purchase tables off (an opening bike has no
-- purchase; the purchase page removes its own bikes itself)
DO $$
DECLARE
    c record;
BEGIN
    FOR c IN
        SELECT con.conname
        FROM   pg_constraint con
        JOIN   pg_class t  ON t.oid  = con.conrelid
        JOIN   pg_class rt ON rt.oid = con.confrelid
        WHERE  con.contype = 'f'
        AND    t.relname   = 'MotorBikeUnits'
        AND    rt.relname IN ('PurchasesMb', 'PurchasesMbLines')
    LOOP
        EXECUTE format('ALTER TABLE public."MotorBikeUnits" DROP CONSTRAINT %I', c.conname);
        RAISE NOTICE 'MotorBikeUnits : foreign key % taken off', c.conname;
    END LOOP;
END $$;

DO $$
BEGIN
    IF NOT EXISTS
    (
        SELECT 1 FROM pg_constraint
        WHERE  conname = 'CK_MotorBikeUnits_Source'
    )
    THEN
        ALTER TABLE public."MotorBikeUnits"
            ADD CONSTRAINT "CK_MotorBikeUnits_Source"
            CHECK ("PurchaseId" > 0 OR "OpeningStockId" IS NOT NULL);
    END IF;
END $$;


