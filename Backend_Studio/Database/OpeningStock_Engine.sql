-- ------------------------------------------------------------
-- 4. Page actions : Post and Cancel on Opening Stock
-- ------------------------------------------------------------

INSERT INTO "MasterActivityPages" ("MasterActivityCode", "NavigationSubmenuCode", "CreatedBy")
SELECT a."Code", s."Code", 1
FROM   "MasterActivities" a
JOIN   "NavigationSubmenus" s
       ON s."Route" ILIKE '/inventory-management/%/opening-stock'
      AND s."IsDeleted" = false
WHERE  a."IsDeleted" = false
AND    a."ActivityScope" = 'Page'
AND    a."Name" IN ('Post', 'Cancel')
ON CONFLICT ("MasterActivityCode", "NavigationSubmenuCode") DO NOTHING;


-- ------------------------------------------------------------
-- 5. Auto Journal Registers : the opening journals
-- ------------------------------------------------------------

INSERT INTO public."AutoJournalSources"
    ("VoucherType", "SourceTable", "NavigationSubmenuCode", "IsAutoJournal", "DisplayOrder", "Remarks")
SELECT
    v.voucher_type,
    '',
    COALESCE(s."Code", ''),
    true,
    v.ord,
    v.remarks
FROM
(
    VALUES
        (21, 'OPMB', 'Opening Stock - Motor Bikes'),
        (22, 'OPSP', 'Opening Stock - Spare Parts & Lubricants'),
        (23, 'OPAC', 'Opening Stock - Accessories')
) AS v (ord, voucher_type, remarks)
LEFT JOIN LATERAL
(
    SELECT n."Code"
    FROM   "NavigationSubmenus" n
    WHERE  n."IsDeleted" = false
    AND    lower(n."Route") LIKE '%/opening-stock'
    ORDER  BY n."Id"
    LIMIT  1
) AS s ON true
ON CONFLICT ("VoucherType", "SourceTable") DO UPDATE
SET    "NavigationSubmenuCode" = EXCLUDED."NavigationSubmenuCode"
WHERE  public."AutoJournalSources"."NavigationSubmenuCode" = ''
AND    EXCLUDED."NavigationSubmenuCode" <> '';


-- ------------------------------------------------------------
-- 6. Switch : Lock Opening Stock Ledger (CFG-MOD-012-0006)
--    Critical, on the Opening Stock page, ON by default.
--    ON  = the credit ledger is always Posting Setup › Opening
--          Stock (the page shows it locked; the server forces it).
--    OFF = the ledger can be chosen per document.
--    A switch that already exists is left as it is (a row made by
--    an earlier copy of this script under another name is renamed).
-- ------------------------------------------------------------

DO $$
DECLARE
    v_module_id   bigint;
    v_module_code text;
    v_page_code   text;
    v_menu_code   text;
BEGIN
    SELECT m."Id", m."Code"
    INTO   v_module_id, v_module_code
    FROM   "NavigationModules" m
    WHERE  lower(trim(m."Name")) = 'inventory management'
    AND    NOT m."IsDeleted"
    LIMIT  1;

    IF v_module_id IS NULL OR upper(trim(v_module_code)) <> 'MOD-012' THEN
        RAISE EXCEPTION 'Inventory Management module MOD-012 not found - switch not added. Tell Claude the code.';
    END IF;

    IF EXISTS
    (
        SELECT 1 FROM "SystemConfigurations" c
        WHERE  c."ConfigurationCode" = 'CFG-MOD-012-0006'
        AND    c."ConfigurationName" NOT IN ('Lock Opening Stock Ledger', 'Opening Stock Entry Open')
    )
    THEN
        RAISE EXCEPTION 'CFG-MOD-012-0006 is already used by another switch - nothing changed. Tell Claude.';
    END IF;

    SELECT s."Code", mn."Code"
    INTO   v_page_code, v_menu_code
    FROM   "NavigationSubmenus" s
    JOIN   "NavigationMenus" mn ON mn."Id" = s."NavigationMenuId"
    WHERE  s."Route" ILIKE '/inventory-management/%/opening-stock'
    AND    NOT s."IsDeleted"
    LIMIT  1;

    IF v_page_code IS NULL THEN
        RAISE EXCEPTION 'Opening Stock page not found by route - switch not added.';
    END IF;

    INSERT INTO "SystemConfigurations"
    (
        "NavigationModuleId", "ScopeType", "NavigationMenuCode", "NavigationSubmenuCode",
        "ConfigurationCode", "ConfigurationName", "OnDescription", "OffDescription",
        "IsEnabled", "Value",
        "ValueType", "ValueUnit", "ValueMin", "ValueMax", "ValueEmptyText",
        "DefaultEnabled", "DefaultValue", "ParentConfigurationCode",
        "IsCritical", "IsSystemDefined", "DisplayOrder", "Remarks",
        "IsDeleted", "CreatedBy", "CreatedDate"
    )
    SELECT
        v_module_id, 'Submenu', v_menu_code, v_page_code,
        'CFG-MOD-012-0006', 'Lock Opening Stock Ledger',
        'The credit ledger of every opening stock is the one set on Posting Setup › Opening Stock; it cannot be changed on the page.',
        'The credit ledger can be chosen per opening stock (Posting Setup gives the default).',
        true, '',
        'None', '', NULL, NULL, '',
        true, '', NULL,
        true, true, 10, 'Dr Inventory / Cr this ledger on every opening stock post.',
        false, 1, now()
    WHERE NOT EXISTS
    (
        SELECT 1 FROM "SystemConfigurations" c
        WHERE  c."ConfigurationCode" = 'CFG-MOD-012-0006'
    );

    -- An earlier copy of this script named it differently
    UPDATE "SystemConfigurations"
    SET    "ConfigurationName" = 'Lock Opening Stock Ledger',
           "OnDescription"     = 'The credit ledger of every opening stock is the one set on Posting Setup › Opening Stock; it cannot be changed on the page.',
           "OffDescription"    = 'The credit ledger can be chosen per opening stock (Posting Setup gives the default).',
           "ValueType"         = 'None',
           "Value"             = '',
           "ValueEmptyText"    = '',
           "IsEnabled"         = true,
           "DefaultEnabled"    = true
    WHERE  "ConfigurationCode" = 'CFG-MOD-012-0006'
    AND    "ConfigurationName" = 'Opening Stock Entry Open';

    RAISE NOTICE 'Lock Opening Stock Ledger : ready (page %, menu %)', v_page_code, v_menu_code;
END $$;


