CREATE TABLE IF NOT EXISTS public."HrSalaryAdvances"
(
    "AdvanceId"         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"          uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"              character varying(20)    NOT NULL,
    "EmployeeId"        bigint                   NOT NULL,
    -- Advance / Loan
    "AdvanceType"       character varying(10)    NOT NULL DEFAULT 'Advance',
    "AdvanceDate"       date                     NOT NULL,
    "Amount"            numeric(18,2)            NOT NULL,
    -- Taken from each month's salary
    "InstallmentAmount" numeric(18,2)            NOT NULL,
    -- The first salary month the installment is taken from
    "StartYear"         integer                  NOT NULL,
    "StartMonth"        integer                  NOT NULL,
    "Reason"            character varying(500)   NOT NULL DEFAULT '',
    -- The Payment Voucher that paid it out (typed; '' = none)
    "VoucherNo"         character varying(30)    NOT NULL DEFAULT '',
    -- Recovery is stopped (the balance is left as it is)
    "IsClosed"          boolean                  NOT NULL DEFAULT false,
    "IsDeleted"         boolean                  NOT NULL DEFAULT false,
    "DeletedBy"         bigint                   NULL,
    "DeletedDate"       timestamp with time zone NULL,
    "CreatedBy"         bigint                   NOT NULL,
    "CreatedDate"       timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"        bigint                   NULL,
    "ModifiedDate"      timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrSalaryAdvances_PublicId" ON public."HrSalaryAdvances" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrSalaryAdvances_Code"     ON public."HrSalaryAdvances" ("Code");
CREATE INDEX        IF NOT EXISTS "IX_HrSalaryAdvances_Employee" ON public."HrSalaryAdvances" ("EmployeeId");


CREATE TABLE IF NOT EXISTS public."HrSalarySheets"
(
    "SalarySheetId"     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"          uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"              character varying(20)    NOT NULL,
    "Year"              integer                  NOT NULL,
    "Month"             integer                  NOT NULL,
    "BranchId"          bigint                   NOT NULL,
    -- Draft / Approved / Posted
    "Status"            character varying(10)    NOT NULL DEFAULT 'Draft',
    -- This many late days cut one day of Basic (0 = no cut)
    "LateDaysPerCut"    integer                  NOT NULL DEFAULT 0,
    "EmployeeCount"     integer                  NOT NULL DEFAULT 0,
    "TotalGross"        numeric(18,2)            NOT NULL DEFAULT 0,
    "TotalEarned"       numeric(18,2)            NOT NULL DEFAULT 0,
    "TotalDeductions"   numeric(18,2)            NOT NULL DEFAULT 0,
    "TotalNet"          numeric(18,2)            NOT NULL DEFAULT 0,
    "Remarks"           character varying(500)   NOT NULL DEFAULT '',
    "ApprovedBy"        bigint                   NULL,
    "ApprovedDate"      timestamp with time zone NULL,
    "PostedBy"          bigint                   NULL,
    "PostedDate"        timestamp with time zone NULL,
    "JournalVoucherId"  bigint                   NULL,
    "JournalVoucherNo"  character varying(30)    NOT NULL DEFAULT '',
    "IsDeleted"         boolean                  NOT NULL DEFAULT false,
    "DeletedBy"         bigint                   NULL,
    "DeletedDate"       timestamp with time zone NULL,
    "CreatedBy"         bigint                   NOT NULL,
    "CreatedDate"       timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"        bigint                   NULL,
    "ModifiedDate"      timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrSalarySheets_PublicId" ON public."HrSalarySheets" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrSalarySheets_Code"     ON public."HrSalarySheets" ("Code");

-- one live sheet per branch per month
CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrSalarySheets_Month"
    ON public."HrSalarySheets" ("Year", "Month", "BranchId")
    WHERE NOT "IsDeleted";


CREATE TABLE IF NOT EXISTS public."HrSalarySheetLines"
(
    "SalarySheetLineId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "SalarySheetId"       bigint                 NOT NULL
        REFERENCES public."HrSalarySheets" ("SalarySheetId") ON DELETE CASCADE,
    "EmployeeId"          bigint                 NOT NULL,

    -- The employee as on the day the sheet was made
    "EmployeeCode"        character varying(20)  NOT NULL DEFAULT '',
    "EmployeeName"        character varying(150) NOT NULL DEFAULT '',
    "DesignationName"     character varying(150) NOT NULL DEFAULT '',
    "DepartmentName"      character varying(150) NOT NULL DEFAULT '',
    "PaymentMode"         character varying(10)  NOT NULL DEFAULT 'Cash',
    "PaymentAccount"      character varying(150) NOT NULL DEFAULT '',

    -- Attendance of the month
    "MonthDays"           integer                NOT NULL DEFAULT 0,
    "PayableDays"         numeric(6,2)           NOT NULL DEFAULT 0,
    "UnpaidDays"          numeric(6,2)           NOT NULL DEFAULT 0,
    "LateDays"            integer                NOT NULL DEFAULT 0,
    "OvertimeHours"       numeric(8,2)           NOT NULL DEFAULT 0,

    -- Salary structure
    "BasicSalary"         numeric(18,2)          NOT NULL DEFAULT 0,
    "GrossSalary"         numeric(18,2)          NOT NULL DEFAULT 0,

    -- Worked out
    "AbsenceDeduction"    numeric(18,2)          NOT NULL DEFAULT 0,
    "LateDeduction"       numeric(18,2)          NOT NULL DEFAULT 0,
    "OvertimeAmount"      numeric(18,2)          NOT NULL DEFAULT 0,
    -- Typed on the sheet
    "OtherEarning"        numeric(18,2)          NOT NULL DEFAULT 0,
    "OtherDeduction"      numeric(18,2)          NOT NULL DEFAULT 0,
    -- Gross - absence - late + overtime + other earning
    "EarnedSalary"        numeric(18,2)          NOT NULL DEFAULT 0,
    -- Deductions of the structure (provident fund, tax ...)
    "StructureDeduction"  numeric(18,2)          NOT NULL DEFAULT 0,
    "AdvanceDeduction"    numeric(18,2)          NOT NULL DEFAULT 0,
    "NetPay"              numeric(18,2)          NOT NULL DEFAULT 0,

    "Remarks"             character varying(200) NOT NULL DEFAULT '',

    -- The net pay was handed over
    "IsPaid"              boolean                NOT NULL DEFAULT false,
    "PaidDate"            date                   NULL,
    "PaidNote"            character varying(100) NOT NULL DEFAULT ''
);

CREATE INDEX        IF NOT EXISTS "IX_HrSalarySheetLines_Sheet"    ON public."HrSalarySheetLines" ("SalarySheetId");
CREATE INDEX        IF NOT EXISTS "IX_HrSalarySheetLines_Employee" ON public."HrSalarySheetLines" ("EmployeeId");


CREATE TABLE IF NOT EXISTS public."HrSalarySheetLineHeads"
(
    "SalarySheetLineHeadId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "SalarySheetLineId"     bigint                 NOT NULL
        REFERENCES public."HrSalarySheetLines" ("SalarySheetLineId") ON DELETE CASCADE,
    "SalaryHeadId"          bigint                 NOT NULL,
    "HeadName"              character varying(100) NOT NULL DEFAULT '',
    -- Earning / Deduction
    "HeadType"              character varying(10)  NOT NULL DEFAULT '',
    "Amount"                numeric(18,2)          NOT NULL DEFAULT 0,
    "DisplayOrder"          integer                NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS "IX_HrSalarySheetLineHeads_Line" ON public."HrSalarySheetLineHeads" ("SalarySheetLineId");


CREATE TABLE IF NOT EXISTS public."HrAdvanceRecoveries"
(
    "AdvanceRecoveryId"  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "AdvanceId"          bigint        NOT NULL,
    "SalarySheetId"      bigint        NOT NULL
        REFERENCES public."HrSalarySheets" ("SalarySheetId") ON DELETE CASCADE,
    "SalarySheetLineId"  bigint        NOT NULL,
    "EmployeeId"         bigint        NOT NULL,
    "Amount"             numeric(18,2) NOT NULL DEFAULT 0
