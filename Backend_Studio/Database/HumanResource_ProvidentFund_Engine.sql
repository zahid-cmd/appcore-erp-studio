CREATE TABLE IF NOT EXISTS public."HrPfPolicy"
(
    "PfPolicyId"            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- contributions : percent of the base, every month
    "EmployeePercent"       numeric(7,3)             NOT NULL DEFAULT 10,
    "CompanyContributes"    boolean                  NOT NULL DEFAULT true,
    "CompanyPercent"        numeric(7,3)             NOT NULL DEFAULT 10,
    -- Basic / Gross
    "ContributionBase"      character varying(10)    NOT NULL DEFAULT 'Basic',
    -- who can join : Joining / Confirmation / Months (after joining)
    "EligibilityRule"       character varying(15)    NOT NULL DEFAULT 'Confirmation',
    "EligibilityMonths"     integer                  NOT NULL DEFAULT 0,
    -- yearly interest
    "InterestEnabled"       boolean                  NOT NULL DEFAULT false,
    "InterestRate"          numeric(7,3)             NOT NULL DEFAULT 0,
    -- loans against the fund
    "LoanEnabled"           boolean                  NOT NULL DEFAULT true,
    -- percent of the member's own balance that can be on loan
    "LoanMaxPercent"        numeric(7,3)             NOT NULL DEFAULT 80,
    "LoanMaxInstallments"   integer                  NOT NULL DEFAULT 24,
    -- forfeiture : the company part needs this many years
    -- (0 = always paid), counted from Joining / Membership
    "VestingYears"          numeric(5,2)             NOT NULL DEFAULT 2,
    "VestingFrom"           character varying(12)    NOT NULL DEFAULT 'Joining',
    -- termination for misconduct : no company part, whatever the years
    "ForfeitOnMisconduct"   boolean                  NOT NULL DEFAULT true,
    -- death / retirement : the whole company part, whatever the years
    "FullOnDeathRetirement" boolean                  NOT NULL DEFAULT true,
    "Remarks"               character varying(500)   NOT NULL DEFAULT '',
    -- always true and unique : a second row cannot be added
    "OnlyOne"               boolean                  NOT NULL DEFAULT true,
    "CreatedBy"             bigint                   NOT NULL DEFAULT 1,
    "CreatedDate"           timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"            bigint                   NULL,
    "ModifiedDate"          timestamp with time zone NULL,
    CONSTRAINT "CK_HrPfPolicy_OnlyOne" CHECK ("OnlyOne")
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrPfPolicy_OnlyOne" ON public."HrPfPolicy" ("OnlyOne");

INSERT INTO public."HrPfPolicy" ("Remarks")
SELECT 'Starter policy : change it to yours.'
WHERE NOT EXISTS (SELECT 1 FROM public."HrPfPolicy");

