    ADD COLUMN IF NOT EXISTS "PfLoan"     numeric(18,2) NOT NULL DEFAULT 0;

-- ------------------------------------------------------------
-- 3. The salary head "Provident Fund" belongs to the fund now :
--    it is worked out by payroll from the policy (not a line of a
--    salary structure any more)
-- ------------------------------------------------------------

UPDATE public."HrSalaryHeads"
SET    "SystemKey" = 'PF'
WHERE  "SystemKey" = ''
AND    "HeadType" = 'Deduction'
AND    lower(trim("Name")) IN ('provident fund', 'pf', 'provident fund (pf)');

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables
               WHERE table_schema = 'public' AND table_name = 'HrSalaryStructureLines')
    THEN
        DELETE FROM public."HrSalaryStructureLines"
        WHERE "SalaryHeadId" IN (SELECT "SalaryHeadId" FROM public."HrSalaryHeads" WHERE "SystemKey" = 'PF');
    END IF;

    DELETE FROM public."HrEmployeeSalaryLines"
    WHERE "SalaryHeadId" IN (SELECT "SalaryHeadId" FROM public."HrSalaryHeads" WHERE "SystemKey" = 'PF');
END $$;

-- ------------------------------------------------------------
-- 4. Menu Provident Fund and its pages
-- ------------------------------------------------------------

DO $$
DECLARE
    v_module   record;
    v_menu     record;
    v_seq      int;
    v_code     text;
    s          record;
BEGIN
    SELECT "Id", "SequenceNo", "RouteKey", "Code", "Name" INTO v_module
    FROM   "NavigationModules"
    WHERE  lower(trim("RouteKey")) = 'human-resource-manangement'
    AND    "IsDeleted" = false
    LIMIT  1;

    IF v_module."Id" IS NULL THEN
        RAISE EXCEPTION 'Module with route key human-resource-manangement not found - no menu or page was added.';
    END IF;

    -- ---------- Menu ----------
    IF NOT EXISTS (SELECT 1 FROM "NavigationMenus"
                   WHERE "NavigationModuleId" = v_module."Id"
                   AND   lower(trim("RouteKey")) = 'provident-fund'
                   AND   "IsDeleted" = false) THEN

        SELECT COALESCE(MAX("SequenceNo"), 0) + 1 INTO v_seq
        FROM   "NavigationMenus"
        WHERE  "NavigationModuleId" = v_module."Id";

        INSERT INTO "NavigationMenus"
            ("NavigationModuleId", "SequenceNo", "Code", "Name", "Icon",
             "RouteKey", "Route", "DisplayOrder", "Remarks",
             "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
        VALUES
            (v_module."Id", v_seq,
             'MNU-' || lpad(v_module."SequenceNo"::text, 3, '0') || '-' || lpad(v_seq::text, 3, '0'),
             'Provident Fund', 'fa-solid fa-piggy-bank',
             'provident-fund', '/' || v_module."RouteKey" || '/provident-fund',
             v_seq, NULL,
             true, false, 1, now());

        RAISE NOTICE 'Menu created : Provident Fund';
    ELSE
        RAISE NOTICE 'Menu exists, skipped : Provident Fund';
    END IF;

    SELECT "Id", "SequenceNo", "RouteKey" INTO v_menu
    FROM   "NavigationMenus"
    WHERE  "NavigationModuleId" = v_module."Id"
    AND    lower(trim("RouteKey")) = 'provident-fund'
    AND    "IsDeleted" = false
    LIMIT  1;

    -- ---------- Pages ----------
    FOR s IN
        SELECT * FROM (VALUES
            (1, 'Provident Fund Policy', 'fa-solid fa-scale-balanced',       'provident-fund-policy', 'The rules of the fund : contributions, eligibility, interest, loans and forfeiture. One record.'),
            (2, 'PF Members',            'fa-solid fa-id-card-clip',         'pf-members',            'Employees in the provident fund, their opening balances and nominees.'),
            (3, 'PF Loans',              'fa-solid fa-hand-holding-dollar',  'pf-loans',              'Loans against the provident fund, recovered from the salary.'),
            (4, 'PF Settlements',        'fa-solid fa-money-check-dollar',   'pf-settlements',        'Payment, cancellation and forfeiture : what a member gets on leaving the fund.'),
            (5, 'PF Interest',           'fa-solid fa-percent',              'pf-interest',           'The yearly interest of the fund, worked out and credited to the members.')
        ) AS x (ord, name, icon, route_key, remarks)
        ORDER BY ord
    LOOP
        IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
                   WHERE "NavigationMenuId" = v_menu."Id"
                   AND   lower(trim("RouteKey")) = s.route_key
                   AND   "IsDeleted" = false) THEN
            RAISE NOTICE 'Page exists, skipped : %', s.name;
            CONTINUE;
        END IF;

        IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
                   WHERE lower(trim("Name")) = lower(s.name) AND "IsDeleted" = false) THEN
            RAISE EXCEPTION 'A submenu named "%" already exists elsewhere : names must be unique. Tell Claude.', s.name;
        END IF;

        SELECT COALESCE(MAX("SequenceNo"), 0) + 1 INTO v_seq
        FROM   "NavigationSubmenus"
        WHERE  "NavigationMenuId" = v_menu."Id";

        v_code :=
            'SUB-' || lpad(v_module."SequenceNo"::text, 3, '0')
                   || '-' || lpad(v_menu."SequenceNo"::text, 3, '0')
                   || '-' || lpad(v_seq::text, 3, '0');

        INSERT INTO "NavigationSubmenus"
            ("NavigationMenuId", "SequenceNo", "Code", "Name", "Icon",
             "RouteKey", "Route", "DisplayOrder", "Remarks",
             "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
        VALUES
            (v_menu."Id", v_seq, v_code, s.name, s.icon,
             s.route_key,
             '/' || v_module."RouteKey" || '/' || v_menu."RouteKey" || '/' || s.route_key,
             v_seq, s.remarks || ' Hand-written page : never run Submenu / Code Sync.',
             true, false, 1, now());

        RAISE NOTICE 'Page created : % %', v_code, s.name;
    END LOOP;
END $$;


