-- ------------------------------------------------------------
-- 1b. Interest on the fund loans (2026-11-14)
--     The policy : yes / no, the yearly rate and the method
--       Flat      rate x the whole loan x the years, fixed at the
--                 start and spread over the instalments
--       Reducing  every month, rate / 12 on what is still unpaid
--                 (equal instalments)
--     A loan settled early pays the interest of the months used
--     only (never the interest still planned).
--     A loan keeps the terms it was given with. The
--     interest is income of the fund ("InterestAmount" of what is
--     recovered), not the member's money.
-- ------------------------------------------------------------

ALTER TABLE public."HrPfPolicy"
    ADD COLUMN IF NOT EXISTS "LoanInterestEnabled"   boolean               NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS "LoanInterestRate"      numeric(7,3)          NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS "LoanInterestMethod"    character varying(10) NOT NULL DEFAULT 'Flat',
    -- (not used : an early settlement pays the months used only)
    ADD COLUMN IF NOT EXISTS "LoanEarlyFullInterest" boolean               NOT NULL DEFAULT false;

-- The yearly interest of the members is worked out on :
--   Monthly : the balance at the end of every month of the
--             financial year x rate / 12 (money earns interest
--             for the months it was in the fund)
--   Closing : the balance on the last day of the year x rate
ALTER TABLE public."HrPfPolicy"
    ADD COLUMN IF NOT EXISTS "InterestBasis" character varying(10) NOT NULL DEFAULT 'Monthly';

ALTER TABLE public."HrPfLoans"
    ADD COLUMN IF NOT EXISTS "InterestRate"      numeric(7,3)          NOT NULL DEFAULT 0,
    -- '' (no interest) / Flat / Reducing
    ADD COLUMN IF NOT EXISTS "InterestMethod"    character varying(10) NOT NULL DEFAULT '',
    -- the interest of the whole loan as planned when it was given
    ADD COLUMN IF NOT EXISTS "TotalInterest"     numeric(18,2)         NOT NULL DEFAULT 0,
    -- (not used : always false)
    ADD COLUMN IF NOT EXISTS "EarlyFullInterest" boolean               NOT NULL DEFAULT false;

-- the part of "Amount" that is interest (income of the fund)
ALTER TABLE public."HrPfLoanRecoveries"
    ADD COLUMN IF NOT EXISTS "InterestAmount" numeric(18,2) NOT NULL DEFAULT 0;

