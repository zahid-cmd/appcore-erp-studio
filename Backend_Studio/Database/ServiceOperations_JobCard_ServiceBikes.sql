-- The New Job page, button Add of the Bike section (owner 2026-11-18) :
-- a bike we do not sell (another brand, model or colour) is added to
-- a list of the workshop only :
--
--   WorkshopServiceBikes   Brand (Brand Management) + model name
--                          (typed) + colour (Color Management).
--
-- It is NOT a product : no product code, no ledger, no stock. It
-- shows only in the Motor Bike list of the job card.
--
-- Run ServiceOperations_JobCard_Opening.sql first.
-- Safe to run more than once. Run the whole script (F5). ASCII only.
--
-- AFTER : restart the API.
-- =====================================================================

CREATE TABLE IF NOT EXISTS public."WorkshopServiceBikes"
(
    "WorkshopServiceBikeId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BrandManagementId"     bigint       NOT NULL,
    "ModelName"             varchar(150) NOT NULL,
    "ColorManagementId"     bigint       NOT NULL,
    "IsDeleted"             boolean      NOT NULL DEFAULT false,
    "CreatedBy"             bigint       NOT NULL,
    "CreatedDate"           timestamp with time zone NOT NULL DEFAULT now()
);

-- one brand + model + colour once
CREATE UNIQUE INDEX IF NOT EXISTS "UX_WorkshopServiceBikes_Bike"
    ON public."WorkshopServiceBikes" ("BrandManagementId", lower("ModelName"), "ColorManagementId")
    WHERE "IsDeleted" = false;


