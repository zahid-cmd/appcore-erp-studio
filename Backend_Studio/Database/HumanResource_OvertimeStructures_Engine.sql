-- Human Resource Management : overtime structures
-- (hand-written page : NEVER run Submenu / Code Sync for it)
-- Run HumanResource_Phase1_Engine.sql first (and Phase 3 for payroll).
--
--   Human Resource Setup (existing menu)
--     Overtime Structures
--       /human-resource-manangement/human-resource-setup/overtime-structures
--
--   HrOvertimeStructures  OTS-001  how overtime is paid. One structure
--                                  is the Default. Named by the program :
--                                  Overtime Structure - 1 / 2 / 3.
--
--   Overtime is paid on two bases :
--     1. Extra hours   the overtime hours typed on Daily Attendance
--        pay = hours x hour rate x multiplier
--              (another multiplier for hours on a weekly holiday or a
--               public holiday)
--     2. Extra days    the days worked on a weekly holiday or a public
--                      holiday : the days attended above the working
--                      days of the month
--        pay = extra days x day rate x multiplier
--
--     day rate  = base / days in the month
--     hour rate = day rate / hours a day (the working hours of the
--                 employee's shift : shift hours less the break)
--     base      = Basic salary or Gross salary of the employee
--                 (or a fixed Tk an hour : day rate = that x hours a day)
--     days in the month = a fixed number (26, 30 ...) or the real days
--
--   HrEmployees."OvertimeStructureId"   picked on the Employee Profile
--       when Overtime allowed is on. An employee with the old typed
--       rate ("OvertimeRate") and no structure keeps hours x that rate.
--   HrSalarySheetLines."OvertimeDays"   the extra days paid on a sheet
--
-- IMPORTANT : run this before opening Employee Profiles, Overtime
-- Structures or Salary Sheets again : the program reads the new
-- columns.
--
-- Safe to run again. Run the whole script (F5) on AppCoreERP_Studio.
--
-- AFTER : Security & Permission > Activity Assignment : tick View /
-- Add / Update / Delete / Restore on Overtime Structures for the
-- roles, then log in again.
-- ASCII only.
-- =====================================================================

-- ------------------------------------------------------------
-- 1. Table
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."HrOvertimeStructures"
(
    "OvertimeStructureId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"              uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"                  character varying(20)    NOT NULL,
    "Name"                  character varying(100)   NOT NULL,
    -- Basic / Gross / Fixed
    "RateBase"              character varying(10)    NOT NULL DEFAULT 'Basic',
    -- Tk an hour (RateBase Fixed)
    "FixedHourRate"         numeric(18,2)            NOT NULL DEFAULT 0,
    -- Fixed ("MonthDays") / Actual (the real days of the month)
    "MonthDaysMode"         character varying(10)    NOT NULL DEFAULT 'Fixed',
    "MonthDays"             integer                  NOT NULL DEFAULT 26,
    -- not typed any more : the hours a day are the working hours
    -- of the employee's shift (the column is not used)
    "HoursPerDay"           numeric(5,2)             NOT NULL DEFAULT 8,
    -- 1. extra hours
    "PayExtraHours"         boolean                  NOT NULL DEFAULT true,
    "HourMultiplier"        numeric(6,3)             NOT NULL DEFAULT 1,
    "HolidayHourMultiplier" numeric(6,3)             NOT NULL DEFAULT 1,
    -- 2. extra days
    "PayExtraDays"          boolean                  NOT NULL DEFAULT true,
    "DayMultiplier"         numeric(6,3)             NOT NULL DEFAULT 1,
    -- The structure an Employee Profile starts with (one only)
    "IsDefault"             boolean                  NOT NULL DEFAULT false,
    "Remarks"               character varying(500)   NOT NULL DEFAULT '',
    "IsActive"              boolean                  NOT NULL DEFAULT true,
    "IsDeleted"             boolean                  NOT NULL DEFAULT false,
    "DeletedBy"             bigint                   NULL,
    "DeletedDate"           timestamp with time zone NULL,
    "CreatedBy"             bigint                   NOT NULL,
    "CreatedDate"           timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"            bigint                   NULL,
    "ModifiedDate"          timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrOvertimeStructures_PublicId" ON public."HrOvertimeStructures" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrOvertimeStructures_Code"     ON public."HrOvertimeStructures" ("Code");

-- the multipliers start at 1 (a table made before that had 2)
ALTER TABLE public."HrOvertimeStructures"
    ALTER COLUMN "HourMultiplier"        SET DEFAULT 1,
    ALTER COLUMN "HolidayHourMultiplier" SET DEFAULT 1;

-- one Default among live, active structures
CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrOvertimeStructures_Default"
    ON public."HrOvertimeStructures" ("IsDefault")
    WHERE "IsDefault" AND "IsActive" AND NOT "IsDeleted";

-- ------------------------------------------------------------
-- 2. The employee's overtime structure
-- ------------------------------------------------------------

ALTER TABLE public."HrEmployees"
    ADD COLUMN IF NOT EXISTS "OvertimeStructureId" bigint NULL;

CREATE INDEX IF NOT EXISTS "IX_HrEmployees_OvertimeStructure"
    ON public."HrEmployees" ("OvertimeStructureId");

-- ------------------------------------------------------------
-- 3. The extra days paid on a salary sheet (when phase 3 was run)
-- ------------------------------------------------------------

ALTER TABLE IF EXISTS public."HrSalarySheetLines"
    ADD COLUMN IF NOT EXISTS "OvertimeDays" numeric(6,2) NOT NULL DEFAULT 0;


-- ------------------------------------------------------------
-- 4. Page Human Resource Setup > Overtime Structures
-- ------------------------------------------------------------

DO $$
DECLARE
    v_module record;
    v_menu   record;
    v_seq    int;
BEGIN
    SELECT "Id", "SequenceNo", "RouteKey" INTO v_module
    FROM   "NavigationModules"
    WHERE  lower(trim("RouteKey")) = 'human-resource-manangement'
    AND    "IsDeleted" = false
    LIMIT  1;

    IF v_module."Id" IS NULL THEN
        RAISE EXCEPTION 'Module with route key human-resource-manangement not found - no page was added.';
    END IF;

    SELECT "Id", "SequenceNo", "RouteKey" INTO v_menu
    FROM   "NavigationMenus"
    WHERE  "NavigationModuleId" = v_module."Id"
    AND    lower(trim("RouteKey")) = 'human-resource-setup'
    AND    "IsDeleted" = false
    LIMIT  1;

    IF v_menu."Id" IS NULL THEN
        RAISE EXCEPTION 'Menu human-resource-setup not found - no page was added.';
    END IF;

    IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
               WHERE "NavigationMenuId" = v_menu."Id"
               AND   lower(trim("RouteKey")) = 'overtime-structures'
               AND   "IsDeleted" = false) THEN
        RAISE NOTICE 'Page exists, skipped : Overtime Structures';
    ELSE
        IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
                   WHERE lower(trim("Name")) = 'overtime structures' AND "IsDeleted" = false) THEN
            RAISE EXCEPTION 'A submenu named "Overtime Structures" already exists elsewhere : names must be unique. Tell Claude.';
        END IF;

        SELECT COALESCE(MAX("SequenceNo"), 0) + 1 INTO v_seq
        FROM   "NavigationSubmenus"
        WHERE  "NavigationMenuId" = v_menu."Id";

        INSERT INTO "NavigationSubmenus"
            ("NavigationMenuId", "SequenceNo", "Code", "Name", "Icon",
             "RouteKey", "Route", "DisplayOrder", "Remarks",
             "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
        VALUES
            (v_menu."Id", v_seq,
             'SUB-' || lpad(v_module."SequenceNo"::text, 3, '0')
                    || '-' || lpad(v_menu."SequenceNo"::text, 3, '0')
                    || '-' || lpad(v_seq::text, 3, '0'),
             'Overtime Structures', 'fa-solid fa-stopwatch',
             'overtime-structures',
             '/' || v_module."RouteKey" || '/' || v_menu."RouteKey" || '/overtime-structures',
             v_seq, 'How overtime is paid : extra hours and extra days; picked on the Employee Profile. Hand-written page : never run Submenu / Code Sync.',
             true, false, 1, now());

        RAISE NOTICE 'Page created : Overtime Structures';
    END IF;
END $$;



