-- ==============================================================
-- Motor Bike Specifications : tables + sales switch
--
--   MotorBikeSpecifications      one per bike model (Registration
--                                Data for BRTA Form-17, size and
--                                tyres, website flag)
--   MotorBikeSpecificationItems  technical rows (Section, Label,
--                                Value)
--
-- 1. Drops the Code Sync baseline table "MotorBikeSpecifications"
--    (the one with an "Id" column) only when it is empty.
-- 2. Creates the two tables (safe to run again).
-- 3. Adds the switch CFG-MOD-008-0020 "Specifications Required
--    for Sale" on Sales Invoices - MB (critical, default ON) when
--    that page exists. An existing switch is left as it is.
--
-- Needs PostgreSQL 18 (uuidv7). ASCII only. Run the whole script.
-- ==============================================================

BEGIN;

-- --------------------------------------------------------------
-- 1. Baseline table from Code Sync
-- --------------------------------------------------------------

DO $$
DECLARE
    v_rows bigint;
BEGIN
    IF EXISTS
    (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'MotorBikeSpecifications'
          AND column_name = 'Id'
    )
    THEN
        EXECUTE 'SELECT count(*) FROM "MotorBikeSpecifications"' INTO v_rows;

        IF v_rows = 0 THEN
            DROP TABLE "MotorBikeSpecifications";
            RAISE NOTICE 'Baseline table MotorBikeSpecifications dropped.';
        ELSE
            RAISE EXCEPTION 'Baseline table MotorBikeSpecifications has % row(s). Clear it first, then run this script again.', v_rows;
        END IF;
    END IF;
END $$;


-- --------------------------------------------------------------
-- 2. Specifications (one live row per bike model)
-- --------------------------------------------------------------

CREATE TABLE IF NOT EXISTS "MotorBikeSpecifications"
(
    "MotorBikeSpecificationId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"                 uuid          NOT NULL DEFAULT uuidv7(),
    "SpecificationCode"        varchar(30)   NOT NULL,
    "BikeModelId"              bigint        NOT NULL,
    "EngineCc"                 numeric(8,2)  NOT NULL DEFAULT 0,
    "MotorPowerWatts"          integer       NOT NULL DEFAULT 0,
    "FuelType"                 varchar(20)   NOT NULL DEFAULT 'Petrol',
    "Cylinders"                integer       NOT NULL DEFAULT 1,
    "VehicleClass"             varchar(60)   NOT NULL DEFAULT '',
    "BodyType"                 varchar(60)   NOT NULL DEFAULT '',
    "SeatingCapacity"          integer       NOT NULL DEFAULT 2,
    "UnladenWeightKg"          numeric(8,2)  NOT NULL DEFAULT 0,
    "LadenWeightKg"            numeric(8,2)  NOT NULL DEFAULT 0,
    "Maker"                    varchar(150)  NOT NULL DEFAULT '',
    "CountryOfOrigin"          varchar(80)   NOT NULL DEFAULT '',
    "HorsePower"               varchar(60)   NOT NULL DEFAULT '',
    "Rpm"                      integer       NOT NULL DEFAULT 0,
    "WheelBaseMm"              integer       NOT NULL DEFAULT 0,
    "LengthMm"                 integer       NOT NULL DEFAULT 0,
    "WidthMm"                  integer       NOT NULL DEFAULT 0,
    "HeightMm"                 integer       NOT NULL DEFAULT 0,
    "TyreCount"                integer       NOT NULL DEFAULT 2,
    "FrontTyreSize"            varchar(40)   NOT NULL DEFAULT '',
    "RearTyreSize"             varchar(40)   NOT NULL DEFAULT '',
    "AxleCount"                integer       NOT NULL DEFAULT 1,
    "ShowOnWebsite"            boolean       NOT NULL DEFAULT true,
    "Remarks"                  varchar(1000) NOT NULL DEFAULT '',
    "Status"                   boolean       NOT NULL DEFAULT true,
    "IsDeleted"                boolean       NOT NULL DEFAULT false,
    "DeletedBy"                bigint        NULL,
    "DeletedDate"              timestamp with time zone NULL,
    "CreatedBy"                bigint        NOT NULL DEFAULT 0,
    "CreatedDate"              timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"               bigint        NULL,
    "ModifiedDate"             timestamp with time zone NULL,

    CONSTRAINT "CK_MotorBikeSpecifications_Fuel"
        CHECK ("FuelType" IN ('Petrol', 'Octane', 'Electric', 'Hybrid', 'Diesel', 'CNG')),

    CONSTRAINT "CK_MotorBikeSpecifications_Power"
        CHECK (("FuelType" = 'Electric' AND "MotorPowerWatts" > 0)
            OR ("FuelType" <> 'Electric' AND "EngineCc" > 0)),

    CONSTRAINT "CK_MotorBikeSpecifications_Seats"
        CHECK ("SeatingCapacity" BETWEEN 1 AND 9),

    CONSTRAINT "CK_MotorBikeSpecifications_Weights"
        CHECK ("UnladenWeightKg" >= 0 AND "LadenWeightKg" >= 0)
);

-- Form-17 fields (added 2026-11-07 18:40) : for a table made by
-- the first version of this script
ALTER TABLE "MotorBikeSpecifications"
    ADD COLUMN IF NOT EXISTS "HorsePower"    varchar(60) NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS "Rpm"           integer     NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS "WheelBaseMm"   integer     NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS "LengthMm"      integer     NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS "WidthMm"       integer     NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS "HeightMm"      integer     NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS "TyreCount"     integer     NOT NULL DEFAULT 2,
    ADD COLUMN IF NOT EXISTS "FrontTyreSize" varchar(40) NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS "RearTyreSize"  varchar(40) NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS "AxleCount"     integer     NOT NULL DEFAULT 1;

-- BRTA portal : a motor cycle has 1 axle (2026-11-07 19:21)
ALTER TABLE "MotorBikeSpecifications"
    ALTER COLUMN "AxleCount" SET DEFAULT 1;

CREATE UNIQUE INDEX IF NOT EXISTS "UX_MotorBikeSpecifications_PublicId"
    ON "MotorBikeSpecifications" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_MotorBikeSpecifications_Code"
    ON "MotorBikeSpecifications" ("SpecificationCode");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_MotorBikeSpecifications_Model_Live"
    ON "MotorBikeSpecifications" ("BikeModelId")
    WHERE "IsDeleted" = false;


-- --------------------------------------------------------------
-- 3. Technical rows
-- --------------------------------------------------------------

CREATE TABLE IF NOT EXISTS "MotorBikeSpecificationItems"
(
    "MotorBikeSpecificationItemId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "MotorBikeSpecificationId"     bigint       NOT NULL
        REFERENCES "MotorBikeSpecifications" ("MotorBikeSpecificationId") ON DELETE CASCADE,
    "Section"                      varchar(40)  NOT NULL,
    "LineNo"                       integer      NOT NULL DEFAULT 1,
    "Label"                        varchar(80)  NOT NULL,
    "Value"                        varchar(250) NOT NULL
);

CREATE INDEX IF NOT EXISTS "IX_MotorBikeSpecificationItems_Specification"
    ON "MotorBikeSpecificationItems" ("MotorBikeSpecificationId");


-- --------------------------------------------------------------
-- 4. Switch : Specifications Required for Sale (MB 0020)
-- --------------------------------------------------------------

DO $$
DECLARE
    v_module_id bigint;
    v_page_code text;
    v_menu_code text;
BEGIN
    IF EXISTS (SELECT 1 FROM "SystemConfigurations" WHERE "ConfigurationCode" = 'CFG-MOD-008-0020') THEN
        RAISE NOTICE 'Switch CFG-MOD-008-0020 already exists - left as it is.';
        RETURN;
    END IF;

    SELECT m."Id"
    INTO   v_module_id
    FROM   "NavigationModules" m
    WHERE  lower(trim(m."RouteKey")) = 'sales-operations'
    AND    upper(trim(m."Code")) = 'MOD-008'
    AND    NOT m."IsDeleted"
    LIMIT  1;

    SELECT s."Code", mn."Code"
    INTO   v_page_code, v_menu_code
    FROM   "NavigationSubmenus" s
    JOIN   "NavigationMenus" mn ON mn."Id" = s."NavigationMenuId"
    WHERE  s."Route" ILIKE '/sales-operations/%/sales-invoices-mb'
    AND    NOT s."IsDeleted"
    LIMIT  1;

    IF v_module_id IS NULL OR v_page_code IS NULL THEN
        RAISE NOTICE 'Sales Invoices - MB page not found - switch not added (run SalesOperations_Switches.sql later; it adds it too).';
        RETURN;
    END IF;

    INSERT INTO "SystemConfigurations"
    (
        "NavigationModuleId", "ScopeType", "NavigationMenuCode", "NavigationSubmenuCode",
        "ConfigurationCode", "ConfigurationName", "OnDescription", "OffDescription",
        "IsEnabled", "Value",
        "ValueType", "ValueUnit", "ValueMin", "ValueMax", "ValueEmptyText",
        "DefaultEnabled", "DefaultValue", "ParentConfigurationCode",
        "IsCritical", "IsSystemDefined", "DisplayOrder", "Remarks",
        "IsDeleted", "CreatedBy", "CreatedDate"
    )
    VALUES
    (
        v_module_id, 'Submenu', v_menu_code, v_page_code,
        'CFG-MOD-008-0020', 'Specifications Required for Sale',
        'A bike can be sold only when its model has an active Motor Bike Specification (Engine CC / motor power for registration).',
        'A bike can be sold without a specification.',
        true, '',
        'None', '', NULL, NULL, '',
        true, '', NULL,
        true, true, 20, 'Critical. Specifications : Settings > Product Settings > Motor Bike Specifications.',
        false, 1, now()
    );

    RAISE NOTICE 'Switch CFG-MOD-008-0020 Specifications Required for Sale added (ON).';
END $$;

COMMIT;


-- Check
SELECT table_name, count(*) AS columns
FROM information_schema.columns
WHERE table_schema = current_schema()
  AND table_name IN ('MotorBikeSpecifications', 'MotorBikeSpecificationItems')
GROUP BY table_name
ORDER BY table_name;

SELECT "ConfigurationCode", "ConfigurationName", "IsEnabled", "IsCritical"
FROM "SystemConfigurations"
WHERE "ConfigurationCode" = 'CFG-MOD-008-0020';
