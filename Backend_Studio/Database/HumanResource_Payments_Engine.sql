-- =====================================================================
-- HumanResource_Payments_Engine.sql   (2026-11-14)
-- ---------------------------------------------------------------------
-- Payments of Human Resource : one page, four kinds of payment.
--
--   Payroll Management > Payroll Payments
--       Salary          the net pay of a POSTED salary sheet
--       Overtime        the overtime of a POSTED salary sheet
--   Provident Fund > PF Payments
--       PfSettlement    the net payable of a settlement
--       PfLoan          a loan paid out to the member
--
-- A payment (PPY-010101-2627-11-00001, numbered as a voucher : branch,
-- financial year, month, serial; PFP- for the fund) pays one source (a salary sheet, a settlement
-- or a loan), in full or in part : any number of payments, never more
-- than what is still due. Saving it writes ONE Payment Voucher, posted
-- at once; cancelling the payment cancels that voucher.
--
--   Dr  Salary Payable / Overtime Payable / PF Settlement Payable /
--       PF Loan Receivable           (Posting Setup)
--   Cr  the cash / bank / MFS account(s) of the Payment Desk
--
-- 1. PaymentVoucher : "SourceType" and "ReferenceNo". A voucher with a
--    source belongs to another page : it shows on Payment Voucher with
--    its reference, and cannot be edited, cancelled or deleted there.
-- 2. HrPayments / HrPaymentLines.
-- 3. The two pages.
--
-- Safe to run more than once. ASCII only.
-- =====================================================================


-- ------------------------------------------------------------
-- 1. Payment Voucher : where it came from
-- ------------------------------------------------------------

ALTER TABLE public."PaymentVoucher"
    ADD COLUMN IF NOT EXISTS "SourceType"  character varying(30) NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS "ReferenceNo" character varying(60) NOT NULL DEFAULT '';


-- ------------------------------------------------------------
-- 2. Payments
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."HrPayments"
(
    "PaymentId"        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"         uuid                     NOT NULL DEFAULT uuidv7(),
    -- PPY-010101-2627-11-00001 (as a voucher number : branch,
    -- financial year, month, serial); PFP- for the fund
    "Code"             character varying(30)    NOT NULL,
    -- Salary / Overtime / PfSettlement / PfLoan
    "PaymentType"      character varying(15)    NOT NULL,
    -- SalarySheetId / PfSettlementId / PfLoanId
    "SourceId"         bigint                   NOT NULL,
    -- SAL-0001 / OTS-0001 / PFS-0001 / PFL-0001
    "SourceCode"       character varying(20)    NOT NULL DEFAULT '',
    "BranchId"         bigint                   NOT NULL,
    "PaymentDate"      date                     NOT NULL,
    "TotalAmount"      numeric(18,2)            NOT NULL DEFAULT 0,
    -- "Cash, Bank"
    "PaymentModes"     character varying(60)    NOT NULL DEFAULT '',
    "Remarks"          character varying(500)   NOT NULL DEFAULT '',
    "PaymentVoucherId" bigint                   NULL,
    "PaymentVoucherNo" character varying(30)    NOT NULL DEFAULT '',
    "IsCancelled"      boolean                  NOT NULL DEFAULT false,
    "CancelReason"     character varying(300)   NOT NULL DEFAULT '',
    "CancelledBy"      bigint                   NULL,
    "CancelledDate"    timestamp with time zone NULL,
    "CreatedBy"        bigint                   NOT NULL,
    "CreatedDate"      timestamp with time zone NOT NULL DEFAULT now()
);

-- (the table made before the number got the voucher format)
ALTER TABLE public."HrPayments"
    ALTER COLUMN "Code" TYPE character varying(30);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrPayments_PublicId" ON public."HrPayments" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrPayments_Code"     ON public."HrPayments" ("Code");
CREATE INDEX        IF NOT EXISTS "IX_HrPayments_Source"   ON public."HrPayments" ("PaymentType", "SourceId");

CREATE TABLE IF NOT EXISTS public."HrPaymentLines"
(
    "PaymentLineId"     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PaymentId"         bigint        NOT NULL
        REFERENCES public."HrPayments" ("PaymentId") ON DELETE CASCADE,
    "EmployeeId"        bigint        NOT NULL,
    -- the line of the salary sheet (0 : a settlement / a loan)
    "SalarySheetLineId" bigint        NOT NULL DEFAULT 0,
    "Amount"            numeric(18,2) NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS "IX_HrPaymentLines_Payment" ON public."HrPaymentLines" ("PaymentId");
CREATE INDEX IF NOT EXISTS "IX_HrPaymentLines_Line"    ON public."HrPaymentLines" ("SalarySheetLineId");


-- ------------------------------------------------------------
-- 3. Pages : Payroll Payments, PF Payments
-- ------------------------------------------------------------

DO $$
DECLARE
    v_module   record;
    v_menu     record;
    v_seq      int;
    v_code     text;
    s          record;
BEGIN
    SELECT "Id", "SequenceNo", "RouteKey" INTO v_module
    FROM   "NavigationModules"
    WHERE  lower(trim("RouteKey")) = 'human-resource-manangement'
    AND    "IsDeleted" = false
    LIMIT  1;

    IF v_module."Id" IS NULL THEN
        RAISE EXCEPTION 'Module with route key human-resource-manangement not found - no page was added.';
    END IF;

    FOR s IN
        SELECT * FROM (VALUES
            ('payroll-management', 'Payroll Payments', 'fa-solid fa-money-bill-transfer', 'payroll-payments', 'Pays the salary and the overtime of the posted salary sheets, in full or in part; every payment writes a Payment Voucher.'),
            ('provident-fund',     'PF Payments',      'fa-solid fa-money-bill-transfer', 'pf-payments',      'Pays the provident fund settlements and the loans of the fund; every payment writes a Payment Voucher.')
        ) AS x (menu_key, name, icon, route_key, remarks)
    LOOP
        SELECT "Id", "SequenceNo", "RouteKey" INTO v_menu
        FROM   "NavigationMenus"
        WHERE  "NavigationModuleId" = v_module."Id"
        AND    lower(trim("RouteKey")) = s.menu_key
        AND    "IsDeleted" = false
        LIMIT  1;

        IF v_menu."Id" IS NULL THEN
            RAISE EXCEPTION 'Menu % not found - run its engine script first.', s.menu_key;
        END IF;

        IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
                   WHERE "NavigationMenuId" = v_menu."Id"
                   AND   lower(trim("RouteKey")) = s.route_key
                   AND   "IsDeleted" = false) THEN
            RAISE NOTICE 'Page exists, skipped : %', s.name;
            CONTINUE;
        END IF;

        IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
                   WHERE lower(trim("Name")) = lower(s.name) AND "IsDeleted" = false) THEN
            RAISE EXCEPTION 'A submenu named "%" already exists elsewhere : names must be unique. Tell Claude.', s.name;
        END IF;

        SELECT COALESCE(MAX("SequenceNo"), 0) + 1 INTO v_seq
        FROM   "NavigationSubmenus"
        WHERE  "NavigationMenuId" = v_menu."Id";

        v_code :=
            'SUB-' || lpad(v_module."SequenceNo"::text, 3, '0')
                   || '-' || lpad(v_menu."SequenceNo"::text, 3, '0')
                   || '-' || lpad(v_seq::text, 3, '0');

        INSERT INTO "NavigationSubmenus"
            ("NavigationMenuId", "SequenceNo", "Code", "Name", "Icon",
             "RouteKey", "Route", "DisplayOrder", "Remarks",
             "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
        VALUES
            (v_menu."Id", v_seq, v_code, s.name, s.icon,
             s.route_key,
             '/' || v_module."RouteKey" || '/' || v_menu."RouteKey" || '/' || s.route_key,
             v_seq, s.remarks || ' Hand-written page : never run Submenu / Code Sync.',
             true, false, 1, now());

        RAISE NOTICE 'Page created : % %', v_code, s.name;
    END LOOP;
END $$;


-- ------------------------------------------------------------
-- Check (run on its own)
-- ------------------------------------------------------------
SELECT s."Code", s."Name", s."Route"
FROM   "NavigationSubmenus" s
WHERE  lower(s."RouteKey") IN ('payroll-payments', 'pf-payments') AND s."IsDeleted" = false
ORDER  BY s."Code";
