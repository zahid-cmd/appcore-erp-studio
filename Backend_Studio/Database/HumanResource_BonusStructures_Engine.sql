-- Bonus Structures (Human Resource Setup) : how a festival bonus is
-- worked out, and who gets it by the length of employment.
--
--   HrBonusStructures       BNS-0001 "Bonus Structure - 1" ...; one is
--                           the Default.
--                             RateBase       Basic / Gross
--                             ServiceFrom    Joining / Confirmation :
--                                            where the service is
--                                            counted from
--                             ConfirmedOnly  only confirmed employees
--   HrBonusStructureSlabs   the service slabs : from so many months of
--                           service, so many percent of the salary.
--                           An employee below the first slab gets no
--                           bonus.
--
--   bonus = salary (Basic or Gross) x the percent of the slab the
--           employee's months of service fall in       (whole taka)
--
-- Festival Bonus (generate) picks a structure. The sheet keeps what
-- the structure said that day (name, basis); each line keeps its
-- percent.
--
-- Run AFTER HumanResource_Bonus_Encashment_Engine.sql. Safe to run more
-- than once. ASCII only.
-- =====================================================================


-- ------------------------------------------------------------
-- 1. Tables
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."HrBonusStructures"
(
    "BonusStructureId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"         uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"             character varying(20)    NOT NULL,
    "Name"             character varying(100)   NOT NULL,
    -- Basic / Gross
    "RateBase"         character varying(10)    NOT NULL DEFAULT 'Basic',
    -- Joining / Confirmation
    "ServiceFrom"      character varying(15)    NOT NULL DEFAULT 'Joining',
    "ConfirmedOnly"    boolean                  NOT NULL DEFAULT false,
    "IsDefault"        boolean                  NOT NULL DEFAULT false,
    "Remarks"          character varying(500)   NOT NULL DEFAULT '',
    "IsActive"         boolean                  NOT NULL DEFAULT true,
    "IsDeleted"        boolean                  NOT NULL DEFAULT false,
    "DeletedBy"        bigint                   NULL,
    "DeletedDate"      timestamp with time zone NULL,
    "CreatedBy"        bigint                   NOT NULL,
    "CreatedDate"      timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"       bigint                   NULL,
    "ModifiedDate"     timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrBonusStructures_PublicId" ON public."HrBonusStructures" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_HrBonusStructures_Code"     ON public."HrBonusStructures" ("Code");

CREATE TABLE IF NOT EXISTS public."HrBonusStructureSlabs"
(
    "BonusStructureSlabId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BonusStructureId"     bigint       NOT NULL
        REFERENCES public."HrBonusStructures" ("BonusStructureId") ON DELETE CASCADE,
    -- from this many whole months of service (and above)
    "FromMonths"           integer      NOT NULL DEFAULT 0,
    "BonusPercent"         numeric(7,3) NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS "IX_HrBonusStructureSlabs_Structure" ON public."HrBonusStructureSlabs" ("BonusStructureId");


-- ------------------------------------------------------------
-- 2. The bonus sheet remembers its structure
-- ------------------------------------------------------------

ALTER TABLE public."HrBonusSheets"
    ADD COLUMN IF NOT EXISTS "BonusStructureId" bigint                 NULL,
    ADD COLUMN IF NOT EXISTS "StructureName"    character varying(100) NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS "ServiceFrom"      character varying(15)  NOT NULL DEFAULT 'Joining';

ALTER TABLE public."HrBonusSheetLines"
    ADD COLUMN IF NOT EXISTS "BonusPercent" numeric(7,3) NOT NULL DEFAULT 0;


-- ------------------------------------------------------------
-- 3. A first structure : the usual rule (only when there is none)
--      under 6 months        no bonus
--      6 to under 12 months  50 %
--      12 months and above   100 %
-- ------------------------------------------------------------

DO $$
DECLARE
    v_id bigint;
BEGIN
    IF EXISTS (SELECT 1 FROM public."HrBonusStructures") THEN
        RAISE NOTICE 'Bonus structures exist : no starter structure added.';
        RETURN;
    END IF;

    INSERT INTO public."HrBonusStructures"
        ("Code", "Name", "RateBase", "ServiceFrom", "ConfirmedOnly", "IsDefault", "Remarks", "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
    VALUES
        ('BNS-0001', 'Bonus Structure - 1', 'Basic', 'Joining', false, true, 'Starter structure : change it to your rule.', true, false, 1, now())
    RETURNING "BonusStructureId" INTO v_id;

    INSERT INTO public."HrBonusStructureSlabs" ("BonusStructureId", "FromMonths", "BonusPercent")
    VALUES (v_id, 6, 50), (v_id, 12, 100);

    RAISE NOTICE 'Starter structure added : BNS-0001 Bonus Structure - 1 (Default).';
END $$;


-- ------------------------------------------------------------
-- 4. Page : Bonus Structures (Human Resource Setup)
-- ------------------------------------------------------------

DO $$
DECLARE
    v_module   record;
    v_menu     record;
    v_seq      int;
    v_code     text;
BEGIN
    SELECT "Id", "SequenceNo", "RouteKey" INTO v_module
    FROM   "NavigationModules"
    WHERE  lower(trim("RouteKey")) = 'human-resource-manangement'
    AND    "IsDeleted" = false
    LIMIT  1;

    IF v_module."Id" IS NULL THEN
        RAISE EXCEPTION 'Module with route key human-resource-manangement not found - no page was added.';
    END IF;

    SELECT "Id", "SequenceNo", "RouteKey" INTO v_menu
    FROM   "NavigationMenus"
    WHERE  "NavigationModuleId" = v_module."Id"
    AND    lower(trim("RouteKey")) = 'human-resource-setup'
    AND    "IsDeleted" = false
    LIMIT  1;

    IF v_menu."Id" IS NULL THEN
        RAISE EXCEPTION 'Menu human-resource-setup not found - no page was added.';
    END IF;

    IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
               WHERE "NavigationMenuId" = v_menu."Id"
               AND   lower(trim("RouteKey")) = 'bonus-structures'
               AND   "IsDeleted" = false) THEN
        RAISE NOTICE 'Page exists, skipped : Bonus Structures';
        RETURN;
    END IF;

    IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
               WHERE lower(trim("Name")) = 'bonus structures' AND "IsDeleted" = false) THEN
        RAISE EXCEPTION 'A submenu named "Bonus Structures" already exists elsewhere : names must be unique. Tell Claude.';
    END IF;

    SELECT COALESCE(MAX("SequenceNo"), 0) + 1 INTO v_seq
    FROM   "NavigationSubmenus"
    WHERE  "NavigationMenuId" = v_menu."Id";

    v_code :=
        'SUB-' || lpad(v_module."SequenceNo"::text, 3, '0')
               || '-' || lpad(v_menu."SequenceNo"::text, 3, '0')
               || '-' || lpad(v_seq::text, 3, '0');

    INSERT INTO "NavigationSubmenus"
        ("NavigationMenuId", "SequenceNo", "Code", "Name", "Icon",
         "RouteKey", "Route", "DisplayOrder", "Remarks",
         "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
    VALUES
        (v_menu."Id", v_seq, v_code, 'Bonus Structures', 'fa-solid fa-gift',
         'bonus-structures',
         '/' || v_module."RouteKey" || '/' || v_menu."RouteKey" || '/bonus-structures',
         v_seq, 'How a festival bonus is worked out, and who gets it by the length of employment. Hand-written page : never run Submenu / Code Sync.',
         true, false, 1, now());

    RAISE NOTICE 'Page created : % Bonus Structures', v_code;
END $$;


-- ------------------------------------------------------------
-- Check (run on its own)
-- ------------------------------------------------------------
SELECT s."Code", s."Name", s."RateBase", s."ServiceFrom", s."IsDefault",
       (SELECT string_agg(l."FromMonths" || ' m : ' || l."BonusPercent" || ' %', ', ' ORDER BY l."FromMonths")
        FROM public."HrBonusStructureSlabs" l WHERE l."BonusStructureId" = s."BonusStructureId") AS "Slabs"
FROM   public."HrBonusStructures" s
WHERE  s."IsDeleted" = false
ORDER  BY s."Code";
