-- Settings > Account Settings > Check Books
--   /settings/account-settings/check-books
--   (hand-written page : NEVER run Submenu / Code Sync for it)
--
--   CheckBooks        CB-0001  one check book of one of our bank
--                              accounts (Payment = Yes) : a range of
--                              leaves, e.g. 1000001 - 1000050
--   CheckBookLeaves            one row per leaf : Unused / Issued /
--                              Cancelled / Lost / Void, and the
--                              voucher it went out on (phase 2 :
--                              Payment Voucher, Fund Transfer,
--                              Check Reconciliation)
--
-- Switches (Settings module MOD-003, page Check Books; the server
-- reads them by NAME, the code is the next free CFG-MOD-003-nnnn) :
--   "Check Leaf : Allow Choosing Another Leaf"   critical, ON
--       ON  : a voucher fills in the next unused leaf of the bank
--             account; the user may pick another unused leaf.
--       OFF : always the next unused leaf (lowest number).
--   "Low Check Leaf Warning"                     ON, 10 leaves
--       ON  : warns when a bank account has fewer unused leaves
--             than this; OFF : no warning.
--
-- Safe to run again (tables / indexes / submenu / switches are
-- skipped when they exist). Run the whole script (F5) on
-- AppCoreERP_Studio.
--
-- AFTER : Security & Permission > Activity Assignment : tick View /
-- Add / Update / Delete / Restore on Check Books for the roles,
-- then log in again.
-- ASCII only.
-- =====================================================================

-- ------------------------------------------------------------
-- 1. Tables
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public."CheckBooks"
(
    "CheckBookId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"      uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"          character varying(20)    NOT NULL,
    "BankAccountId" bigint                   NOT NULL,
    "BookNo"        character varying(50)    NOT NULL DEFAULT '',
    "Prefix"        character varying(10)    NOT NULL DEFAULT '',
    "StartNo"       bigint                   NOT NULL,
    "EndNo"         bigint                   NOT NULL,
    "NumberWidth"   integer                  NOT NULL DEFAULT 0,
    "LeafCount"     integer                  NOT NULL,
    "ReceivedDate"  date                     NOT NULL,
    "Remarks"       character varying(500)   NOT NULL DEFAULT '',
    "IsActive"      boolean                  NOT NULL DEFAULT true,
    "IsDeleted"     boolean                  NOT NULL DEFAULT false,
    "DeletedBy"     bigint                   NULL,
    "DeletedDate"   timestamp with time zone NULL,
    "CreatedBy"     bigint                   NOT NULL,
    "CreatedDate"   timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"    bigint                   NULL,
    "ModifiedDate"  timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_CheckBooks_PublicId"
    ON public."CheckBooks" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_CheckBooks_Code"
    ON public."CheckBooks" ("Code");

CREATE INDEX IF NOT EXISTS "IX_CheckBooks_BankAccount"
    ON public."CheckBooks" ("BankAccountId");

CREATE TABLE IF NOT EXISTS public."CheckBookLeaves"
(
    "CheckBookLeafId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CheckBookId"     bigint                   NOT NULL,
    "BankAccountId"   bigint                   NOT NULL,
    "LeafNo"          bigint                   NOT NULL,
    "CheckNo"         character varying(30)    NOT NULL,
    "Status"          character varying(20)    NOT NULL DEFAULT 'Unused',
    "SourceType"      character varying(10)    NOT NULL DEFAULT '',
    "SourceId"        bigint                   NULL,
    "SourceNo"        character varying(40)    NOT NULL DEFAULT '',
    "PayeeName"       character varying(200)   NOT NULL DEFAULT '',
    "Amount"          numeric(18,2)            NOT NULL DEFAULT 0,
    "IssuedDate"      date                     NULL,
    "Reason"          character varying(300)   NOT NULL DEFAULT '',
    "StatusBy"        bigint                   NULL,
    "StatusDate"      timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_CheckBookLeaves_Book_Leaf"
    ON public."CheckBookLeaves" ("CheckBookId", "LeafNo");

CREATE INDEX IF NOT EXISTS "IX_CheckBookLeaves_Account_Status"
    ON public."CheckBookLeaves" ("BankAccountId", "Status", "LeafNo");

CREATE INDEX IF NOT EXISTS "IX_CheckBookLeaves_Source"
    ON public."CheckBookLeaves" ("SourceType", "SourceId");

-- ------------------------------------------------------------
-- 2. Submenu Settings > Account Settings > Check Books
-- ------------------------------------------------------------
DO $$
DECLARE
    v_module record;
    v_menu   record;
    v_seq    int;
BEGIN
    SELECT "Id", "SequenceNo", "RouteKey" INTO v_module
    FROM   "NavigationModules"
    WHERE  lower("RouteKey") = 'settings' AND "IsDeleted" = false;

    IF v_module."Id" IS NULL THEN
        RAISE EXCEPTION 'Module with route key settings not found - nothing changed.';
    END IF;

    SELECT "Id", "SequenceNo", "RouteKey" INTO v_menu
    FROM   "NavigationMenus"
    WHERE  "NavigationModuleId" = v_module."Id"
    AND    lower("RouteKey") = 'account-settings'
    AND    "IsDeleted" = false;

    IF v_menu."Id" IS NULL THEN
        RAISE EXCEPTION 'Menu account-settings not found under Settings - nothing changed.';
    END IF;

    IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
               WHERE "NavigationMenuId" = v_menu."Id"
               AND   lower("RouteKey") = 'check-books'
               AND   "IsDeleted" = false) THEN
        RAISE NOTICE 'Submenu Check Books exists, skipped.';
    ELSE
        IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
                   WHERE lower("Name") = 'check books' AND "IsDeleted" = false) THEN
            RAISE EXCEPTION 'A submenu named "Check Books" already exists elsewhere : names must be unique.';
        END IF;

        SELECT COALESCE(MAX("SequenceNo"), 0) + 1 INTO v_seq
        FROM   "NavigationSubmenus"
        WHERE  "NavigationMenuId" = v_menu."Id";

        INSERT INTO "NavigationSubmenus"
            ("NavigationMenuId", "SequenceNo", "Code", "Name", "Icon",
             "RouteKey", "Route", "DisplayOrder", "Remarks",
             "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
        VALUES
            (v_menu."Id", v_seq,
             'SUB-' || lpad(v_module."SequenceNo"::text, 3, '0')
                    || '-' || lpad(v_menu."SequenceNo"::text, 3, '0')
                    || '-' || lpad(v_seq::text, 3, '0'),
             'Check Books', 'fa-solid fa-money-check',
             'check-books',
             '/' || v_module."RouteKey" || '/' || v_menu."RouteKey" || '/check-books',
             v_seq, 'Hand-written page : never run Submenu / Code Sync.',
             true, false, 1, now());

        RAISE NOTICE 'Submenu created : Check Books';
    END IF;
END $$;

-- ------------------------------------------------------------
-- 3. Switches (page switches of Check Books, Settings MOD-003)
-- ------------------------------------------------------------
DO $$
DECLARE
    v_module_id   bigint;
    v_module_code text;
    v_page_code   text;
    v_menu_code   text;
    v_next        int;
    v_switch      record;
BEGIN
    SELECT m."Id", m."Code" INTO v_module_id, v_module_code
    FROM   "NavigationModules" m
    WHERE  lower(trim(m."RouteKey")) = 'settings' AND NOT m."IsDeleted"
    LIMIT  1;

    IF upper(trim(v_module_code)) <> 'MOD-003' THEN
        RAISE EXCEPTION 'Settings module code is % (expected MOD-003) - switches not added. Tell Claude the code.', v_module_code;
    END IF;

    SELECT s."Code", mn."Code" INTO v_page_code, v_menu_code
    FROM   "NavigationSubmenus" s
    JOIN   "NavigationMenus" mn ON mn."Id" = s."NavigationMenuId"
    WHERE  lower(s."RouteKey") = 'check-books' AND NOT s."IsDeleted"
    LIMIT  1;

    IF v_page_code IS NULL THEN
        RAISE EXCEPTION 'The Check Books submenu is missing - switches not added.';
    END IF;

    FOR v_switch IN
        SELECT *
        FROM
        (
            VALUES
            (1,
             'Check Leaf : Allow Choosing Another Leaf',
             'A voucher fills in the next unused leaf of the bank account; the user may pick another unused leaf of that account.',
             'A voucher always takes the next unused leaf (the lowest number) of the bank account; it cannot be changed.',
             true, '', 'None', '', NULL::int, NULL::int, true,
             'Critical : changing it needs a reason / approval. Used by Payment Voucher and Fund Transfer check rows.'),
            (2,
             'Low Check Leaf Warning',
             'Warns on Check Books and on the vouchers when a bank account has fewer unused leaves than this.',
             'No warning about the leaves left.',
             true, '10', 'Number', 'leaves', 1, 500, false,
             'Counts the unused leaves of the active books of each bank account.')
        ) AS s (no, name, on_text, off_text, enabled, val, vtype, vunit, vmin, vmax, critical, remarks)
    LOOP
        IF EXISTS (SELECT 1 FROM "SystemConfigurations"
                   WHERE "ConfigurationName" = v_switch.name
                   AND   "NavigationSubmenuCode" = v_page_code
                   AND   NOT "IsDeleted") THEN
            RAISE NOTICE 'Switch "%" exists, skipped.', v_switch.name;
            CONTINUE;
        END IF;

        -- next free CFG-MOD-003-nnnn (all codes of the module count)
        SELECT COALESCE(MAX(substring("ConfigurationCode" FROM 13)::int), 0) + 1 INTO v_next
        FROM   "SystemConfigurations"
        WHERE  "ConfigurationCode" ~ '^CFG-MOD-003-[0-9]{4}$';

        INSERT INTO "SystemConfigurations"
        (
            "NavigationModuleId", "ScopeType", "NavigationMenuCode", "NavigationSubmenuCode",
            "ConfigurationCode", "ConfigurationName", "OnDescription", "OffDescription",
            "IsEnabled", "Value",
            "ValueType", "ValueUnit", "ValueMin", "ValueMax", "ValueEmptyText",
            "DefaultEnabled", "DefaultValue", "ParentConfigurationCode",
            "IsCritical", "IsSystemDefined", "DisplayOrder", "Remarks",
            "IsDeleted", "CreatedBy", "CreatedDate"
        )
        VALUES
        (
            v_module_id, 'Submenu', v_menu_code, v_page_code,
            'CFG-MOD-003-' || lpad(v_next::text, 4, '0'), v_switch.name, v_switch.on_text, v_switch.off_text,
            v_switch.enabled, v_switch.val,
            v_switch.vtype, v_switch.vunit, v_switch.vmin, v_switch.vmax, '',
            v_switch.enabled, v_switch.val, NULL,
            v_switch.critical, true, v_switch.no, v_switch.remarks,
            false, 1, now()
        );

        RAISE NOTICE 'Switch "%" added as CFG-MOD-003-%.', v_switch.name, lpad(v_next::text, 4, '0');
    END LOOP;
END $$;

