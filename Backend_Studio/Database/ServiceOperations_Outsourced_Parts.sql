-- Service Operations : Parts Outsourcing on a job card.
--
-- A part the store does not have (or cannot give in time) is bought
-- from a local vendor for ONE job card. No purchase order, no purchase
-- invoice, no stock : the part goes straight to the job.
--
--   JobCardOutsourcedParts   WOP-<branch>-<FY>-<MM>-00001 : one part
--                            bought outside for a job card. The part
--                            is one of the product lists (the same
--                            branded part) or typed. The vendor is a
--                            Supplier Profile or a typed name.
--                            CostRate  = what the vendor charges
--                            SellRate  = what the customer pays (the
--                                        price of Price Setup unless
--                                        changed; above it only with
--                                        the page action below)
--
-- Accounting (voucher type WOP, posted when the entry is saved) :
--   Dr Workshop WIP              Cr the payable ledger of the supplier
--                                   (Supplier Profile), or the ledger
--                                   of Posting Setup "Workshop -
--                                   Outsourced Parts Payable" when the
--                                   vendor is typed
-- The service invoice bills the part at SellRate and moves its cost :
--   Dr cost of goods sold        Cr Workshop WIP
-- (a typed part : Posting Setup "Workshop - Outsourced Parts Cost").
-- The vendor is paid later with a Payment Voucher.
--
-- Page action "Sell Above MRP" on Job Cards : the users who have it
-- can bill an outsourced part above its price of Price Setup.
--
-- No new page : the entry is on the job card, tab Parts Needed.
-- Hand-written pages : NEVER run Menu / Submenu / Code Sync for them.
--
-- Run ServiceOperations_Workshop_Engine.sql, ServiceOperations_Parts_
-- Engine.sql and ServiceOperations_Billing_Engine.sql first.
-- Safe to run more than once. Run the whole script (F5). ASCII only.
--
-- AFTER : restart the API. Settings > Account Settings > Posting Setup
-- (group Service Operations) : select the two new ledgers. Security &
-- Permission > Activity Assignment : tick Sell Above MRP on Job Cards
-- for the roles that may, log in again.
-- =====================================================================


-- ------------------------------------------------------------
-- 1. The table
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."JobCardOutsourcedParts"
(
    "JobCardOutsourcedPartId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"          uuid                     NOT NULL DEFAULT gen_random_uuid(),
    "PurchaseNo"        character varying(30)    NOT NULL,
    "PurchaseDate"      date                     NOT NULL,
    "BranchId"          bigint                   NOT NULL,
    "JobCardId"         bigint                   NOT NULL,
    "ItemKind"          character varying(20)    NOT NULL DEFAULT 'Other',
    "ItemId"            bigint                   NULL,
    "ItemCode"          character varying(40)    NOT NULL DEFAULT '',
    "ItemName"          character varying(200)   NOT NULL DEFAULT '',
    "SupplierId"        bigint                   NULL,
    "SupplierCode"      character varying(30)    NOT NULL DEFAULT '',
    "VendorName"        character varying(150)   NOT NULL DEFAULT '',
    "BillNo"            character varying(60)    NOT NULL DEFAULT '',
    "Quantity"          numeric(18,2)            NOT NULL DEFAULT 0,
    "CostRate"          numeric(18,2)            NOT NULL DEFAULT 0,
    "CostAmount"        numeric(18,2)            NOT NULL DEFAULT 0,
    "Mrp"               numeric(18,2)            NULL,
    "SellRate"          numeric(18,2)            NOT NULL DEFAULT 0,
    "SellAmount"        numeric(18,2)            NOT NULL DEFAULT 0,
    "WipLedgerCode"     character varying(30)    NOT NULL DEFAULT '',
    "PayableLedgerCode" character varying(30)    NOT NULL DEFAULT '',
    "Status"            character varying(20)    NOT NULL DEFAULT 'Posted',
    "CancelReason"      character varying(300)   NOT NULL DEFAULT '',
    "Note"              character varying(200)   NOT NULL DEFAULT '',
    "CreatedBy"         bigint                   NOT NULL DEFAULT 1,
    "CreatedDate"       timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"        bigint                   NULL,
    "ModifiedDate"      timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_JobCardOutsourcedParts_PublicId" ON public."JobCardOutsourcedParts" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_JobCardOutsourcedParts_No"       ON public."JobCardOutsourcedParts" ("PurchaseNo");
CREATE INDEX        IF NOT EXISTS "IX_JobCardOutsourcedParts_JobCard"  ON public."JobCardOutsourcedParts" ("JobCardId");
CREATE INDEX        IF NOT EXISTS "IX_JobCardOutsourcedParts_Supplier" ON public."JobCardOutsourcedParts" ("SupplierId");


