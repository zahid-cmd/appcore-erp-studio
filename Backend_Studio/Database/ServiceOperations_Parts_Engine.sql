-- Service Operations, step 3 (claude\blueprint-service-operations.md) :
-- the parts of a job card.
--
--   PartsRequisitions        PRQ-000001 : the workshop asks the store
--                            for parts of a job card.
--                            Open -> Partly Issued -> Issued; Cancelled.
--   PartsRequisitionLines    spare parts / lubricants / accessories of
--                            the product lists, with what was issued
--   PartsIssues              WPI-<branch>-<FY>-<MM>-00001 : the store issues parts to a
--                            job card from a warehouse of the service
--                            center. FIFO batches; stock goes out; the
--                            cost moves to Workshop WIP (journal
--                            voucher : Dr Workshop WIP, Cr inventory).
--                            Posted at once (no draft).
--   PartsIssueLines          with the FIFO cost and what came back
--   PartsReturns             WPR-<branch>-<FY>-<MM>-00001 : unused parts of an issue go
--                            back to the same batches (journal voucher
--                            : Dr inventory, Cr Workshop WIP)
--   PartsReturnLines
--   PartsReturnAllocations   which batch slice of the issue each
--                            returned quantity went back to
--   WorkshopConfiguration    + IssueWithoutRequisition : ON = parts
--                            can be issued to a job card directly;
--                            OFF = only against a requisition
--
-- Parts Back-Orders has no table : it is the list of requisition
-- lines still waiting that the service center has not enough stock
-- for.
--
-- The pages are there already (ServiceOperations_Navigation.sql) :
-- Workshop Management > Parts Requisitions / Parts Issues / Parts
-- Returns / Parts Back-Orders. Hand-written pages : NEVER run Menu /
-- Submenu / Code Sync for them.
--
-- Run ServiceOperations_Workshop_Engine.sql and ServiceOperations_
-- Estimates_Engine.sql first. Safe to run more than once. Run the
-- whole script (F5). ASCII only.
--
-- AFTER : Security & Permission > Activity Assignment : tick the four
-- pages for the roles, log in again. Settings > Account Settings >
-- Posting Setup, group "Service Operations" : select the Workshop WIP
-- ledger (needed before the first parts issue).
-- =====================================================================


