-- ------------------------------------------------------------
-- 5. Stock movement types : PartsIssue / PartsReturn are added to
--    the list the table allows (whatever the list is now)
-- ------------------------------------------------------------

DO $$
DECLARE
    v_def text;
    v_new text;
BEGIN
    SELECT pg_get_constraintdef(c.oid) INTO v_def
    FROM   pg_constraint c
    WHERE  c.conname = 'CK_StockMovements_Type'
    AND    c.conrelid = 'public."StockMovements"'::regclass;

    IF v_def IS NULL THEN
        RAISE NOTICE 'CK_StockMovements_Type not found : nothing to change.';
    ELSIF position('PartsIssue' in v_def) > 0 THEN
        RAISE NOTICE 'CK_StockMovements_Type : parts movement types are there already.';
    ELSE
        -- the list is rebuilt from the names found in the present
        -- check, whatever way PostgreSQL writes it
        SELECT string_agg(quote_literal(m[1]), ', ') INTO v_new
        FROM   regexp_matches(v_def, '''([^'']+)''', 'g') AS m;

        IF v_new IS NULL THEN
            RAISE EXCEPTION 'CK_StockMovements_Type has no movement types : %', v_def;
        END IF;

        v_new := 'CHECK ("MovementType" IN (' || v_new || ', ''PartsIssue'', ''PartsReturn''))'
                 || CASE WHEN v_def LIKE '%NOT VALID' THEN ' NOT VALID' ELSE '' END;

        ALTER TABLE public."StockMovements" DROP CONSTRAINT "CK_StockMovements_Type";

        EXECUTE 'ALTER TABLE public."StockMovements" ADD CONSTRAINT "CK_StockMovements_Type" ' || v_new;

        RAISE NOTICE 'CK_StockMovements_Type : PartsIssue and PartsReturn added.';
    END IF;
END $$;


-- ------------------------------------------------------------
-- 6. Auto Journal Registers : the journals of the parts issues
--    (WPI) and parts returns (WPR) under their pages
-- ------------------------------------------------------------

DO $$
DECLARE
    p      record;
    v_code text;
BEGIN
    IF to_regclass('public."AutoJournalSources"') IS NULL THEN
        RAISE NOTICE 'AutoJournalSources not found : skipped (the journals show under Other).';
        RETURN;
    END IF;

    FOR p IN
        SELECT * FROM (VALUES
            ('WPI', 'parts-issues',  71, 'Parts issue : workshop WIP, stock out'),
            ('WPR', 'parts-returns', 72, 'Parts return : stock back, workshop WIP')
        ) AS x (voucher_type, route_key, ord, remarks)
    LOOP
        SELECT s."Code" INTO v_code
        FROM   "NavigationSubmenus" s
        WHERE  s."Route" ILIKE '/service-operations/%/' || p.route_key
        AND    NOT s."IsDeleted"
        LIMIT  1;

        INSERT INTO public."AutoJournalSources"
            ("VoucherType", "SourceTable", "NavigationSubmenuCode", "IsAutoJournal", "DisplayOrder", "Remarks")
        VALUES
            (p.voucher_type, '', COALESCE(v_code, ''), true, p.ord, p.remarks)
        ON CONFLICT ("VoucherType", "SourceTable") DO UPDATE
        SET "NavigationSubmenuCode" = EXCLUDED."NavigationSubmenuCode"
        WHERE public."AutoJournalSources"."NavigationSubmenuCode" = ''
        AND   EXCLUDED."NavigationSubmenuCode" <> '';
    END LOOP;
END $$;


