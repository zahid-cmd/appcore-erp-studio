-- ============================================================
-- Product Fitments (Product Settings) - 2026-11-06
--
-- "Fits models" : a spare part / accessory lives in ONE sub
-- category (its home : stock, price, ledgers) and may also fit
-- other sub categories (models) of the same Product Category.
-- One row per extra sub category. Information only : no stock,
-- price or ledger moves with a link.
--
-- Plain statements only : run in a NEW pgAdmin Query Tool with
-- F5. Safe to run again.
-- ============================================================

CREATE TABLE IF NOT EXISTS public."SparePartFitments"
(
    "SparePartFitmentId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "SparePartId"          bigint                   NOT NULL,
    "ProductSubCategoryId" bigint                   NOT NULL,
    "CreatedBy"            bigint                   NOT NULL,
    "CreatedDate"          timestamp with time zone NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_SparePartFitments_Part_SubCategory"
    ON public."SparePartFitments" ("SparePartId", "ProductSubCategoryId");

CREATE INDEX IF NOT EXISTS "IX_SparePartFitments_SubCategory"
    ON public."SparePartFitments" ("ProductSubCategoryId");


CREATE TABLE IF NOT EXISTS public."AccessoryFitments"
(
    "AccessoryFitmentId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "AccessoryId"          bigint                   NOT NULL,
    "ProductSubCategoryId" bigint                   NOT NULL,
    "CreatedBy"            bigint                   NOT NULL,
    "CreatedDate"          timestamp with time zone NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_AccessoryFitments_Accessory_SubCategory"
    ON public."AccessoryFitments" ("AccessoryId", "ProductSubCategoryId");

CREATE INDEX IF NOT EXISTS "IX_AccessoryFitments_SubCategory"
    ON public."AccessoryFitments" ("ProductSubCategoryId");


SELECT
    (SELECT count(*) FROM public."SparePartFitments") AS "SparePartFitments",
    (SELECT count(*) FROM public."AccessoryFitments") AS "AccessoryFitments";
