-- ============================================================
-- Storage Bins - Stage 1 (2026-11-02).
-- Warehouse -> Zone -> Rack -> Shelf -> Bin. The BIN is the
-- location : one bin holds ONE item (spare part OR accessory).
--
-- Plain statements and DO blocks : run in a NEW pgAdmin Query
-- Tool (F5). Safe to run again. Nothing existing breaks : every
-- saved place becomes bin 1 of its shelf.
--
-- 1. RackZones          : zones of a warehouse (Z-01, Z-02 ...)
-- 2. RackShelves        : bins per shelf of every rack
-- 3. RackSubCategories  : sub categories a rack is assigned to
-- 4. RackManagements    : + RackZoneId, ProductCategoryId,
--                         PrimeShelfFrom, PrimeShelfTo
-- 5. Seed : a zone "Z-01 General" (priority 1) for every
--    warehouse that has racks and no zone; its racks are put in
--    it. One RackShelves row (1 bin) per existing shelf.
-- 6. BinNumber on SparePartLocations / AccessoryLocations
--    (existing rows = bin 1)
-- 7. Bin on the lines that carry a place :
--      OpeningStockLines.BinNumber
--      MotorBikeReceivingLines / SparePartsLubricantsReceivingLines /
--      AccessoriesReceivingLines .BinNumber
--      ProductTransferLines.ToBinNo
--      MassStoringLines.FromBinNo / ToBinNo
--    (existing placed lines = bin 1; a table that does not exist
--    yet is skipped)
-- 8. MovementClass / MovementClassAuto on SpareParts and
--    Accessories (default Slow)
-- ============================================================


-- ------------------------------------------------------------
-- 1. RackZones
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."RackZones"
(
    "RackZoneId"         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BranchId"           bigint                  NOT NULL,
    "WarehouseId"        bigint                  NOT NULL,
    "ZoneCode"           character varying(20)   NOT NULL,
    "ZoneName"           character varying(100)  NOT NULL,
    "Priority"           integer                 NOT NULL DEFAULT 1,
    "Remarks"            character varying(1000) NOT NULL DEFAULT '',
    "IsActive"           boolean                 NOT NULL DEFAULT true,
    "IsDeleted"          boolean                 NOT NULL DEFAULT false,
    "DeletedBy"          bigint                  NULL,
    "DeletedDate"        timestamp with time zone NULL,
    "CreatedBy"          bigint                  NOT NULL,
    "CreatedDate"        timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"         bigint                  NULL,
    "ModifiedDate"       timestamp with time zone NULL,
    CONSTRAINT "CK_RackZones_Priority" CHECK ("Priority" >= 1)
);

CREATE INDEX IF NOT EXISTS "IX_RackZones_WarehouseId"
    ON public."RackZones" ("WarehouseId");

CREATE UNIQUE INDEX IF NOT EXISTS "IX_RackZones_WarehouseId_ZoneCode"
    ON public."RackZones" ("WarehouseId", "ZoneCode")
    WHERE "IsDeleted" = false;


-- ------------------------------------------------------------
-- 2. RackShelves (one row per shelf; BinCount 1 .. 60)
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."RackShelves"
(
    "RackShelfId"        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "RackManagementId"   bigint                  NOT NULL,
    "ShelfNumber"        integer                 NOT NULL,
    "BinCount"           integer                 NOT NULL DEFAULT 1,
    CONSTRAINT "CK_RackShelves_BinCount" CHECK ("BinCount" BETWEEN 1 AND 60)
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_RackShelves_RackManagementId_ShelfNumber"
    ON public."RackShelves" ("RackManagementId", "ShelfNumber");


-- ------------------------------------------------------------
-- 3. RackSubCategories
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."RackSubCategories"
(
    "RackSubCategoryId"    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "RackManagementId"     bigint                NOT NULL,
    "ProductSubCategoryId" bigint                NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_RackSubCategories_RackManagementId_ProductSubCategoryId"
    ON public."RackSubCategories" ("RackManagementId", "ProductSubCategoryId");


-- ------------------------------------------------------------
-- 4. RackManagements : zone, assignment, prime shelves
-- ------------------------------------------------------------

ALTER TABLE public."RackManagements" ADD COLUMN IF NOT EXISTS "RackZoneId"        bigint  NULL;
ALTER TABLE public."RackManagements" ADD COLUMN IF NOT EXISTS "ProductCategoryId" bigint  NULL;
ALTER TABLE public."RackManagements" ADD COLUMN IF NOT EXISTS "PrimeShelfFrom"    integer NULL;
ALTER TABLE public."RackManagements" ADD COLUMN IF NOT EXISTS "PrimeShelfTo"      integer NULL;

CREATE INDEX IF NOT EXISTS "IX_RackManagements_RackZoneId"
    ON public."RackManagements" ("RackZoneId");


-- ------------------------------------------------------------
-- 5a. Seed : "Z-01 General" for every warehouse that has live
--     racks and no zone yet. The old Zone / Aisle texts of its
--     racks are kept in the zone's Remarks.
-- ------------------------------------------------------------

INSERT INTO public."RackZones"
(
    "BranchId", "WarehouseId", "ZoneCode", "ZoneName", "Priority",
    "Remarks", "IsActive", "IsDeleted", "CreatedBy", "CreatedDate"
)
SELECT
    MIN(r."BranchId"),
    r."WarehouseId",
    'Z-01',
    'General',
    1,
    LEFT(COALESCE('Old Zone / Aisle: ' || string_agg(DISTINCT NULLIF(trim(r."ZoneAisle"), ''), ', '), ''), 1000),
    true,
    false,
    MIN(r."CreatedBy"),
    now()
FROM public."RackManagements" r
WHERE r."IsDeleted" = false
  AND NOT EXISTS
      (
          SELECT 1
          FROM   public."RackZones" z
          WHERE  z."WarehouseId" = r."WarehouseId"
      )
GROUP BY r."WarehouseId";


-- ------------------------------------------------------------
-- 5b. Racks without a zone -> the first live zone of their
--     warehouse (priority, then code)
-- ------------------------------------------------------------

UPDATE public."RackManagements" r
SET    "RackZoneId" =
       (
           SELECT z."RackZoneId"
           FROM   public."RackZones" z
           WHERE  z."WarehouseId" = r."WarehouseId"
             AND  z."IsDeleted" = false
           ORDER  BY z."Priority", z."ZoneCode"
           LIMIT  1
       )
WHERE  r."RackZoneId" IS NULL
  AND  EXISTS
       (
           SELECT 1
           FROM   public."RackZones" z
           WHERE  z."WarehouseId" = r."WarehouseId"
             AND  z."IsDeleted" = false
       );


-- ------------------------------------------------------------
-- 5c. One RackShelves row (1 bin) for every shelf of every rack
-- ------------------------------------------------------------

INSERT INTO public."RackShelves" ("RackManagementId", "ShelfNumber", "BinCount")
SELECT r."RackManagementId", s.n, 1
FROM   public."RackManagements" r
CROSS  JOIN LATERAL generate_series(1, GREATEST(r."ShelfCount", 0)) AS s(n)
ON CONFLICT ("RackManagementId", "ShelfNumber") DO NOTHING;


-- ------------------------------------------------------------
-- 6. Product locations : the bin (existing rows = bin 1)
-- ------------------------------------------------------------

ALTER TABLE public."SparePartLocations" ADD COLUMN IF NOT EXISTS "BinNumber" integer NOT NULL DEFAULT 1;

ALTER TABLE public."AccessoryLocations" ADD COLUMN IF NOT EXISTS "BinNumber" integer NOT NULL DEFAULT 1;

UPDATE public."SparePartLocations" SET "BinNumber" = 1 WHERE "BinNumber" < 1;

UPDATE public."AccessoryLocations" SET "BinNumber" = 1 WHERE "BinNumber" < 1;

CREATE INDEX IF NOT EXISTS "IX_SparePartLocations_Rack_Shelf_Bin"
    ON public."SparePartLocations" ("RackManagementId", "ShelfNumber", "BinNumber");

CREATE INDEX IF NOT EXISTS "IX_AccessoryLocations_Rack_Shelf_Bin"
    ON public."AccessoryLocations" ("RackManagementId", "ShelfNumber", "BinNumber");


-- ------------------------------------------------------------
-- 7a. Opening Stock and Product Receiving lines : BinNumber
--     (0 = no place, like ShelfNumber 0; placed lines = bin 1)
-- ------------------------------------------------------------

DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['OpeningStockLines',
                             'MotorBikeReceivingLines',
                             'SparePartsLubricantsReceivingLines',
                             'AccessoriesReceivingLines']
    LOOP
        IF to_regclass(format('public.%I', t)) IS NULL THEN
            RAISE NOTICE '% : table not found, skipped', t;
            CONTINUE;
        END IF;

        EXECUTE format('ALTER TABLE public.%I ADD COLUMN IF NOT EXISTS "BinNumber" integer NOT NULL DEFAULT 0', t);

        EXECUTE format('UPDATE public.%I SET "BinNumber" = 1 WHERE "ShelfNumber" > 0 AND "BinNumber" < 1', t);

        RAISE NOTICE '% : BinNumber ready', t;
    END LOOP;
END $$;


-- ------------------------------------------------------------
-- 7b. Product Transfer lines : ToBinNo (next to ToShelfNo)
-- ------------------------------------------------------------

DO $$
BEGIN
    IF to_regclass('public."ProductTransferLines"') IS NULL THEN
        RAISE NOTICE 'ProductTransferLines : table not found, skipped';
        RETURN;
    END IF;

    ALTER TABLE public."ProductTransferLines" ADD COLUMN IF NOT EXISTS "ToBinNo" integer NULL;

    UPDATE public."ProductTransferLines"
    SET    "ToBinNo" = 1
    WHERE  "ToShelfNo" IS NOT NULL
      AND  "ToBinNo" IS NULL;

    RAISE NOTICE 'ProductTransferLines : ToBinNo ready';
END $$;


-- ------------------------------------------------------------
-- 7c. Mass Storing lines : FromBinNo / ToBinNo
-- ------------------------------------------------------------

DO $$
BEGIN
    IF to_regclass('public."MassStoringLines"') IS NULL THEN
        RAISE NOTICE 'MassStoringLines : table not found, skipped';
        RETURN;
    END IF;

    ALTER TABLE public."MassStoringLines" ADD COLUMN IF NOT EXISTS "FromBinNo" integer NULL;

    ALTER TABLE public."MassStoringLines" ADD COLUMN IF NOT EXISTS "ToBinNo" integer NULL;

    UPDATE public."MassStoringLines"
    SET    "FromBinNo" = 1
    WHERE  "FromShelfNo" IS NOT NULL
      AND  "FromBinNo" IS NULL;

    UPDATE public."MassStoringLines"
    SET    "ToBinNo" = 1
    WHERE  "ToShelfNo" IS NOT NULL
      AND  "ToBinNo" IS NULL;

    RAISE NOTICE 'MassStoringLines : FromBinNo / ToBinNo ready';
END $$;


-- ------------------------------------------------------------
-- 8. Movement Class (Spare Parts and Accessories)
--    SuperFast / Fast / Regular / Periodic / Slow (default)
--    MovementClassAuto : reserved (automatic class from sales)
-- ------------------------------------------------------------

DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['SpareParts', 'Accessories']
    LOOP
        IF to_regclass(format('public.%I', t)) IS NULL THEN
            RAISE NOTICE '% : table not found, skipped', t;
            CONTINUE;
        END IF;

        EXECUTE format('ALTER TABLE public.%I ADD COLUMN IF NOT EXISTS "MovementClass" character varying(20) NOT NULL DEFAULT ''Slow''', t);

        EXECUTE format('ALTER TABLE public.%I ADD COLUMN IF NOT EXISTS "MovementClassAuto" boolean NOT NULL DEFAULT false', t);

        -- Anything unknown back to Slow before the check
        EXECUTE format('UPDATE public.%I SET "MovementClass" = ''Slow'' WHERE "MovementClass" NOT IN (''SuperFast'', ''Fast'', ''Regular'', ''Periodic'', ''Slow'')', t);

        IF NOT EXISTS
        (
            SELECT 1
            FROM   pg_constraint
            WHERE  conname = 'CK_' || t || '_MovementClass'
        )
        THEN
            EXECUTE format('ALTER TABLE public.%I ADD CONSTRAINT %I CHECK ("MovementClass" IN (''SuperFast'', ''Fast'', ''Regular'', ''Periodic'', ''Slow''))',
                           t, 'CK_' || t || '_MovementClass');
        END IF;

        RAISE NOTICE '% : MovementClass ready', t;
    END LOOP;
END $$;


-- ------------------------------------------------------------
-- Check
-- ------------------------------------------------------------

SELECT 'Zones' AS "What", COUNT(*) AS "Rows" FROM public."RackZones" WHERE "IsDeleted" = false
UNION ALL
SELECT 'Racks without a zone', COUNT(*) FROM public."RackManagements" WHERE "IsDeleted" = false AND "RackZoneId" IS NULL
UNION ALL
SELECT 'Rack shelves', COUNT(*) FROM public."RackShelves"
UNION ALL
SELECT 'Spare part locations', COUNT(*) FROM public."SparePartLocations"
UNION ALL
SELECT 'Accessory locations', COUNT(*) FROM public."AccessoryLocations";
