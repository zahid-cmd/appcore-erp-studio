-- ------------------------------------------------------------
-- 5. Pages : Festival Bonus, Leave Encashments (Payroll Management)
-- ------------------------------------------------------------

DO $$
DECLARE
    v_module   record;
    v_menu     record;
    v_seq      int;
    v_code     text;
    s          record;
BEGIN
    SELECT "Id", "SequenceNo", "RouteKey" INTO v_module
    FROM   "NavigationModules"
    WHERE  lower(trim("RouteKey")) = 'human-resource-manangement'
    AND    "IsDeleted" = false
    LIMIT  1;

    IF v_module."Id" IS NULL THEN
        RAISE EXCEPTION 'Module with route key human-resource-manangement not found - no page was added.';
    END IF;

    SELECT "Id", "SequenceNo", "RouteKey" INTO v_menu
    FROM   "NavigationMenus"
    WHERE  "NavigationModuleId" = v_module."Id"
    AND    lower(trim("RouteKey")) = 'payroll-management'
    AND    "IsDeleted" = false
    LIMIT  1;

    IF v_menu."Id" IS NULL THEN
        RAISE EXCEPTION 'Menu Payroll Management not found - run HumanResource_Phase3_Engine.sql first.';
    END IF;

    FOR s IN
        SELECT * FROM (VALUES
            (1, 'Festival Bonus',    'fa-solid fa-gift',                  'festival-bonus',    'The festival bonus of a branch : a percent of the salary, posted to the accounts and paid on Payroll Payments.'),
            (2, 'Leave Encashments', 'fa-solid fa-calendar-check',        'leave-encashments', 'Leave days paid as money : taken off the leave balance, posted to the accounts and paid on Payroll Payments.')
        ) AS x (ord, name, icon, route_key, remarks)
        ORDER BY ord
    LOOP
        IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
                   WHERE "NavigationMenuId" = v_menu."Id"
                   AND   lower(trim("RouteKey")) = s.route_key
                   AND   "IsDeleted" = false) THEN
            RAISE NOTICE 'Page exists, skipped : %', s.name;
            CONTINUE;
        END IF;

        IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
                   WHERE lower(trim("Name")) = lower(s.name) AND "IsDeleted" = false) THEN
            RAISE EXCEPTION 'A submenu named "%" already exists elsewhere : names must be unique. Tell Claude.', s.name;
        END IF;

        SELECT COALESCE(MAX("SequenceNo"), 0) + 1 INTO v_seq
        FROM   "NavigationSubmenus"
        WHERE  "NavigationMenuId" = v_menu."Id";

        v_code :=
            'SUB-' || lpad(v_module."SequenceNo"::text, 3, '0')
                   || '-' || lpad(v_menu."SequenceNo"::text, 3, '0')
                   || '-' || lpad(v_seq::text, 3, '0');

        INSERT INTO "NavigationSubmenus"
            ("NavigationMenuId", "SequenceNo", "Code", "Name", "Icon",
             "RouteKey", "Route", "DisplayOrder", "Remarks",
             "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
        VALUES
            (v_menu."Id", v_seq, v_code, s.name, s.icon,
             s.route_key,
             '/' || v_module."RouteKey" || '/' || v_menu."RouteKey" || '/' || s.route_key,
             v_seq, s.remarks || ' Hand-written page : never run Submenu / Code Sync.',
             true, false, 1, now());

        RAISE NOTICE 'Page created : % %', v_code, s.name;
    END LOOP;
END $$;


-- ------------------------------------------------------------
-- 6. Auto Journal Registers : the journals of the two pages
--    (only when AutoJournalRegisters_Sources.sql was run)
-- ------------------------------------------------------------

CREATE OR REPLACE VIEW public."HrBonusSheetVouchers" AS
SELECT DISTINCT "JournalVoucherNo" AS "VoucherNo"
FROM   public."HrBonusSheets"
WHERE  "JournalVoucherNo" <> '';

CREATE OR REPLACE VIEW public."HrLeaveEncashmentVouchers" AS
SELECT DISTINCT "JournalVoucherNo" AS "VoucherNo"
FROM   public."HrLeaveEncashments"
WHERE  "JournalVoucherNo" <> '';

DO $$
BEGIN
    IF to_regclass('public."AutoJournalSources"') IS NULL THEN
        RAISE NOTICE 'AutoJournalSources not found : the journals are not listed on Auto Journal Registers.';
        RETURN;
    END IF;

    INSERT INTO public."AutoJournalSources"
        ("VoucherType", "SourceTable", "NavigationSubmenuCode", "IsAutoJournal", "DisplayOrder", "Remarks")
    SELECT v.voucher_type, v.source_table, COALESCE(s."Code", ''), true, v.ord, v.remarks
    FROM
    (
        VALUES
            (64, 'JV', 'HrBonusSheetVouchers',      '/festival-bonus',    'Human Resource : festival bonus posted'),
            (65, 'JV', 'HrLeaveEncashmentVouchers', '/leave-encashments', 'Human Resource : leave encashment')
    ) AS v (ord, voucher_type, source_table, route_end, remarks)
    LEFT JOIN LATERAL
    (
        SELECT n."Code"
        FROM   "NavigationSubmenus" n
        WHERE  n."IsDeleted" = false
        AND    lower(n."Route") LIKE '/human-resource-manangement/%' || v.route_end
        ORDER  BY n."Id"
        LIMIT  1
    ) AS s ON true
    ON CONFLICT ("VoucherType", "SourceTable") DO UPDATE
    SET    "NavigationSubmenuCode" = EXCLUDED."NavigationSubmenuCode"
    WHERE  public."AutoJournalSources"."NavigationSubmenuCode" = ''
    AND    EXCLUDED."NavigationSubmenuCode" <> '';
END $$;


