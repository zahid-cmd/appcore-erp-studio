-- Payroll Management : Festival Bonus and Leave Encashments; Payroll
-- Payments also pays them, and pays a salary advance out.
--
-- FESTIVAL BONUS (BON-0001)
--   A bonus sheet of a branch for an occasion : a percent of the Basic
--   or the Gross salary for every active employee with the months of
--   service asked. Draft (the amounts can be changed) -> Posted.
--       Dr  Payroll - Bonus Expense      Cr  Payroll - Bonus Payable
--   Paid on Payroll Payments (Paid For : Festival Bonus).
--
-- LEAVE ENCASHMENT (LEN-0001)
--   Leave days an employee does not take, paid as money : days x the
--   day rate (Basic or Gross / 30). Only a leave type marked
--   "Encashable" (Leave Types), never more than the days left of the
--   year. The days are taken off the leave balance.
--       Dr  Payroll - Leave Encashment Expense
--       Cr  Payroll - Leave Encashment Payable
--   Paid on Payroll Payments (Paid For : Leave Encashment).
--
-- SALARY ADVANCE
--   Paid out on Payroll Payments (Paid For : Salary Advance) :
--       Dr  Payroll - Staff Advance      Cr  cash / bank
--   (no table of its own : HrPayments, HumanResource_Payments_Engine.sql)
--
-- Run AFTER HumanResource_Payments_Engine.sql. Safe to run more than
-- once. ASCII only.
-- =====================================================================


