-- Creates the table the Membership Fees Collection page reads
-- (MembershipFeesCollectionConfiguration.cs). Column names are
-- exactly the ones the configuration maps (camelCase, plus
-- "PublicId" for links).
--
-- Note : the page is still the cloned template (Code, Name,
-- Sample Search Dropdown, Sample Field, Status, Remarks). Its
-- real fields are to be designed later; the table can then be
-- altered.
--
-- Plain statements only : run in a NEW pgAdmin Query Tool with
-- F5. Safe to run again. Needs PostgreSQL 18 (uuidv7).
-- ============================================================

CREATE TABLE IF NOT EXISTS public."MembershipFeesCollection"
(
    "id"                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"               uuid                     NOT NULL DEFAULT uuidv7(),
    "code"                   character varying(50)    NOT NULL DEFAULT '',
    "name"                   character varying(200)   NOT NULL DEFAULT '',
    "sampleSearchDropdownId" bigint                   NULL,
    "sampleField"            character varying(500)   NOT NULL DEFAULT '',
    "status"                 boolean                  NOT NULL DEFAULT true,
    "remarks"                character varying(1000)  NOT NULL DEFAULT '',
    "isActive"               boolean                  NOT NULL DEFAULT true,
    "isDeleted"              boolean                  NOT NULL DEFAULT false,
    "createdBy"              bigint                   NOT NULL DEFAULT 0,
    "createdDate"            timestamp with time zone NOT NULL DEFAULT now(),
    "modifiedBy"             bigint                   NULL,
    "modifiedDate"           timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_MembershipFeesCollection_PublicId"
    ON public."MembershipFeesCollection" ("PublicId");

CREATE INDEX IF NOT EXISTS "IX_MembershipFeesCollection_Code"
    ON public."MembershipFeesCollection" ("code");

SELECT count(*) AS "MembershipFeesCollection" FROM public."MembershipFeesCollection";
