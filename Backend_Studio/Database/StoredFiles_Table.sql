-- ============================================================
-- StoredFiles (2026-11-06) : uploaded pictures kept in the
-- database, so every PC that runs an API on this database shows
-- the same pictures (motor bikes, brands, colours, spare parts,
-- company logo, user / customer photos, website images, login
-- components).
--
-- The API (Platform\Uploads\UploadsMirror.cs) fills and reads
-- this table by itself :
--   - at start and every 30 seconds it copies the files of its
--     wwwroot\uploads folder here, writes the missing ones to
--     disk, and removes the ones deleted on another PC;
--   - a new / deleted file is copied / marked within a second.
-- The upload pages are unchanged.
--
-- Path    : the URL path as saved on the record
--           (/uploads/motor-bike-images/xxx.png)
-- PathKey : Path in lower case (one row per file)
-- Deleted files keep their row (IsDeleted = true, no content) so
-- the other PCs delete their copy too.
--
-- ASCII only; safe to run more than once. Run the whole script.
-- ============================================================

CREATE TABLE IF NOT EXISTS public."StoredFiles"
(
    "StoredFileId"  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Path"          character varying(500)   NOT NULL,
    "PathKey"       character varying(500)   NOT NULL,
    "ContentType"   character varying(100)   NOT NULL DEFAULT '',
    "Length"        bigint                   NOT NULL DEFAULT 0,
    "Content"       bytea                    NULL,
    "IsDeleted"     boolean                  NOT NULL DEFAULT false,
    "CreatedDate"   timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedDate"  timestamp with time zone NOT NULL DEFAULT now(),
    "MachineName"   character varying(100)   NOT NULL DEFAULT ''
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_StoredFiles_PathKey"
    ON public."StoredFiles" ("PathKey");


