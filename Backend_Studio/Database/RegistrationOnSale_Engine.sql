-- ============================================================
-- Registration on the Sales Invoice - MB (2026-11-11)
--
-- 1. SalesInvoicesMb : the registration taken on the invoice
--    (type, amount per chassis, chassis count, total, commission,
--    status Active / Reversed and the reversal Journal Voucher).
--    SalesInvoicesMbLines : IsRegistered (the chassis registered).
-- 2. RegistrationProfiles : one per registered chassis, made on
--    Post (status Processing when the invoice is fully paid, else
--    Pending), costs copied from Registration Configuration.
-- 3. Submenu "Registration Files" renamed "Registration Profiles"
--    (route key registration-profiles). Hand-written page : NEVER
--    run Submenu / Code Synchronization for it.
-- 4. Switch CFG-MOD-008-0083 "Show Registration on Print - MB"
--    (ON; critical). Switch 0013 "Registration Fees on Invoice"
--    shows the Registration button on the invoice.
-- 5. Page action "Reverse Registration" on Sales Invoices - MB
--    (admin : reverses the registration of a posted invoice by a
--    Journal Voucher).
--
-- Plain statements, safe to run again. ASCII only.
-- ============================================================

