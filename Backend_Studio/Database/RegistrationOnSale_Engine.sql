-- ------------------------------------------------------------
-- 4. Switch : Show Registration on Print - MB
-- ------------------------------------------------------------

DO $$
DECLARE
    v_module_id   bigint;
    v_module_code text;
    v_page_code   text;
    v_menu_code   text;
    v_name        text;
BEGIN
    SELECT m."Id", m."Code" INTO v_module_id, v_module_code
    FROM   "NavigationModules" m
    WHERE  lower(trim(m."RouteKey")) = 'sales-operations' AND NOT m."IsDeleted"
    LIMIT  1;

    IF v_module_id IS NULL OR upper(trim(v_module_code)) <> 'MOD-008' THEN
        RAISE EXCEPTION 'Sales Operations module (MOD-008) not found - nothing changed.';
    END IF;

    SELECT "ConfigurationName" INTO v_name
    FROM   "SystemConfigurations"
    WHERE  "ConfigurationCode" = 'CFG-MOD-008-0083';

    IF v_name IS NOT NULL AND v_name <> 'Show Registration on Print - MB' THEN
        RAISE EXCEPTION 'CFG-MOD-008-0083 is already used by "%" - nothing changed. Tell Claude.', v_name;
    END IF;

    IF v_name IS NULL THEN
        SELECT s."Code", mn."Code" INTO v_page_code, v_menu_code
        FROM   "NavigationSubmenus" s
        JOIN   "NavigationMenus" mn ON mn."Id" = s."NavigationMenuId"
        WHERE  s."Route" ILIKE '/sales-operations/%/sales-invoices-mb'
        AND    NOT s."IsDeleted"
        LIMIT  1;

        IF v_page_code IS NULL THEN
            RAISE EXCEPTION 'Sales Invoices - MB page not found by route - nothing changed.';
        END IF;

        INSERT INTO "SystemConfigurations"
        (
            "NavigationModuleId", "ScopeType", "NavigationMenuCode", "NavigationSubmenuCode",
            "ConfigurationCode", "ConfigurationName", "OnDescription", "OffDescription",
            "IsEnabled", "Value",
            "ValueType", "ValueUnit", "ValueMin", "ValueMax", "ValueEmptyText",
            "DefaultEnabled", "DefaultValue", "ParentConfigurationCode",
            "IsCritical", "IsSystemDefined", "DisplayOrder", "Remarks",
            "IsDeleted", "CreatedBy", "CreatedDate"
        )
        VALUES
        (
            v_module_id, 'Submenu', v_menu_code, v_page_code,
            'CFG-MOD-008-0083', 'Show Registration on Print - MB',
            'The customer copy of the invoice (A4 and thermal) and the Money Receipt show the Registration line and include it in the total and the amount received.',
            'The Registration line is left off the customer copy and the Money Receipt; their total and amount received leave it out.',
            true, '',
            'None', '', NULL, NULL, '',
            true, '', NULL,
            true, true, 19, 'Critical. The office copy and the books always keep the registration.',
            false, 1, now()
        );

        RAISE NOTICE 'Switch CFG-MOD-008-0083 Show Registration on Print - MB added (ON).';
    ELSE
        RAISE NOTICE 'Switch CFG-MOD-008-0083 exists, left as it is.';
    END IF;
END $$;


-- ------------------------------------------------------------
-- 5. Page action "Reverse Registration" (Sales Invoices - MB)
-- ------------------------------------------------------------

INSERT INTO "MasterActivities"
    ("SequenceNo", "Code", "Name", "DisplayOrder", "Remarks",
     "ActivityScope", "LinkToSwitchPages",
     "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
SELECT
    m.max_seq + 1,
    'ACT-' || lpad((m.max_seq + 1)::text, 4, '0'),
    'Reverse Registration',
    m.max_order + 1,
    'Sales Invoices - MB : reverse the registration of a posted invoice with a reason (Journal Voucher : Dr the registration ledgers / Cr the customer; its Registration Profiles cancelled). Admins only.',
    'Page',
    false,
    true,
    false,
    1,
    now()
FROM
(
    SELECT COALESCE(MAX("SequenceNo"), 0)   AS max_seq,
           COALESCE(MAX("DisplayOrder"), 0) AS max_order
    FROM   "MasterActivities"
) AS m
WHERE NOT EXISTS
(
    SELECT 1 FROM "MasterActivities" a
    WHERE  a."IsDeleted" = false AND lower(trim(a."Name")) = 'reverse registration'
);

INSERT INTO "MasterActivityPages" ("MasterActivityCode", "NavigationSubmenuCode", "CreatedBy")
SELECT a."Code", s."Code", 1
FROM   "MasterActivities" a
JOIN   "NavigationSubmenus" s
       ON s."IsDeleted" = false
      AND s."Route" ILIKE '/sales-operations/%/sales-invoices-mb'
WHERE  a."IsDeleted" = false
AND    a."ActivityScope" = 'Page'
AND    lower(a."Name") = 'reverse registration'
ON CONFLICT ("MasterActivityCode", "NavigationSubmenuCode") DO NOTHING;


