-- ============================================================
-- Sales Quotations - MB / SP / AC (2026-11-11)
--
-- The quotation pages are the Sales Invoice page in quotation
-- mode (hand-written; NEVER run Code Sync for them again : the
-- placeholder tables SalesQuotationsMb / Sp / Ac stay unused).
--
-- 1. SalesQuotations + SalesQuotationLines (ProductType MB / SP /
--    AC). A quotation is for a customer or a prospect (name +
--    phone, no profile). Lines : product + quantity (MB : the
--    model, no chassis) with the prices / discounts of the day.
--    Status : Open -> Converted (its invoice posted) / Cancelled.
--    Expired = Open past ValidUntil (shown only).
-- 2. SalesInvoicesMb / Sp / Ac : QuotationId, QuotationNo (the
--    quotation the invoice was made from).
-- 3. Switch "Quotation Validity" (days) on each quotation page :
--      CFG-MOD-008-0103 MB, 0104 SP, 0105 AC (ON, 7 days)
--
-- Safe to run again. ASCII only.
-- ============================================================

ROLLBACK;


-- ------------------------------------------------------------
-- 1. Tables
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."SalesQuotations"
(
    "SalesQuotationId"     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"             uuid                     NOT NULL DEFAULT uuidv7(),
    "ProductType"          character varying(2)     NOT NULL,
    "QuotationNo"          character varying(40)    NOT NULL,
    "QuotationDate"        date                     NOT NULL,
    "ValidUntil"           date                     NULL,

    "BranchId"             bigint                   NOT NULL,
    "WarehouseId"          bigint                   NOT NULL DEFAULT 0,
    "SalesPersonId"        bigint                   NULL,
    "SalesPersonName"      character varying(150)   NOT NULL DEFAULT '',

    -- A customer (CustomerId) or a prospect (CustomerId NULL)
    "CustomerId"           bigint                   NULL,
    "CustomerCode"         character varying(20)    NOT NULL DEFAULT '',
    "CustomerName"         character varying(200)   NOT NULL DEFAULT '',
    "CustomerPhone"        character varying(20)    NOT NULL DEFAULT '',
    "CustomerAddress"      character varying(500)   NOT NULL DEFAULT '',

    -- MB : Regular / Corporate ('' others)
    "SaleType"             character varying(10)    NOT NULL DEFAULT '',

    "InvoiceSpecialType"   character varying(10)    NOT NULL DEFAULT 'None',
    "InvoiceSpecialValue"  numeric(18,2)            NOT NULL DEFAULT 0,
    "FractionalDiscount"   numeric(18,2)            NOT NULL DEFAULT 0,

    "TotalQuantity"        numeric(18,2)            NOT NULL DEFAULT 0,
    "GrossAmount"          numeric(18,2)            NOT NULL DEFAULT 0,
    "DiscountAmount"       numeric(18,2)            NOT NULL DEFAULT 0,
    "QuotationTotal"       numeric(18,2)            NOT NULL DEFAULT 0,
    "TotalVatInside"       numeric(18,2)            NOT NULL DEFAULT 0,

    "Narration"            character varying(500)   NOT NULL DEFAULT '',
    "Terms"                character varying(1000)  NOT NULL DEFAULT '',

    -- Open / Converted / Cancelled
    "Status"               character varying(20)    NOT NULL DEFAULT 'Open',

    "SalesInvoiceId"       bigint                   NULL,
    "SalesInvoiceNo"       character varying(50)    NOT NULL DEFAULT '',
    "ConvertedDate"        date                     NULL,

    "CancelReason"         character varying(500)   NOT NULL DEFAULT '',
    "CancelledBy"          bigint                   NULL,
    "CancelledDate"        timestamp with time zone NULL,

    "IsDeleted"            boolean                  NOT NULL DEFAULT false,
    "DeletedBy"            bigint                   NULL,
    "DeletedDate"          timestamp with time zone NULL,
    "CreatedBy"            bigint                   NOT NULL,
    "CreatedDate"          timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"           bigint                   NULL,
    "ModifiedDate"         timestamp with time zone NULL,

    CONSTRAINT "CK_SalesQuotations_Type"   CHECK ("ProductType" IN ('MB', 'SP', 'AC')),
    CONSTRAINT "CK_SalesQuotations_Status" CHECK ("Status" IN ('Open', 'Converted', 'Cancelled'))
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_SalesQuotations_PublicId" ON public."SalesQuotations" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_SalesQuotations_No" ON public."SalesQuotations" ("QuotationNo");

CREATE INDEX IF NOT EXISTS "IX_SalesQuotations_Type" ON public."SalesQuotations" ("ProductType", "Status", "QuotationDate");


CREATE TABLE IF NOT EXISTS public."SalesQuotationLines"
(
    "SalesQuotationLineId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "SalesQuotationId"     bigint                   NOT NULL REFERENCES public."SalesQuotations" ("SalesQuotationId"),
    "LineNo"               integer                  NOT NULL DEFAULT 1,
    "ProductId"            bigint                   NOT NULL,
    "ProductCode"          character varying(50)    NOT NULL DEFAULT '',
    "PartNumber"           character varying(50)    NOT NULL DEFAULT '',
    "ProductName"          character varying(250)   NOT NULL DEFAULT '',
    "Unit"                 character varying(20)    NOT NULL DEFAULT '',
    "Quantity"             numeric(18,2)            NOT NULL DEFAULT 1,

    -- As typed (null = the MRP / no special)
    "TypedPrice"           numeric(18,2)            NULL,
    "TypedSpecialPercent"  numeric(9,2)             NULL,
    "TypedSpecialTk"       numeric(18,2)            NULL,

    -- As priced on the quotation day
    "Mrp"                  numeric(18,2)            NOT NULL DEFAULT 0,
    "UnitPrice"            numeric(18,4)            NOT NULL DEFAULT 0,
    "GrossAmount"          numeric(18,2)            NOT NULL DEFAULT 0,
    "DiscountLabel"        character varying(100)   NOT NULL DEFAULT '',
    "DiscountAmount"       numeric(18,2)            NOT NULL DEFAULT 0,
    "NetAmount"            numeric(18,2)            NOT NULL DEFAULT 0,
    "VatInside"            numeric(18,2)            NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS "IX_SalesQuotationLines_Quotation" ON public."SalesQuotationLines" ("SalesQuotationId");


