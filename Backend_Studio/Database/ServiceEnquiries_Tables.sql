CREATE TABLE IF NOT EXISTS public."ServiceEnquiries"
(
    "ServiceEnquiryId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "EnquiryNo"          character varying(30)  NOT NULL,
    "EnquiryYear"        integer                NOT NULL,
    "EnquiryMonth"       integer                NOT NULL,
    "SequenceNo"         integer                NOT NULL,
    "EnquiryDate"        date                   NOT NULL,
    "BranchId"           bigint                 NOT NULL,
    "BranchName"         character varying(150) NOT NULL DEFAULT '',
    "EnquiryType"        character varying(10)  NOT NULL DEFAULT 'Service',
    "SourceId"           bigint                 NOT NULL,
    "StatusId"           bigint                 NOT NULL,
    "ExecutiveUserId"    bigint                 NOT NULL DEFAULT 0,
    "ExecutiveName"      character varying(150) NOT NULL DEFAULT '',
    "EnquiryContactId"   bigint                 NOT NULL,
    "EnquirerMobile"     character varying(20)  NOT NULL,
    "EnquirerName"       character varying(150) NOT NULL,
    "ModelId"            bigint                 NULL,
    "ModelName"          character varying(150) NOT NULL DEFAULT '',
    "BrandManagementId"  bigint                 NULL,
    "BrandName"          character varying(150) NOT NULL DEFAULT '',
    "RegistrationNo"     character varying(30)  NOT NULL DEFAULT '',
    "ChassisNo"          character varying(50)  NOT NULL DEFAULT '',
    "KmReading"          integer                NULL,
    "Complaint"          character varying(500) NOT NULL DEFAULT '',
    "PreferredDate"      date                   NULL,
    "PreferredSlot"      character varying(20)  NOT NULL DEFAULT '',
    "PickupDrop"         boolean                NOT NULL DEFAULT false,
    "EstimatedTotal"     numeric(18,2)          NOT NULL DEFAULT 0,
    "NextFollowUpDate"   date                   NULL,
    "FollowUpMethodId"   bigint                 NULL,
    "LastFollowUpDate"   date                   NULL,
    "LastFollowUpNote"   character varying(500) NOT NULL DEFAULT '',
    "LostReasonId"       bigint                 NULL,
    "ClosedDate"         date                   NULL,
    "Remarks"            character varying(500) NOT NULL DEFAULT '',
    "FromWebsite"        boolean                NOT NULL DEFAULT false,
    "IsConverted"        boolean                NOT NULL DEFAULT false,
    "ConvertedDate"      date                   NULL,
    "ConvertedDocType"   character varying(20)  NOT NULL DEFAULT '',
    "ConvertedDocId"     bigint                 NULL,
    "ConvertedDocNo"     character varying(40)  NOT NULL DEFAULT '',
    "IsDeleted"          boolean                NOT NULL DEFAULT false,
    "DeletedBy"          bigint                 NULL,
    "DeletedDate"        timestamp with time zone NULL,
    "CreatedBy"          bigint                 NOT NULL,
    "CreatedDate"        timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"         bigint                 NULL,
    "ModifiedDate"       timestamp with time zone NULL,

    CONSTRAINT "CK_ServiceEnquiries_Type"  CHECK ("EnquiryType" IN ('Service', 'Parts')),
    CONSTRAINT "CK_ServiceEnquiries_Month" CHECK ("EnquiryMonth" BETWEEN 1 AND 12)
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_ServiceEnquiries_EnquiryNo" ON public."ServiceEnquiries" ("EnquiryNo");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_ServiceEnquiries_Month_Sequence" ON public."ServiceEnquiries" ("EnquiryYear", "EnquiryMonth", "SequenceNo");

CREATE INDEX IF NOT EXISTS "IX_ServiceEnquiries_EnquirerMobile" ON public."ServiceEnquiries" ("EnquirerMobile");

CREATE INDEX IF NOT EXISTS "IX_ServiceEnquiries_Registration" ON public."ServiceEnquiries" ("RegistrationNo");

CREATE TABLE IF NOT EXISTS public."ServiceEnquiryLines"
(
    "ServiceEnquiryLineId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ServiceEnquiryId"     bigint                 NOT NULL,
    "LineNo"               integer                NOT NULL,
    "LineType"             character varying(10)  NOT NULL,
    "ItemKind"             character varying(20)  NOT NULL DEFAULT 'Other',
    "ItemId"               bigint                 NULL,
    "ItemCode"             character varying(50)  NOT NULL DEFAULT '',
    "ItemName"             character varying(200) NOT NULL,
    "Quantity"             numeric(10,2)          NOT NULL DEFAULT 1,
    "Rate"                 numeric(18,2)          NOT NULL DEFAULT 0,
    "Amount"               numeric(18,2)          NOT NULL DEFAULT 0,
    "Note"                 character varying(200) NOT NULL DEFAULT '',

    CONSTRAINT "CK_ServiceEnquiryLines_Type" CHECK ("LineType" IN ('Service', 'Part'))
);

CREATE INDEX IF NOT EXISTS "IX_ServiceEnquiryLines_Enquiry" ON public."ServiceEnquiryLines" ("ServiceEnquiryId");
