-- Booking Management : Bookings per product type (2026-11-11)
--   Bookings - MB  /sales-operations/booking-management/bookings-mb
--   Bookings - SP  /sales-operations/booking-management/bookings-sp
--   Bookings - AC  /sales-operations/booking-management/bookings-ac
--
-- Replaces BookingsMB_Engine.sql (safe whether that one was run
-- or not). Hand-written pages : NEVER run Submenu / Code Sync.
--
-- 1. Bookings (ProductType MB / SP / AC) + BookingCollections
--    + BookingLines (SP / AC : items with quantity). A booking
--    has no price lock. Each collection posts a Receipt Voucher :
--    Dr cash / bank / MFS ... Cr the customer's own ledger.
-- 2. SalesInvoicesMb / Sp / Ac : BookingId, BookingNo,
--    BookingAdvance. The invoice takes the advance as already
--    paid; posting converts the booking, cancelling the invoice
--    re-opens it.
-- 3. Pages : the old "Bookings" page becomes "Bookings - MB"
--    (route bookings-mb, its switches and permissions kept);
--    "Bookings - SP" and "Bookings - AC" added with the same
--    page activities.
-- 4. Switches per page :
--      MB 0091-0094, SP 0095-0098, AC 0099-0102
--      Minimum Booking Amount / Booking Validity / Refund on
--      Cancel / Forfeit on Cancel
-- 5. Posting Setup : BOOKING-FORFEIT-MB / -SP / -AC (income).
-- 6. Page action "Cancel Booking" on the three pages.
-- 7. Old submenus "Booking Collections" and "Booking
--    Cancellations & Refunds" removed (tabs on each page).
--
-- AFTER : Activity Assignment : tick the new pages for the roles.
-- Safe to run again. ASCII only.
-- ============================================================

