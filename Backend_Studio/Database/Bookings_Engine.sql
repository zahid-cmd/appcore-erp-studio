DO $$
DECLARE
    v_module   record;
    v_menu     record;
    v_mb       record;
    v_seq      int;
    v_code     text;
    v_links    int;
    t          record;
    a          record;
BEGIN
    SELECT "Id", "SequenceNo", "RouteKey", "Code" INTO v_module
    FROM   "NavigationModules"
    WHERE  lower(trim("RouteKey")) = 'sales-operations' AND NOT "IsDeleted"
    LIMIT  1;

    IF v_module."Id" IS NULL THEN
        RAISE EXCEPTION 'Sales Operations module not found - nothing changed.';
    END IF;

    SELECT "Id", "SequenceNo", "RouteKey", "Code" INTO v_menu
    FROM   "NavigationMenus"
    WHERE  "NavigationModuleId" = v_module."Id"
    AND    lower(trim("RouteKey")) = 'booking-management'
    AND    NOT "IsDeleted"
    LIMIT  1;

    IF v_menu."Id" IS NULL THEN
        RAISE EXCEPTION 'Menu Booking Management (route key booking-management) not found - nothing changed.';
    END IF;

    -- The motor bike page : the old Bookings page renamed
    SELECT "Id", "Code", "Name", "Route" INTO v_mb
    FROM   "NavigationSubmenus"
    WHERE  "NavigationMenuId" = v_menu."Id"
    AND    NOT "IsDeleted"
    AND    lower("Route") IN ('/sales-operations/booking-management/bookings',
                              '/sales-operations/booking-management/bookings-mb')
    ORDER  BY ("Route" = '/sales-operations/booking-management/bookings-mb') DESC
    LIMIT  1;

    IF v_mb."Id" IS NULL THEN
        RAISE EXCEPTION 'Bookings page not found (route /sales-operations/booking-management/bookings) - nothing changed.';
    END IF;

    UPDATE "NavigationSubmenus"
    SET    "Name"         = 'Bookings - MB',
           "RouteKey"     = 'bookings-mb',
           "Route"        = '/sales-operations/booking-management/bookings-mb',
           "DisplayOrder" = 1
    WHERE  "Id" = v_mb."Id"
    AND    ("Name" <> 'Bookings - MB' OR "Route" <> '/sales-operations/booking-management/bookings-mb');

    RAISE NOTICE 'Page % : Bookings - MB (bookings-mb)', v_mb."Code";

    -- SP and AC pages (same activities as the MB page)
    FOR t IN
        SELECT * FROM (VALUES
            ('Bookings - SP', 'bookings-sp', 2, 'Spare parts / lubricant bookings : items, advance, conversion to sale, cancellation.'),
            ('Bookings - AC', 'bookings-ac', 3, 'Accessories bookings : items, advance, conversion to sale, cancellation.')
        ) AS x (name, route_key, ord, remarks)
    LOOP
        SELECT "Code" INTO v_code
        FROM   "NavigationSubmenus"
        WHERE  "NavigationMenuId" = v_menu."Id"
        AND    lower("RouteKey") = t.route_key
        AND    NOT "IsDeleted";

        IF v_code IS NULL THEN
            IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
                       WHERE lower("Name") = lower(t.name) AND NOT "IsDeleted") THEN
                RAISE EXCEPTION 'A submenu named "%" already exists elsewhere - nothing changed.', t.name;
            END IF;

            SELECT COALESCE(MAX("SequenceNo"), 0) + 1 INTO v_seq
            FROM   "NavigationSubmenus"
            WHERE  "NavigationMenuId" = v_menu."Id";

            v_code :=
                'SUB-' || lpad(v_module."SequenceNo"::text, 3, '0')
                       || '-' || lpad(v_menu."SequenceNo"::text, 3, '0')
                       || '-' || lpad(v_seq::text, 3, '0');

            INSERT INTO "NavigationSubmenus"
                ("NavigationMenuId", "SequenceNo", "Code", "Name", "Icon",
                 "RouteKey", "Route", "DisplayOrder", "Remarks",
                 "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
            VALUES
                (v_menu."Id", v_seq, v_code, t.name, 'fa-solid fa-calendar-check',
                 t.route_key, '/sales-operations/booking-management/' || t.route_key,
                 t.ord, t.remarks,
                 true, false, 1, now());

            RAISE NOTICE 'Page created : % %', v_code, t.name;
        ELSE
            RAISE NOTICE 'Page exists, skipped : % %', v_code, t.name;
        END IF;

        v_links := 0;

        FOR a IN
            SELECT DISTINCT p."MasterActivityCode"
            FROM   "MasterActivityPages" p
            WHERE  p."NavigationSubmenuCode" = v_mb."Code"
        LOOP
            IF NOT EXISTS (SELECT 1 FROM "MasterActivityPages"
                           WHERE "MasterActivityCode" = a."MasterActivityCode"
                           AND   "NavigationSubmenuCode" = v_code) THEN
                INSERT INTO "MasterActivityPages" ("MasterActivityCode", "NavigationSubmenuCode", "CreatedBy")
                VALUES (a."MasterActivityCode", v_code, 1);

                v_links := v_links + 1;
            END IF;
        END LOOP;

        RAISE NOTICE '  activities linked from Bookings - MB : %', v_links;
    END LOOP;
END $$;


