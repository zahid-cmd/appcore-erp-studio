-- Plain statements : run in a NEW pgAdmin Query Tool (F5).
-- Safe to run again.
--
-- 1. The sample table made by the page sync ("ProductPricing"
--    with Name / SampleField ...) is dropped : it only held test
--    rows. The real tables take its place.
-- 2. ProductPricing      : one price change (PC-<MB|SP|AC>-0001).
--    ProductPricingLines : one row per ticked stock batch, with
--                          its MRP before and the new one.
-- 3. Page actions Post and Cancel linked to the Product Pricing
--    page (Add, Update, Delete, View, Print, Restore are common).
-- MRP (VAT inclusive) is the sale price : posting sets
-- StockBatches.Mrp; no journal.
-- ============================================================


-- 1. The sync's sample table : a "ProductPricing" table without
--    the real "PricingNo" column (its columns are id / code / name /
--    sampleField ...) is dropped

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables
               WHERE table_schema = 'public' AND table_name = 'ProductPricing')
       AND NOT EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = 'ProductPricing' AND column_name = 'PricingNo') THEN
        DROP TABLE public."ProductPricing" CASCADE;
        RAISE NOTICE 'The sample ProductPricing table was dropped.';
    END IF;
END $$;


-- 2. Tables

CREATE TABLE IF NOT EXISTS public."ProductPricing"
(
    "ProductPricingId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PageType"           character varying(5)   NOT NULL,
    "PricingNo"          character varying(30)  NOT NULL,
    "SequenceNo"         integer                NOT NULL DEFAULT 0,
    "PricingDate"        date                   NOT NULL,
    "Remarks"            character varying(500) NOT NULL DEFAULT '',
    "ProductCount"       integer                NOT NULL DEFAULT 0,
    "BatchCount"         integer                NOT NULL DEFAULT 0,
    "Status"             character varying(20)  NOT NULL DEFAULT 'Draft',
    "PostedBy"           bigint                 NULL,
    "PostedDate"         timestamp with time zone NULL,
    "CancelReason"       character varying(500) NOT NULL DEFAULT '',
    "CancelledBy"        bigint                 NULL,
    "CancelledDate"      timestamp with time zone NULL,
    "IsDeleted"          boolean                NOT NULL DEFAULT false,
    "DeletedBy"          bigint                 NULL,
    "DeletedDate"        timestamp with time zone NULL,
    "CreatedBy"          bigint                 NOT NULL,
    "CreatedDate"        timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"         bigint                 NULL,
    "ModifiedDate"       timestamp with time zone NULL,
    CONSTRAINT "CK_ProductPricing_PageType" CHECK ("PageType" IN ('MB', 'SP', 'AC')),
    CONSTRAINT "CK_ProductPricing_Status"   CHECK ("Status" IN ('Draft', 'Posted', 'Cancelled'))
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_ProductPricing_PricingNo"
    ON public."ProductPricing" ("PricingNo");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_ProductPricing_Type_Sequence"
    ON public."ProductPricing" ("PageType", "SequenceNo")
    WHERE "SequenceNo" > 0;

CREATE TABLE IF NOT EXISTS public."ProductPricingLines"
(
    "ProductPricingLineId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ProductPricingId"   bigint                 NOT NULL REFERENCES public."ProductPricing" ("ProductPricingId") ON DELETE CASCADE,
    "LineNo"             integer                NOT NULL,
    "ProductId"          bigint                 NOT NULL,
    "ProductCode"        character varying(40)  NOT NULL DEFAULT '',
    "ProductName"        character varying(250) NOT NULL DEFAULT '',
    "Unit"               character varying(30)  NOT NULL DEFAULT '',
    "StockBatchId"       bigint                 NOT NULL,
    "BatchNo"            character varying(40)  NOT NULL DEFAULT '',
    "SourceType"         character varying(20)  NOT NULL DEFAULT '',
    "SourceNo"           character varying(40)  NOT NULL DEFAULT '',
    "BranchId"           bigint                 NOT NULL DEFAULT 0,
    "BranchName"         character varying(150) NOT NULL DEFAULT '',
    "Quantity"           numeric(18,2)          NOT NULL DEFAULT 0,
    "UnitCost"           numeric(18,4)          NOT NULL DEFAULT 0,
    "OldMrp"             numeric(18,2)          NOT NULL DEFAULT 0,
    "NewMrp"             numeric(18,2)          NOT NULL DEFAULT 0,
    "Notes"              character varying(200) NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS "IX_ProductPricingLines_ProductPricingId"
    ON public."ProductPricingLines" ("ProductPricingId");

CREATE INDEX IF NOT EXISTS "IX_ProductPricingLines_StockBatchId"
    ON public."ProductPricingLines" ("StockBatchId");


-- 3. Page actions Post and Cancel

INSERT INTO "MasterActivityPages" ("MasterActivityCode", "NavigationSubmenuCode", "CreatedBy")
SELECT a."Code", s."Code", 1
FROM   "MasterActivities" a
JOIN   "NavigationSubmenus" s
       ON s."Route" ILIKE '/inventory-management/%/product-pricing'
      AND s."IsDeleted" = false
WHERE  a."IsDeleted" = false
AND    a."ActivityScope" = 'Page'
AND    a."Name" IN ('Post', 'Cancel')
ON CONFLICT ("MasterActivityCode", "NavigationSubmenuCode") DO NOTHING;


