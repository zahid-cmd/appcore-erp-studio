CREATE INDEX IF NOT EXISTS "IX_FaAcquisitionLines_Acquisition" ON public."FaAcquisitionLines" ("FaAcquisitionId");


-- ------------------------------------------------------------
-- 4. Depreciation
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."FaDepreciationRuns"
(
    "FaDepreciationRunId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"            uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"                character varying(20)    NOT NULL,
    "BranchId"            bigint                   NOT NULL,
    -- yyyymm
    "Period"              integer                  NOT NULL,
    -- the voucher date : the last day of the month
    "RunDate"             date                     NOT NULL,
    "AssetCount"          integer                  NOT NULL DEFAULT 0,
    "TotalAmount"         numeric(18,2)            NOT NULL DEFAULT 0,
    "JournalVoucherId"    bigint                   NULL,
    "JournalVoucherNo"    character varying(30)    NOT NULL DEFAULT '',
    "Remarks"             character varying(500)   NOT NULL DEFAULT '',
    -- an undone run
    "IsDeleted"           boolean                  NOT NULL DEFAULT false,
    "DeletedBy"           bigint                   NULL,
    "DeletedDate"         timestamp with time zone NULL,
    "CreatedBy"           bigint                   NOT NULL,
    "CreatedDate"         timestamp with time zone NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_FaDepreciationRuns_PublicId" ON public."FaDepreciationRuns" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_FaDepreciationRuns_Code"     ON public."FaDepreciationRuns" ("Code");
CREATE INDEX        IF NOT EXISTS "IX_FaDepreciationRuns_Branch"   ON public."FaDepreciationRuns" ("BranchId", "Period");

CREATE TABLE IF NOT EXISTS public."FaDepreciationLines"
(
    "FaDepreciationLineId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "FaDepreciationRunId"  bigint NOT NULL
        REFERENCES public."FaDepreciationRuns" ("FaDepreciationRunId") ON DELETE CASCADE,
    "FaAssetId"            bigint        NOT NULL,
    "FaCategoryId"         bigint        NOT NULL,
    "Period"               integer       NOT NULL,
    -- the cost and the depreciation before this month
    "Cost"                 numeric(18,2) NOT NULL DEFAULT 0,
    "OpeningAccumulated"   numeric(18,2) NOT NULL DEFAULT 0,
    "Charge"               numeric(18,2) NOT NULL DEFAULT 0,
    -- the asset's LastRunPeriod before the run (an undo puts it back)
    "PrevRunPeriod"        integer       NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS "IX_FaDepreciationLines_Run"   ON public."FaDepreciationLines" ("FaDepreciationRunId");
CREATE INDEX IF NOT EXISTS "IX_FaDepreciationLines_Asset" ON public."FaDepreciationLines" ("FaAssetId", "Period");


-- ------------------------------------------------------------
-- 5. Disposal
