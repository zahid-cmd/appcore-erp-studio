CREATE TABLE IF NOT EXISTS public."FaDisposals"
(
    "FaDisposalId"     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"         uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"             character varying(20)    NOT NULL,
    "DisposalDate"     date                     NOT NULL,
    "FaAssetId"        bigint                   NOT NULL,
    "BranchId"         bigint                   NOT NULL,
    -- Sale / Scrap / Write Off / Lost
    "Kind"             character varying(15)    NOT NULL DEFAULT 'Sale',
    "BuyerName"        character varying(150)   NOT NULL DEFAULT '',
    "SalePrice"        numeric(18,2)            NOT NULL DEFAULT 0,
    -- the ledger debited with the price : a customer, or a
    -- receivable ledger
    "DebitLedgerCode"  character varying(30)    NOT NULL DEFAULT '',
    -- Customer / General Ledger
    "DebitLedgerType"  character varying(20)    NOT NULL DEFAULT 'General Ledger',
