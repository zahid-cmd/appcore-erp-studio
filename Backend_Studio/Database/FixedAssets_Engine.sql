-- FixedAssets_Engine.sql   (2026-11-14)
-- ---------------------------------------------------------------------
-- The tables of Fixed Assets Management, and its Posting Setup rows.
--
--   FaCategories          FAC-0001 : an ASSET GROUP (Asset Groups
--                         page). Making one makes its two ledgers
--                         under the account sub groups "Property,
--                         Plant & Equipment" and "Accumulated
--                         Depreciation" :
--                             PPE - <name>   the cost
--                             ACD - <name>   the depreciation so far
--                         Its depreciation is declared on
--                         Depreciation of Fixed Assets : method (None
--                         / StraightLine / ReducingBalance), rate % or
--                         life (years), residual %, and the
--                         depreciation expense ledger.
--   FaLocations           FAL-0001 : where an asset is kept (a branch)
--   FaConfiguration       one row : the switches and the numbering
--   FaAssets              the asset cards (FA-<branch>-<category>-
--                         00001) : cost, improvements, residual,
--                         accumulated depreciation, the last month
--                         depreciated (LastRunPeriod, yyyymm), status
--   FaAcquisitions        FAQ-0001 : buying assets. Draft -> Posted
--   FaAcquisitionLines    (a Journal Voucher, and the cards)
--   FaDepreciationRuns    FDR-0001 : a month of a branch
--   FaDepreciationLines   (one Journal Voucher), the charge by asset
--   FaDisposals           FAD-0001 : sale / scrap / write-off / lost
--                         (a Journal Voucher with the gain or loss)
--   FaVerifications       FAV-0001 : the physical count of a branch /
--   FaVerificationLines   location against the register
--
-- Every posting is a Journal Voucher. Money is paid / received on the
-- Payment and Receipt Vouchers against the payable / receivable
-- ledger the document names.
--
-- Run AFTER FixedAssets_Navigation.sql. Safe to run more than once.
-- Run the whole script (F5). ASCII only.
--
-- AFTER : Settings > Account Settings > Posting Setup, group
-- "Fixed Assets" : choose the ledgers.
-- =====================================================================


-- ------------------------------------------------------------
-- 1. Setup
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."FaCategories"
(
    "FaCategoryId"      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"          uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"              character varying(20)    NOT NULL,
    "Name"              character varying(100)   NOT NULL,
    -- e.g. Furniture & Fixtures (the heading the category sits under)
    "GroupName"         character varying(100)   NOT NULL DEFAULT '',
    -- '' (not declared yet) / None / StraightLine / ReducingBalance
    "Method"            character varying(20)    NOT NULL DEFAULT '',
    -- % a year (reducing balance always; straight line when no life)
    "RatePercent"       numeric(7,3)             NOT NULL DEFAULT 0,
    -- straight line : the useful life (0 = use the rate)
    "LifeYears"         integer                  NOT NULL DEFAULT 0,
    "ResidualPercent"   numeric(7,3)             NOT NULL DEFAULT 0,
    "CostLedgerCode"    character varying(30)    NOT NULL DEFAULT '',
    "AccumLedgerCode"   character varying(30)    NOT NULL DEFAULT '',
    "ExpenseLedgerCode" character varying(30)    NOT NULL DEFAULT '',
    -- '' = the Posting Setup ledger (ASSET-DISPOSAL-GAIN / LOSS)
    "GainLedgerCode"    character varying(30)    NOT NULL DEFAULT '',
    "LossLedgerCode"    character varying(30)    NOT NULL DEFAULT '',
    -- an item below it is an expense, not an asset (0 = no limit)
    "CapitalThreshold"  numeric(18,2)            NOT NULL DEFAULT 0,
    -- one card for a group with a quantity is allowed
    "AllowGroupCard"    boolean                  NOT NULL DEFAULT true,
    "Remarks"           character varying(500)   NOT NULL DEFAULT '',
    "IsActive"          boolean                  NOT NULL DEFAULT true,
    "IsDeleted"         boolean                  NOT NULL DEFAULT false,
    "DeletedBy"         bigint                   NULL,
    "DeletedDate"       timestamp with time zone NULL,
    "CreatedBy"         bigint                   NOT NULL,
    "CreatedDate"       timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"        bigint                   NULL,
    "ModifiedDate"      timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_FaCategories_PublicId" ON public."FaCategories" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_FaCategories_Code"     ON public."FaCategories" ("Code");

CREATE TABLE IF NOT EXISTS public."FaLocations"
(
    "FaLocationId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"     uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"         character varying(20)    NOT NULL,
    "Name"         character varying(100)   NOT NULL,
    "BranchId"     bigint                   NOT NULL,
    "Remarks"      character varying(500)   NOT NULL DEFAULT '',
    "IsActive"     boolean                  NOT NULL DEFAULT true,
    "IsDeleted"    boolean                  NOT NULL DEFAULT false,
    "DeletedBy"    bigint                   NULL,
    "DeletedDate"  timestamp with time zone NULL,
    "CreatedBy"    bigint                   NOT NULL,
    "CreatedDate"  timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"   bigint                   NULL,
    "ModifiedDate" timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_FaLocations_PublicId" ON public."FaLocations" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_FaLocations_Code"     ON public."FaLocations" ("Code");

CREATE TABLE IF NOT EXISTS public."FaConfiguration"
(
    "FaConfigurationId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- an asset card must name its location / its custodian
    "RequireLocation"   boolean                  NOT NULL DEFAULT false,
    "RequireCustodian"  boolean                  NOT NULL DEFAULT false,
    -- the method, rate and life of a card may differ from its
    -- category (until its first depreciation run)
    "AllowAssetRule"    boolean                  NOT NULL DEFAULT true,
    -- a depreciation run may be made for a month that has not ended
    "AllowRunningMonth" boolean                  NOT NULL DEFAULT false,
    "AssetNoPrefix"     character varying(10)    NOT NULL DEFAULT 'FA',
    "AssetNoDigits"     integer                  NOT NULL DEFAULT 5,
    "ModifiedBy"        bigint                   NULL,
    "ModifiedDate"      timestamp with time zone NULL
);

-- the account sub groups the ledgers of an asset group are made
-- under ('' : found by name)
ALTER TABLE public."FaConfiguration"
    ADD COLUMN IF NOT EXISTS "PpeSubGroupCode" character varying(30) NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS "AcdSubGroupCode" character varying(30) NOT NULL DEFAULT '';

ALTER TABLE public."FaCategories" ALTER COLUMN "Method" SET DEFAULT '';

-- "Payable To" of an acquisition / an improvement : the ledgers of the
-- account sub group Liability For Capital Assets, by its code
ALTER TABLE public."FaConfiguration"
    ADD COLUMN IF NOT EXISTS "PayableSubGroupCode" character varying(30) NOT NULL DEFAULT 'SUB-003-002-005';

INSERT INTO public."FaConfiguration" ("RequireLocation", "RequireCustodian", "AllowAssetRule", "AllowRunningMonth", "AssetNoPrefix", "AssetNoDigits")
SELECT false, false, true, false, 'FA', 5
WHERE  NOT EXISTS (SELECT 1 FROM public."FaConfiguration");


-- ------------------------------------------------------------
-- 2. The asset cards
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."FaAssets"
(
    "FaAssetId"               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"                uuid                     NOT NULL DEFAULT uuidv7(),
    "AssetNo"                 character varying(40)    NOT NULL,
    "Name"                    character varying(150)   NOT NULL,
    "FaCategoryId"            bigint                   NOT NULL,
    "Description"             character varying(500)   NOT NULL DEFAULT '',
    "Brand"                   character varying(100)   NOT NULL DEFAULT '',
    "Model"                   character varying(100)   NOT NULL DEFAULT '',
    "SerialNo"                character varying(100)   NOT NULL DEFAULT '',
    "BranchId"                bigint                   NOT NULL,
    "FaLocationId"            bigint                   NULL,
    -- an employee (Human Resource)
    "CustodianEmployeeId"     bigint                   NULL,
    "SupplierName"            character varying(150)   NOT NULL DEFAULT '',
    "PurchaseRef"             character varying(60)    NOT NULL DEFAULT '',
    "PurchaseDate"            date                     NOT NULL,
    -- depreciation starts in the month of this date
    "UseDate"                 date                     NOT NULL,
    -- 1 : one item; more : a group card
    "Quantity"                numeric(10,2)            NOT NULL DEFAULT 1,
    "Cost"                    numeric(18,2)            NOT NULL DEFAULT 0,
    "ImprovementCost"         numeric(18,2)            NOT NULL DEFAULT 0,
    "ResidualValue"           numeric(18,2)            NOT NULL DEFAULT 0,
    "Method"                  character varying(20)    NOT NULL DEFAULT 'StraightLine',
    "RatePercent"             numeric(7,3)             NOT NULL DEFAULT 0,
    "LifeYears"               integer                  NOT NULL DEFAULT 0,
    -- an opening asset : the depreciation before the module
    "OpeningAccumulated"      numeric(18,2)            NOT NULL DEFAULT 0,
    -- everything to date (the opening and the runs)
    "AccumulatedDepreciation" numeric(18,2)            NOT NULL DEFAULT 0,
    -- yyyymm of the last month depreciated (0 = none yet)
    "LastRunPeriod"           integer                  NOT NULL DEFAULT 0,
    -- In Use / Idle / Under Repair / Disposed / Written Off / Lost
    "Status"                  character varying(20)    NOT NULL DEFAULT 'In Use',
    -- Acquisition / Opening
    "Source"                  character varying(15)    NOT NULL DEFAULT 'Opening',
    "FaAcquisitionId"         bigint                   NULL,
    "DisposedDate"            date                     NULL,
    "Remarks"                 character varying(500)   NOT NULL DEFAULT '',
    "IsDeleted"               boolean                  NOT NULL DEFAULT false,
    "DeletedBy"               bigint                   NULL,
    "DeletedDate"             timestamp with time zone NULL,
    "CreatedBy"               bigint                   NOT NULL,
    "CreatedDate"             timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"              bigint                   NULL,
    "ModifiedDate"            timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_FaAssets_PublicId" ON public."FaAssets" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_FaAssets_AssetNo"  ON public."FaAssets" ("AssetNo");
CREATE INDEX        IF NOT EXISTS "IX_FaAssets_Branch"   ON public."FaAssets" ("BranchId", "Status");
CREATE INDEX        IF NOT EXISTS "IX_FaAssets_Category" ON public."FaAssets" ("FaCategoryId");


