    "Accumulated"      numeric(18,2)            NOT NULL DEFAULT 0,
    "BookValue"        numeric(18,2)            NOT NULL DEFAULT 0,
    -- price less book value (a loss is negative)
    "GainLoss"         numeric(18,2)            NOT NULL DEFAULT 0,
    -- the status of the asset before (a delete puts it back)
    "PrevStatus"       character varying(20)    NOT NULL DEFAULT 'In Use',
    "JournalVoucherId" bigint                   NULL,
    "JournalVoucherNo" character varying(30)    NOT NULL DEFAULT '',
    "Remarks"          character varying(500)   NOT NULL DEFAULT '',
    "IsDeleted"        boolean                  NOT NULL DEFAULT false,
    "DeletedBy"        bigint                   NULL,
    "DeletedDate"      timestamp with time zone NULL,
    "CreatedBy"        bigint                   NOT NULL,
    "CreatedDate"      timestamp with time zone NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_FaDisposals_PublicId" ON public."FaDisposals" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_FaDisposals_Code"     ON public."FaDisposals" ("Code");
