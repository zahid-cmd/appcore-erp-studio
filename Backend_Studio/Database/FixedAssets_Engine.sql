    "Brand"               character varying(100) NOT NULL DEFAULT '',
    "Model"               character varying(100) NOT NULL DEFAULT '',
    "SerialNo"            character varying(100) NOT NULL DEFAULT '',
    "Quantity"            numeric(10,2)          NOT NULL DEFAULT 1,
    "UnitCost"            numeric(18,2)          NOT NULL DEFAULT 0,
    "Amount"              numeric(18,2)          NOT NULL DEFAULT 0,
    -- Each (one card an item) / Group (one card with the quantity)
