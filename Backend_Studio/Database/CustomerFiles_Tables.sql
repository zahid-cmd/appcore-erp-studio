CREATE TABLE IF NOT EXISTS public."CustomerFiles"
(
    "CustomerFileId"      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"            uuid                   NOT NULL DEFAULT uuidv7(),
    "CustomerFileNo"      character varying(60)  NOT NULL,
    "Source"              character varying(20)  NOT NULL,
    "FileDate"            date                   NOT NULL,
    "BranchId"            bigint                 NOT NULL DEFAULT 0,

    "SalesInvoiceId"      bigint                 NULL,
    "SalesInvoiceNo"      character varying(50)  NOT NULL DEFAULT '',
    "SalesInvoiceDate"    date                   NULL,
    "SalesmanName"        character varying(150) NOT NULL DEFAULT '',

    "MotorBikeId"         bigint                 NOT NULL,
    "ChassisNo"           character varying(50)  NOT NULL,
    "EngineNo"            character varying(50)  NOT NULL DEFAULT '',
    "VehiclePower"        character varying(20)  NOT NULL DEFAULT 'Fuel',

    "OriginalCustomerId"  bigint                 NOT NULL,
    "CurrentCustomerId"   bigint                 NOT NULL,

    "RegistrationBy"      character varying(20)  NOT NULL DEFAULT 'Dealer',
    "RegistrationTypeId"  bigint                 NULL,
    "RegistrationFileNo"  character varying(60)  NOT NULL DEFAULT '',

    "TransferCount"       integer                NOT NULL DEFAULT 0,
    "FileReadyDate"       date                   NULL,
    "CollectedDate"       date                   NULL,
    "Status"              character varying(30)  NOT NULL DEFAULT 'Open',
    "Remarks"             character varying(500) NOT NULL DEFAULT '',

    "IsDeleted"           boolean                NOT NULL DEFAULT false,
    "DeletedBy"           bigint                 NULL,
    "DeletedDate"         timestamp with time zone NULL,
    "CreatedBy"           bigint                 NOT NULL,
    "CreatedDate"         timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"          bigint                 NULL,
    "ModifiedDate"        timestamp with time zone NULL,

    CONSTRAINT "CK_CustomerFiles_Source"
        CHECK ("Source" IN ('Invoice', 'Opening')),

    CONSTRAINT "CK_CustomerFiles_Power"
        CHECK ("VehiclePower" IN ('Fuel', 'Electric')),

    CONSTRAINT "CK_CustomerFiles_RegistrationBy"
        CHECK ("RegistrationBy" IN ('Dealer', 'Customer')),

    CONSTRAINT "CK_CustomerFiles_Status"
        CHECK ("Status" IN ('Open', 'ReadyForDelivery', 'Delivered', 'Cancelled'))
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_CustomerFiles_PublicId"
    ON public."CustomerFiles" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_CustomerFiles_No"
    ON public."CustomerFiles" ("CustomerFileNo");

-- One live file per chassis
CREATE UNIQUE INDEX IF NOT EXISTS "UX_CustomerFiles_Chassis"
    ON public."CustomerFiles" (upper("ChassisNo"))
    WHERE "IsDeleted" = false AND "Status" <> 'Cancelled';

CREATE INDEX IF NOT EXISTS "IX_CustomerFiles_CurrentCustomer"
    ON public."CustomerFiles" ("CurrentCustomerId");


CREATE TABLE IF NOT EXISTS public."CustomerFileNameTransfers"
(
    "NameTransferId"      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"            uuid                   NOT NULL DEFAULT uuidv7(),
    "TransferNo"          character varying(20)  NOT NULL,
    "CustomerFileId"      bigint                 NOT NULL
        REFERENCES public."CustomerFiles" ("CustomerFileId"),
    "TransferDate"        date                   NOT NULL,
    "FromCustomerId"      bigint                 NOT NULL,
    "ToCustomerId"        bigint                 NOT NULL,
    "NameTransferRuleId"  bigint                 NULL,
    "FeeAmount"           numeric(18,2)          NOT NULL DEFAULT 0,
    -- Codes of the documents received, e.g. 'NTD-001,NTD-003'
    "DocumentCodes"       character varying(500) NOT NULL DEFAULT '',
    "Remarks"             character varying(500) NOT NULL DEFAULT '',

    "IsDeleted"           boolean                NOT NULL DEFAULT false,
    "DeletedBy"           bigint                 NULL,
    "DeletedDate"         timestamp with time zone NULL,
    "CreatedBy"           bigint                 NOT NULL,
    "CreatedDate"         timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"          bigint                 NULL,
    "ModifiedDate"        timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_CustomerFileNameTransfers_PublicId"
    ON public."CustomerFileNameTransfers" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_CustomerFileNameTransfers_No"
    ON public."CustomerFileNameTransfers" ("TransferNo");

CREATE INDEX IF NOT EXISTS "IX_CustomerFileNameTransfers_File"
    ON public."CustomerFileNameTransfers" ("CustomerFileId");


SELECT 'Customer Files' AS "List", count(*) AS "Rows" FROM public."CustomerFiles" WHERE "IsDeleted" = false
UNION ALL
SELECT 'Name Transfers', count(*) FROM public."CustomerFileNameTransfers" WHERE "IsDeleted" = false;
