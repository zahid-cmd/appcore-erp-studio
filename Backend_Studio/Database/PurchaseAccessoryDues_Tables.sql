-- ==============================================================
-- Free accessories due from the supplier on MB Purchases
--
--   PurchaseAccessoryDues      one row per purchase / scheme /
--                              accessory (due, received, closed)
--   PurchaseAccessoryReceipts  what each Motor Bike Receiving
--                              took in (own zero-cost batch)
--
-- 1. Creates the two tables (safe to run again).
-- 2. One-time fill for MB purchases already posted : the
--    Supplier schemes valid on each purchase date (bikes incl.
--    free bikes x quantity per bike). A purchase that already
--    has due rows is skipped, so running it again adds nothing.
--
-- Run after BikeAccessorySchemes_Tables.sql. Needs PostgreSQL 18
-- (uuidv7). ASCII only.
-- ==============================================================

BEGIN;

CREATE TABLE IF NOT EXISTS "PurchaseAccessoryDues"
(
    "PurchaseAccessoryDueId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"               uuid          NOT NULL DEFAULT uuidv7(),
    "PurchaseId"             bigint        NOT NULL,
    "PurchaseNo"             varchar(50)   NOT NULL,
    "PurchaseDate"           date          NOT NULL,
    "BranchId"               bigint        NOT NULL,
    "SupplierCode"           varchar(50)   NOT NULL DEFAULT '',
    "SupplierName"           varchar(200)  NOT NULL DEFAULT '',
    "BikeAccessorySchemeId"  bigint        NOT NULL,
    "SchemeCode"             varchar(30)   NOT NULL,
    "SchemeName"             varchar(150)  NOT NULL,
    "SchemeKind"             varchar(20)   NOT NULL,
    "AccessoryId"            bigint        NOT NULL,
    "ProductCode"            varchar(50)   NOT NULL DEFAULT '',
    "AccessoryName"          varchar(200)  NOT NULL DEFAULT '',
    "Unit"                   varchar(30)   NOT NULL DEFAULT '',
    "BikeQuantity"           numeric(18,2) NOT NULL DEFAULT 0,
    "QuantityDue"            numeric(18,2) NOT NULL DEFAULT 0,
    "QuantityReceived"       numeric(18,2) NOT NULL DEFAULT 0,
    "QuantityClosed"         numeric(18,2) NOT NULL DEFAULT 0,
    "CloseReason"            varchar(500)  NOT NULL DEFAULT '',
    "ClosedBy"               bigint        NULL,
    "ClosedDate"             timestamp with time zone NULL,
    "Status"                 varchar(20)   NOT NULL DEFAULT 'Pending',
    "CreatedBy"              bigint        NOT NULL DEFAULT 0,
    "CreatedDate"            timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"             bigint        NULL,
    "ModifiedDate"           timestamp with time zone NULL,

    CONSTRAINT "CK_PurchaseAccessoryDues_Status"
        CHECK ("Status" IN ('Pending', 'Received', 'Closed', 'Cancelled')),

    CONSTRAINT "CK_PurchaseAccessoryDues_Quantities"
        CHECK ("QuantityReceived" >= 0 AND "QuantityClosed" >= 0
               AND "QuantityReceived" + "QuantityClosed" <= "QuantityDue")
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_PurchaseAccessoryDues_PublicId"
    ON "PurchaseAccessoryDues" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_PurchaseAccessoryDues_Purchase_Scheme_Accessory"
    ON "PurchaseAccessoryDues" ("PurchaseId", "BikeAccessorySchemeId", "AccessoryId");

CREATE INDEX IF NOT EXISTS "IX_PurchaseAccessoryDues_Branch_Status"
    ON "PurchaseAccessoryDues" ("BranchId", "Status");


CREATE TABLE IF NOT EXISTS "PurchaseAccessoryReceipts"
(
    "PurchaseAccessoryReceiptId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ReceivingId"            bigint        NOT NULL,
    "ReceivingNo"            varchar(50)   NOT NULL,
    "ReceivingDate"          date          NOT NULL,
    "PurchaseAccessoryDueId" bigint        NOT NULL
        REFERENCES "PurchaseAccessoryDues" ("PurchaseAccessoryDueId"),
    "PurchaseId"             bigint        NOT NULL,
    "AccessoryId"            bigint        NOT NULL,
    "ProductCode"            varchar(50)   NOT NULL DEFAULT '',
    "AccessoryName"          varchar(200)  NOT NULL DEFAULT '',
    "Unit"                   varchar(30)   NOT NULL DEFAULT '',
    "Quantity"               numeric(18,2) NOT NULL,
    "StockBatchId"           bigint        NOT NULL,
    "BatchNo"                varchar(50)   NOT NULL DEFAULT '',
    "WarehouseId"            bigint        NOT NULL,
    "IsCancelled"            boolean       NOT NULL DEFAULT false,
    "CreatedBy"              bigint        NOT NULL DEFAULT 0,
    "CreatedDate"            timestamp with time zone NOT NULL DEFAULT now(),

    CONSTRAINT "CK_PurchaseAccessoryReceipts_Qty"
        CHECK ("Quantity" > 0)
);

CREATE INDEX IF NOT EXISTS "IX_PurchaseAccessoryReceipts_Receiving"
    ON "PurchaseAccessoryReceipts" ("ReceivingId");

CREATE INDEX IF NOT EXISTS "IX_PurchaseAccessoryReceipts_Due"
    ON "PurchaseAccessoryReceipts" ("PurchaseAccessoryDueId");


-- --------------------------------------------------------------
-- One-time fill : posted MB purchases without due rows
-- --------------------------------------------------------------

INSERT INTO "PurchaseAccessoryDues"
(
    "PurchaseId", "PurchaseNo", "PurchaseDate", "BranchId",
    "SupplierCode", "SupplierName",
    "BikeAccessorySchemeId", "SchemeCode", "SchemeName", "SchemeKind",
    "AccessoryId", "ProductCode", "AccessoryName", "Unit",
    "BikeQuantity", "QuantityDue", "QuantityReceived", "QuantityClosed",
    "CloseReason", "Status", "CreatedBy", "CreatedDate"
)
SELECT
    p."PurchaseId", left(p."PurchaseNo", 50), p."PurchaseDate", p."BranchId",
    left(p."SupplierCode", 50), left(p."SupplierName", 200),
    s."BikeAccessorySchemeId", s."SchemeCode", s."SchemeName", s."SchemeKind",
    i."AccessoryId", left(a."ProductCode", 50), left(a."AccessoryName", 200), left(a."Unit", 30),
    b.bikes, b.bikes * i."QuantityPerBike", 0, 0,
    '', 'Pending', 0, now()
FROM "PurchasesMb" p
JOIN LATERAL
(
    SELECT sm."BikeAccessorySchemeId", sum(l."Quantity" + l."FreeQuantity") AS bikes
    FROM "PurchasesMbLines" l
    JOIN "MotorBikes" mb ON mb."MotorBikeId" = l."ProductId"
    JOIN "ProductSubCategories" sc ON sc."ProductSubCategoryId" = mb."ProductSubCategoryId"
    JOIN "BikeAccessorySchemeModels" sm ON sm."BikeModelId" = sc."BikeModelId"
    WHERE l."PurchaseId" = p."PurchaseId"
    GROUP BY sm."BikeAccessorySchemeId"
) b ON true
JOIN "BikeAccessorySchemes" s ON s."BikeAccessorySchemeId" = b."BikeAccessorySchemeId"
JOIN "BikeAccessorySchemeItems" i ON i."BikeAccessorySchemeId" = s."BikeAccessorySchemeId"
JOIN "Accessories" a ON a."AccessoryId" = i."AccessoryId"
WHERE p."Status" = 'Posted'
  AND NOT p."IsDeleted"
  AND s."SchemeSource" = 'Supplier'
  AND s."Status"
  AND NOT s."IsDeleted"
  AND s."ValidFrom" <= p."PurchaseDate"
  AND (s."ValidTo" IS NULL OR s."ValidTo" >= p."PurchaseDate")
  AND b.bikes > 0
  AND NOT EXISTS
  (
      SELECT 1 FROM "PurchaseAccessoryDues" d WHERE d."PurchaseId" = p."PurchaseId"
  );

COMMIT;


-- Check : due rows per purchase
SELECT "PurchaseNo", "SchemeCode", "AccessoryName", "BikeQuantity", "QuantityDue", "Status"
FROM "PurchaseAccessoryDues"
ORDER BY "PurchaseDate", "PurchaseNo", "SchemeCode", "AccessoryName";
