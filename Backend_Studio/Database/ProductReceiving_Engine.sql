-- ============================================================
-- Product Receiving - MB / SP / AC : tables, switches, actions
-- (2026-11-01). Run after Purchases_Shared.sql.
--
-- 1. Tables (same columns on the three pages)
--      MotorBikeReceiving / SparePartsLubricantsReceiving /
--      AccessoriesReceiving             header (Goods Received Note)
--      …Lines                           one row per purchase line
--    The empty baseline tables (Code / Name / SampleField) made by
--    the page generator are replaced. A table that already has the
--    real columns is left as it is.
--    MotorBikeUnits : + ReceivingId, WarehouseId
--
-- 2. Switches (Inventory Management MOD-012), read BY CODE :
--      CFG-MOD-012-0001  Back Dated Receiving        Motor Bike Receiving
--      CFG-MOD-012-0002  Back Dated Receiving        Spare Parts & Lubricants Receiving
--      CFG-MOD-012-0003  Shelf Required at Receiving Spare Parts & Lubricants Receiving
--      CFG-MOD-012-0004  Back Dated Receiving        Accessories Receiving
--      CFG-MOD-012-0005  Shelf Required at Receiving Accessories Receiving
--    Motor bike numbers : the Purchases - MB switches (Units
--    Required 0048, Unique Key No 0049, Unique Battery No 0050).
--    A switch that already exists is left as it is.
--
-- 3. Page action Cancel linked to the three pages (Add, View,
--    Print are common actions).
--
-- After running : tick Add / View / Print / Cancel for the roles in
-- Security & Permission > Activity Assignment, then log in again.
--
-- Safe to run more than once. Run the whole script (F5).
-- ============================================================


-- ------------------------------------------------------------
-- 1a. Baseline tables out (only the generator's empty ones)
-- ------------------------------------------------------------

DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['MotorBikeReceiving', 'SparePartsLubricantsReceiving', 'AccessoriesReceiving']
    LOOP
        IF EXISTS
        (
            SELECT 1 FROM information_schema.tables
            WHERE  table_schema = 'public' AND table_name = t
        )
        AND NOT EXISTS
        (
            SELECT 1 FROM information_schema.columns
            WHERE  table_schema = 'public' AND table_name = t AND column_name = 'ReceivingNo'
        )
        THEN
            EXECUTE format('DROP TABLE public.%I CASCADE', t);
            RAISE NOTICE '% : baseline table replaced', t;
        END IF;
    END LOOP;
END $$;


-- ------------------------------------------------------------
-- 1b. Header and lines
-- ------------------------------------------------------------

DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['MotorBikeReceiving', 'SparePartsLubricantsReceiving', 'AccessoriesReceiving']
    LOOP
        EXECUTE format($f$
            CREATE TABLE IF NOT EXISTS public.%1$I
            (
                "ReceivingId"        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "PageType"           character varying(5)   NOT NULL,
                "ReceivingNo"        character varying(30)  NOT NULL,
                "ReceivingDate"      date                   NOT NULL,
                "BranchId"           bigint                 NOT NULL,
                "BranchCode"         character varying(30)  NOT NULL DEFAULT '',
                "BranchName"         character varying(150) NOT NULL DEFAULT '',
                "FinancialYearId"    bigint                 NOT NULL,
                "WarehouseId"        bigint                 NOT NULL,
                "WarehouseName"      character varying(150) NOT NULL DEFAULT '',

                "PurchaseId"         bigint                 NOT NULL,
                "PurchaseNo"         character varying(30)  NOT NULL,
                "PurchaseDate"       date                   NOT NULL,
                "SupplierCode"       character varying(30)  NOT NULL DEFAULT '',
                "SupplierName"       character varying(200) NOT NULL DEFAULT '',
                "SupplierInvoiceNo"  character varying(50)  NOT NULL DEFAULT '',
                "MushakNo"           character varying(50)  NOT NULL DEFAULT '',
                "DoReference"        character varying(50)  NOT NULL DEFAULT '',
                "GatePassNo"         character varying(50)  NOT NULL DEFAULT '',

                "ReceivedBy"         character varying(150) NOT NULL DEFAULT '',
                "Remarks"            character varying(500) NOT NULL DEFAULT '',
                "TotalQuantity"      numeric(18,2)          NOT NULL DEFAULT 0,

                "Status"             character varying(20)  NOT NULL DEFAULT 'Posted',
                "CancelReason"       character varying(500) NOT NULL DEFAULT '',
                "CancelledBy"        bigint                 NULL,
                "CancelledDate"      timestamp with time zone NULL,

                "IsDeleted"          boolean                NOT NULL DEFAULT false,
                "CreatedBy"          bigint                 NOT NULL,
                "CreatedDate"        timestamp with time zone NOT NULL DEFAULT now(),
                "ModifiedBy"         bigint                 NULL,
                "ModifiedDate"       timestamp with time zone NULL,

                CONSTRAINT %2$I CHECK ("Status" IN ('Posted', 'Cancelled'))
            )$f$,
            t, 'CK_' || t || '_Status');

        EXECUTE format('CREATE UNIQUE INDEX IF NOT EXISTS %I ON public.%I ("ReceivingNo") WHERE "IsDeleted" = false',
                       'IX_' || t || '_ReceivingNo', t);

        EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON public.%I ("PurchaseId")',
                       'IX_' || t || '_PurchaseId', t);

        EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON public.%I ("ReceivingDate")',
                       'IX_' || t || '_ReceivingDate', t);

        EXECUTE format($f$
            CREATE TABLE IF NOT EXISTS public.%1$I
            (
                "ReceivingLineId"    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "ReceivingId"        bigint                 NOT NULL REFERENCES public.%2$I ("ReceivingId") ON DELETE CASCADE,
                "LineNo"             integer                NOT NULL,
                "PurchaseLineId"     bigint                 NOT NULL,
                "StockBatchId"       bigint                 NOT NULL,
                "BatchNo"            character varying(50)  NOT NULL DEFAULT '',
                "ProductType"        character varying(50)  NOT NULL DEFAULT '',
                "ProductId"          bigint                 NOT NULL,
                "ProductCode"        character varying(30)  NOT NULL,
                "ProductName"        character varying(200) NOT NULL DEFAULT '',
                "Unit"               character varying(30)  NOT NULL DEFAULT '',
                "PurchasedQuantity"  numeric(18,2)          NOT NULL DEFAULT 0,
                "ReceivedBefore"     numeric(18,2)          NOT NULL DEFAULT 0,
                "Quantity"           numeric(18,2)          NOT NULL,
                "UnitCost"           numeric(18,4)          NOT NULL DEFAULT 0,
                "RackManagementId"   bigint                 NULL,
                "RackCode"           character varying(50)  NOT NULL DEFAULT '',
                "ShelfNumber"        integer                NOT NULL DEFAULT 0,
                "ShortNotes"         character varying(200) NOT NULL DEFAULT ''
            )$f$,
            t || 'Lines', t);

        EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON public.%I ("ReceivingId")',
                       'IX_' || t || 'Lines_ReceivingId', t || 'Lines');

        EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON public.%I ("StockBatchId")',
                       'IX_' || t || 'Lines_StockBatchId', t || 'Lines');

        RAISE NOTICE '% / %Lines : ready', t, t;
    END LOOP;
END $$;


