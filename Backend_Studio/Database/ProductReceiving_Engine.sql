-- ------------------------------------------------------------
-- 2. Switches
-- ------------------------------------------------------------

DO $$
DECLARE
    v_module_id   bigint;
    v_module_code text;
    v_page        record;
    v_page_code   text;
    v_menu_code   text;
    n             integer;
BEGIN
    SELECT m."Id", m."Code"
    INTO   v_module_id, v_module_code
    FROM   "NavigationModules" m
    WHERE  lower(trim(m."Name")) = 'inventory management'
    AND    NOT m."IsDeleted"
    LIMIT  1;

    IF v_module_id IS NULL THEN
        RAISE EXCEPTION 'Inventory Management module not found - nothing changed.';
    END IF;

    IF upper(trim(v_module_code)) <> 'MOD-012' THEN
        RAISE EXCEPTION 'Inventory Management module code is % (expected MOD-012) - nothing changed. Tell Claude the code.', v_module_code;
    END IF;

    -- A code taken by some other switch stops the script
    IF EXISTS
    (
        SELECT 1
        FROM   "SystemConfigurations" c
        WHERE  c."ConfigurationCode" BETWEEN 'CFG-MOD-012-0001' AND 'CFG-MOD-012-0005'
        AND    c."ConfigurationName" NOT IN ('Back Dated Receiving', 'Shelf Required at Receiving')
    )
    THEN
        RAISE EXCEPTION 'Some of CFG-MOD-012-0001 .. 0005 are already used by other switches - nothing changed. Tell Claude.';
    END IF;

    FOR v_page IN
        SELECT *
        FROM
        (
            VALUES
            ('MB', 'motor-bike-receiving',             1, NULL::int),
            ('SP', 'spare-parts-lubricants-receiving', 2, 3),
            ('AC', 'accessories-receiving',            4, 5)
        ) AS p (page_type, route, back_no, shelf_no)
    LOOP
        v_page_code := NULL;
        v_menu_code := NULL;

        SELECT s."Code", mn."Code"
        INTO   v_page_code, v_menu_code
        FROM   "NavigationSubmenus" s
        JOIN   "NavigationMenus" mn ON mn."Id" = s."NavigationMenuId"
        WHERE  s."Route" ILIKE '/inventory-management/%/' || v_page.route
        AND    NOT s."IsDeleted"
        LIMIT  1;

        IF v_page_code IS NULL THEN
            RAISE EXCEPTION 'Receiving page % not found by route (/inventory-management/.../%) - nothing changed.', v_page.page_type, v_page.route;
        END IF;

        INSERT INTO "SystemConfigurations"
        (
            "NavigationModuleId", "ScopeType", "NavigationMenuCode", "NavigationSubmenuCode",
            "ConfigurationCode", "ConfigurationName", "OnDescription", "OffDescription",
            "IsEnabled", "Value",
            "ValueType", "ValueUnit", "ValueMin", "ValueMax", "ValueEmptyText",
            "DefaultEnabled", "DefaultValue", "ParentConfigurationCode",
            "IsCritical", "IsSystemDefined", "DisplayOrder", "Remarks",
            "IsDeleted", "CreatedBy", "CreatedDate"
        )
        SELECT
            v_module_id, 'Submenu', v_menu_code, v_page_code,
            v.code, v.name, v.on_text, v.off_text,
            v.def_on, v.def_value,
            v.value_type, v.unit, v.vmin, v.vmax, v.empty_text,
            v.def_on, v.def_value, NULL,
            false, true, v.ord, v.remarks,
            false, 1, now()
        FROM
        (
            VALUES
            ('CFG-MOD-012-' || lpad(v_page.back_no::text, 4, '0'), 10,
             'Back Dated Receiving',
             'The receiving date may be earlier than today (Value = most days back; empty = any day of the open year).',
             'The receiving date must be today.',
             true, '3', 'Number', 'days', 1::int, 365::int, 'Any day',
             'Never before the purchase date, never after today.'),

            (CASE WHEN v_page.shelf_no IS NULL THEN NULL ELSE 'CFG-MOD-012-' || lpad(v_page.shelf_no::text, 4, '0') END, 20,
             'Shelf Required at Receiving',
             'Every received line needs its rack and shelf in the warehouse.',
             'Rack and shelf are optional at receiving.',
             true, '', 'None', '', NULL, NULL, '',
             'The rack and shelf can be saved as the product''s default in the warehouse.')
        ) AS v (code, ord, name, on_text, off_text, def_on, def_value, value_type, unit, vmin, vmax, empty_text, remarks)
        WHERE v.code IS NOT NULL
        AND   NOT EXISTS
        (
            SELECT 1
            FROM   "SystemConfigurations" c
            WHERE  c."ConfigurationCode" = v.code
        );

        GET DIAGNOSTICS n = ROW_COUNT;
        RAISE NOTICE 'Receiving - % : % switches added (page %, menu %)', v_page.page_type, n, v_page_code, v_menu_code;
    END LOOP;
END $$;


-- ------------------------------------------------------------
-- 3. Page action : Cancel on the three pages
-- ------------------------------------------------------------

INSERT INTO "MasterActivityPages" ("MasterActivityCode", "NavigationSubmenuCode", "CreatedBy")
SELECT a."Code", s."Code", 1
FROM   "MasterActivities" a
JOIN   "NavigationSubmenus" s
       ON s."Route" ILIKE '/inventory-management/product-receiving/%'
      AND s."IsDeleted" = false
WHERE  a."IsDeleted" = false
AND    a."ActivityScope" = 'Page'
AND    a."Name" IN ('Cancel')
ON CONFLICT ("MasterActivityCode", "NavigationSubmenuCode") DO NOTHING;


-- ------------------------------------------------------------
-- Check (run on its own) : pages, actions, switches
-- ------------------------------------------------------------

SELECT s."Code"  AS "Submenu",
       s."Name"  AS "Page",
       s."Route",
       COALESCE((SELECT string_agg(a."Name", ', ' ORDER BY a."DisplayOrder")
                 FROM   "MasterActivityPages" p
                 JOIN   "MasterActivities" a ON a."Code" = p."MasterActivityCode" AND a."IsDeleted" = false
                 WHERE  p."NavigationSubmenuCode" = s."Code"), '') AS "Page Actions",
       COALESCE((SELECT string_agg(c."ConfigurationCode" || ' ' || c."ConfigurationName", ', ' ORDER BY c."ConfigurationCode")
                 FROM   "SystemConfigurations" c
                 WHERE  c."NavigationSubmenuCode" = s."Code" AND NOT c."IsDeleted"), '') AS "Switches"
FROM   "NavigationSubmenus" s
WHERE  s."Route" ILIKE '/inventory-management/product-receiving/%'
AND    s."IsDeleted" = false
ORDER  BY s."Code";
