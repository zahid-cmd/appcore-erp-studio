-- Service Operations, step 2 (claude\blueprint-service-operations.md) :
-- Service Estimates. The job card follows the approved estimate.
--
--   ServiceEstimates       EST-000001 (with a version : 1, 2 ...) : what
--                          the job of a job card will cost. Made from a
--                          job card.
--                          Draft -> Sent -> Approved / Rejected.
--                          Revise : the estimate becomes Revised and a
--                          new Draft with the next version is made.
--                          One estimate of a job card is live at a time
--                          (Draft / Sent / Approved).
--                          Approved : the labour and part lines of the
--                          job card become those of the estimate, and
--                          they are locked on the job card.
--   ServiceEstimateLines   the labour lines (LineType Service) and the
--                          part lines (LineType Part)
--   WorkshopConfiguration  + RequireEstimate : work cannot start on a
--                          job card without an approved estimate (not
--                          for Free Service / Warranty / Rework /
--                          Internal jobs : the customer does not pay)
--
-- The page is there already (ServiceOperations_Navigation.sql) :
-- Workshop Management > Service Estimates. Hand-written page : NEVER
-- run Menu / Submenu / Code Sync for it.
--
-- Run ServiceOperations_Workshop_Engine.sql first (once). Safe to run
-- more than once. Run the whole script (F5). ASCII only.
--
-- AFTER : Security & Permission > Activity Assignment : tick Service
-- Estimates for the roles, log in again.
-- =====================================================================


-- ------------------------------------------------------------
-- 1. The switch
-- ------------------------------------------------------------

ALTER TABLE public."WorkshopConfiguration"
    ADD COLUMN IF NOT EXISTS "RequireEstimate" boolean NOT NULL DEFAULT false;


-- ------------------------------------------------------------
-- 2. Service Estimates
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."ServiceEstimates"
(
    "ServiceEstimateId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"          uuid                     NOT NULL DEFAULT uuidv7(),
    -- EST-000001 : every version of an estimate keeps the number
    "EstimateNo"        character varying(30)    NOT NULL,
    "Version"           integer                  NOT NULL DEFAULT 1,
    "EstimateDate"      date                     NOT NULL,
    "ValidUntil"        date                     NULL,
    "BranchId"          bigint                   NOT NULL,
    "JobCardId"         bigint                   NOT NULL
        REFERENCES public."JobCards" ("JobCardId"),
    -- Draft / Sent / Approved / Rejected / Revised
    "Status"            character varying(10)    NOT NULL DEFAULT 'Draft',
    "StatusDate"        timestamp with time zone NOT NULL DEFAULT now(),
    -- what the customer said (why it was rejected ...)
    "StatusNote"        character varying(300)   NOT NULL DEFAULT '',
    "LabourTotal"       numeric(18,2)            NOT NULL DEFAULT 0,
    "PartsTotal"        numeric(18,2)            NOT NULL DEFAULT 0,
    "GrandTotal"        numeric(18,2)            NOT NULL DEFAULT 0,
    "Remarks"           character varying(500)   NOT NULL DEFAULT '',
    "IsDeleted"         boolean                  NOT NULL DEFAULT false,
    "DeletedBy"         bigint                   NULL,
    "DeletedDate"       timestamp with time zone NULL,
    "CreatedBy"         bigint                   NOT NULL,
    "CreatedDate"       timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"        bigint                   NULL,
    "ModifiedDate"      timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_ServiceEstimates_PublicId" ON public."ServiceEstimates" ("PublicId");
-- the estimate number is EST-<branch>-<FY>-<MM>-00001 (2026-11-16) :
-- a table made before that gets the room for it
ALTER TABLE public."ServiceEstimates" ALTER COLUMN "EstimateNo" TYPE character varying(30);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_ServiceEstimates_No"       ON public."ServiceEstimates" ("EstimateNo", "Version");
CREATE INDEX        IF NOT EXISTS "IX_ServiceEstimates_JobCard"  ON public."ServiceEstimates" ("JobCardId", "Status");
CREATE INDEX        IF NOT EXISTS "IX_ServiceEstimates_Branch"   ON public."ServiceEstimates" ("BranchId", "Status");

CREATE TABLE IF NOT EXISTS public."ServiceEstimateLines"
(
    "ServiceEstimateLineId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ServiceEstimateId"     bigint NOT NULL
        REFERENCES public."ServiceEstimates" ("ServiceEstimateId") ON DELETE CASCADE,
    -- Service (labour) / Part
    "LineType"              character varying(10)  NOT NULL DEFAULT 'Service',
    "LineNo"                integer                NOT NULL DEFAULT 0,
    -- Service : Scheduled / LaborChart / Customized / Membership / Other
    -- Part    : SparePart / Accessory / Other
    "ItemKind"              character varying(15)  NOT NULL DEFAULT 'Other',
    "ItemId"                bigint                 NULL,
    "ItemCode"              character varying(40)  NOT NULL DEFAULT '',
    "ItemName"              character varying(200) NOT NULL,
    "Quantity"              numeric(10,2)          NOT NULL DEFAULT 1,
    "Rate"                  numeric(18,2)          NOT NULL DEFAULT 0,
    "Amount"                numeric(18,2)          NOT NULL DEFAULT 0,
    -- a free scheduled service : its charge is waived for the customer
    "IsFree"                boolean                NOT NULL DEFAULT false,
    "Note"                  character varying(200) NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS "IX_ServiceEstimateLines_Estimate" ON public."ServiceEstimateLines" ("ServiceEstimateId");


