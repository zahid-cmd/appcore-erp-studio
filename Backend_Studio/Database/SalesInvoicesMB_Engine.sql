-- ------------------------------------------------------------
-- 5. Page actions : the new "Give Special Discount" (only when it
--    is not there yet), then the links to Sales Invoices - MB
--    (found by its code or its route)
-- ------------------------------------------------------------

INSERT INTO "MasterActivities"
    ("SequenceNo", "Code", "Name", "DisplayOrder", "Remarks",
     "ActivityScope", "LinkToSwitchPages",
     "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
SELECT
    m.max_seq + 1,
    'ACT-' || lpad((m.max_seq + 1)::text, 4, '0'),
    'Give Special Discount',
    m.max_order + 1,
    'Give a special discount (line % or on the whole invoice) on the sales invoice pages, within the Allow Discount limit.',
    'Page',
    false,
    true,
    false,
    1,
    now()
FROM
(
    SELECT COALESCE(MAX("SequenceNo"), 0)   AS max_seq,
           COALESCE(MAX("DisplayOrder"), 0) AS max_order
    FROM   "MasterActivities"
) AS m
WHERE NOT EXISTS
(
    SELECT 1
    FROM   "MasterActivities" a
    WHERE  a."IsDeleted" = false
    AND    lower(trim(a."Name")) = 'give special discount'
);

INSERT INTO "MasterActivityPages" ("MasterActivityCode", "NavigationSubmenuCode", "CreatedBy")
SELECT a."Code", s."Code", 1
FROM   "MasterActivities" a
JOIN   "NavigationSubmenus" s
       ON s."Route" ILIKE '/sales-operations/%/sales-invoices-mb'
      AND s."IsDeleted" = false
WHERE  a."IsDeleted" = false
AND    a."ActivityScope" = 'Page'
AND    a."Name" IN ('Approve', 'Return', 'Post', 'Cancel', 'Give Special Discount')
ON CONFLICT ("MasterActivityCode", "NavigationSubmenuCode") DO NOTHING;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM "NavigationSubmenus" s
                   WHERE s."Route" ILIKE '/sales-operations/%/sales-invoices-mb'
                   AND s."IsDeleted" = false) THEN
        RAISE NOTICE 'Sales Invoices - MB page not found (route /sales-operations/.../sales-invoices-mb) : no page actions linked.';
    END IF;
END $$;


-- ------------------------------------------------------------
-- 6. Auto Journal Registers : SIMB journals under this page (only
--    when AutoJournalRegisters_Sources.sql has made the table; a
--    row that exists keeps its settings, an empty page code is
--    filled in)
-- ------------------------------------------------------------

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables
               WHERE table_schema = 'public' AND table_name = 'AutoJournalSources') THEN
        INSERT INTO public."AutoJournalSources"
            ("VoucherType", "SourceTable", "NavigationSubmenuCode", "IsAutoJournal", "DisplayOrder", "Remarks")
        SELECT 'SIMB', '', COALESCE(s."Code", ''), true, 30, 'Sales Invoices - Motor Bikes'
        FROM   (SELECT 1) AS one
        LEFT   JOIN LATERAL
        (
            SELECT n."Code"
            FROM   "NavigationSubmenus" n
            WHERE  n."IsDeleted" = false
            AND    lower(n."Route") LIKE '%/sales-invoices-mb'
            ORDER  BY n."Id"
            LIMIT  1
        ) AS s ON true
        ON CONFLICT ("VoucherType", "SourceTable") DO UPDATE
        SET    "NavigationSubmenuCode" = EXCLUDED."NavigationSubmenuCode"
        WHERE  public."AutoJournalSources"."NavigationSubmenuCode" = ''
        AND    EXCLUDED."NavigationSubmenuCode" <> '';
    ELSE
        RAISE NOTICE 'AutoJournalSources does not exist yet : run AutoJournalRegisters_Sources.sql, then this script again.';
    END IF;
END $$;


