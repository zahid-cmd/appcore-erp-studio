-- ------------------------------------------------------------
-- 1. Tables
-- ------------------------------------------------------------

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables
               WHERE table_schema = 'public' AND table_name = 'ProductPricingMotorBikes')
       AND NOT EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = 'ProductPricingMotorBikes' AND column_name = 'CardNo') THEN
        DROP TABLE public."ProductPricingMotorBikes" CASCADE;
        RAISE NOTICE 'The sample ProductPricingMotorBikes table was dropped.';
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS public."ProductPricingMotorBikes"
(
    "Id"             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"       uuid                     NOT NULL DEFAULT uuidv7(),
    "CardNo"         character varying(30)    NOT NULL,
    "SequenceNo"     integer                  NOT NULL,
    "SupplierCode"   character varying(40)    NOT NULL,
    "SupplierName"   character varying(250)   NOT NULL DEFAULT '',
    "CardType"       character varying(10)    NOT NULL DEFAULT 'Regular',
    "EffectiveFrom"  date                     NOT NULL,
    "EffectiveTo"    date                     NULL,
    "Reference"      character varying(100)   NOT NULL DEFAULT '',
    "Remarks"        character varying(500)   NOT NULL DEFAULT '',
    "ProductCount"   integer                  NOT NULL DEFAULT 0,
    "Status"         character varying(20)    NOT NULL DEFAULT 'Draft',
    "PostedBy"       bigint                   NULL,
    "PostedDate"     timestamp with time zone NULL,
    "CancelledBy"    bigint                   NULL,
    "CancelledDate"  timestamp with time zone NULL,
    "CancelReason"   character varying(500)   NOT NULL DEFAULT '',
    "IsDeleted"      boolean                  NOT NULL DEFAULT false,
    "DeletedBy"      bigint                   NULL,
    "DeletedDate"    timestamp with time zone NULL,
    "CreatedBy"      bigint                   NOT NULL,
    "CreatedDate"    timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"     bigint                   NULL,
    "ModifiedDate"   timestamp with time zone NULL,
    CONSTRAINT "CK_ProductPricingMotorBikes_Type"   CHECK ("CardType" IN ('Regular', 'Campaign')),
    CONSTRAINT "CK_ProductPricingMotorBikes_Status" CHECK ("Status" IN ('Draft', 'Posted', 'Cancelled')),
    CONSTRAINT "CK_ProductPricingMotorBikes_Dates"  CHECK ("EffectiveTo" IS NULL OR "EffectiveTo" >= "EffectiveFrom")
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_ProductPricingMotorBikes_PublicId"
    ON public."ProductPricingMotorBikes" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_ProductPricingMotorBikes_CardNo"
    ON public."ProductPricingMotorBikes" ("CardNo");

CREATE INDEX IF NOT EXISTS "IX_ProductPricingMotorBikes_Supplier"
    ON public."ProductPricingMotorBikes" ("SupplierCode", "Status", "EffectiveFrom");

CREATE TABLE IF NOT EXISTS public."ProductPricingMotorBikeLines"
(
    "Id"                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CardId"             bigint                 NOT NULL REFERENCES public."ProductPricingMotorBikes" ("Id") ON DELETE CASCADE,
    "LineNo"             integer                NOT NULL,
    "ModelId"            bigint                 NOT NULL DEFAULT 0,
    "ModelName"          character varying(250) NOT NULL DEFAULT '',
    "MotorBikeId"        bigint                 NULL,
    "ProductCode"        character varying(40)  NOT NULL DEFAULT '',
    "ProductName"        character varying(250) NOT NULL DEFAULT '',
    "Dp"                 numeric(18,2)          NOT NULL,
    "Mrp"                numeric(18,2)          NOT NULL,
    "VatRate"            numeric(9,4)           NOT NULL DEFAULT 0,
    "VatInside"          numeric(18,2)          NOT NULL DEFAULT 0,
    "NetSale"            numeric(18,2)          NOT NULL DEFAULT 0,
    "Commission"         numeric(18,2)          NOT NULL DEFAULT 0,
    "CommissionPercent"  numeric(9,4)           NOT NULL DEFAULT 0,
    CONSTRAINT "CK_ProductPricingMotorBikeLines_Dp"  CHECK ("Dp" > 0),
    CONSTRAINT "CK_ProductPricingMotorBikeLines_Mrp" CHECK ("Mrp" > 0)
);

CREATE INDEX IF NOT EXISTS "IX_ProductPricingMotorBikeLines_CardId"
    ON public."ProductPricingMotorBikeLines" ("CardId");

CREATE INDEX IF NOT EXISTS "IX_ProductPricingMotorBikeLines_MotorBikeId"
    ON public."ProductPricingMotorBikeLines" ("MotorBikeId");

-- 1b. Model level prices (2026-11-09) : a table made by the
--     first version (one line per colour) gets ModelId / ModelName,
--     MotorBikeId becomes optional, and each saved draft gets one
--     model line per model (its first colour's prices); colours
--     with the same DP / MRP as their model line are folded in,
--     the others stay as colour exceptions.

ALTER TABLE public."ProductPricingMotorBikeLines"
    ADD COLUMN IF NOT EXISTS "ModelId" bigint NOT NULL DEFAULT 0;

ALTER TABLE public."ProductPricingMotorBikeLines"
    ADD COLUMN IF NOT EXISTS "ModelName" character varying(250) NOT NULL DEFAULT '';

ALTER TABLE public."ProductPricingMotorBikeLines"
    ALTER COLUMN "MotorBikeId" DROP NOT NULL;

UPDATE public."ProductPricingMotorBikeLines" l
SET "ModelId" = b."ProductSubCategoryId"
FROM public."MotorBikes" b
WHERE l."ModelId" = 0
  AND l."MotorBikeId" = b."MotorBikeId";

UPDATE public."ProductPricingMotorBikeLines" l
SET "ModelName" = s."SubCategoryName"
FROM public."ProductSubCategories" s
WHERE l."ModelName" = ''
  AND l."ModelId" = s."ProductSubCategoryId";

INSERT INTO public."ProductPricingMotorBikeLines"
    ("CardId", "LineNo", "ModelId", "ModelName", "MotorBikeId", "ProductCode", "ProductName",
     "Dp", "Mrp", "VatRate", "VatInside", "NetSale", "Commission", "CommissionPercent")
SELECT f."CardId", 0, f."ModelId", f."ModelName", NULL, '', f."ModelName",
       f."Dp", f."Mrp", f."VatRate", f."VatInside", f."NetSale", f."Commission", f."CommissionPercent"
FROM
(
    SELECT DISTINCT ON (l."CardId", l."ModelId") l.*
    FROM public."ProductPricingMotorBikeLines" l
    WHERE l."MotorBikeId" IS NOT NULL
      AND l."ModelId" > 0
    ORDER BY l."CardId", l."ModelId", l."LineNo"
) f
WHERE NOT EXISTS
(
    SELECT 1 FROM public."ProductPricingMotorBikeLines" m
    WHERE m."CardId" = f."CardId" AND m."ModelId" = f."ModelId" AND m."MotorBikeId" IS NULL
);

DELETE FROM public."ProductPricingMotorBikeLines" c
USING public."ProductPricingMotorBikeLines" m
WHERE c."MotorBikeId" IS NOT NULL
  AND m."MotorBikeId" IS NULL
  AND m."CardId" = c."CardId"
  AND m."ModelId" = c."ModelId"
  AND m."Dp" = c."Dp"
  AND m."Mrp" = c."Mrp";

-- Line numbers again : model, then its colour exceptions
UPDATE public."ProductPricingMotorBikeLines" l
SET "LineNo" = n.rn
FROM
(
    SELECT "Id",
           ROW_NUMBER() OVER (PARTITION BY "CardId"
                              ORDER BY "ModelName", "ModelId",
                                       CASE WHEN "MotorBikeId" IS NULL THEN 0 ELSE 1 END,
                                       "ProductName") AS rn
    FROM public."ProductPricingMotorBikeLines"
) n
WHERE n."Id" = l."Id"
  AND l."LineNo" <> n.rn;

UPDATE public."ProductPricingMotorBikes" h
SET "ProductCount" = c.cnt
FROM
(
    SELECT "CardId", COUNT(*) AS cnt
    FROM public."ProductPricingMotorBikeLines"
    WHERE "MotorBikeId" IS NULL
    GROUP BY "CardId"
) c
WHERE c."CardId" = h."Id"
  AND h."ProductCount" <> c.cnt;

CREATE UNIQUE INDEX IF NOT EXISTS "UX_ProductPricingMotorBikeLines_Model"
    ON public."ProductPricingMotorBikeLines" ("CardId", "ModelId")
    WHERE "MotorBikeId" IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS "UX_ProductPricingMotorBikeLines_Colour"
    ON public."ProductPricingMotorBikeLines" ("CardId", "MotorBikeId")
    WHERE "MotorBikeId" IS NOT NULL;

CREATE INDEX IF NOT EXISTS "IX_ProductPricingMotorBikeLines_ModelId"
    ON public."ProductPricingMotorBikeLines" ("ModelId");

-- 1c. One current Regular card per supplier (2026-11-09) : a new
--     Regular card replaces the whole previous card from its
--     Effective From. Posted Regular cards already there are
--     chained by date (each replaced by the next one).

ALTER TABLE public."ProductPricingMotorBikes"
    ADD COLUMN IF NOT EXISTS "SupersededById" bigint NULL;

ALTER TABLE public."ProductPricingMotorBikes"
    ADD COLUMN IF NOT EXISTS "SupersededByNo" character varying(30) NOT NULL DEFAULT '';

ALTER TABLE public."ProductPricingMotorBikes"
    ADD COLUMN IF NOT EXISTS "SupersededFrom" date NULL;

UPDATE public."ProductPricingMotorBikes" h
SET "SupersededById" = n.next_id,
    "SupersededByNo" = n.next_no,
    "SupersededFrom" = n.next_from
FROM
(
    SELECT "Id",
           LEAD("Id")            OVER w AS next_id,
           LEAD("CardNo")        OVER w AS next_no,
           LEAD("EffectiveFrom") OVER w AS next_from
    FROM public."ProductPricingMotorBikes"
    WHERE "Status" = 'Posted'
      AND "CardType" = 'Regular'
      AND NOT "IsDeleted"
    WINDOW w AS (PARTITION BY "SupplierCode" ORDER BY "EffectiveFrom", "Id")
) n
WHERE n."Id" = h."Id"
  AND n.next_id IS NOT NULL
  AND h."SupersededById" IS NULL;

CREATE INDEX IF NOT EXISTS "IX_ProductPricingMotorBikes_SupersededById"
    ON public."ProductPricingMotorBikes" ("SupersededById");

-- 1d. Regular cards only (2026-11-10) : a campaign changes neither
--     the MRP nor the VAT, so its discount is entered on the
--     purchase invoice. Campaign drafts are removed; a posted
--     Campaign card (if any) is cancelled.

DELETE FROM public."ProductPricingMotorBikeLines" l
USING public."ProductPricingMotorBikes" h
WHERE l."CardId" = h."Id"
  AND h."CardType" = 'Campaign'
  AND h."Status" = 'Draft';

DELETE FROM public."ProductPricingMotorBikes"
WHERE "CardType" = 'Campaign'
  AND "Status" = 'Draft';

UPDATE public."ProductPricingMotorBikes"
SET "Status" = 'Cancelled',
    "CancelledDate" = COALESCE("CancelledDate", now()),
    "CancelReason" = 'Campaign cards removed : campaign discounts are entered on the purchase invoice'
WHERE "CardType" = 'Campaign'
  AND "Status" = 'Posted';


-- ------------------------------------------------------------
-- 2. Page actions Post and Cancel
-- ------------------------------------------------------------

INSERT INTO "MasterActivityPages" ("MasterActivityCode", "NavigationSubmenuCode", "CreatedBy")
SELECT a."Code", s."Code", 1
FROM   "MasterActivities" a
JOIN   "NavigationSubmenus" s
       ON s."Route" ILIKE '/inventory-management/%/product-pricing-motor-bikes'
      AND s."IsDeleted" = false
WHERE  a."IsDeleted" = false
AND    a."ActivityScope" = 'Page'
AND    a."Name" IN ('Post', 'Cancel')
ON CONFLICT ("MasterActivityCode", "NavigationSubmenuCode") DO NOTHING;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM "NavigationSubmenus" s
                   WHERE s."Route" ILIKE '/inventory-management/%/product-pricing-motor-bikes'
                   AND s."IsDeleted" = false) THEN
        RAISE NOTICE 'Product Pricing - Motor Bikes page not found by route : Post / Cancel not linked.';
    END IF;
END $$;


