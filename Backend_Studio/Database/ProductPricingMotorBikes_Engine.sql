     'Difference between the VAT paid at source (Mushak 6.3) and the VAT inside the MRP on each Motor Bike sale : debit when the 6.3 VAT is higher, credit when lower. Settled monthly with the VAT payable (debit balance reduces it, credit balance increases it).',
