-- ============================================================
-- Booking Management : Bookings (motor bikes) and the link to
-- Sales Invoices - MB (2026-11-11)
--
-- 1. Bookings + BookingCollections tables. A booking holds the
--    customer, model and colour (no chassis, no price lock). Each
--    collection posts a Receipt Voucher : Dr cash / bank / MFS ...
--    Cr the customer's own ledger (advance).
-- 2. SalesInvoicesMb : BookingId, BookingNo, BookingAdvance. The
--    invoice takes the advance as already paid; posting converts
--    the booking, cancelling the invoice re-opens it.
-- 3. Switches on the Bookings page :
--      CFG-MOD-008-0091 Minimum Booking Amount (Tk)   ON 1000
--      CFG-MOD-008-0092 Booking Validity (days)       ON 30
--      CFG-MOD-008-0093 Refund on Cancel              ON
--      CFG-MOD-008-0094 Forfeit on Cancel (%)         OFF 0
-- 4. Posting Setup purpose BOOKING-FORFEIT-MB (income ledger for
--    the forfeited part of a cancelled booking).
-- 5. Page action "Cancel Booking" (Bookings).
-- 6. Submenus "Booking Collections" and "Booking Cancellations &
--    Refunds" removed for good : one Bookings page with tabs.
--    Hand-written page : NEVER run Submenu / Code Sync for it.
--
-- Safe to run again. ASCII only.
-- ============================================================

