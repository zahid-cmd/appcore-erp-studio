-- 3. Switches (Bookings page)
-- ------------------------------------------------------------

DO $$
DECLARE
    v_module_id   bigint;
    v_module_code text;
    v_page_code   text;
    v_menu_code   text;
    v_name        text;
    p             record;
BEGIN
    SELECT m."Id", m."Code" INTO v_module_id, v_module_code
    FROM   "NavigationModules" m
    WHERE  lower(trim(m."RouteKey")) = 'sales-operations' AND NOT m."IsDeleted"
    LIMIT  1;

    IF v_module_id IS NULL OR upper(trim(v_module_code)) <> 'MOD-008' THEN
        RAISE EXCEPTION 'Sales Operations module (MOD-008) not found - nothing changed.';
    END IF;

    SELECT s."Code", mn."Code" INTO v_page_code, v_menu_code
    FROM   "NavigationSubmenus" s
    JOIN   "NavigationMenus" mn ON mn."Id" = s."NavigationMenuId"
    WHERE  lower(s."Route") LIKE '/sales-operations/booking-management/bookings'
    AND    NOT s."IsDeleted"
    LIMIT  1;

    IF v_page_code IS NULL THEN
        RAISE EXCEPTION 'Bookings page not found (route /sales-operations/booking-management/bookings) - nothing changed.';
    END IF;

    FOR p IN
        SELECT * FROM (VALUES
            ('CFG-MOD-008-0091', 'Minimum Booking Amount', true, '1000', 'Number', 'Tk', 1, 10000000, 'no minimum', false, 1,
             'A booking needs at least this first collection (Tk).',
             'Any amount above 0 books the bike.'),
            ('CFG-MOD-008-0092', 'Booking Validity', true, '30', 'Number', 'days', 1, 365, 'no expiry', false, 2,
             'A booking is valid for these days from the booking date (shown Expired after; it can still be sold or cancelled).',
             'Bookings never expire.'),
            ('CFG-MOD-008-0093', 'Refund on Cancel', true, '', 'None', '', NULL, NULL, '', true, 3,
             'A cancelled booking leaves the advance (less the forfeit) on the customer''s ledger to refund by Payment Voucher.',
             'Cancelling a booking forfeits the whole advance (income).'),
            ('CFG-MOD-008-0094', 'Forfeit on Cancel', false, '0', 'Number', '%', 0, 100, '0 %', true, 4,
             'This % of the advance is suggested as forfeit when a booking is cancelled (it can be changed).',
             'No forfeit is suggested (0).')
        ) AS x (code, name, enabled, val, vtype, unit, vmin, vmax, empty_text, critical, ord, on_text, off_text)
    LOOP
        SELECT "ConfigurationName" INTO v_name
        FROM   "SystemConfigurations"
        WHERE  "ConfigurationCode" = p.code;

        IF v_name IS NOT NULL AND v_name <> p.name THEN
            RAISE EXCEPTION '% is already used by "%" - nothing changed. Tell Claude.', p.code, v_name;
        END IF;

        CONTINUE WHEN v_name IS NOT NULL;

        INSERT INTO "SystemConfigurations"
        (
            "NavigationModuleId", "ScopeType", "NavigationMenuCode", "NavigationSubmenuCode",
            "ConfigurationCode", "ConfigurationName", "OnDescription", "OffDescription",
            "IsEnabled", "Value",
            "ValueType", "ValueUnit", "ValueMin", "ValueMax", "ValueEmptyText",
            "DefaultEnabled", "DefaultValue", "ParentConfigurationCode",
            "IsCritical", "IsSystemDefined", "DisplayOrder", "Remarks",
            "IsDeleted", "CreatedBy", "CreatedDate"
        )
        VALUES
        (
            v_module_id, 'Submenu', v_menu_code, v_page_code,
            p.code, p.name, p.on_text, p.off_text,
            p.enabled, p.val,
            p.vtype, p.unit, p.vmin, p.vmax, p.empty_text,
            p.enabled, p.val, NULL,
            p.critical, true, p.ord, '',
            false, 1, now()
        );

        RAISE NOTICE 'Switch % % added.', p.code, p.name;
    END LOOP;
END $$;


