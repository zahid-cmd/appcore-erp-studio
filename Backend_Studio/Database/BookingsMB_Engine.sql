-- ------------------------------------------------------------
-- 1. Tables
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."Bookings"
(
    "BookingId"          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"           uuid                     NOT NULL DEFAULT uuidv7(),
    "BookingNo"          character varying(40)    NOT NULL,
    "BookingDate"        date                     NOT NULL,
    "BranchId"           bigint                   NOT NULL,

    "CustomerId"         bigint                   NOT NULL,
    "CustomerCode"       character varying(20)    NOT NULL DEFAULT '',
    "CustomerName"       character varying(200)   NOT NULL DEFAULT '',
    "CustomerPhone"      character varying(20)    NOT NULL DEFAULT '',

    "MotorBikeId"        bigint                   NOT NULL,
    "ModelName"          character varying(250)   NOT NULL DEFAULT '',

    "ValidUntil"         date                     NULL,
    "ExpectedDate"       date                     NULL,
    "SalesPersonName"    character varying(150)   NOT NULL DEFAULT '',
    "Remarks"            character varying(500)   NOT NULL DEFAULT '',

    -- Sum of the collections
    "AdvanceAmount"      numeric(18,2)            NOT NULL DEFAULT 0,

    -- Open / Converted / Cancelled (Expired = Open past ValidUntil)
    "Status"             character varying(20)    NOT NULL DEFAULT 'Open',

    "SalesInvoiceId"     bigint                   NULL,
    "SalesInvoiceNo"     character varying(50)    NOT NULL DEFAULT '',
    "ConvertedDate"      date                     NULL,

    "CancelReason"       character varying(500)   NOT NULL DEFAULT '',
    "CancelledBy"        bigint                   NULL,
    "CancelledDate"      timestamp with time zone NULL,
    "ForfeitAmount"      numeric(18,2)            NOT NULL DEFAULT 0,
    "ForfeitVoucherId"   bigint                   NULL,
    "ForfeitVoucherNo"   character varying(30)    NOT NULL DEFAULT '',
    -- Left on the customer's ledger to refund (Payment Voucher)
    "RefundAmount"       numeric(18,2)            NOT NULL DEFAULT 0,

    "IsDeleted"          boolean                  NOT NULL DEFAULT false,
    "DeletedBy"          bigint                   NULL,
    "DeletedDate"        timestamp with time zone NULL,
    "CreatedBy"          bigint                   NOT NULL,
    "CreatedDate"        timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"         bigint                   NULL,
    "ModifiedDate"       timestamp with time zone NULL,

    CONSTRAINT "CK_Bookings_Status"
        CHECK ("Status" IN ('Open', 'Converted', 'Cancelled'))
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_Bookings_PublicId" ON public."Bookings" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_Bookings_No" ON public."Bookings" ("BookingNo");

CREATE INDEX IF NOT EXISTS "IX_Bookings_Customer" ON public."Bookings" ("CustomerId", "Status");


CREATE TABLE IF NOT EXISTS public."BookingCollections"
(
    "BookingCollectionId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"            uuid                     NOT NULL DEFAULT uuidv7(),
    "BookingId"           bigint                   NOT NULL REFERENCES public."Bookings" ("BookingId"),
    "CollectionDate"      date                     NOT NULL,
    "Amount"              numeric(18,2)            NOT NULL DEFAULT 0,
    "ReceiptVoucherId"    bigint                   NULL,
    "ReceiptVoucherNo"    character varying(30)    NOT NULL DEFAULT '',
    "Remarks"             character varying(500)   NOT NULL DEFAULT '',
    "CreatedBy"           bigint                   NOT NULL,
    "CreatedDate"         timestamp with time zone NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_BookingCollections_PublicId" ON public."BookingCollections" ("PublicId");

CREATE INDEX IF NOT EXISTS "IX_BookingCollections_Booking" ON public."BookingCollections" ("BookingId");


