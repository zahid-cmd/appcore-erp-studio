-- ============================================================
-- Product Price Index + Product Pricing switches (2026-11-01).
-- Plain statements : run in a NEW pgAdmin Query Tool (F5).
-- Safe to run again.
--
-- 1. ProductPriceIndex : the declared MRP (VAT inclusive, the
--    sale price) of every product over time. Current MRP = its
--    latest entry not cancelled, stock or no stock. Written by a
--    posted MRP purchase invoice, opening stock and price change;
--    cancelling the document cancels its entries.
-- 2. Start : each product's latest priced stock batch becomes its
--    first entry ("Initial"), when it has none yet.
-- 3. Switches on the Product Pricing page :
--      CFG-MOD-012-0011  Pricing Grid MRP Editable              ON
--      CFG-MOD-012-0012  Raise Old Stock to a Higher New MRP    ON
--      CFG-MOD-012-0013  Price Reduction Applies to All Stock   OFF
--                        (OFF = only new purchases : stock in
--                        hand keeps its MRP on a reduction)
--    A switch that already exists is left as it is.
-- ============================================================


-- 1. Table

CREATE TABLE IF NOT EXISTS public."ProductPriceIndex"
(
    "ProductPriceIndexId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ProductType"        character varying(5)   NOT NULL,
    "ProductId"          bigint                 NOT NULL,
    "ProductCode"        character varying(40)  NOT NULL DEFAULT '',
    "ProductName"        character varying(250) NOT NULL DEFAULT '',
    "Mrp"                numeric(18,2)          NOT NULL,
    "EffectiveDate"      date                   NOT NULL,
    "SourceType"         character varying(20)  NOT NULL,
    "SourceId"           bigint                 NOT NULL DEFAULT 0,
    "SourceNo"           character varying(40)  NOT NULL DEFAULT '',
    "IsCancelled"        boolean                NOT NULL DEFAULT false,
    "CancelledDate"      timestamp with time zone NULL,
    "CreatedBy"          bigint                 NOT NULL DEFAULT 1,
    "CreatedDate"        timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT "CK_ProductPriceIndex_Type" CHECK ("ProductType" IN ('MB', 'SP', 'AC')),
    CONSTRAINT "CK_ProductPriceIndex_Mrp"  CHECK ("Mrp" > 0)
);

CREATE INDEX IF NOT EXISTS "IX_ProductPriceIndex_Product"
    ON public."ProductPriceIndex" ("ProductType", "ProductId", "EffectiveDate" DESC);

CREATE INDEX IF NOT EXISTS "IX_ProductPriceIndex_Source"
    ON public."ProductPriceIndex" ("SourceType", "ProductType", "SourceId");


-- 2. Start from the stock batches

INSERT INTO public."ProductPriceIndex"
    ("ProductType", "ProductId", "ProductCode", "ProductName", "Mrp", "EffectiveDate", "SourceType", "SourceId", "SourceNo", "CreatedBy")
SELECT DISTINCT ON (b."ProductType", b."ProductId")
       b."ProductType", b."ProductId", b."ProductCode", left(b."ProductName", 250), b."Mrp", b."SourceDate", 'Initial', b."StockBatchId", left(b."BatchNo", 40), 1
FROM   public."StockBatches" b
WHERE  b."Mrp" > 0
AND    b."Status" <> 'Cancelled'
AND    b."ProductType" IN ('MB', 'SP', 'AC')
AND    NOT EXISTS (SELECT 1 FROM public."ProductPriceIndex" i
                   WHERE i."ProductType" = b."ProductType" AND i."ProductId" = b."ProductId")
ORDER  BY b."ProductType", b."ProductId", b."StockBatchId" DESC;


-- 3. Switches

INSERT INTO "SystemConfigurations"
(
    "NavigationModuleId", "ScopeType", "NavigationMenuCode", "NavigationSubmenuCode",
    "ConfigurationCode", "ConfigurationName", "OnDescription", "OffDescription",
    "IsEnabled", "Value",
    "ValueType", "ValueUnit", "ValueMin", "ValueMax", "ValueEmptyText",
    "DefaultEnabled", "DefaultValue", "ParentConfigurationCode",
    "IsCritical", "IsSystemDefined", "DisplayOrder", "Remarks",
    "IsDeleted", "CreatedBy", "CreatedDate"
)
SELECT
    m."Id", 'Submenu', mn."Code", s."Code",
    v.code, v.name, v.on_text, v.off_text,
    v.def_on, '',
    'None', '', NULL, NULL, '',
    v.def_on, '', NULL,
    true, true, v.ord, 'MRP (VAT inclusive) is the sale price.',
    false, 1, now()
FROM
(
    VALUES
        ('CFG-MOD-012-0011', 'Pricing Grid MRP Editable',
         'The new MRP on the pricing grid can be typed over.',
         'The new MRP on the pricing grid is the calculated one; it cannot be typed over.',
         true, 30),
        ('CFG-MOD-012-0012', 'Raise Old Stock to a Higher New MRP',
         'When a new price is higher, the older stock of the product with a lower MRP is raised to it too.',
         'A new price applies only to the batches priced by the document; older stock keeps its MRP.',
         true, 31),
        ('CFG-MOD-012-0013', 'Price Reduction Applies to All Stock',
         'A repricing applies to all stock in hand, up or down (full revise).',
         'On a reduction (or no change) the stock in hand keeps its MRP; only the declared price changes, for new purchases. Increases always apply to the stock in hand.',
         false, 32)
) AS v (code, name, on_text, off_text, def_on, ord)
CROSS JOIN LATERAL
(
    SELECT nm."Id"
    FROM   "NavigationModules" nm
    WHERE  lower(trim(nm."Name")) = 'inventory management'
    AND    NOT nm."IsDeleted"
    LIMIT  1
) AS m
CROSS JOIN LATERAL
(
    SELECT sm."Code", sm."NavigationMenuId"
    FROM   "NavigationSubmenus" sm
    WHERE  sm."Route" ILIKE '/inventory-management/%/product-pricing'
    AND    NOT sm."IsDeleted"
    LIMIT  1
) AS s
JOIN "NavigationMenus" mn ON mn."Id" = s."NavigationMenuId"
WHERE NOT EXISTS
(
    SELECT 1 FROM "SystemConfigurations" c
    WHERE  c."ConfigurationCode" = v.code
);


