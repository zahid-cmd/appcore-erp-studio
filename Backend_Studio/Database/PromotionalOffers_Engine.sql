-- ============================================================
-- Business Promotions : Promotional Offers (2026-11-12)
--
-- Three hand-written pages share these tables (NEVER run Code
-- Sync for them) :
--   Sales Center    (Channel 'SalesCenter',    invoices MB)
--   Service Center  (Channel 'ServiceCenter',  invoices SP)
--   Accessory Shop  (Channel 'AccessoryShop',  invoices AC)
--
-- An offer : name, start / end date, branches (all or chosen),
-- the brand, who pays it (Company = own cost, Campaign Discount
-- ledger of the type; Distributor = reimbursable, posted to the
-- brand's Offer Adjustment ledger, Brand Management), a type :
--   Sales Center   : Fixed Discount / Scratch Card / SMS Offer
--   Service Center : Parts Discount / Free Service
--   Accessory Shop : Direct Discount / Scratch Card
-- Targets : what it covers (Sales Center : models = sub
-- categories, or one colour = one product; Service Center /
-- Accessory Shop : categories, sub categories or products, or
-- everything of the brand). A target may carry its own discount.
-- Prizes : Scratch Card / SMS Offer prizes with quantities.
-- Status : Draft -> Active -> Closed, or Cancelled.
--
-- Discount offers (Fixed / Parts / Direct) are applied by the
-- sales invoices automatically (campaign OR membership, the
-- better one). Scratch Card / SMS prizes and Free Service are
-- recorded in the next step.
--
-- 2. Sales invoice lines (MB / SP / AC) : the offer applied and
--    the ledger its discount went to.
--
-- Safe to run again. ASCII only. Needs PostgreSQL 18 (uuidv7).
-- ============================================================

ROLLBACK;


CREATE TABLE IF NOT EXISTS public."PromotionalOffers"
(
    "PromotionalOfferId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"             uuid                     NOT NULL DEFAULT uuidv7(),
    -- SalesCenter / ServiceCenter / AccessoryShop
    "Channel"              character varying(20)    NOT NULL,
    -- POSC-0001 / POSV-0001 / POAS-0001
    "OfferNo"              character varying(20)    NOT NULL,
    "OfferName"            character varying(150)   NOT NULL,
    "OfferType"            character varying(30)    NOT NULL,

    "BrandManagementId"    bigint                   NULL,
    "BrandName"            character varying(100)   NOT NULL DEFAULT '',
    -- Company / Distributor
    "FundedBy"             character varying(20)    NOT NULL DEFAULT 'Company',

    "StartDate"            date                     NOT NULL,
    "EndDate"              date                     NOT NULL,
    "AllBranches"          boolean                  NOT NULL DEFAULT true,
    -- comma separated BranchIds when not all
    "BranchIds"            character varying(1000)  NOT NULL DEFAULT '',

    -- Discount offers : Percent / Amount (Tk per unit)
    "DiscountType"         character varying(10)    NOT NULL DEFAULT 'Percent',
    "DiscountValue"        numeric(18,2)            NOT NULL DEFAULT 0,

    -- Free Service : services given free per bike
    "FreeServiceCount"     integer                  NOT NULL DEFAULT 0,
    -- SMS Offer : days after the sale the prize may be recorded
    "ClaimDays"            integer                  NOT NULL DEFAULT 0,

    "Terms"                character varying(1000)  NOT NULL DEFAULT '',
    -- Draft / Active / Closed / Cancelled
    "Status"               character varying(20)    NOT NULL DEFAULT 'Draft',
    "StatusReason"         character varying(500)   NOT NULL DEFAULT '',

    "IsDeleted"            boolean                  NOT NULL DEFAULT false,
    "DeletedBy"            bigint                   NULL,
    "DeletedDate"          timestamp with time zone NULL,
    "CreatedBy"            bigint                   NOT NULL,
    "CreatedDate"          timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"           bigint                   NULL,
    "ModifiedDate"         timestamp with time zone NULL,

    CONSTRAINT "CK_PromotionalOffers_Channel" CHECK ("Channel" IN ('SalesCenter', 'ServiceCenter', 'AccessoryShop')),
    CONSTRAINT "CK_PromotionalOffers_Funded"  CHECK ("FundedBy" IN ('Company', 'Distributor')),
    CONSTRAINT "CK_PromotionalOffers_Status"  CHECK ("Status" IN ('Draft', 'Active', 'Closed', 'Cancelled')),
    CONSTRAINT "CK_PromotionalOffers_Dates"   CHECK ("EndDate" >= "StartDate")
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_PromotionalOffers_PublicId" ON public."PromotionalOffers" ("PublicId");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_PromotionalOffers_No" ON public."PromotionalOffers" ("OfferNo");

CREATE INDEX IF NOT EXISTS "IX_PromotionalOffers_Live" ON public."PromotionalOffers" ("Channel", "Status", "StartDate", "EndDate");


CREATE TABLE IF NOT EXISTS public."PromotionalOfferTargets"
(
    "PromotionalOfferTargetId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PromotionalOfferId"   bigint                   NOT NULL REFERENCES public."PromotionalOffers" ("PromotionalOfferId"),
    "LineNo"               integer                  NOT NULL DEFAULT 1,
    -- All / Category / SubCategory / Product
    "TargetType"           character varying(20)    NOT NULL,
    "TargetId"             bigint                   NOT NULL DEFAULT 0,
    "TargetName"           character varying(250)   NOT NULL DEFAULT '',
    -- null = the offer's discount
    "DiscountType"         character varying(10)    NULL,
    "DiscountValue"        numeric(18,2)            NULL
);

CREATE INDEX IF NOT EXISTS "IX_PromotionalOfferTargets_Offer" ON public."PromotionalOfferTargets" ("PromotionalOfferId");


CREATE TABLE IF NOT EXISTS public."PromotionalOfferPrizes"
(
    "PromotionalOfferPrizeId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PromotionalOfferId"   bigint                   NOT NULL REFERENCES public."PromotionalOffers" ("PromotionalOfferId"),
    "LineNo"               integer                  NOT NULL DEFAULT 1,
    "PrizeName"            character varying(150)   NOT NULL,
    -- Cash (credited to the customer) / Item (an accessory or a
    -- product) / Service (free services)
    "PrizeKind"            character varying(20)    NOT NULL DEFAULT 'Cash',
    "PrizeValue"           numeric(18,2)            NOT NULL DEFAULT 0,
    "Quantity"             integer                  NOT NULL DEFAULT 0,
    "GivenQuantity"        integer                  NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS "IX_PromotionalOfferPrizes_Offer" ON public."PromotionalOfferPrizes" ("PromotionalOfferId");


