-- Purchases - MB with "Products Received on Purchase" ON (0045) :
-- the supplier's free accessories (Bike Accessory Schemes) can be
-- received with the purchase itself.
--
-- 1. PurchaseAccessoryTakes : the quantities entered on the purchase
--    (draft), one row per purchase . scheme . accessory; replaced on
--    every draft save, taken in on Post (zero-cost batches, on hand
--    in the purchase's warehouse). The rest stays due for Motor
--    Bike Receiving.
-- 2. PurchaseAccessoryReceipts."ReceivedOn" : 'Receiving' (Motor Bike
--    Receiving, ReceivingId = the receiving) / 'Purchase' (received
--    with the purchase, ReceivingId = the purchase).
-- 3. StockBatches : the free-accessory batches of a receiving and of
--    a purchase share SourceType 'AccessoryScheme'; their SourceId is
--    a receiving id or a purchase id, so the index on them is no
--    longer unique (BatchNo stays unique).
--
-- Run StockBatches_AccessoryScheme_Fix.sql first.
-- Plain statements, safe to run again. Run the whole script (F5).
-- ASCII only.
-- =====================================================================


-- Clears a transaction left open by an earlier failed run in the
-- same pgAdmin tab (a harmless warning when there is none).
ROLLBACK;

BEGIN;

CREATE TABLE IF NOT EXISTS public."PurchaseAccessoryTakes"
(
    "PurchaseAccessoryTakeId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PurchaseId"              bigint        NOT NULL,
    "BikeAccessorySchemeId"   bigint        NOT NULL,
    "AccessoryId"             bigint        NOT NULL,
    "Quantity"                numeric(18,2) NOT NULL,
    "CreatedBy"               bigint        NOT NULL DEFAULT 0,
    "CreatedDate"             timestamp with time zone NOT NULL DEFAULT now(),

    CONSTRAINT "CK_PurchaseAccessoryTakes_Qty"
        CHECK ("Quantity" > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_PurchaseAccessoryTakes_Purchase_Scheme_Accessory"
    ON public."PurchaseAccessoryTakes" ("PurchaseId", "BikeAccessorySchemeId", "AccessoryId");


ALTER TABLE public."PurchaseAccessoryReceipts"
    ADD COLUMN IF NOT EXISTS "ReceivedOn" character varying(10) NOT NULL DEFAULT 'Receiving';

ALTER TABLE public."PurchaseAccessoryReceipts"
    DROP CONSTRAINT IF EXISTS "CK_PurchaseAccessoryReceipts_ReceivedOn";

ALTER TABLE public."PurchaseAccessoryReceipts"
    ADD CONSTRAINT "CK_PurchaseAccessoryReceipts_ReceivedOn"
    CHECK ("ReceivedOn" IN ('Receiving', 'Purchase'));

CREATE INDEX IF NOT EXISTS "IX_PurchaseAccessoryReceipts_Purchase"
    ON public."PurchaseAccessoryReceipts" ("PurchaseId", "ReceivedOn");


DROP INDEX IF EXISTS public."IX_StockBatches_SchemeSource";

CREATE INDEX IF NOT EXISTS "IX_StockBatches_SchemeSource"
    ON public."StockBatches" ("SourceType", "ProductType", "SourceId", "SourceLineId")
    WHERE "SourceType" = 'AccessoryScheme';

COMMIT;


