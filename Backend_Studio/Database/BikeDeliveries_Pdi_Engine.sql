--    when "Delivery without PDI" is ON.
-- 4. Page action "Undo Delivery" on Bike Deliveries (give it to
--    admins only in Activity Assignment).
-- 5. Seed : the REVOO PDI template (from the REVOO / SwiftTech
--    sheet), linked to every REVOO model not in a template yet.
--
-- Bangla : the database is WIN1252, so Bangla text is stored
-- escaped (\u0995 ...) in the "...Bn" columns; the pages and
-- prints show it as Bangla. The file is ASCII only.
--
-- After running : Activity Assignment : PDI Templates (View, Add,
-- Update, Delete, Restore, History, Print), Bike Deliveries
-- (View, Add, Print, History) and Undo Delivery (admins); log in
-- again.
--
-- Safe to run more than once (tables, rows, switch and seed that
-- exist are left as they are). Run the whole script (F5).
-- ============================================================

