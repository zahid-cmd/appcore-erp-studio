-- 2. Submenu : Settings > Service Settings > PDI Templates
-- ------------------------------------------------------------
DO $$
DECLARE
    v_module record;
    v_menu   record;
    v_seq    int;
BEGIN
    SELECT "Id", "SequenceNo", "RouteKey" INTO v_module
    FROM   "NavigationModules"
    WHERE  lower("RouteKey") = 'settings' AND "IsDeleted" = false;

    IF v_module."Id" IS NULL THEN
        RAISE EXCEPTION 'Module with route key settings not found - nothing changed.';
    END IF;

    SELECT "Id", "SequenceNo", "RouteKey" INTO v_menu
    FROM   "NavigationMenus"
    WHERE  "NavigationModuleId" = v_module."Id"
    AND    lower("RouteKey") = 'service-settings'
    AND    "IsDeleted" = false;

    IF v_menu."Id" IS NULL THEN
        RAISE EXCEPTION 'Menu Service Settings (route key service-settings) not found - nothing changed.';
    END IF;

    IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
               WHERE "NavigationMenuId" = v_menu."Id"
               AND   lower("RouteKey") = 'pdi-templates'
               AND   "IsDeleted" = false) THEN
        RAISE NOTICE 'Submenu PDI Templates exists, skipped.';
    ELSE
        IF EXISTS (SELECT 1 FROM "NavigationSubmenus"
                   WHERE lower("Name") = 'pdi templates' AND "IsDeleted" = false) THEN
            RAISE EXCEPTION 'A submenu named "PDI Templates" already exists elsewhere : names must be unique (Code Sync).';
        END IF;

        SELECT COALESCE(MAX("SequenceNo"), 0) + 1 INTO v_seq
        FROM   "NavigationSubmenus"
        WHERE  "NavigationMenuId" = v_menu."Id";

        INSERT INTO "NavigationSubmenus"
            ("NavigationMenuId", "SequenceNo", "Code", "Name", "Icon",
             "RouteKey", "Route", "DisplayOrder", "Remarks",
             "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
        VALUES
            (v_menu."Id", v_seq,
             'SUB-' || lpad(v_module."SequenceNo"::text, 3, '0')
                    || '-' || lpad(v_menu."SequenceNo"::text, 3, '0')
                    || '-' || lpad(v_seq::text, 3, '0'),
             'PDI Templates', 'fa-solid fa-clipboard-check',
             'pdi-templates',
             '/' || v_module."RouteKey" || '/' || v_menu."RouteKey" || '/pdi-templates',
             v_seq, 'Hand-written page : never run Submenu / Code Sync.',
             true, false, 1, now());

        RAISE NOTICE 'Submenu created : PDI Templates';
    END IF;
END $$;

-- ------------------------------------------------------------
-- 3. Switch "Delivery without PDI" on Bike Deliveries
-- ------------------------------------------------------------
DO $$
DECLARE
    v_module_id bigint;
    v_page_code text;
    v_menu_code text;
    v_name      text;
BEGIN
    SELECT m."Id" INTO v_module_id
    FROM   "NavigationModules" m
    WHERE  lower(trim(m."RouteKey")) = 'sales-operations' AND NOT m."IsDeleted"
    LIMIT  1;

    SELECT s."Code", mn."Code" INTO v_page_code, v_menu_code
    FROM   "NavigationSubmenus" s
    JOIN   "NavigationMenus" mn ON mn."Id" = s."NavigationMenuId"
    WHERE  s."Route" ILIKE '/sales-operations/%/bike-deliveries'
    AND    NOT s."IsDeleted"
    LIMIT  1;

    IF v_module_id IS NULL OR v_page_code IS NULL THEN
        RAISE EXCEPTION 'Bike Deliveries page not found by route (/sales-operations/.../bike-deliveries) - nothing changed.';
    END IF;

    SELECT "ConfigurationName" INTO v_name
    FROM   "SystemConfigurations"
    WHERE  "ConfigurationCode" = 'CFG-MOD-008-0081';

    IF v_name IS NOT NULL AND v_name <> 'Delivery without PDI' THEN
        RAISE EXCEPTION 'CFG-MOD-008-0081 is already used by "%" - nothing changed. Tell Claude.', v_name;
    END IF;

    IF v_name IS NULL THEN
        INSERT INTO "SystemConfigurations"
        (
            "NavigationModuleId", "ScopeType", "NavigationMenuCode", "NavigationSubmenuCode",
            "ConfigurationCode", "ConfigurationName", "OnDescription", "OffDescription",
            "IsEnabled", "Value",
            "ValueType", "ValueUnit", "ValueMin", "ValueMax", "ValueEmptyText",
            "DefaultEnabled", "DefaultValue", "ParentConfigurationCode",
            "IsCritical", "IsSystemDefined", "DisplayOrder", "Remarks",
            "IsDeleted", "CreatedBy", "CreatedDate"
        )
        VALUES
        (
            v_module_id, 'Submenu', v_menu_code, v_page_code,
            'CFG-MOD-008-0081', 'Delivery without PDI',
            'A bike can be delivered without the PDI sheet (the sheet is optional). Delivery on Sale works only while this is ON.',
            'The PDI sheet of the bike''s model must be filled before the delivery can be saved.',
            false, '',
            'None', '', NULL, NULL, '',
            false, '', NULL,
            true, true, 1, 'Critical. PDI Templates : Settings > Service Settings > PDI Templates.',
            false, 1, now()
        );
        RAISE NOTICE 'Switch CFG-MOD-008-0081 Delivery without PDI added (OFF).';
    ELSE
        RAISE NOTICE 'Switch CFG-MOD-008-0081 exists, left as it is.';
    END IF;

    UPDATE "SystemConfigurations"
    SET    "OnDescription" = 'Posting the invoice also records the bike delivery (shown on Bike Deliveries). Works only while "Delivery without PDI" is ON; otherwise the bike stays Pending for Bike Deliveries.'
    WHERE  "ConfigurationCode" = 'CFG-MOD-008-0011'
    AND    "OnDescription" NOT LIKE '%Delivery without PDI%';
END $$;

-- ------------------------------------------------------------
-- 4. Page action "Undo Delivery" (Bike Deliveries)
-- ------------------------------------------------------------
INSERT INTO "MasterActivities"
    ("SequenceNo", "Code", "Name", "DisplayOrder", "Remarks",
     "ActivityScope", "LinkToSwitchPages",
     "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
SELECT
    m.max_seq + 1,
    'ACT-' || lpad((m.max_seq + 1)::text, 4, '0'),
    'Undo Delivery',
    m.max_order + 1,
    'Bike Deliveries : undo a saved delivery with a reason (the bike goes back to Pending, its warranty record is voided). Admins only.',
    'Page',
    false,
    true,
    false,
    1,
    now()
FROM
(
    SELECT COALESCE(MAX("SequenceNo"), 0)   AS max_seq,
           COALESCE(MAX("DisplayOrder"), 0) AS max_order
    FROM   "MasterActivities"
) AS m
WHERE NOT EXISTS
(
    SELECT 1 FROM "MasterActivities" a
    WHERE  a."IsDeleted" = false AND lower(trim(a."Name")) = 'undo delivery'
);

INSERT INTO "MasterActivityPages" ("MasterActivityCode", "NavigationSubmenuCode", "CreatedBy")
SELECT a."Code", s."Code", 1
FROM   "MasterActivities" a
JOIN   "NavigationSubmenus" s
       ON s."IsDeleted" = false
      AND s."Route" ILIKE '/sales-operations/%/bike-deliveries'
WHERE  a."IsDeleted" = false
AND    a."ActivityScope" = 'Page'
AND    lower(a."Name") = 'undo delivery'
ON CONFLICT ("MasterActivityCode", "NavigationSubmenuCode") DO NOTHING;

