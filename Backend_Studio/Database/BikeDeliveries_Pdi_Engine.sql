-- 1. Tables
--    PdiTemplates          PDI-0001 ...  one PDI sheet layout,
--                                        used by one or more models
--    PdiTemplateModels                   the models of a template
--                                        (a model : one template)
--    PdiTemplateSections                 ordered sections
--    PdiTemplateItems                    ordered items : Check /
--                                        Reading (unit) / Text
--    BikeDeliveries        BDL-...       one delivered bike (the
--                                        Code Sync baseline table
--                                        is replaced)
--    BikeDeliveryAnswers                 the PDI sheet as filled
--                                        (a copy of the template
--                                        text, so later template
--                                        edits do not change it)
--    SalesWarrantyRecords  SWR-...       the warranty of a sold
--                                        bike, from its delivery
--    SalesWarrantyRecordParts            part-level warranty
--                                        (Warranty Coverages)
-- 2. Submenu "PDI Templates" : Settings > Service Settings
--    (hand-written page : NEVER run Submenu / Code Sync for it,
--    nor for Bike Deliveries; if Code Sync was run, this script
--    drops its sample table and the hand-written files replace
--    the generated ones).
-- 3. Switch CFG-MOD-008-0081 "Delivery without PDI" on Bike
--    Deliveries (critical, default OFF = the PDI sheet is
