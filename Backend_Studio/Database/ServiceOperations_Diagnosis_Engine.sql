SELECT a."Code", a."Name", p."NavigationSubmenuCode"
FROM   "MasterActivities" a
LEFT   JOIN "MasterActivityPages" p ON p."MasterActivityCode" = a."Code"
WHERE  a."IsDeleted" = false
AND    lower(a."Name") = 'add observation';
