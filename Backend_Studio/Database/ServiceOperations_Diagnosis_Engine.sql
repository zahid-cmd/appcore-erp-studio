-- =====================================================================
-- ServiceOperations_Diagnosis_Engine.sql   (2026-11-16)
-- ---------------------------------------------------------------------
-- Service Operations : observations and diagnoses.
--
--   WorkshopObservations         OBS-0001 : a problem seen on a bike or
--                                told by the customer ("Engine noise").
--                                Kept in Workshop Configuration, tab
--                                Observations.
--   WorkshopDiagnoses            DGN-0001 : what was found ("Clutch
--                                plate worn"). It can belong to one
--                                observation. Tab Diagnoses.
--   WorkshopDiagnosisItems       the labour and the parts a diagnosis
--                                suggests
--   ServiceEstimateObservations  the observations of a service estimate,
--                                each with its diagnosis and a note
--   WorkshopConfiguration        + DiagnosisSuggests : ON = picking a
--                                diagnosis on an estimate puts its
--                                labour and parts on the estimate
--
-- Page action "Add Observation" on Service Estimates : the users who
-- have it can add a new observation or diagnosis from the estimate.
--
-- No new page : the lists are tabs of Workshop Configuration, the
-- estimate has the tab Observations. Hand-written pages : NEVER run
-- Menu / Submenu / Code Sync for them.
--
-- Run ServiceOperations_Workshop_Engine.sql, ServiceOperations_
-- Estimates_Engine.sql and ServiceOperations_Estimates_Open.sql first.
-- Safe to run more than once. Run the whole script (F5). ASCII only.
--
-- AFTER : restart the API. Security & Permission > Activity
-- Assignment : tick Add Observation on Service Estimates for the roles
-- that may add one, log in again.
-- =====================================================================


-- ------------------------------------------------------------
-- 1. The switch
-- ------------------------------------------------------------

ALTER TABLE public."WorkshopConfiguration"
    ADD COLUMN IF NOT EXISTS "DiagnosisSuggests" boolean NOT NULL DEFAULT false;


-- ------------------------------------------------------------
-- 2. Observations
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."WorkshopObservations"
(
    "WorkshopObservationId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"              uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"                  character varying(20)    NOT NULL,
    "Name"                  character varying(150)   NOT NULL,
    "Remarks"               character varying(500)   NOT NULL DEFAULT '',
    "IsActive"              boolean                  NOT NULL DEFAULT true,
    "IsDeleted"             boolean                  NOT NULL DEFAULT false,
    "DeletedBy"             bigint                   NULL,
    "DeletedDate"           timestamp with time zone NULL,
    "CreatedBy"             bigint                   NOT NULL,
    "CreatedDate"           timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"            bigint                   NULL,
    "ModifiedDate"          timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_WorkshopObservations_PublicId" ON public."WorkshopObservations" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_WorkshopObservations_Code"     ON public."WorkshopObservations" ("Code");


-- ------------------------------------------------------------
-- 3. Diagnoses and what they suggest
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."WorkshopDiagnoses"
(
    "WorkshopDiagnosisId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"              uuid                     NOT NULL DEFAULT uuidv7(),
    "Code"                  character varying(20)    NOT NULL,
    "Name"                  character varying(150)   NOT NULL,
    -- the observation it explains (null : any observation)
    "WorkshopObservationId" bigint                   NULL,
    "Remarks"               character varying(500)   NOT NULL DEFAULT '',
    "IsActive"              boolean                  NOT NULL DEFAULT true,
    "IsDeleted"             boolean                  NOT NULL DEFAULT false,
    "DeletedBy"             bigint                   NULL,
    "DeletedDate"           timestamp with time zone NULL,
    "CreatedBy"             bigint                   NOT NULL,
    "CreatedDate"           timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"            bigint                   NULL,
    "ModifiedDate"          timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_WorkshopDiagnoses_PublicId"    ON public."WorkshopDiagnoses" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_WorkshopDiagnoses_Code"        ON public."WorkshopDiagnoses" ("Code");
CREATE INDEX        IF NOT EXISTS "IX_WorkshopDiagnoses_Observation" ON public."WorkshopDiagnoses" ("WorkshopObservationId");

CREATE TABLE IF NOT EXISTS public."WorkshopDiagnosisItems"
(
    "WorkshopDiagnosisItemId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WorkshopDiagnosisId"     bigint                 NOT NULL,
    "LineNo"                  integer                NOT NULL DEFAULT 1,
    -- Service (labour) / Part
    "LineType"                character varying(10)  NOT NULL,
    -- Service : Scheduled / LaborChart / Customized / Membership
    -- Part    : SparePart / Accessory
    "ItemKind"                character varying(20)  NOT NULL,
    "ItemId"                  bigint                 NOT NULL,
    "ItemCode"                character varying(60)  NOT NULL DEFAULT '',
    "ItemName"                character varying(200) NOT NULL DEFAULT '',
    "Quantity"                numeric(18,3)          NOT NULL DEFAULT 1
);

CREATE INDEX IF NOT EXISTS "IX_WorkshopDiagnosisItems_Diagnosis" ON public."WorkshopDiagnosisItems" ("WorkshopDiagnosisId");


-- ------------------------------------------------------------
-- 4. The observations of an estimate
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."ServiceEstimateObservations"
(
    "ServiceEstimateObservationId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ServiceEstimateId"            bigint                 NOT NULL,
    "LineNo"                       integer                NOT NULL DEFAULT 1,
    "WorkshopObservationId"        bigint                 NULL,
    -- the names as they were when the estimate was saved
    "Observation"                  character varying(150) NOT NULL DEFAULT '',
    "WorkshopDiagnosisId"          bigint                 NULL,
    "Diagnosis"                    character varying(150) NOT NULL DEFAULT '',
    "Note"                         character varying(300) NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS "IX_ServiceEstimateObservations_Estimate" ON public."ServiceEstimateObservations" ("ServiceEstimateId");


-- ------------------------------------------------------------
-- 5. Page action Add Observation on Service Estimates
-- ------------------------------------------------------------

INSERT INTO "MasterActivities"
    ("SequenceNo", "Code", "Name", "DisplayOrder", "Remarks",
     "ActivityScope", "LinkToSwitchPages",
     "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
SELECT
    m.max_seq + 1,
    'ACT-' || lpad((m.max_seq + 1)::text, 4, '0'),
    'Add Observation',
    m.max_order + 1,
    'Service Estimates : add a new observation or diagnosis to the lists.',
    'Page',
    false,
    true,
    false,
    1,
    now()
FROM
(
    SELECT COALESCE(MAX("SequenceNo"), 0)   AS max_seq,
           COALESCE(MAX("DisplayOrder"), 0) AS max_order
    FROM   "MasterActivities"
) AS m
WHERE NOT EXISTS
(
    SELECT 1
    FROM   "MasterActivities" a
    WHERE  a."IsDeleted" = false
    AND    lower(trim(a."Name")) = 'add observation'
);

INSERT INTO "MasterActivityPages" ("MasterActivityCode", "NavigationSubmenuCode", "CreatedBy")
SELECT a."Code", s."Code", 1
FROM   "MasterActivities" a
JOIN   "NavigationSubmenus" s
       ON s."IsDeleted" = false
      AND s."Route" ILIKE '/service-operations/%/service-estimates'
WHERE  a."IsDeleted" = false
AND    a."ActivityScope" = 'Page'
AND    lower(a."Name") = 'add observation'
ON CONFLICT ("MasterActivityCode", "NavigationSubmenuCode") DO NOTHING;


-- ------------------------------------------------------------
-- Check (run on its own)
