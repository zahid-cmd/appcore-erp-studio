-- Settings > Account Settings > Check Books : cheque printing
--
--   CheckPrintLayouts   one row per bank account : where each field
--                       sits on the real cheque leaf (mm), kept as a
--                       JSON text the page owns : leaf size, printer
--                       offset, date boxes, payee, amount in words /
--                       figures, A/C Payee crossing, counterfoil.
--
-- No submenu, no switch : the layout is edited on the Check Books
-- page (Cheque Layout button, needs Update), and the A/C Payee and
-- Counterfoil choices are made on the print page itself.
--
-- Safe to run again. Run the whole script (F5) on AppCoreERP_Studio
-- after CheckBooks_Engine.sql. ASCII only.
-- =====================================================================

CREATE TABLE IF NOT EXISTS public."CheckPrintLayouts"
(
    "CheckPrintLayoutId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BankAccountId"      bigint                   NOT NULL,
    "LayoutJson"         text                     NOT NULL DEFAULT '{}',
    "CreatedBy"          bigint                   NOT NULL,
    "CreatedDate"        timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"         bigint                   NULL,
    "ModifiedDate"       timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_CheckPrintLayouts_BankAccount"
    ON public."CheckPrintLayouts" ("BankAccountId");

SELECT 'CheckPrintLayouts ready' AS "Result",
       (SELECT count(*) FROM public."CheckPrintLayouts") AS "Layouts";
