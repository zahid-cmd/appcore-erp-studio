-- Step 1 removes the EMPTY Code Sync baseline table
-- "SalesEnquiries" (it has the sample columns). It does nothing
-- once the real table exists, so the script is safe to run again.
--
-- Run it in a NEW pgAdmin Query Tool with F5.
