-- ------------------------------------------------------------
-- 1. Drop the Code Sync baseline table (only the baseline one)
-- ------------------------------------------------------------

DO $$
BEGIN
    IF EXISTS
    (
        SELECT 1
        FROM   information_schema.columns
        WHERE  table_schema = 'public'
        AND    table_name   = 'SalesEnquiries'
        AND    column_name IN ('SampleField', 'samplefield', 'sample_field')
    )
    THEN
        EXECUTE 'DROP TABLE public."SalesEnquiries"';
        RAISE NOTICE 'Baseline table SalesEnquiries dropped.';
    END IF;
END
$$;


-- ------------------------------------------------------------
-- 2. Enquirer list
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."EnquiryContacts"
(
    "EnquiryContactId"  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Mobile"            character varying(11)  NOT NULL,
    "ContactName"       character varying(150) NOT NULL,
    "AltPhone"          character varying(11)  NOT NULL DEFAULT '',
    "LocationId"        bigint                 NULL,
    "Address"           character varying(300) NOT NULL DEFAULT '',

    "IsDeleted"         boolean                NOT NULL DEFAULT false,
    "CreatedBy"         bigint                 NOT NULL,
    "CreatedDate"       timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"        bigint                 NULL,
    "ModifiedDate"      timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_EnquiryContacts_Mobile"
    ON public."EnquiryContacts" ("Mobile")
    WHERE "IsDeleted" = false;


-- ------------------------------------------------------------
-- 3. Sales enquiries
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."SalesEnquiries"
(
    "SalesEnquiryId"        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    "EnquiryNo"             character varying(30)  NOT NULL,
    "EnquiryYear"           integer                NOT NULL,
    "EnquiryMonth"          integer                NOT NULL,
    "SequenceNo"            integer                NOT NULL,

    "EnquiryDate"           date                   NOT NULL,
    "BranchId"              bigint                 NOT NULL,
    "BranchName"            character varying(150) NOT NULL DEFAULT '',
    "SourceId"              bigint                 NOT NULL,
    "StatusId"              bigint                 NOT NULL,
    "InterestLevelId"       bigint                 NULL,
    "ExecutiveUserId"       bigint                 NOT NULL,
    "ExecutiveName"         character varying(150) NOT NULL DEFAULT '',

    "EnquiryContactId"      bigint                 NOT NULL,
    "EnquirerMobile"        character varying(11)  NOT NULL,
    "EnquirerName"          character varying(150) NOT NULL,
    "EnquiryFor"            character varying(10)  NOT NULL DEFAULT 'Self',

    "ModelId"               bigint                 NOT NULL,
    "ModelName"             character varying(200) NOT NULL DEFAULT '',
    "BrandName"             character varying(150) NOT NULL DEFAULT '',
    "SecondModelId"         bigint                 NULL,
    "SecondModelName"       character varying(200) NOT NULL DEFAULT '',
    "Quantity"              integer                NOT NULL DEFAULT 1,
    "Budget"                numeric(18,2)          NOT NULL DEFAULT 0,
    "PaymentMode"           character varying(10)  NOT NULL DEFAULT 'Cash',
    "ExchangeBike"          character varying(200) NOT NULL DEFAULT '',
    "ExpectedPurchaseDate"  date                   NULL,

    "NextFollowUpDate"      date                   NULL,
    "FollowUpMethodId"      bigint                 NULL,
    "LastFollowUpDate"      date                   NULL,
    "LastFollowUpNote"      character varying(500) NOT NULL DEFAULT '',
    "LostReasonId"          bigint                 NULL,
    "ClosedDate"            date                   NULL,
    "Remarks"               character varying(500) NOT NULL DEFAULT '',

    "IsMatured"             boolean                NOT NULL DEFAULT false,
    "MaturedDate"           date                   NULL,
    "SaleId"                bigint                 NULL,
    "SaleNo"                character varying(40)  NOT NULL DEFAULT '',
    "CustomerId"            bigint                 NULL,
    "CustomerName"          character varying(200) NOT NULL DEFAULT '',

    "IsDeleted"             boolean                NOT NULL DEFAULT false,
    "DeletedBy"             bigint                 NULL,
    "DeletedDate"           timestamp with time zone NULL,
    "CreatedBy"             bigint                 NOT NULL,
    "CreatedDate"           timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"            bigint                 NULL,
    "ModifiedDate"          timestamp with time zone NULL,

    CONSTRAINT "CK_SalesEnquiries_EnquiryFor"  CHECK ("EnquiryFor" IN ('Self', 'Referrer')),
    CONSTRAINT "CK_SalesEnquiries_PaymentMode" CHECK ("PaymentMode" IN ('Cash', 'EMI', 'Exchange')),
    CONSTRAINT "CK_SalesEnquiries_Quantity"    CHECK ("Quantity" BETWEEN 1 AND 99),
    CONSTRAINT "CK_SalesEnquiries_Month"       CHECK ("EnquiryMonth" BETWEEN 1 AND 12)
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_SalesEnquiries_EnquiryNo"
    ON public."SalesEnquiries" ("EnquiryNo");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_SalesEnquiries_Month_Sequence"
    ON public."SalesEnquiries" ("EnquiryYear", "EnquiryMonth", "SequenceNo");

CREATE INDEX IF NOT EXISTS "IX_SalesEnquiries_EnquirerMobile"
    ON public."SalesEnquiries" ("EnquirerMobile");

CREATE INDEX IF NOT EXISTS "IX_SalesEnquiries_NextFollowUpDate"
    ON public."SalesEnquiries" ("NextFollowUpDate")
    WHERE "IsDeleted" = false;


