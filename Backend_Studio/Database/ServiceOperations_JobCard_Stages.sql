-- =====================================================================
-- ServiceOperations_JobCard_Stages.sql   (2026-11-17)
-- ---------------------------------------------------------------------
-- The job card becomes a chain of stages, strictly in order, each stage
-- a desk with its own permission (owner, 2026-11-17) :
--
--   1 Opening      2 Assignment     3 Work (parts, extra items)
--   4 Closing      5 Billing        6 Delivery
--
-- STEP 1 of the build (this script) : the stage engine.
--
--   JobCards              + ServiceEngineerEmployeeId, WorkshopBayId,
--                           AssignedAt, AssignedBy
--   JobCardTechnicians    the technicians a card is assigned to (the
--                           first : the lead)
--   Status "Assigned"     Open -> Assigned (Job Card Assignment) ->
--                           In Progress -> ... as before. Work, parts
--                           requisitions / issues and outsourcing need
--                           an assigned card; only a technician of the
--                           assignment can start work on it.
--
-- Page actions on Job Cards (a desk is blocked from the other stages) :
--   Add / Update          the opening desk : a new card, and changing it
--                           while it is Open
--   Assign Job Card       the service engineer, the bay, the technicians
--   Job Card Work         the lines, the work and the statuses of an
--                           assigned card
-- (Closing, Billing and Delivery come with the next steps; until then
-- the service invoice does them.)
--
-- Run ServiceOperations_Workshop_Engine.sql first.
-- Safe to run more than once. Run the whole script (F5). ASCII only.
--
-- AFTER : restart the API. Security & Permission > Activity Assignment :
-- tick Assign Job Card and Job Card Work on Job Cards for the roles
-- that may, log in again.
-- =====================================================================


-- ------------------------------------------------------------
-- 1. The assignment of a job card
-- ------------------------------------------------------------

ALTER TABLE public."JobCards"
    ADD COLUMN IF NOT EXISTS "ServiceEngineerEmployeeId" bigint                   NULL,
    ADD COLUMN IF NOT EXISTS "WorkshopBayId"             bigint                   NULL,
    ADD COLUMN IF NOT EXISTS "AssignedAt"                timestamp with time zone NULL,
    ADD COLUMN IF NOT EXISTS "AssignedBy"                bigint                   NULL;

CREATE TABLE IF NOT EXISTS public."JobCardTechnicians"
(
    "JobCardTechnicianId"  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "JobCardId"            bigint NOT NULL
        REFERENCES public."JobCards" ("JobCardId") ON DELETE CASCADE,
    -- 1 : the lead
    "LineNo"               integer NOT NULL DEFAULT 0,
    "WorkshopTechnicianId" bigint  NOT NULL
);

CREATE INDEX IF NOT EXISTS "IX_JobCardTechnicians_JobCard"    ON public."JobCardTechnicians" ("JobCardId");
CREATE INDEX IF NOT EXISTS "IX_JobCardTechnicians_Technician" ON public."JobCardTechnicians" ("WorkshopTechnicianId");


-- ------------------------------------------------------------
-- 2. Page actions of the stages, on Job Cards
-- ------------------------------------------------------------

INSERT INTO "MasterActivities"
    ("SequenceNo", "Code", "Name", "DisplayOrder", "Remarks",
     "ActivityScope", "LinkToSwitchPages",
     "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
SELECT
    m.max_seq + 1,
    'ACT-' || lpad((m.max_seq + 1)::text, 4, '0'),
    'Assign Job Card',
    m.max_order + 1,
    'Job Cards : give a job card its service engineer, bay and technicians (stage 2).',
    'Page',
    false,
    true,
    false,
    1,
    now()
FROM
(
    SELECT COALESCE(MAX("SequenceNo"), 0)   AS max_seq,
           COALESCE(MAX("DisplayOrder"), 0) AS max_order
    FROM   "MasterActivities"
) AS m
WHERE NOT EXISTS
(
    SELECT 1
    FROM   "MasterActivities" a
    WHERE  a."IsDeleted" = false
    AND    lower(trim(a."Name")) = 'assign job card'
);

INSERT INTO "MasterActivityPages" ("MasterActivityCode", "NavigationSubmenuCode", "CreatedBy")
SELECT a."Code", s."Code", 1
FROM   "MasterActivities" a
JOIN   "NavigationSubmenus" s
       ON s."IsDeleted" = false
      AND s."Route" ILIKE '/service-operations/%/job-cards'
WHERE  a."IsDeleted" = false
AND    a."ActivityScope" = 'Page'
AND    lower(a."Name") = 'assign job card'
ON CONFLICT ("MasterActivityCode", "NavigationSubmenuCode") DO NOTHING;

INSERT INTO "MasterActivities"
    ("SequenceNo", "Code", "Name", "DisplayOrder", "Remarks",
     "ActivityScope", "LinkToSwitchPages",
     "IsActive", "IsDeleted", "CreatedBy", "CreatedDate")
SELECT
    m.max_seq + 1,
    'ACT-' || lpad((m.max_seq + 1)::text, 4, '0'),
    'Job Card Work',
    m.max_order + 1,
    'Job Cards : the lines, the work and the statuses of an assigned job card (stage 3).',
    'Page',
    false,
    true,
    false,
    1,
    now()
FROM
(
    SELECT COALESCE(MAX("SequenceNo"), 0)   AS max_seq,
           COALESCE(MAX("DisplayOrder"), 0) AS max_order
    FROM   "MasterActivities"
) AS m
WHERE NOT EXISTS
(
    SELECT 1
    FROM   "MasterActivities" a
    WHERE  a."IsDeleted" = false
    AND    lower(trim(a."Name")) = 'job card work'
);

INSERT INTO "MasterActivityPages" ("MasterActivityCode", "NavigationSubmenuCode", "CreatedBy")
SELECT a."Code", s."Code", 1
FROM   "MasterActivities" a
JOIN   "NavigationSubmenus" s
       ON s."IsDeleted" = false
      AND s."Route" ILIKE '/service-operations/%/job-cards'
WHERE  a."IsDeleted" = false
AND    a."ActivityScope" = 'Page'
AND    lower(a."Name") = 'job card work'
ON CONFLICT ("MasterActivityCode", "NavigationSubmenuCode") DO NOTHING;


-- ------------------------------------------------------------
-- Check (run on its own) : the two page actions and their page
-- ------------------------------------------------------------
SELECT a."Code", a."Name", p."NavigationSubmenuCode"
FROM   "MasterActivities" a
LEFT   JOIN "MasterActivityPages" p ON p."MasterActivityCode" = a."Code"
WHERE  a."IsDeleted" = false
AND    lower(a."Name") IN ('assign job card', 'job card work')
ORDER  BY a."Code";
