-- ============================================================
-- Sold bikes (our outlet) : service schedules (2026-11-03)
--
-- Enquiry Management › Service Enquiries › Sold Bikes tab
--   ServiceVehicles          one row per chassis sold from the
--                            outlet (sales invoice, or by hand)
--   ServiceVehicleSchedules  its services, from the brand's
--                            Service Policy
--   ServiceEnquiries."ServiceVehicleScheduleId"  enquiry raised
--                            by a schedule row
--   Source of Enquiry "Scheduled" made when it is missing
--
-- Plain statements only : run in a NEW pgAdmin Query Tool with
-- F5. Safe to run again.
-- ============================================================

CREATE TABLE IF NOT EXISTS public."ServiceVehicles"
(
    "ServiceVehicleId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ChassisNo"          character varying(50)  NOT NULL,
    "EngineNo"           character varying(50)  NOT NULL DEFAULT '',
    "RegistrationNo"     character varying(30)  NOT NULL DEFAULT '',
    "ModelId"            bigint                 NOT NULL,
    "ModelName"          character varying(150) NOT NULL DEFAULT '',
    "BrandManagementId"  bigint                 NOT NULL DEFAULT 0,
    "BrandName"          character varying(150) NOT NULL DEFAULT '',
    "ColorName"          character varying(50)  NOT NULL DEFAULT '',
    "ServicePolicyId"    bigint                 NULL,
    "PolicyCode"         character varying(20)  NOT NULL DEFAULT '',
    "WarrantyYears"      integer                NOT NULL DEFAULT 0,
    "WarrantyKm"         integer                NOT NULL DEFAULT 0,
    "WarrantyUntil"      date                   NULL,
    "SaleDate"           date                   NOT NULL,
    "SaleSource"         character varying(10)  NOT NULL DEFAULT 'Manual',
    "SaleDocType"        character varying(30)  NOT NULL DEFAULT '',
    "SaleDocId"          bigint                 NULL,
    "SaleDocNo"          character varying(40)  NOT NULL DEFAULT '',
    "CustomerId"         bigint                 NULL,
    "CustomerName"       character varying(150) NOT NULL DEFAULT '',
    "Mobile"             character varying(20)  NOT NULL DEFAULT '',
    "BranchId"           bigint                 NOT NULL,
    "BranchName"         character varying(150) NOT NULL DEFAULT '',
    "LastKm"             integer                NULL,
    "Remarks"            character varying(500) NOT NULL DEFAULT '',
    "IsActive"           boolean                NOT NULL DEFAULT true,
    "IsDeleted"          boolean                NOT NULL DEFAULT false,
    "DeletedBy"          bigint                 NULL,
    "DeletedDate"        timestamp with time zone NULL,
    "CreatedBy"          bigint                 NOT NULL,
    "CreatedDate"        timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"         bigint                 NULL,
    "ModifiedDate"       timestamp with time zone NULL,

    CONSTRAINT "CK_ServiceVehicles_SaleSource" CHECK ("SaleSource" IN ('Sale', 'Manual'))
);

CREATE INDEX IF NOT EXISTS "IX_ServiceVehicles_Chassis" ON public."ServiceVehicles" ("ChassisNo");

CREATE UNIQUE INDEX IF NOT EXISTS "UX_ServiceVehicles_Chassis_Live" ON public."ServiceVehicles" ("ChassisNo") WHERE "IsDeleted" = false;

CREATE INDEX IF NOT EXISTS "IX_ServiceVehicles_Mobile" ON public."ServiceVehicles" ("Mobile");

CREATE TABLE IF NOT EXISTS public."ServiceVehicleSchedules"
(
    "ServiceVehicleScheduleId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ServiceVehicleId"   bigint                 NOT NULL,
    "SequenceNo"         integer                NOT NULL,
    "ServiceType"        character varying(10)  NOT NULL DEFAULT 'Free',
    "ServiceName"        character varying(150) NOT NULL DEFAULT '',
    "ScheduledServiceId" bigint                 NULL,
    "IntervalDays"       integer                NOT NULL DEFAULT 0,
    "IntervalKm"         integer                NOT NULL DEFAULT 0,
    "GraceDays"          integer                NOT NULL DEFAULT 0,
    "DueDate"            date                   NOT NULL,
    "DueKm"              integer                NOT NULL DEFAULT 0,
    "LastDate"           date                   NOT NULL,
    "DueDateEdited"      boolean                NOT NULL DEFAULT false,
    "Status"             character varying(12)  NOT NULL DEFAULT 'Upcoming',
    "ServiceEnquiryId"   bigint                 NULL,
    "EnquiryNo"          character varying(30)  NOT NULL DEFAULT '',
    "TakenDate"          date                   NULL,
    "TakenKm"            integer                NULL,
    "TakenDocType"       character varying(30)  NOT NULL DEFAULT '',
    "TakenDocNo"         character varying(40)  NOT NULL DEFAULT '',
    "Note"               character varying(200) NOT NULL DEFAULT '',
    "CreatedBy"          bigint                 NOT NULL,
    "CreatedDate"        timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"         bigint                 NULL,
    "ModifiedDate"       timestamp with time zone NULL,

    CONSTRAINT "CK_ServiceVehicleSchedules_Type"   CHECK ("ServiceType" IN ('Free', 'Paid')),
    CONSTRAINT "CK_ServiceVehicleSchedules_Status" CHECK ("Status" IN ('Upcoming', 'Enquired', 'Taken', 'Skipped'))
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_ServiceVehicleSchedules_Vehicle_Sequence" ON public."ServiceVehicleSchedules" ("ServiceVehicleId", "SequenceNo");

CREATE INDEX IF NOT EXISTS "IX_ServiceVehicleSchedules_Status_Due" ON public."ServiceVehicleSchedules" ("Status", "DueDate");

ALTER TABLE public."ServiceEnquiries"
    ADD COLUMN IF NOT EXISTS "ServiceVehicleScheduleId" bigint NULL;

INSERT INTO public."EnquirySetups"
    ("SetupType", "Code", "Name", "ColorCode", "Stage", "DisplayOrder",
     "IsDefault", "IsSystem", "Remarks", "IsActive", "IsDeleted",
     "CreatedBy", "CreatedDate")
SELECT
    'Source',
    'SRC-' || lpad(s.n::text, 3, '0'),
    'Scheduled',
    '', '', s.n,
    false, false, 'Raised by the service schedule of a bike sold from the outlet', true, false,
    1, now()
FROM
(
    SELECT COALESCE(MAX(substring("Code" FROM 5)::int), 0) + 1 AS n
    FROM   public."EnquirySetups"
    WHERE  "SetupType" = 'Source'
      AND  "Code" ~ '^SRC-[0-9]+$'
) AS s
WHERE NOT EXISTS
(
    SELECT 1
    FROM   public."EnquirySetups" e
    WHERE  e."SetupType" = 'Source'
      AND  e."IsDeleted" = false
      AND  lower(e."Name") = 'scheduled'
);

UPDATE public."EnquirySetups"
SET    "IsActive" = true
WHERE  "SetupType" = 'Source'
  AND  "IsDeleted" = false
  AND  lower("Name") = 'scheduled';
