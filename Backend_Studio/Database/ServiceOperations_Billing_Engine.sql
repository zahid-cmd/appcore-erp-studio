-- Service Operations, steps 4 and 5 (claude\blueprint-service-
-- operations.md) : service billing.
--
--   ServiceInvoices          SVI-<branch>-<FY>-<MM>-00001 : one invoice per job card,
--                            posted at once. Labour of the job card,
--                            the parts ISSUED to it (less returns),
--                            outside work. VAT from VAT Setup. The
--                            collection is a posted Receipt Voucher.
--   ServiceInvoiceLines      Service / Part / Outside, with the ledger
--                            each line was credited to, the FIFO cost
--                            of a part and the brand reimbursement of
--                            a free service
--   ServiceInvoicePayments   how it was collected (Cash / Bank / MFS)
--   ServiceReturns           SVR-000001 : the whole invoice reversed
--                            (journal, VAT register, optionally the
--                            receipt and the parts back to the store)
--   FreeServiceClaims        FSC-000001 : the reimbursements of free
--                            services of one brand, collected into a
--                            claim; settled by a ledger (bank, or the
--                            brand's supplier account)
--   WorkshopConfiguration    + AllowCreditInvoice : ON = a service
--                            invoice may leave a due (only for users
--                            with the page action Credit Sale)
--
-- Posting Setup (group Service Operations) gets the purposes
-- SERVICE-DISCOUNT, SERVICE-OTHER-INCOME and OUTSIDE-WORK-PAYABLE.
--
-- The pages are there already (ServiceOperations_Navigation.sql) :
-- Service Billing > Service Invoices / Service Returns / Free Service
-- Claims. Hand-written pages : NEVER run Menu / Submenu / Code Sync
-- for them.
--
-- Run ServiceOperations_Workshop_Engine.sql, ServiceOperations_
-- Estimates_Engine.sql and ServiceOperations_Parts_Engine.sql first.
-- Safe to run more than once. Run the whole script (F5). ASCII only.
--
-- AFTER : Security & Permission > Activity Assignment : tick the three
-- pages for the roles (and Credit Sale on Service Invoices for the
-- manager / owner), log in again. Posting Setup, group "Service
-- Operations" : select the ledgers that are used.
-- =====================================================================


