-- ------------------------------------------------------------
-- 2. Free Service Claims (before the invoice lines that point to it)
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."FreeServiceClaims"
(
    "FreeServiceClaimId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"           uuid                     NOT NULL DEFAULT uuidv7(),
    "ClaimNo"            character varying(30)    NOT NULL,
    "ClaimDate"          date                     NOT NULL,
    "BrandManagementId"  bigint                   NOT NULL,
    "BrandName"          character varying(100)   NOT NULL DEFAULT '',
    "TotalAmount"        numeric(18,2)            NOT NULL DEFAULT 0,
    -- Open / Settled / Cancelled
    "Status"             character varying(15)    NOT NULL DEFAULT 'Open',
    "SettledDate"        date                     NULL,
    -- the ledger the brand settled into (bank, or its supplier account)
    "SettledLedgerCode"  character varying(40)    NOT NULL DEFAULT '',
    "SettledLedgerName"  character varying(250)   NOT NULL DEFAULT '',
    -- the voucher of the settlement (FSC-...)
    "SettlementNo"       character varying(30)    NOT NULL DEFAULT '',
    "SettlementRef"      character varying(100)   NOT NULL DEFAULT '',
    "Remarks"            character varying(500)   NOT NULL DEFAULT '',
    "CreatedBy"          bigint                   NOT NULL,
    "CreatedDate"        timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"         bigint                   NULL,
    "ModifiedDate"       timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_FreeServiceClaims_PublicId" ON public."FreeServiceClaims" ("PublicId");
-- the number is <PREFIX>-<branch>-<FY>-<MM>-00001 (2026-11-16) :
-- a table made before that gets the room for it
ALTER TABLE public."FreeServiceClaims" ALTER COLUMN "ClaimNo" TYPE character varying(30);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_FreeServiceClaims_No"       ON public."FreeServiceClaims" ("ClaimNo");


-- ------------------------------------------------------------
-- 3. Service Invoices
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public."ServiceInvoices"
(
    "ServiceInvoiceId"     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicId"             uuid                     NOT NULL DEFAULT uuidv7(),
    -- the voucher number of its journal
    "InvoiceNo"            character varying(30)    NOT NULL,
    "InvoiceDate"          date                     NOT NULL,
    "BranchId"             bigint                   NOT NULL,
    "JobCardId"            bigint                   NOT NULL
        REFERENCES public."JobCards" ("JobCardId"),
    "JobType"              character varying(30)    NOT NULL DEFAULT '',
    "CustomerId"           bigint                   NULL,
    "CustomerCode"         character varying(30)    NOT NULL DEFAULT '',
    "CustomerName"         character varying(200)   NOT NULL DEFAULT '',
    "Mobile"               character varying(30)    NOT NULL DEFAULT '',
    "ReceivableLedgerCode" character varying(40)    NOT NULL DEFAULT '',
    "BrandName"            character varying(100)   NOT NULL DEFAULT '',
    "LabourTotal"          numeric(18,2)            NOT NULL DEFAULT 0,
    "PartsTotal"           numeric(18,2)            NOT NULL DEFAULT 0,
    "OutsideTotal"         numeric(18,2)            NOT NULL DEFAULT 0,
    -- the VAT inside or on top of the three totals
    "VatTotal"             numeric(18,2)            NOT NULL DEFAULT 0,
    "Discount"             numeric(18,2)            NOT NULL DEFAULT 0,
    -- what the customer owes for the job
    "GrandTotal"           numeric(18,2)            NOT NULL DEFAULT 0,
    "PaidAmount"           numeric(18,2)            NOT NULL DEFAULT 0,
    -- FIFO cost of the parts billed (Workshop WIP -> cost of goods sold)
    "PartsCost"            numeric(18,2)            NOT NULL DEFAULT 0,
    "ReceiptVoucherId"     bigint                   NULL,
    "ReceiptVoucherNo"     character varying(30)    NOT NULL DEFAULT '',
    -- Posted / Returned
    "Status"               character varying(15)    NOT NULL DEFAULT 'Posted',
    "IsDelivered"          boolean                  NOT NULL DEFAULT false,
    "DeliveredAt"          timestamp with time zone NULL,
    "DeliveredBy"          bigint                   NULL,
    "ReturnNo"             character varying(30)    NOT NULL DEFAULT '',
    "Remarks"              character varying(500)   NOT NULL DEFAULT '',
    "CreatedBy"            bigint                   NOT NULL,
    "CreatedDate"          timestamp with time zone NOT NULL DEFAULT now(),
    "ModifiedBy"           bigint                   NULL,
    "ModifiedDate"         timestamp with time zone NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_ServiceInvoices_PublicId" ON public."ServiceInvoices" ("PublicId");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_ServiceInvoices_No"       ON public."ServiceInvoices" ("InvoiceNo");
CREATE INDEX        IF NOT EXISTS "IX_ServiceInvoices_JobCard"  ON public."ServiceInvoices" ("JobCardId");
CREATE INDEX        IF NOT EXISTS "IX_ServiceInvoices_Date"     ON public."ServiceInvoices" ("BranchId", "InvoiceDate");

CREATE TABLE IF NOT EXISTS public."ServiceInvoiceLines"
(
    "ServiceInvoiceLineId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ServiceInvoiceId"     bigint NOT NULL
        REFERENCES public."ServiceInvoices" ("ServiceInvoiceId") ON DELETE CASCADE,
    "LineNo"               integer                NOT NULL DEFAULT 0,
    -- Service / Part / Outside
    "LineType"             character varying(10)  NOT NULL,
    -- Service : Scheduled / LaborChart / Customized / Membership / Other
    -- Part    : SparePart / Accessory / Other
    "ItemKind"             character varying(15)  NOT NULL DEFAULT 'Other',
    "ItemId"               bigint                 NULL,
    "ItemCode"             character varying(40)  NOT NULL DEFAULT '',
    "ItemName"             character varying(200) NOT NULL,
    "Quantity"             numeric(10,2)          NOT NULL DEFAULT 1,
    "Rate"                 numeric(18,2)          NOT NULL DEFAULT 0,
    -- quantity x rate (a free service : 0)
    "Amount"               numeric(18,2)          NOT NULL DEFAULT 0,
    "IsFree"               boolean                NOT NULL DEFAULT false,
    -- a free scheduled service : what the brand pays back, the ledger
    -- it is claimed on, the claim it is on
    "ClaimAmount"          numeric(18,2)          NOT NULL DEFAULT 0,
    "ClaimLedgerCode"      character varying(40)  NOT NULL DEFAULT '',
    "BrandManagementId"    bigint                 NULL,
    "FreeServiceClaimId"   bigint                 NULL
        REFERENCES public."FreeServiceClaims" ("FreeServiceClaimId"),
    "VatRate"              numeric(9,4)           NOT NULL DEFAULT 0,
    "VatAmount"            numeric(18,2)          NOT NULL DEFAULT 0,
    -- what the customer pays for the line (VAT in it)
    "Total"                numeric(18,2)          NOT NULL DEFAULT 0,
    -- a part : its FIFO cost. Outside work : what the vendor charges
    "Cost"                 numeric(18,2)          NOT NULL DEFAULT 0,
    "IncomeLedgerCode"     character varying(40)  NOT NULL DEFAULT '',
    -- outside work : the vendor
    "Note"                 character varying(200) NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS "IX_ServiceInvoiceLines_Invoice" ON public."ServiceInvoiceLines" ("ServiceInvoiceId");
CREATE INDEX IF NOT EXISTS "IX_ServiceInvoiceLines_Claim"   ON public."ServiceInvoiceLines" ("FreeServiceClaimId");

CREATE TABLE IF NOT EXISTS public."ServiceInvoicePayments"
(
    "ServiceInvoicePaymentId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ServiceInvoiceId"        bigint NOT NULL
        REFERENCES public."ServiceInvoices" ("ServiceInvoiceId") ON DELETE CASCADE,
    "LineNo"                  integer                NOT NULL DEFAULT 0,
    -- Cash / Bank / MFS
    "Mode"                    character varying(10)  NOT NULL,
    "LedgerCode"              character varying(40)  NOT NULL,
    "LedgerName"              character varying(250) NOT NULL DEFAULT '',
    "Amount"                  numeric(18,2)          NOT NULL DEFAULT 0,
    "TransactionRef"          character varying(100) NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS "IX_ServiceInvoicePayments_Invoice" ON public."ServiceInvoicePayments" ("ServiceInvoiceId");


