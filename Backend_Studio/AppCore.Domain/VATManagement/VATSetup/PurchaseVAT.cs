namespace AppCore.Domain.Entities.VatManagement.VatSetup;


//===============================================================
// Purchase VAT
//
// One VAT rate rule for a VAT Type, valid from Effective From to
// Valid To (default : the end of the financial year, 30 June).
// Same rate next period = Extend (move Valid To); a new rate = a
// new rule. Active rules of a type never overlap. After Valid To
// with no next rule, purchase / sale entries are blocked.
//
//   VAT Type        : Motor Bikes / Spare Parts / Lubricants / Accessories
//   VAT Rate        : % (0 – 100, 2 decimals)
//   Input Credit Allowed : Yes = this VAT is set off against sales VAT
//   Ledger          : the VAT Current Account (General Ledger,
//                     stored by code)
//===============================================================

public class PurchaseVat
{
    //===========================================================
    // Primary Key
    //===========================================================

    public long PurchaseVatId { get; set; }


    //===========================================================
    // Rule
    //===========================================================

    // PVT-0001 (generated by the server, never reused)
    public string VatCode { get; set; } = string.Empty;

    // Motor Bikes / Spare Parts / Lubricants / Accessories (locked after saving)
    public string VatType { get; set; } = string.Empty;

    public decimal VatRate { get; set; }

    public bool InputCreditAllowed { get; set; }

    public DateOnly EffectiveFrom { get; set; }

    public DateOnly ValidTo { get; set; }


    //===========================================================
    // Ledger (VAT Current Account, by code)
    //===========================================================

    public string LedgerCode { get; set; } = string.Empty;


    //===========================================================
    // Status & Description
    //===========================================================

    public string Remarks { get; set; } = string.Empty;

    public bool Status { get; set; }


    //===========================================================
    // Soft Delete
    //===========================================================

    public bool IsDeleted { get; set; }

    public long? DeletedBy { get; set; }

    public DateTime? DeletedDate { get; set; }


    //===========================================================
    // Audit
    //===========================================================

    public long CreatedBy { get; set; }

    public DateTime CreatedDate { get; set; }

    public long? ModifiedBy { get; set; }

    public DateTime? ModifiedDate { get; set; }
}