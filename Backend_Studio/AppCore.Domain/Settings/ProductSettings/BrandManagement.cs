namespace AppCore.Domain.Entities.Settings.ProductSettings;


//===============================================================
// Brand Management
//===============================================================

public class BrandManagement
{
    //===========================================================
    // Primary Key
    //===========================================================

    public long BrandManagementId { get; set; }


    //===========================================================
    // Brand Code (BRAND-001, generated by the server)
    //===========================================================

    public string BrandCode { get; set; } = string.Empty;


    //===========================================================
    // Brand Name
    //===========================================================

    public string BrandName { get; set; } = string.Empty;


    //===========================================================
    // Brand Image (relative path, e.g. /uploads/brand-images/x.png;
    // empty when there is no image)
    //===========================================================

    public string BrandImagePath { get; set; } = string.Empty;


    //===========================================================
    // Remarks (optional)
    //===========================================================

    public string Remarks { get; set; } = string.Empty;


    //===========================================================
    // Status
    //===========================================================

    public bool Status { get; set; }


    //===========================================================
    // Soft Delete
    //===========================================================

    public bool IsDeleted { get; set; } = false;

    public long? DeletedBy { get; set; }

    public DateTime? DeletedDate { get; set; }


    //===========================================================
    // Audit Information
    //===========================================================

    public long CreatedBy { get; set; }

    public DateTime CreatedDate { get; set; }

    public long? ModifiedBy { get; set; }

    public DateTime? ModifiedDate { get; set; }
}