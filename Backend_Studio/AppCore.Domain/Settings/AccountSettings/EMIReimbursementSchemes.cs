namespace AppCore.Domain.Entities.Settings.AccountSettings;


//===============================================================
// EMI Reimbursement Schemes
//
// Per brand : how much of the showroom's share of the EMI-sale
// charges the brand's Motor Bikes Supplier pays back.
//
//   Swap charge  : Basis (Percent / Fixed) + Value [+ Swap Cap]
//   EMI charge   : Basis (Percent / Fixed) + Value [+ EMI Cap]
//   Total Cap    : swap + EMI claim together, per sale
//
// Percent = % of the showroom's share of that charge (never of
// the customer's share); Fixed = Tk per sale. Caps are optional
// (null = no limit). Claim per sale =
//   min( min(swap, Swap Cap) + min(emi, EMI Cap), Total Cap ),
// never more than the showroom's share.
//
// Tenure : 0 = all tenures, else the EMI months (3 … 36).
// Valid To : null = open ended.
//===============================================================

public class EmiReimbursementSchemes
{
    //===========================================================
    // Primary Key
    //===========================================================

    public long EmiReimbursementSchemeId { get; set; }


    //===========================================================
    // Scheme
    //===========================================================

    // ERS-0001 (generated by the server, never reused)
    public string SchemeCode { get; set; } = string.Empty;

    // Brand Management → BrandCode (stored by code)
    public string BrandCode { get; set; } = string.Empty;


    //===========================================================
    // Validity & Tenure
    //===========================================================

    public DateOnly ValidFrom { get; set; }

    public DateOnly? ValidTo { get; set; }

    // 0 = all tenures
    public int TenureMonths { get; set; }


    //===========================================================
    // Reimbursement
    //===========================================================

    // Percent / Fixed
    public string SwapBasis { get; set; } = string.Empty;

    public decimal SwapValue { get; set; }

    public decimal? SwapCap { get; set; }

    // Percent / Fixed
    public string EmiBasis { get; set; } = string.Empty;

    public decimal EmiValue { get; set; }

    public decimal? EmiCap { get; set; }

    // Swap + EMI claim together, per sale
    public decimal? TotalCap { get; set; }


    //===========================================================
    // Status & Description
    //===========================================================

    public string Remarks { get; set; } = string.Empty;

    public bool Status { get; set; }


    //===========================================================
    // Soft Delete
    //===========================================================

    public bool IsDeleted { get; set; }

    public long? DeletedBy { get; set; }

    public DateTime? DeletedDate { get; set; }


    //===========================================================
    // Audit
    //===========================================================

    public long CreatedBy { get; set; }

    public DateTime CreatedDate { get; set; }

    public long? ModifiedBy { get; set; }

    public DateTime? ModifiedDate { get; set; }
}