    private IQueryable<ScheduledServicesDto>
        ScheduledServiceQuery()
    {
        return _context
            .Set<ScheduledServiceEntity>()
            .AsNoTracking()
            .Where
            (
                x =>
                    !x.IsDeleted
            )
            .Select
            (
                x =>
                    new ScheduledServicesDto
                    {
                        ScheduledServiceId =
                            x.ScheduledServiceId,

                        ServicePolicyId =
                            x.ServicePolicyId,

                        PolicyCode =
                            _context
                                .Set<ServicePolicyEntity>()
                                .Where(p => p.ServicePolicyId == x.ServicePolicyId)
                                .Select(p => p.PolicyCode)
                                .FirstOrDefault()
                            ??
                            string.Empty,

                        BrandManagementId =
                            x.BrandManagementId,

                        BrandName =
                            _context
                                .Set<BrandManagementEntity>()
                                .Where(b => b.BrandManagementId == x.BrandManagementId)
                                .Select(b => b.BrandName)
                                .FirstOrDefault()
                            ??
                            string.Empty,

                        SequenceNo =
                            x.SequenceNo,

                        ServiceType =
                            x.ServiceType,

                        ServiceTypeNo =
                            x.ServiceTypeNo,

                        PositionName =
                            x.PositionName,

                        ServiceName =
                            x.ServiceName,

                        IntervalDays =
                            x.IntervalDays,

                        IntervalKm =
                            x.IntervalKm,

                        GraceDays =
                            x.GraceDays,

                        InPolicy =
                            x.InPolicy,

                        IsConfigured =
                            x.IsConfigured,

                        ServiceSubCategoryId =
                            x.ServiceSubCategoryId,

                        SubCategoryCode =
                            _context
                                .Set<ServiceSubCategoryEntity>()
                                .Where(s => s.ServiceSubCategoryId == x.ServiceSubCategoryId)
                                .Select(s => s.SubCategoryCode)
                                .FirstOrDefault()
                            ??
                            string.Empty,

                        SubCategoryName =
                            _context
                                .Set<ServiceSubCategoryEntity>()
                                .Where(s => s.ServiceSubCategoryId == x.ServiceSubCategoryId)
                                .Select(s => s.SubCategoryName)
                                .FirstOrDefault()
                            ??
                            string.Empty,

                        ServiceCode =
                            x.ServiceCode,

                        CustomerCharge =
                            x.CustomerCharge,

                        BrandReimbursement =
                            x.BrandReimbursement,

                        IncomeLedgerCode =
                            x.IncomeLedgerCode,

                        IncomeLedgerName =
                            x.IncomeLedgerName,

                        Remarks =
                            x.Remarks,

                        IsActive =
                            x.IsActive,

                        Readiness =
                            !x.InPolicy
                                ? NotInPolicyState
                                : x.IsConfigured
                                    ? ReadyState
                                    : PendingState,

                        IsInvoiceable =
                            x.InPolicy
                            &&
                            x.IsConfigured
                            &&
                            x.IsActive,

                        IsDeleted =
                            x.IsDeleted,

                        DeletedBy =
                            x.DeletedBy,

                        DeletedDate =
                            x.DeletedDate,

                        CreatedBy =
                            x.CreatedBy,

                        CreatedDate =
                            x.CreatedDate,

                        ModifiedBy =
                            x.ModifiedBy,

                        ModifiedDate =
                            x.ModifiedDate
                    }
            );
    }


    //===========================================================
    // Get All (policies synced first)
    //===========================================================

    public async Task<List<ScheduledServicesDto>>
        GetAllAsync()
    {
        await ScheduledServicesSync.SyncAllAsync(
            _context,
            1);

        return await ScheduledServiceQuery()
            .OrderBy
            (
                x =>
                    x.BrandName
            )
            .ThenBy
            (
                x =>
                    x.SequenceNo
            )
            .ToListAsync();
    }


    //===========================================================
    // Get By Id (with the sub category / codes a first save uses)
    //===========================================================

    public async Task<ScheduledServicesDto?>
        GetByIdAsync
        (
            long id
        )
    {
        ScheduledServicesDto? dto =
            await ScheduledServiceQuery()
                .FirstOrDefaultAsync
                (
                    x =>
                        x.ScheduledServiceId ==
                        id
                );

        if
        (
            dto == null
        )
        {
            return null;
        }

        if
        (
            !dto.InPolicy
        )
        {
            dto.SubCategoryMessage =
                dto.IsConfigured
                    ? string.Empty
                    : "This position is no longer in the Service Policy.";

            return dto;
        }

        if
        (
            dto.ServiceSubCategoryId.HasValue
            &&
            !string.IsNullOrWhiteSpace(dto.ServiceCode)
            &&
            !string.IsNullOrWhiteSpace(dto.IncomeLedgerCode)
        )
        {
            return dto;
        }

        try
        {
            ScheduledServiceEntity entity =
                await _context
                    .Set<ScheduledServiceEntity>()
                    .AsNoTracking()
                    .FirstAsync
                    (
                        x =>
                            x.ScheduledServiceId ==
                            id
                    );

            ServiceSubCategoryEntity subCategory =
                await ResolveSubCategoryAsync(
                    entity,
                    true);

            LedgerParent parent =
                await ResolveLedgerParentAsync(
                    subCategory);

            dto.ServiceSubCategoryId ??=
                subCategory.ServiceSubCategoryId;

            dto.SubCategoryCode =
                subCategory.SubCategoryCode;

            dto.SubCategoryName =
                subCategory.SubCategoryName;

            dto.NextServiceCode =
                string.IsNullOrWhiteSpace(dto.ServiceCode)
                    ? await NextServiceCodeAsync(subCategory)
                    : dto.ServiceCode;

            dto.NextIncomeLedgerCode =
                string.IsNullOrWhiteSpace(dto.IncomeLedgerCode)
                    ? await NextLedgerCodeAsync(parent)
                    : dto.IncomeLedgerCode;
        }
        catch
        (
            InvalidOperationException ex
        )
        {
            dto.SubCategoryMessage =
                ex.Message;
        }

        return dto;
    }


    //===========================================================
    // Resolve the brand's Scheduled Services sub category
    //===========================================================

    private async Task<ServiceSubCategoryEntity>
        ResolveSubCategoryAsync
        (
            ScheduledServiceEntity entity,
            bool requireUsable
        )
    {
        string brandName =
            await _context
                .Set<BrandManagementEntity>()
                .AsNoTracking()
                .Where
                (
                    x =>
                        x.BrandManagementId ==
                        entity.BrandManagementId
                )
                .Select
                (
                    x =>
                        x.BrandName
                )
                .FirstOrDefaultAsync()
            ??
            "this brand";

        //=======================================================
        // Already linked : keep it (while it is live)
        //=======================================================

        ServiceSubCategoryEntity? subCategory =
            entity.ServiceSubCategoryId.HasValue
                ? await _context
                    .Set<ServiceSubCategoryEntity>()
                    .AsNoTracking()
                    .FirstOrDefaultAsync
                    (
                        x =>
                            x.ServiceSubCategoryId ==
                            entity.ServiceSubCategoryId
                            &&
                            !x.IsDeleted
                    )
                : null;

        if
        (
            subCategory == null
        )
        {
            ServiceCategoryEntity? category =
                await _context
                    .Set<ServiceCategoryEntity>()
                    .AsNoTracking()
                    .FirstOrDefaultAsync
                    (
                        x =>
                            !x.IsDeleted
                            &&
                            x.CategoryType ==
                            BrandServicesType
                            &&
                            x.BrandManagementId ==
                            entity.BrandManagementId
                    );

            if
            (
                category == null
            )
            {
                throw new InvalidOperationException(
                    $"Create the Brand Services category for {brandName} first, " +
                    $"then its {ScheduledServicesType} sub category.");
            }

            subCategory =
                await _context
                    .Set<ServiceSubCategoryEntity>()
                    .AsNoTracking()
                    .FirstOrDefaultAsync
                    (
                        x =>
                            !x.IsDeleted
                            &&
                            x.ServiceCategoryId ==
                            category.ServiceCategoryId
                            &&
                            x.SubCategoryType ==
                            ScheduledServicesType
                    );

            if
            (
                subCategory == null
            )
            {
                throw new InvalidOperationException(
                    $"Create the {ScheduledServicesType} sub category for {brandName} " +
                    $"(under '{category.CategoryName}') first.");
            }
        }

        if
        (
            requireUsable
            &&
            !subCategory.IsActive
        )
        {
            throw new InvalidOperationException(
                $"Sub category '{subCategory.SubCategoryName}' ({subCategory.SubCategoryCode}) is inactive.");
        }

        if
        (
            requireUsable
            &&
            !subCategory.ItemCreationAllowed
        )
        {
            throw new InvalidOperationException(
                $"Sub category '{subCategory.SubCategoryName}' ({subCategory.SubCategoryCode}) does not allow item creation.");
        }

        return subCategory;
    }


    //===========================================================
    // Ledger parent : the sub category's account sub group
    //===========================================================

    private sealed class LedgerParent
    {
        public AccountClassEntity Class { get; set; } = null!;

        public AccountGroupEntity Group { get; set; } = null!;

        public AccountSubGroupEntity SubGroup { get; set; } = null!;
    }


    private async Task<LedgerParent>
        ResolveLedgerParentAsync
        (
            ServiceSubCategoryEntity subCategory
        )
    {
        AccountSubGroupEntity? subGroup =
            await _context
                .Set<AccountSubGroupEntity>()
                .AsNoTracking()
                .FirstOrDefaultAsync
                (
                    x =>
                        x.SubGroupCode ==
                        subCategory.IncomeSubGroupCode
                        &&
                        !x.IsDeleted
                );

        AccountGroupEntity? group =
            subGroup == null
                ? null
                : await _context
                    .Set<AccountGroupEntity>()
                    .AsNoTracking()
                    .FirstOrDefaultAsync
                    (
                        x =>
                            x.AccountGroupId ==
                            subGroup.AccountGroupId
                            &&
                            !x.IsDeleted
                    );

        AccountClassEntity? accountClass =
            subGroup == null
                ? null
                : await _context
                    .Set<AccountClassEntity>()
                    .AsNoTracking()
                    .FirstOrDefaultAsync
                    (
                        x =>
                            x.AccountClassId ==
                            subGroup.AccountClassId
                            &&
                            !x.IsDeleted
                    );

        if
        (
            subGroup == null
            ||
            group == null
            ||
            accountClass == null
        )
        {
            throw new InvalidOperationException(
                $"The account sub group {subCategory.IncomeSubGroupCode} of sub category " +
                $"'{subCategory.SubCategoryName}' was not found. Open and save the sub category to rebuild it.");
        }

        return new LedgerParent
        {
            Class =
                accountClass,

            Group =
                group,

            SubGroup =
                subGroup
        };
    }


    //===========================================================
    // Code Helpers
    //===========================================================

    // "SUB-005-007-002" -> 2, "GRP-005-007" -> 7
    private static int LastNumber
    (
        string? code
    )
    {
        string[] parts =
            (code ?? string.Empty)
                .Trim()
                .Split(
                    '-',
                    StringSplitOptions.RemoveEmptyEntries);

        if
        (
            parts.Length < 2
            ||
            !int.TryParse(
                parts[^1],
                out int number)
            ||
            number < 1
        )
        {
            throw new InvalidOperationException(
                $"Invalid account code '{code}'.");
        }

        return number;
    }


    // Next Service Code : MSS-<sub category numbers>-nnnnn
    //   sub category BRS-001-002 -> MSS-001-002-00001
    private async Task<string>
        NextServiceCodeAsync
        (
            ServiceSubCategoryEntity subCategory
        )
    {
        (int categoryNo, int subCategoryNo) =
            SubCategoryNumbers(
                subCategory.SubCategoryCode);

        // "MSS-001-002-" : the generator's code without its running number
        string first =
            CodeGenerator.GenerateScheduledServiceItemCode(
                categoryNo,
                subCategoryNo,
                1);

        string prefix =
            first.Substring(
                0,
                first.LastIndexOf('-') + 1);

        List<string> codes =
            await _context
                .Set<ScheduledServiceEntity>()
                .AsNoTracking()
                .Where
                (
                    x =>
                        x.ServiceCode.StartsWith(
                            prefix)
                )
                .Select
                (
                    x =>
                        x.ServiceCode
                )
                .ToListAsync();

        int highest =
            codes
                .Select
                (
                    code =>
                        int.TryParse(
                            code.Substring(prefix.Length),
                            out int number)
                            ? number
                            : 0
                )
                .DefaultIfEmpty(0)
                .Max();

        // Central code generator : MSS-001-002-00001
        return CodeGenerator.GenerateScheduledServiceItemCode(
            categoryNo,
            subCategoryNo,
            highest + 1);
    }


    // "BRS-001-002" -> (1, 2)
    private static (int CategoryNo, int SubCategoryNo) SubCategoryNumbers
    (
        string? subCategoryCode
    )
    {
        string[] parts =
            (subCategoryCode ?? string.Empty)
                .Trim()
                .Split(
                    '-',
                    StringSplitOptions.RemoveEmptyEntries);

        if
        (
            parts.Length != 3
            ||
            !int.TryParse(parts[1], out int categoryNo)
            ||
            !int.TryParse(parts[2], out int subCategoryNo)
        )
        {
            throw new InvalidOperationException(
                $"Invalid Service Sub Category code '{subCategoryCode}'.");
        }

        return (categoryNo, subCategoryNo);
    }


    // Next Income Ledger Code : GLR-ccc-ggg-sss-nnnnn in the sub group
    private async Task<string>
        NextLedgerCodeAsync
        (
            LedgerParent parent
        )
    {
        int classNo =
            LastNumber(parent.Class.ClassCode);

        int groupNo =
            LastNumber(parent.Group.GroupCode);

        int subGroupNo =
            LastNumber(parent.SubGroup.SubGroupCode);

        string parentPart =
            $"{classNo:D3}-{groupNo:D3}-{subGroupNo:D3}";

        List<string> ledgerCodes =
            await _context
                .Set<GeneralLedgerEntity>()
                .AsNoTracking()
                .Where
                (
                    x =>
                        x.AccountSubGroupId ==
                        parent.SubGroup.AccountSubGroupId
                )
                .Select
                (
                    x =>
                        x.LedgerCode
                )
                .ToListAsync();

        List<string> serviceCodes =
            await _context
                .Set<ScheduledServiceEntity>()
                .AsNoTracking()
                .Where
                (
                    x =>
                        x.IncomeLedgerCode != ""
                )
                .Select
                (
                    x =>
                        x.IncomeLedgerCode
                )
                .ToListAsync();

        int highest =
            ledgerCodes
                .Concat(serviceCodes)
                .Select
                (
                    code =>
                    {
                        string[] parts =
                            (code ?? string.Empty)
                                .Trim()
                                .Split(
                                    '-',
                                    StringSplitOptions.RemoveEmptyEntries);

                        return parts.Length == 5
                            &&
                            string.Equals(
                                parts[0],
                                LedgerPrefix,
                                StringComparison.OrdinalIgnoreCase)
                            &&
                            $"{parts[1]}-{parts[2]}-{parts[3]}" ==
                            parentPart
                            &&
                            int.TryParse(
                                parts[4],
                                out int number)
                                ? number
                                : 0;
                    }
                )
                .DefaultIfEmpty(0)
                .Max();

        return CodeGenerator.GenerateGeneralLedgerCode(
            classNo,
            groupNo,
            subGroupNo,
            highest + 1);
    }


    //===========================================================
    // Validate Charges
    //===========================================================

    private static (decimal CustomerCharge, decimal BrandReimbursement)
        ValidateCharges
        (
            string serviceType,
            decimal customerCharge,
            decimal brandReimbursement
        )
    {
        decimal customer =
            Math.Round(
                customerCharge,
                2);

        decimal reimbursement =
            Math.Round(
                brandReimbursement,
                2);

        if
        (
            customer < 0
            ||
            reimbursement < 0
        )
        {
            throw new InvalidOperationException(
                "Amounts cannot be negative.");
        }

        if
        (
            customer > MaxAmount
            ||
            reimbursement > MaxAmount
        )
        {
            throw new InvalidOperationException(
                $"Amounts cannot be more than {MaxAmount:N2}.");
        }

        if
        (
            string.Equals(
                serviceType,
                FreeType,
                StringComparison.OrdinalIgnoreCase)
        )
        {
            if
            (
                reimbursement <= 0
            )
            {
                throw new InvalidOperationException(
                    "Brand Reimbursement is required for a free service.");
            }

            return (0, reimbursement);
        }

        if
        (
            string.Equals(
                serviceType,
                PaidType,
                StringComparison.OrdinalIgnoreCase)
        )
        {
            if
            (
                customer <= 0
            )
            {
                throw new InvalidOperationException(
                    "Customer Charge is required for a paid service.");
            }

            return (customer, 0);
        }

        throw new InvalidOperationException(
            $"Unknown service type '{serviceType}'.");
    }


    //===========================================================
    // Sync Income Ledger (create when missing, follow the row)
    //===========================================================

    private async Task
        SyncLedgerAsync
        (
            ScheduledServiceEntity entity,
            LedgerParent parent,
            long userId
        )
    {
        GeneralLedgerEntity? ledger =
            await _context
                .Set<GeneralLedgerEntity>()
                .FirstOrDefaultAsync
                (
                    x =>
                        x.LedgerCode ==
                        entity.IncomeLedgerCode
                        &&
                        !x.IsDeleted
                );

        bool active =
            entity.InPolicy
            &&
            entity.IsActive;

        if
        (
            ledger == null
        )
        {
            _context
                .Set<GeneralLedgerEntity>()
                .Add
                (
                    new GeneralLedgerEntity
                    {
                        AccountClassId =
                            parent.Class.AccountClassId,

                        AccountGroupId =
                            parent.Group.AccountGroupId,

                        AccountSubGroupId =
                            parent.SubGroup.AccountSubGroupId,

                        ClassCode =
                            parent.Class.ClassCode,

                        Mode =
                            parent.Class.Mode,

                        GroupCode =
                            parent.Group.GroupCode,

                        SubGroupCode =
                            parent.SubGroup.SubGroupCode,

                        LedgerCode =
                            entity.IncomeLedgerCode,

                        LedgerName =
                            entity.IncomeLedgerName,

                        Remarks =
                            $"System generated from Scheduled Service {entity.ServiceCode}.",

                        IsActive =
                            active,

                        IsDeleted =
                            false,

                        CreatedBy =
                            userId,

                        CreatedDate =
                            DateTime.UtcNow
                    }
                );

            return;
        }

        if
        (
            ledger.AccountSubGroupId !=
            parent.SubGroup.AccountSubGroupId
        )
        {
            throw new InvalidOperationException(
                $"General Ledger '{entity.IncomeLedgerCode}' belongs to a different sub group.");
        }

        if
        (
            ledger.LedgerName == entity.IncomeLedgerName
            &&
            ledger.IsActive == active
        )
        {
            return;
        }

        ledger.LedgerName =
            entity.IncomeLedgerName;

        ledger.IsActive =
            active;

        ledger.ModifiedBy =
            userId;

        ledger.ModifiedDate =
            DateTime.UtcNow;
    }


    //===========================================================
    // Activity History
