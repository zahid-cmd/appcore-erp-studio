    public async Task<bool>
        ExistsAsync
        (
            long id
        )
    {
        return await _context
            .Set<ScheduledServiceEntity>()
            .AnyAsync
            (
                x =>
                    x.ScheduledServiceId ==
                    id
                    &&
                    !x.IsDeleted
            );
    }
