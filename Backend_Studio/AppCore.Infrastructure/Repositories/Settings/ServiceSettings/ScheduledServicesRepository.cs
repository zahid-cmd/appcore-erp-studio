    private void AddHistory
    (
        ScheduledServiceEntity entity,
        string activityType,
        string verb,
        long userId
    )
    {
        _context.ActivityHistories.Add(
            new ActivityHistory
            {
                Module =
                    "Service Settings",

                EntityName =
                    "Scheduled Service",

                EntityId =
                    entity.ScheduledServiceId,

                ActivityType =
                    activityType,

                ActivityTitle =
                    $"Scheduled Service {verb}",

                ActivityDescription =
                    $"Scheduled Service '{entity.ServiceName}' ({entity.ServiceCode}) {verb.ToLower()}.",

                PerformedBy =
                    userId,

                PerformedByName =
                    "System",

                PerformedDate =
                    DateTime.UtcNow
            }
        );
    }


    //===========================================================
    // Configure (price a generated row; first save or again)
    //===========================================================

    public async Task
        ConfigureAsync
        (
            ConfigureScheduledServicesDto dto,
            long userId
        )
    {
        // Pick up any policy change made since the page was opened
        await ScheduledServicesSync.SyncAllAsync(
            _context,
            userId);

        ScheduledServiceEntity? entity =
            await _context
                .Set<ScheduledServiceEntity>()
                .FirstOrDefaultAsync
                (
                    x =>
                        x.ScheduledServiceId ==
                        dto.ScheduledServiceId
                        &&
                        !x.IsDeleted
                );

        if
        (
            entity == null
        )
        {
            throw new KeyNotFoundException(
                "Scheduled Service not found. Its position may have been removed from the Service Policy.");
        }

        if
        (
            !entity.InPolicy
            &&
            dto.IsActive
        )
        {
            throw new InvalidOperationException(
                $"'{entity.ServiceName}' is no longer in the Service Policy, so it cannot be active.");
        }

        if
        (
            !entity.InPolicy
            &&
            !entity.IsConfigured
        )
        {
            throw new InvalidOperationException(
                $"'{entity.ServiceName}' is no longer in the Service Policy.");
        }

        (decimal customerCharge, decimal brandReimbursement) =
            ValidateCharges(
                entity.ServiceType,
                dto.CustomerCharge,
                dto.BrandReimbursement);

        bool firstSave =
            string.IsNullOrWhiteSpace(entity.ServiceCode)
            ||
            string.IsNullOrWhiteSpace(entity.IncomeLedgerCode)
            ||
            !entity.ServiceSubCategoryId.HasValue;

        ServiceSubCategoryEntity subCategory =
            await ResolveSubCategoryAsync(
                entity,
                firstSave);

        LedgerParent parent =
            await ResolveLedgerParentAsync(
                subCategory);

        entity.ServiceSubCategoryId ??=
            subCategory.ServiceSubCategoryId;

        if
        (
            string.IsNullOrWhiteSpace(entity.ServiceCode)
        )
        {
            entity.ServiceCode =
                await NextServiceCodeAsync(
                    subCategory);
        }

        if
        (
            string.IsNullOrWhiteSpace(entity.IncomeLedgerCode)
        )
        {
            entity.IncomeLedgerCode =
                await NextLedgerCodeAsync(
                    parent);
        }

        entity.IncomeLedgerName =
            entity.ServiceName;

        entity.CustomerCharge =
            customerCharge;

        entity.BrandReimbursement =
            brandReimbursement;

        entity.IsConfigured =
            true;

        entity.Remarks =
            dto.Remarks?.Trim()
            ??
            string.Empty;

        entity.IsActive =
            dto.IsActive;

        entity.ModifiedBy =
            userId;

        entity.ModifiedDate =
            DateTime.UtcNow;


        await using var transaction =
            await _context.Database.BeginTransactionAsync();

        await SyncLedgerAsync(
            entity,
            parent,
            userId);

        await _context.SaveChangesAsync();

        AddHistory(
            entity,
            "Update",
            firstSave
                ? "Configured"
                : "Updated",
            userId);

        await _context.SaveChangesAsync();

        await transaction.CommitAsync();
    }


