//===============================================================
// Scheduled Service Repository
//
// Rows are generated by Service Policy (ScheduledServicesSync);
// this page only prices them. There is no Create / Delete /
// Restore : positions are added and removed through the policy.
//
// Configure (first save) :
//   Sub Category  the brand's "Scheduled Services" sub category
//                 (under its Brand Services category); must be
//                 active and allow item creation
//   Service Code  MSS-<sub category numbers>-nnnnn
//                 e.g. sub category BRS-001-002 -> MSS-001-002-00001
//   Income Ledger GLR-ccc-ggg-sss-nnnnn under the sub category's
//                 account sub group, named like the service
//   Highest number used (deleted rows included) + 1; never reused.
//
// Charges :
//   Free service : Brand Reimbursement > 0, Customer Charge 0
//   Paid service : Customer Charge > 0,     Brand Reimbursement 0
//
// Readiness :
//   Pending       in policy, not priced
//   Ready         in policy, priced (invoiceable while active)
//   Not in Policy position removed / policy deleted (inactive)
//===============================================================

public class ScheduledServicesRepository :
    IScheduledServicesRepository
{
    //===========================================================
    // Constants
    //===========================================================

    private const string FreeType =
        "Free";

    private const string PaidType =
        "Paid";

    private const string BrandServicesType =
        "Brand Services";

    private const string ScheduledServicesType =
        "Scheduled Services";

    private const string LedgerPrefix =
        "GLR";

    private const decimal MaxAmount =
        99999999.99m;

    private const string PendingState =
        "Pending";

    private const string ReadyState =
        "Ready";

    private const string NotInPolicyState =
        "Not in Policy";


    //===========================================================
    // Private Fields
    //===========================================================

    private readonly AppDbContext _context;


