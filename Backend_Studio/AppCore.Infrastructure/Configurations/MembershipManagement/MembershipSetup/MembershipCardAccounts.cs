//===============================================================
// Membership Card Accounts (manual file : NOT generated by Code
// Synchronization; keep it next to MembershipCardsRepository.cs)
//
// Shared by MembershipCardsRepository and
// MembershipServicesRepository, so both pages build, name and
// sync the card ledgers in exactly one way.
//
// A card owns four ledgers, each named
// "<Sub Group Name> - <Card Name>" :
//
//   On the card                 Sub group (found by CODE only)
//     Fee Ledger                SUB-009-001-001  Membership Fees
//     Discount Ledger           SUB-004-002-002  Membership Discount
//
//   On its Membership Services row
//     Income Ledger             SUB-007-005-001  the income sub group
//                               of the Membership Services sub
//                               category (Service Settings)
//     Expense Ledger            SUB-004-002-001  Membership Service
//                               Charges
//
// Ledger codes : GLR-ccc-ggg-sss-nnnnn (central CodeGenerator),
// highest number used in the sub group (deleted included) + 1.
//===============================================================

public sealed class MembershipLedgerParent
{
    public AccountClassEntity Class { get; set; } = null!;

    public AccountGroupEntity Group { get; set; } = null!;

    public AccountSubGroupEntity SubGroup { get; set; } = null!;
}


public static class MembershipCardAccounts
{
    //===========================================================
    // Sub Groups (by code only, never by name)
    //===========================================================

    public const string FeeSubGroupCode =
        "SUB-009-001-001";

    public const string DiscountSubGroupCode =
        "SUB-004-002-002";

    public const string ServiceIncomeSubGroupCode =
        "SUB-007-005-001";

    public const string ServiceExpenseSubGroupCode =
        "SUB-004-002-001";


    //===========================================================
    // Constants
    //===========================================================

    public const string MembershipServicesType =
        "Membership Services";

    public const string Pending =
        "Pending";

    public const string Ready =
        "Ready";

    public const int MaxLedgerNameLength =
        200;

    private const string LedgerPrefix =
        "GLR";


    //===========================================================
    // Name Helpers
    //===========================================================

    // Trim, single spaces
    public static string Clean
    (
        string? value
    )
    {
        return string.Join(
            " ",
            (value ?? string.Empty)
                .Split(
                    ' ',
                    StringSplitOptions.RemoveEmptyEntries));
    }


    // "Membership Fees" + "GOLD CARD" -> "Membership Fees - GOLD CARD"
    public static string LedgerName
    (
        string? subGroupName,
        string cardName
    )
    {
        return $"{Clean(subGroupName)} - {cardName}";
    }


    // A row is invoiceable once it has a Service Value
    public static string Readiness
    (
        decimal serviceValue
    )
    {
        return serviceValue > 0
            ? Ready
            : Pending;
    }


    //===========================================================
    // Ledger Parent : sub group + its group + its class (live)
    //===========================================================

    public static async Task<MembershipLedgerParent>
        ResolveParentAsync
        (
            AppDbContext context,
            string subGroupCode,
            string purpose,
            bool requireActive
        )
    {
        AccountSubGroupEntity? subGroup =
            await context
                .Set<AccountSubGroupEntity>()
                .AsNoTracking()
                .FirstOrDefaultAsync
                (
                    x =>
                        x.SubGroupCode ==
                        subGroupCode
                        &&
                        !x.IsDeleted
                );

        AccountGroupEntity? group =
            subGroup == null
                ? null
                : await context
                    .Set<AccountGroupEntity>()
                    .AsNoTracking()
                    .FirstOrDefaultAsync
                    (
                        x =>
                            x.AccountGroupId ==
                            subGroup.AccountGroupId
                            &&
                            !x.IsDeleted
                    );

        AccountClassEntity? accountClass =
            subGroup == null
                ? null
                : await context
                    .Set<AccountClassEntity>()
                    .AsNoTracking()
                    .FirstOrDefaultAsync
                    (
                        x =>
                            x.AccountClassId ==
                            subGroup.AccountClassId
                            &&
                            !x.IsDeleted
                    );

        if
        (
            subGroup == null
            ||
            group == null
            ||
            accountClass == null
        )
        {
            throw new InvalidOperationException(
                $"Account sub group {subGroupCode} ({purpose}) was not found or is deleted. " +
                "Membership card ledgers are created under it.");
        }

        if
        (
            requireActive
            &&
            (
                !subGroup.IsActive
                ||
                !group.IsActive
                ||
                !accountClass.IsActive
            )
        )
        {
            throw new InvalidOperationException(
                $"Account sub group {subGroupCode} - {subGroup.SubGroupName} (or its group / class) is inactive. Activate it first.");
        }

        return new MembershipLedgerParent
        {
            Class =
                accountClass,

            Group =
                group,

            SubGroup =
                subGroup
        };
    }


    //===========================================================
    // Membership Services sub category : the live sub category of
    // type "Membership Services" whose income sub group is
    // SUB-007-005-001
    //===========================================================

    public static async Task<ServiceSubCategoryEntity>
        ResolveServiceSubCategoryAsync
        (
            AppDbContext context,
            bool requireUsable
        )
    {
        ServiceSubCategoryEntity subCategory =
            await context
                .Set<ServiceSubCategoryEntity>()
                .AsNoTracking()
                .Where
                (
                    x =>
                        !x.IsDeleted
                        &&
                        x.SubCategoryType ==
                        MembershipServicesType
                        &&
                        x.IncomeSubGroupCode ==
                        ServiceIncomeSubGroupCode
                )
                .OrderBy
                (
                    x =>
                        x.SubCategoryCode
                )
                .FirstOrDefaultAsync()
            ??
            throw new InvalidOperationException(
                $"No '{MembershipServicesType}' service sub category with income sub group {ServiceIncomeSubGroupCode} was found " +
                "(Service Settings > Service Sub Category). Each card creates its complimentary service under it.");

        ServiceCategoryEntity category =
            await context
                .Set<ServiceCategoryEntity>()
                .AsNoTracking()
                .FirstOrDefaultAsync
                (
                    x =>
                        x.ServiceCategoryId ==
                        subCategory.ServiceCategoryId
                        &&
                        !x.IsDeleted
                )
            ??
            throw new InvalidOperationException(
                $"The service category of '{subCategory.SubCategoryName}' was not found.");

        if
        (
            requireUsable
            &&
            (
                !subCategory.IsActive
                ||
                !category.IsActive
            )
        )
        {
            throw new InvalidOperationException(
                $"Service sub category '{subCategory.SubCategoryName}' (or its category) is inactive. Activate it first.");
        }

        if
        (
            requireUsable
            &&
            !subCategory.ItemCreationAllowed
        )
        {
            throw new InvalidOperationException(
                $"Service sub category '{subCategory.SubCategoryName}' does not allow item creation.");
        }

        return subCategory;
    }


    //===========================================================
    // Code Helpers
    //===========================================================

    // "SUB-009-001-001" -> 1
    private static int LastNumber
    (
        string? code
    )
    {
        string[] parts =
            (code ?? string.Empty)
                .Trim()
                .Split(
                    '-',
                    StringSplitOptions.RemoveEmptyEntries);

        if
        (
            parts.Length < 2
            ||
            !int.TryParse(
                parts[^1],
                out int number)
            ||
            number < 1
        )
        {
            throw new InvalidOperationException(
                $"Invalid account code '{code}'.");
        }

        return number;
    }


    //===========================================================
    // Next Ledger Code in a sub group
    //
    // Highest of : General Ledgers of the sub group (deleted
    // included) and every code stored on cards / membership
    // services rows (deleted included), + 1. "reserved" holds codes
    // already handed out in the same save.
    //===========================================================

    public static async Task<string>
        NextLedgerCodeAsync
        (
            AppDbContext context,
            MembershipLedgerParent parent,
            IEnumerable<string>? reserved = null
        )
    {
        int classNo =
            LastNumber(parent.Class.ClassCode);

        int groupNo =
            LastNumber(parent.Group.GroupCode);

        int subGroupNo =
            LastNumber(parent.SubGroup.SubGroupCode);

        string parentPart =
            $"{classNo:D3}-{groupNo:D3}-{subGroupNo:D3}";

        List<string> codes =
            await context
                .Set<GeneralLedgerEntity>()
                .AsNoTracking()
                .Where
                (
                    x =>
                        x.AccountSubGroupId ==
                        parent.SubGroup.AccountSubGroupId
                )
                .Select
                (
                    x =>
                        x.LedgerCode
                )
                .ToListAsync();

        // One query per column (EF cannot translate an array projection)
        codes.AddRange(
            await context
                .Set<MembershipCardEntity>()
                .AsNoTracking()
                .Select(x => x.FeeLedgerCode)
                .ToListAsync());

        codes.AddRange(
            await context
                .Set<MembershipCardEntity>()
                .AsNoTracking()
                .Select(x => x.DiscountLedgerCode)
                .ToListAsync());

        codes.AddRange(
            await context
                .Set<MembershipServiceEntity>()
                .AsNoTracking()
                .Select(x => x.IncomeLedgerCode)
                .ToListAsync());

        codes.AddRange(
            await context
                .Set<MembershipServiceEntity>()
                .AsNoTracking()
                .Select(x => x.ExpenseLedgerCode)
                .ToListAsync());

        if
        (
            reserved != null
        )
        {
            codes.AddRange(
                reserved);
        }

        int highest =
            codes
                .Select
                (
                    code =>
                    {
                        string[] parts =
                            (code ?? string.Empty)
                                .Trim()
                                .Split(
                                    '-',
                                    StringSplitOptions.RemoveEmptyEntries);

                        return parts.Length == 5
                            &&
                            string.Equals(
                                parts[0],
                                LedgerPrefix,
                                StringComparison.OrdinalIgnoreCase)
                            &&
                            $"{parts[1]}-{parts[2]}-{parts[3]}" ==
                            parentPart
                            &&
                            int.TryParse(
                                parts[4],
                                out int number)
                                ? number
                                : 0;
                    }
                )
                .DefaultIfEmpty(0)
                .Max();

        return CodeGenerator.GenerateGeneralLedgerCode(
            classNo,
            groupNo,
            subGroupNo,
            highest + 1);
    }


    //===========================================================
    // Next Service Code (MSC-ccc-sss-nnnnn, central CodeGenerator)
    //===========================================================

    public static async Task<string>
        NextServiceCodeAsync
        (
            AppDbContext context,
            ServiceSubCategoryEntity subCategory
        )
    {
        // "DRS-002-001" -> (2, 1)
        string[] parts =
            (subCategory.SubCategoryCode ?? string.Empty)
                .Trim()
                .Split(
                    '-',
                    StringSplitOptions.RemoveEmptyEntries);

        if
        (
            parts.Length != 3
            ||
            !int.TryParse(parts[1], out int categoryNo)
            ||
            !int.TryParse(parts[2], out int subCategoryNo)
        )
        {
            throw new InvalidOperationException(
                $"Invalid Service Sub Category code '{subCategory.SubCategoryCode}'.");
        }

        // "MSC-002-001-" : the generator's code without its running number
        string first =
            CodeGenerator.GenerateMembershipServiceItemCode(
                categoryNo,
                subCategoryNo,
                1);

        string prefix =
            first.Substring(
                0,
                first.LastIndexOf('-') + 1);

        List<string> serviceCodes =
            await context
                .Set<MembershipServiceEntity>()
                .AsNoTracking()
                .Select
                (
                    x =>
                        x.ServiceCode
                )
                .ToListAsync();

        int highest =
            serviceCodes
                .Where
                (
                    code =>
                        (code ?? string.Empty).StartsWith(
                            prefix,
                            StringComparison.OrdinalIgnoreCase)
                )
                .Select
                (
                    code =>
                        int.TryParse(
                            code.Substring(prefix.Length),
                            out int number)
                            ? number
                            : 0
                )
                .DefaultIfEmpty(0)
                .Max();

        return CodeGenerator.GenerateMembershipServiceItemCode(
            categoryNo,
            subCategoryNo,
            highest + 1);
    }


    //===========================================================
    // Sync One Ledger : create when missing, else follow the name
    // and the active state of its owner
    //===========================================================

    public static async Task
        SyncLedgerAsync
        (
            AppDbContext context,
            string ledgerCode,
            string ledgerName,
            bool isActive,
            string remarks,
            MembershipLedgerParent parent,
            long userId
        )
    {
        if
        (
            string.IsNullOrWhiteSpace(ledgerCode)
        )
        {
            return;
        }

        GeneralLedgerEntity? ledger =
            await context
                .Set<GeneralLedgerEntity>()
                .FirstOrDefaultAsync
                (
                    x =>
                        x.LedgerCode ==
                        ledgerCode
                        &&
                        !x.IsDeleted
                );

        if
        (
            ledger == null
        )
        {
            context
                .Set<GeneralLedgerEntity>()
                .Add
                (
                    new GeneralLedgerEntity
                    {
                        AccountClassId =
                            parent.Class.AccountClassId,

                        AccountGroupId =
                            parent.Group.AccountGroupId,

                        AccountSubGroupId =
                            parent.SubGroup.AccountSubGroupId,

                        ClassCode =
                            parent.Class.ClassCode,

                        Mode =
                            parent.Class.Mode,

                        GroupCode =
                            parent.Group.GroupCode,

                        SubGroupCode =
                            parent.SubGroup.SubGroupCode,

                        LedgerCode =
                            ledgerCode,

                        LedgerName =
                            ledgerName,

                        Remarks =
                            remarks,

                        IsActive =
                            isActive,

                        IsDeleted =
                            false,

                        CreatedBy =
                            userId,

                        CreatedDate =
                            DateTime.UtcNow
                    }
                );

            return;
        }

        if
        (
            ledger.AccountSubGroupId !=
            parent.SubGroup.AccountSubGroupId
        )
        {
            throw new InvalidOperationException(
                $"General Ledger '{ledgerCode}' belongs to a different sub group.");
        }

        if
        (
            ledger.LedgerName == ledgerName
            &&
            ledger.IsActive == isActive
        )
        {
            return;
        }

        ledger.LedgerName =
            ledgerName;

        ledger.IsActive =
            isActive;

        ledger.ModifiedBy =
            userId;

        ledger.ModifiedDate =
            DateTime.UtcNow;
    }


    //===========================================================
    // Delete / Restore ledgers by code
    //
    // Delete  : every live ledger with one of the codes.
    // Restore : for each code without a live ledger, its most
    //           recently deleted one.
    //===========================================================

    public static async Task
        SetLedgersDeletedAsync
        (
            AppDbContext context,
            IEnumerable<string> ledgerCodes,
            bool deleted,
            long userId
        )
    {
        List<string> codes =
            ledgerCodes
                .Where
                (
                    x =>
                        !string.IsNullOrWhiteSpace(x)
                )
                .Distinct()
                .ToList();

        if
        (
            codes.Count == 0
        )
        {
            return;
        }

        DateTime now =
            DateTime.UtcNow;

        if
        (
            deleted
        )
        {
            foreach
            (
                GeneralLedgerEntity ledger
                in await context
                    .Set<GeneralLedgerEntity>()
                    .Where
                    (
                        x =>
                            codes.Contains(x.LedgerCode)
                            &&
                            !x.IsDeleted
                    )
                    .ToListAsync()
            )
            {
                ledger.IsDeleted =
                    true;

                ledger.DeletedBy =
                    userId;

                ledger.DeletedDate =
                    now;
            }

            return;
        }

        foreach
        (
            string code
            in codes
        )
        {
            bool live =
                await context
                    .Set<GeneralLedgerEntity>()
                    .AnyAsync
                    (
                        x =>
                            x.LedgerCode ==
                            code
                            &&
                            !x.IsDeleted
                    );

            if
            (
                live
            )
            {
                continue;
            }

            GeneralLedgerEntity? ledger =
                await context
                    .Set<GeneralLedgerEntity>()
                    .Where
                    (
                        x =>
                            x.LedgerCode ==
                            code
                            &&
                            x.IsDeleted
                    )
                    .OrderByDescending
                    (
                        x =>
                            x.DeletedDate
                    )
                    .FirstOrDefaultAsync();

            if
            (
                ledger == null
            )
            {
                continue;
            }

            ledger.IsDeleted =
                false;

            ledger.DeletedBy =
                null;

            ledger.DeletedDate =
                null;

            ledger.ModifiedBy =
                userId;

            ledger.ModifiedDate =
                now;
        }
    }


    //===========================================================
    // Sub group names by code (live sub groups only)
    //===========================================================

    public static async Task<Dictionary<string, string>>
        SubGroupNamesAsync
        (
            AppDbContext context,
            IEnumerable<string> subGroupCodes
        )
    {
        List<string> codes =
            subGroupCodes
                .Where
                (
                    x =>
                        !string.IsNullOrWhiteSpace(x)
                )
                .Distinct()
                .ToList();

        var rows =
            await context
                .Set<AccountSubGroupEntity>()
                .AsNoTracking()
                .Where
                (
                    x =>
                        codes.Contains(x.SubGroupCode)
                        &&
                        !x.IsDeleted
                )
                .Select
                (
                    x =>
                        new
                        {
                            x.SubGroupCode,
                            x.SubGroupName
                        }
                )
                .ToListAsync();

        Dictionary<string, string> names =
            new Dictionary<string, string>(
                StringComparer.OrdinalIgnoreCase);

        foreach
        (
            var row
            in rows
        )
        {
            names[row.SubGroupCode] =
                Clean(row.SubGroupName);
        }

        return names;
    }


    //===========================================================
    // Sync Names (on every list read of either page)
    //
    // Card renames are applied on save. This catches renames of the
    // four sub groups and of the Membership Services sub category :
    // card ledgers, the card's service row (Service Name, Display
    // Name, Membership Type) and the row's two ledgers follow.
    // A name longer than 200 characters is left as it is.
    //===========================================================

    public static async Task
        SyncNamesAsync
        (
            AppDbContext context
        )
    {
        List<MembershipCardEntity> cards =
            await context
                .Set<MembershipCardEntity>()
                .Where
                (
                    x =>
                        !x.IsDeleted
                )
                .ToListAsync();

        if
        (
            cards.Count == 0
        )
        {
            return;
        }

        List<long> cardIds =
            cards
                .Select(x => x.MembershipCardId)
                .ToList();

        var rows =
            await
            (
                from m in context.Set<MembershipServiceEntity>()
                join s in context.Set<ServiceSubCategoryEntity>()
                    on m.ServiceSubCategoryId equals s.ServiceSubCategoryId
                where !m.IsDeleted
                      && m.MembershipCardId != null
                      && cardIds.Contains(m.MembershipCardId.Value)
                select new
                {
                    Entity = m,
                    s.SubCategoryName,
                    s.IncomeSubGroupCode
                }
            )
            .ToListAsync();

        List<string> subGroupCodes =
            new List<string>
            {
                FeeSubGroupCode,
                DiscountSubGroupCode,
                ServiceExpenseSubGroupCode
            };

        subGroupCodes.AddRange(
            rows.Select(x => x.IncomeSubGroupCode));

        Dictionary<string, string> subGroupNames =
            await SubGroupNamesAsync(
                context,
                subGroupCodes);

        // ledger code -> expected name
        Dictionary<string, string> ledgerNames =
            new Dictionary<string, string>(
                StringComparer.OrdinalIgnoreCase);

        bool changed =
            false;

        string? Expected
        (
            string subGroupCode,
            string cardName
        )
        {
            if
            (
                !subGroupNames.TryGetValue(
                    subGroupCode,
                    out string? subGroupName)
            )
            {
                return null;
            }

            string name =
                LedgerName(
                    subGroupName,
                    cardName);

            return name.Length <= MaxLedgerNameLength
                ? name
                : null;
        }

        foreach
        (
            MembershipCardEntity card
            in cards
        )
        {
            string? feeName =
                Expected(
                    FeeSubGroupCode,
                    card.CardName);

            if
            (
                feeName != null
                &&
                card.FeeLedgerName != feeName
            )
            {
                card.FeeLedgerName =
                    feeName;

                changed =
                    true;
            }

            string? discountName =
                Expected(
                    DiscountSubGroupCode,
                    card.CardName);

            if
            (
                discountName != null
                &&
                card.DiscountLedgerName != discountName
            )
            {
                card.DiscountLedgerName =
                    discountName;

                changed =
                    true;
            }

            ledgerNames[card.FeeLedgerCode] =
                card.FeeLedgerName;

            ledgerNames[card.DiscountLedgerCode] =
                card.DiscountLedgerName;
        }

        Dictionary<long, MembershipCardEntity> cardById =
            cards.ToDictionary(
                x => x.MembershipCardId);

        foreach
        (
            var row
            in rows
        )
        {
            MembershipServiceEntity entity =
                row.Entity;

            MembershipCardEntity card =
                cardById[entity.MembershipCardId!.Value];

            string serviceName =
                Clean(
                    row.SubCategoryName);

            if
            (
                !string.IsNullOrWhiteSpace(serviceName)
                &&
                serviceName.Length <= 150
            )
            {
                string displayName =
                    $"{serviceName} - {card.CardName}";

                if
                (
                    displayName.Length <= MaxLedgerNameLength
                    &&
                    (
                        entity.ServiceName != serviceName
                        ||
                        entity.DisplayName != displayName
                        ||
                        entity.MembershipType != card.CardName
                    )
                )
                {
                    entity.ServiceName =
                        serviceName;

                    entity.DisplayName =
                        displayName;

                    entity.MembershipType =
                        card.CardName;

                    changed =
                        true;
                }
            }

            string? incomeName =
                Expected(
                    row.IncomeSubGroupCode,
                    card.CardName);

            if
            (
                incomeName != null
                &&
                entity.IncomeLedgerName != incomeName
            )
            {
                entity.IncomeLedgerName =
                    incomeName;

                changed =
                    true;
            }

            string? expenseName =
                Expected(
                    ServiceExpenseSubGroupCode,
                    card.CardName);

            if
            (
                expenseName != null
                &&
                entity.ExpenseLedgerName != expenseName
            )
            {
                entity.ExpenseLedgerName =
                    expenseName;

                changed =
                    true;
            }

            ledgerNames[entity.IncomeLedgerCode] =
                entity.IncomeLedgerName;

            ledgerNames[entity.ExpenseLedgerCode] =
                entity.ExpenseLedgerName;
        }

        ledgerNames.Remove(
            string.Empty);

        List<string> ledgerCodes =
            ledgerNames.Keys.ToList();

        foreach
        (
            GeneralLedgerEntity ledger
            in await context
                .Set<GeneralLedgerEntity>()
                .Where
                (
                    x =>
                        ledgerCodes.Contains(x.LedgerCode)
                        &&
                        !x.IsDeleted
                )
                .ToListAsync()
        )
        {
            string name =
                ledgerNames[ledger.LedgerCode];

            if
            (
                ledger.LedgerName == name
            )
            {
                continue;
            }

            ledger.LedgerName =
                name;

            ledger.ModifiedDate =
                DateTime.UtcNow;

            changed =
                true;
        }

        if
        (
            changed
        )
        {
            await context.SaveChangesAsync();
        }
    }
